#!/usr/bin/env python3
"""Independent finite exact certificate: Fano line flips, Walsh modes, covering holonomy."""
import itertools,json,math
from collections import Counter
from fractions import Fraction
N=7
lines=[tuple((i+j)%7 for j in (0,1,3)) for i in range(7)]
point_labels=[1,2,4,3,6,7,5]
def dot(a,b):return (a&b).bit_count()%2
normals=[next(a for a in range(1,8) if all(dot(a,point_labels[v])==0 for v in L)) for L in lines]
edge_line={tuple(sorted((a,b))):i for i,L in enumerate(lines) for a,b in itertools.combinations(L,2)}
def syndrome(m):
 s=0
 for i,a in enumerate(normals):
  if m>>i&1:s^=a
 return s
def arc(a,b,m):return (((b-a)%7 in (1,2,4)) != bool(m>>edge_line[tuple(sorted((a,b)))]&1))
def hp(m):
 d=[[0]*7 for _ in range(128)]
 for v in range(7):d[1<<v][v]=1
 for s in range(1,128):
  for v in range(7):
   if s>>v&1:
    for w in range(7):
     if not s>>w&1 and arc(v,w,m):d[s|1<<w][w]+=d[s][v]
 return sum(d[-1])
h=[hp(m) for m in range(128)]
checks=0
def check(x,msg):
 global checks
 checks+=1
 if not x:raise ValueError(msg)
for m in range(128):
 check(h[m]==(189 if syndrome(m)==0 else 171),'inherited spectrum')
 check(sorted(syndrome(m^(1<<i)) for i in range(7))==sorted(set(range(8))-{syndrome(m)}),'K8 cover')
 check(sum(h[m^(1<<i)] for i in range(7))==1386-h[m],'eigenfunction')
walsh={s:Fraction(sum(h[m]*(-1)**((m&s).bit_count()%2) for m in range(128)),128) for s in range(128)}
nonzero={s:c for s,c in walsh.items() if c}
expected={0:Fraction(693,4)}
for b in range(1,8):expected[sum(dot(b,a)<<i for i,a in enumerate(normals))]=Fraction(9,4)
check(nonzero==expected,'pure fourth order Walsh')
# Independent expansion over all Hamilton words, not reading h or calling hp.
coeff=Counter()
for p in itertools.permutations(range(7)):
 terms={0:1}
 for a,b in zip(p,p[1:]):
  bit=1<<edge_line[tuple(sorted((a,b)))];sign=1 if (b-a)%7 in (1,2,4) else -1
  new=Counter(terms)
  for mask,c in terms.items():new[mask^bit]+=c*sign
  terms=dict(new)
 coeff.update(terms)
expansion={s:Fraction(c,64) for s,c in coeff.items() if c}
check(expansion==expected,'independent path expansion')
# All partial assignments on <=3 coordinates have identical conditional mean.
conditional=[]
for k in range(4):
 for inds in itertools.combinations(range(7),k):
  for vals in itertools.product(range(2),repeat=k):
   ms=[m for m in range(128) if all((m>>i&1)==v for i,v in zip(inds,vals))]
   check(Fraction(sum(h[m] for m in ms),len(ms))==Fraction(693,4),'low-order conditional mean')
   conditional.append([inds,vals])
# Every triangle in quotient lifts to an open length-three path with code displacement.
triangles=[]
for u,v,w in itertools.combinations(range(8),3):
 ds=(u^v,v^w,w^u)
 mask=sum(1<<normals.index(a) for a in ds)
 check(mask.bit_count()==3 and syndrome(mask)==0,'triangle holonomy')
 triangles.append(mask)
code=[m for m in range(128) if syndrome(m)==0]
check(Counter(triangles)==Counter({m:8 for m in code if m.bit_count()==3}),'triangle holonomy classes')
# Code generated by weight-three holonomies; finite closure.
span={0}
for m in set(triangles):span|={x^m for x in list(span)}
check(span==set(code),'holonomy deck group')
# H alone is not deterministic continuation sufficient: seven different repairs.
for s,t in itertools.combinations(range(1,8),2):
 a=next(m for m in range(128) if syndrome(m)==s)
 b=next(m for m in range(128) if syndrome(m)==t)
 i=normals.index(s)
 check(h[a]==h[b] and h[a^(1<<i)]!=h[b^(1<<i)],'H scalar hostile')
# General Hamming cube quotient for r<=5 and character weights.
general=[]
for r in range(2,6):
 cols=range(1,2**r)
 weights=[sum(dot(b,a) for a in cols) for b in range(1,2**r)]
 check(set(weights)=={2**(r-1)},'simplex weight')
 general.append({'r':r,'cube_dimension':2**r-1,'quotient_vertices':2**r,'fiber_size':2**(2**r-1-r),'nonconstant_degree':2**(r-1)})
print(json.dumps({'status':'PASS','checks':checks,'normals':normals,'H_histogram':dict(Counter(h)),'walsh_nonzero':{str(s):str(c) for s,c in expected.items()},'conditional_assignments_checked':len(conditional),'triangle_holonomy_histogram':dict(Counter(triangles)),'code_weight_enumerator':dict(Counter(m.bit_count() for m in code)),'general_hamming_instances':general,'finite_scope':'all 128 Fano line orientations; 5040 independent path words; all 56 K8 triangles'},indent=2,sort_keys=True))
