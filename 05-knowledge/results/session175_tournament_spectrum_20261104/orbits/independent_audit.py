def need(x,m):
    if not x:raise ArithmeticError(m)

def signed_burnside(n):
    edges=list(combinations(range(n),2)); total=0
    for p in permutations(range(n)):
        unseen=set(edges); orbits=0; valid=True
        while unseen:
            initial=next(iter(unseen)); e=initial; flip=0
            while True:
                unseen.remove(e)
                a,b=p[e[0]],p[e[1]]
                flip^=a>b
                e=(min(a,b),max(a,b))
                if e==initial:break
            if flip:valid=False;break
            orbits+=1
        if valid:total+=1<<orbits
    need(total%factorial(n)==0,'signed Burnside divisibility')
    return total//factorial(n)

def reverse(n,projective=False):
    facts=[factorial(i) for i in range(n+1)]
    @lru_cache(None)
    def F(R,L,s):
        if R==0:return 1
        if L==1:return 1<<(R*(R-1)//2+R*s[0])
        total=0
        for c in range(R//L+1):
            r=R-c*L; factor,remainder=divmod(facts[R],facts[r]*L**c*facts[c])
            need(not remainder,'reverse transfer integral')
            if not r:child=1
            else:
                ll=min(L-2,r if r&1 else r-1)
                ss=tuple(s[i]+c*gcd(L,2*i+1) for i in range((ll+1)//2))
                b=min(v//(2*i+1) for i,v in enumerate(ss)) if projective else 0
                ss=tuple(v-b*(2*i+1) for i,v in enumerate(ss))
                child=F(r,ll,ss)<<(b*r)
            exponent=c*s[-1]+L*c*(c-1)//2+c*(L-1)//2
            total+=(factor*child)<<exponent
        return total
    L=n if n&1 else n-1
    v=F(n,L,(0,)*((L+1)//2)) if n else 1
    need(v%facts[n]==0,'reverse final divisibility')
    return v//facts[n],F.cache_info()._asdict()

def completions(M,lengths):
    if not lengths:
        if M==0:yield ()
        return
    j,*rest=lengths
    for k in range(M//j+1):
        for tail in completions(M-j*k,rest):yield (k,)+tail

