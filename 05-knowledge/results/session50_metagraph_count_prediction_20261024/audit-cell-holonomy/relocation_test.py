#!/usr/bin/env python3
"""Actually copy only manifest-listed bytes, then test deep and hostile closure."""
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
ROOT=Path(__file__).resolve().parent

def require(ok,label):
    if not ok: raise RuntimeError(label)

manifest=json.loads((ROOT/'manifest.json').read_text())
with tempfile.TemporaryDirectory(prefix='cell-holonomy-manifest-copy-') as directory:
    destination=Path(directory)/'packet'; destination.mkdir()
    for name in list(manifest['sha256'])+['manifest.json']:
        target=destination/name; target.parent.mkdir(parents=True,exist_ok=True); shutil.copyfile(ROOT/name,target)
    results={}
    for optimized in (False,True):
        command=[sys.executable,'-B']+(['-O'] if optimized else [])+[str(destination/'verify.py'),'--deep']
        result=subprocess.run(command,cwd=directory,capture_output=True)
        require(result.returncode==0,'manifest-copy replay: '+result.stderr.decode())
        summary=json.loads(result.stdout); summary.pop('payload_files',None)
        results['optimized' if optimized else 'normal']=summary
    def rejected(expected):
        r=subprocess.run([sys.executable,'-B','-O',str(destination/'verify.py')],cwd=directory,capture_output=True)
        require(r.returncode!=0 and expected in r.stderr.decode(),'hostile closure check: '+expected)
    hostile=destination/'unlisted-payload'; hostile.write_text('extra\n'); rejected('manifest file closure'); hostile.unlink()
    nested=destination/'unlisted-dir'; nested.mkdir(); hostile=nested/'manifest.json'; hostile.write_text('{}\n'); rejected('manifest file closure'); hostile.unlink(); nested.rmdir()
    payload=destination/'AUDIT.md'; old=payload.read_bytes(); payload.write_bytes(old+b'\nmutated\n'); rejected('digest mismatch'); payload.write_bytes(old)
    link=destination/'unlisted-link'; link.symlink_to('AUDIT.md'); rejected('symlink'); link.unlink()
    cache=destination/'__pycache__'; cache.mkdir(); rejected('generated bytecode or cache'); cache.rmdir()
    bytecode=destination/'generated.pyc'; bytecode.write_bytes(b'cache'); rejected('generated bytecode or cache'); bytecode.unlink()
print(json.dumps({'status':'PASS','manifest_only_actual_copy':True,'changed_working_directory':True,'normal_optimized_deep_replays':results,'unexpected_file_rejected':True,'mutated_payload_rejected':True,'symlink_rejected':True,'generated_cache_rejected':True},sort_keys=True,indent=2))
