#!/usr/bin/env python3
"""Closed packet hashes and executable checks, independent of original paths."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
ROOT=Path(__file__).resolve().parent

def require(ok,label):
    if not ok: raise RuntimeError(label)

def main():
    parser=argparse.ArgumentParser(); parser.add_argument('--deep',action='store_true'); args=parser.parse_args()
    manifest=json.loads((ROOT/'manifest.json').read_text())
    actual=set()
    for path in ROOT.rglob('*'):
        require(not path.is_symlink(),'symlink in closed packet')
        require('__pycache__' not in path.relative_to(ROOT).parts and path.suffix not in {'.pyc','.pyo'},'generated bytecode or cache in closed packet')
        if path.is_file() and str(path.relative_to(ROOT))!='manifest.json': actual.add(str(path.relative_to(ROOT)))
    require(actual==set(manifest['sha256']),'manifest file closure')
    for name,digest in manifest['sha256'].items():
        require(not Path(name).is_absolute() and '..' not in Path(name).parts,'unsafe manifest path')
        require(hashlib.sha256((ROOT/name).read_bytes()).hexdigest()==digest,'digest mismatch: '+name)
    checked=[]
    if args.deep:
        with tempfile.TemporaryDirectory(prefix='cell-holonomy-deep-') as directory:
            for script,expected in [('independent.py','independent.json'),('independent_predictor.py','predictor-independent.json'),('compare_atlas.py','atlas-comparison.json'),('replay_frozen.py','producer-replay.json')]:
                output=Path(directory)/(script+'.json')
                cmd=[sys.executable,'-B']+(['-O'] if sys.flags.optimize else [])+[str(ROOT/script),'--receipt',str(output)]
                result=subprocess.run(cmd,cwd=directory,capture_output=True)
                require(result.returncode==0,'deep replay failed: '+script+' '+result.stderr.decode())
                require(output.read_bytes()==(ROOT/expected).read_bytes(),'deep receipt mismatch: '+script)
                checked.append(script)
    print(json.dumps({'status':'PASS','deep':args.deep,'payload_files':len(actual),'rerun_scripts':checked},sort_keys=True))
if __name__=='__main__': main()
