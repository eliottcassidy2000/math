#!/usr/bin/env python3
"""Exact finite controls for the CFSG-dependent Lucas gap theorem; no asserts."""
import json, math, random

def require(p,msg):
    if not p: raise RuntimeError(msg)
def fib(n):
    a,b=0,1
    for _ in range(n): a,b=b,a+b
    return a
def lucas(n): return fib(n-1)+fib(n+1) if n else 2
def words(n):
    return [x for x in range(1<<n) if not(x&(x<<1)) and not((x&1) and (x>>(n-1)&1))]
def reflect(x,n): return sum(((x>>i)&1)<<((-i)%n) for i in range(n))
def prime(n): return n>1 and all(n%d for d in range(2,math.isqrt(n)+1))
def compose(a,b): return tuple(a[b[i]] for i in range(len(a)))
def cycles(g):
    seen=set(); out=[]
    for i in range(len(g)):
        if i not in seen:
            c=[]; j=i
            while j not in seen: c.append(j); seen.add(j); j=g[j]
            out.append(c)
    return out
def reader(n):
    p=lucas(n); W=words(n)
    alpha=next(a for a in range(p) if (a*a-a-1)%p==0 and pow(a,n,p)==1)
    labels={w:sum(((w>>i)&1)*pow(alpha,i,p) for i in range(n))%p for w in W}
    require(len(set(labels.values()))==p,'bijective reader')
    R=[0]*p
    for w,x in labels.items():R[x]=labels[reflect(w,n)]
    return p,alpha,tuple(R)
def run():
    checks=0; rows=[]
    for n in range(5,1002,2):
        m=(n-1)//2; f=fib(m+2); p=lucas(n)
        require(p-f*f==2*fib(m)*fib(m-1),'gap identity');checks+=1
        require(1<f and f*f<p,'strict gap');checks+=1
        if n%3:
            require(((p-f)//2)%2 == (n%12==11),'parity');checks+=1
    for n in range(5,20,2):
        W=words(n); f=sum(w==reflect(w,n) for w in W)
        require(len(W)==lucas(n) and f==fib((n+3)//2),'direct words');checks+=1
        if prime(len(W)):rows.append({'n':n,'p':len(W),'fixed':f,'transpositions':(len(W)-f)//2,'group': 'PSL(2,11)' if n==5 else ('S' if (len(W)-f)//2%2 else 'A')})
    # Projective integer bounds, not an enumeration of all groups.
    S=lambda q,d:sum(q**i for i in range(d))
    for q in range(2,32):
        for d in range(3,24,2):
            require(S(q,(d+1)//2)**2>S(q,d),'linear bound');checks+=1
        for d in range(2,24):
            require(S(q,d)**2>S(q*q,d),'semilinear bound');checks+=1
    certs=[]
    for n in (7,11,13):
        p,alpha,R=reader(n); rng=random.Random(93000+n); g=tuple(range(p)); exps=[]
        for step in range(1,2001):
            a=rng.randrange(p);exps.append(a)
            g=tuple(R[(g[x]+a)%p] for x in range(p))
            cyc=cycles(g)
            targets=[c for c in cyc if len(c)<=p-3 and prime(len(c)) and all(math.gcd(len(c),len(d))==1 for d in cyc if d is not c)]
            if targets:
                c=min(targets,key=len); power=math.lcm(*(len(d) for d in cyc if d is not c))
                h=tuple(range(p));base=g; e=power
                while e:
                    if e&1:h=compose(base,h)
                    base=compose(base,base);e//=2
                require(prime(p) and prime(len(c)) and len(c)<=p-3 and sorted(len(c) for c in cycles(h) if len(c)>1)==[len(c)],'Jordan power and hypotheses');checks+=1
                certs.append({'n':n,'p':p,'alpha':alpha,'exponents':exps,'cycle_lengths':sorted(map(len,cyc)),'power':power,'isolated_prime_cycle':len(c)})
                break
        else:raise RuntimeError('certificate search exhausted')
    # Hostile inclusive endpoint: D_13 generated by shift and negation.
    require(sum((-x)%13==x for x in range(13))==1,'affine endpoint');checks+=1
    require(7*7>23 and 3*3<11,'Mathieu gap table controls');checks+=1
    # Exact exceptional minimum: actual tournament orbit, not just frame labels.
    p5,a5,R5=reader(5);T5=tuple((x+1)%p5 for x in range(p5))
    group={tuple(range(p5))}; queue=list(group)
    for g in queue:
        for gen in (T5,R5):
            h=compose(gen,g)
            if h not in group: group.add(h);queue.append(h)
        if len(group)>660: raise RuntimeError('unexpected Lucas-five group')
    require(len(group)==660 and a5==4,'exceptional group closure');checks+=1
    H={x*x%p5 for x in range(1,p5)}
    arcs=frozenset((x,y) for x in range(p5) for y in range(p5) if (y-x)%p5 in H)
    orbit=set();stabilizer=0
    for g in group:
        image=frozenset((g[x],g[y]) for x,y in arcs)
        orbit.add(image);stabilizer+=image==arcs
    require(len(arcs)==55 and len(orbit)==12 and stabilizer==55,'actual Paley tournament orbit');checks+=1
    require([d for d in range(57,661,2) if 660%d==0]==[165],'only larger odd stabilizer divisor');checks+=1
    exceptional={'group_order':len(group),'reader_root':a5,'Paley_stabilizer':stabilizer,'Paley_orbit':len(orbit),'minimum_equivariant_decoder_states':12}
    decoder_bounds=[]
    for p,symmetric in ((29,False),(199,True),(521,False)):
        v=sum(p//(2**k) for k in range(1,p.bit_length()+1))-int(not symmetric)
        require(v==p-p.bit_count()-int(not symmetric),'decoder valuation');checks+=1
        decoder_bounds.append({'p':p,'symmetric':symmetric,'minimum_bits':v})
    return {'checks':checks,'exceptional_decoder':exceptional,'decoder_bounds':decoder_bounds,'rows':rows,'Jordan_certificates':certs,'scope':'Finite controls; universal proof in LUCAS_GAP_THEOREM.md uses Jones classification and cited ATLAS tables.'}
if __name__=='__main__':print(json.dumps(run(),sort_keys=True,indent=2))
