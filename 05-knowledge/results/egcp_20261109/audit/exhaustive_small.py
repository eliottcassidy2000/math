def all_graphs(n):
    pairs = [(u, v) for u in range(n) for v in range(u + 1, n)]
    for code in range(1 << len(pairs)):
        yield graph(n, [pairs[e] for e in range(len(pairs)) if (code >> e) & 1])


# (1) Lemma 8
bad_val = bad_unique = bad_crit = tot = nev = 0
for rho in range(1, 6):
    for H in all_graphs(rho):
        for z in range(rho):
            J = jump(H, z)
            m = J[0]
            h = popcount(H[1][z])
            tot += 1
            if m != 2 * rho + 1 - h or dom_count(J) != 2 ** (m - 1) - D_count(H) or not has_leaf(J) or has_universal(J):
                bad_val += 1
            dg = degrees(J)
            unique = dg[rho] == m - 2 and dg.count(m - 2) == 1
            if rho >= 2 and not unique:
                bad_unique += 1
            if unique:
                crit = all(edge_sign(H, p) == perm_sign(p) for p in stabiliser_generators(H, z))
                ev = is_even(J)
                nev += ev
                bad_crit += crit != ev
print("Lemma 8, all labelled H on rho <= 5 and all z (%d cases): value/leaf/no-universal failures %d; "
      "hub not the unique vertex of degree m-2 with rho >= 2: %d; criterion (iii) failures %d (%d even)" % (
          tot, bad_val, bad_unique, bad_crit, nev))
# rho = 1 is the only exception to uniqueness:
J1 = jump(graph(1), 0)
print("  rho = 1: J = K_1 u K_2, degrees", degrees(J1), "(hub ties with its leaf; irrelevant to the theorem)")

# (2) Lemma 7
tot = bad = 0
for n in range(3, 7):
    for G in all_graphs(n):
        if not has_leaf(G) or has_universal(G) or not is_even(G):
            continue
        for q in [v for v, d in enumerate(degrees(G)) if d == 1]:
            S = SR(G, q)
            tot += 1
            if not (dom_count(S) == 3 * 2 ** (n - 1) + dom_count(G) and is_even(S) and has_leaf(S) and not has_universal(S)):
                bad += 1
print("Lemma 7, all labelled even L-graphs on 3..6 vertices, all leaves (%d cases): failures %d" % (tot, bad))

# (3) Lemma 3 classification by brute force over max-degree <= 2 graphs (min degree >= 1), n <= 9


def pairs_in_nbhds(H):
    s = set()
    for v in range(H[0]):
        N = H[1][v]
        if popcount(N) >= 2:
            sub = N
            while sub:
                if popcount(sub) >= 2:
                    s.add(sub)
                sub = (sub - 1) & N
    return s


def components(H):
    n, adj = H
    seen = 0
    comps = []
    for s in range(n):
        if (seen >> s) & 1:
            continue
        comp = 1 << s
        fr = comp
        while fr:
            nxt = 0
            x = fr
            while x:
                low = x & -x
                nxt |= adj[low.bit_length() - 1]
                x ^= low
            fr = nxt & ~comp
            comp |= nxt
        seen |= comp
        comps.append(comp)
    return comps


def shape(H):
    out = []
    for c in components(H):
        k = popcount(c)
        e = sum(popcount(H[1][v] & c) for v in range(H[0]) if (c >> v) & 1) // 2
        out.append(('C%d' % k) if e == k else ('P%d' % k))
    return tuple(sorted(out))


def maxdeg2_graphs(n):
    """all labelled graphs on n vertices with 1 <= degree <= 2 (generated by edge-by-edge backtracking)"""
    pairs = [(u, v) for u in range(n) for v in range(u + 1, n)]
    deg = [0] * n
    chosen = []
    res = []

    def bt(i):
        if i == len(pairs):
            if min(deg) >= 1:
                res.append(graph(n, chosen))
            return
        u, v = pairs[i]
        # prune: vertex u is finished after its last pair; it must have degree >= 1
        bt_skip = True
        if deg[u] < 2 and deg[v] < 2:
            deg[u] += 1; deg[v] += 1; chosen.append((u, v))
            bt(i + 1)
            chosen.pop(); deg[u] -= 1; deg[v] -= 1
        bt(i + 1)

    bt(0)
    return res


summary = {}
for n in range(2, 10):
    for H in maxdeg2_graphs(n):
        k = len(pairs_in_nbhds(H))
        if k in (1, 2):
            sh = shape(H)
            co_even = all(edge_sign(H, p) == perm_sign(p) for p in aut_generators(H))
            summary.setdefault((n, k, sh), [0, 0])
            summary[(n, k, sh)][0] += 1
            summary[(n, k, sh)][1] += co_even
for key in sorted(summary):
    n, k, sh = key
    print("  n=%d pairs=%d shape=%s: %d labelled, co-even %d" % (n, k, sh, summary[key][0], summary[key][1]))
