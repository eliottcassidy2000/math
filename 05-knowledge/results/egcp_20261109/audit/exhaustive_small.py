"""Exhaustive small-order checks (audit code only):
 (1) Lemma 8 over ALL labelled H on rho <= 5 vertices and all z: value formula, leaf, no universal vertex;
     the hub a is the unique vertex of degree m - 2 for every rho >= 2 (so the hypothesis of (iii) is automatic);
     criterion (iii) <=> evenness of J(H, z).
 (2) Lemma 7 over ALL labelled even L-graphs G on n' <= 6 vertices and all leaves q.
 (3) Lemma 3 classification: all labelled H on <= 9 vertices? (too many) -> instead, all max-degree-<=2 graphs H
     with min degree >= 1 on n <= 9 vertices, counted by number of distinct pairs lying in neighbourhoods; checks that
     exactly-one-pair => P_3 u sK_2, exactly-two-pairs => P_4/C_4/2P_3 u sK_2, and that none is co-even.
"""
