"""Actual C5 strong-atom attachments, observer quotients and F25 transport."""
import json
from itertools import product, combinations
from collections import Counter
from pathlib import Path

CHECKS=0
def need(b,msg):
    global CHECKS
    CHECKS+=1
    if not b: raise RuntimeError(msg)

STATES=list(product(range(5),repeat=3))
def add(a,b): return tuple((x+y)%5 for x,y in zip(a,b))
def rotate(a): return (a[2],a[0],a[1])
def converse(a): return tuple(-a[i]%5 for i in (0,2,1))
def rel(a): return ((a[1]-a[0])%5,(a[2]-a[0])%5)
def mul25(a,b):
    # omega^2=-omega-1, irreducible over F5.
    x,y=a; u,v=b
    return ((x*u-y*v)%5,(x*v+y*u-y*v)%5)
def power25(a,n):
    out=(1,0)
    while n:
        if n&1: out=mul25(out,a)
        a=mul25(a,a); n//=2
    return out
def fourier(a):
    # Z=a0+omega*a1+omega^2*a2; S=a0+a1+a2.
    return sum(a)%5,((a[0]-a[2])%5,(a[1]-a[2])%5)
def chart(a): return tuple(5*k+(i+a[k])%5 for k in range(3) for i in range(5))
def image(mask,p): return sum(1<<p[i] for i in range(len(p)) if mask>>i&1)
def strong(rows):
    for reverse in (False,True):
        reached=1
        while True:
            old=reached
            for i in range(len(rows)):
                if reached>>i&1:
                    reached|=sum(1<<j for j in range(len(rows)) if rows[j]>>i&1) if reverse else rows[i]
            if reached==old: break
        if reached!=(1<<len(rows))-1: return False
    return True

T5=tuple(sum(1<<((i+d)%5) for d in (1,2)) for i in range(5))
R=tuple((T5[i]<<(5*k))|(31<<(5*((k+1)%3))) for k in range(3) for i in range(5))
def hub(a, cross_complement=False):
    # Source R and a new T5 hub are actual strong atoms. R(i,t)->hub(u)
    # exactly when u-t=a_i; all complementary cross arcs point back.
    rows=[R[5*k+i]|sum(1<<(15+u) for u in range(5)
          if (((u-i)%5==a[k]) != cross_complement)) for k in range(3) for i in range(5)]
    for u in range(5):
        rows.append((T5[u]<<15)|sum(1<<(5*k+i) for k in range(3) for i in range(5)
                    if (((u-i)%5!=a[k]) != cross_complement)))
    return tuple(rows)
def hub_response(a):
    # Forget only the hub's absolute C5 chart, not its vertex permutation type.
    return min(tuple(1<<((i+a[k]+b)%5) for k in range(3) for i in range(5)) for b in range(5))
def legal(rows,path): return all(rows[u]>>v&1 for u,v in zip(path,path[1:]))
def native_complement(rows,path):
    if not legal(rows,path): return None
    n=len(rows); reverse=[((1<<n)-1)^row^(1<<i) for i,row in enumerate(rows)]
    for u,v in zip(path,path[1:]):
        reverse[u]|=1<<v; reverse[v]&=~(1<<u)
    return tuple(reverse)

def main():
    need(strong(T5) and strong(R),'source strong atoms')
    need(all((x*x+x+1)%5 for x in range(5)),'F25 polynomial irreducible')
    need(len({fourier(a) for a in STATES})==125,'Fourier bijection')
    for a in STATES:
        s,z=fourier(a); sr,zr=fourier(rotate(a)); sc,zc=fourier(converse(a))
        need(sr==s and zr==mul25((0,1),z),'root rotation Fourier action')
        need(sc==(-s)%5 and zc==tuple(-x%5 for x in power25(z,5)),'converse Frobenius action')
        need(strong(hub(a)),'actual hub attachment strong')
        # Converse also toggles cross-edge polarity; it is a separate bit.
        p=tuple(5*(0,2,1)[k]+(-i)%5 for k in range(3) for i in range(5))+tuple(15+(-i)%5 for i in range(5))
        A=hub(a); B=hub(converse(a),True)
        need(all((A[i]>>j&1)==(B[p[j]]>>p[i]&1) for i in range(20) for j in range(20)),
             'actual converse with polarity sidecar')
    # Exhaust all one-vertex labelled attachments to R. The active modules
    # are exactly those on which the binary row is nonconstant.
    probe_counts=Counter(); charts=[chart(a) for a in STATES]
    for mask in range(1<<15):
        active=sum(((mask>>(5*k))&31) not in (0,31) for k in range(3))
        stabilizer=sum(image(mask,p)==mask for p in charts)
        need(stabilizer==5**(3-active),'named-probe kernel')
        probe_counts[active]+=1
    need(dict(probe_counts)=={0:8,1:360,2:5400,3:27000},'probe census')
    responses={a:hub_response(a) for a in STATES}
    need(len(set(responses.values()))==25,'unmarked hub quotient')
    for a in STATES:
        for b in STATES:
            same=responses[a]==responses[b]
            need(same==(rel(a)==rel(b))==(fourier(a)[1]==fourier(b)[1]),'actual hub / field quotient')
            if same:
                need(responses[rotate(a)]==responses[rotate(b)] and responses[converse(a)]==responses[converse(b)],'restricted closure')
                # Translations are generated by the three unit coordinate updates.
                for t in ((1,0,0),(0,1,0),(0,0,1)):
                    need(responses[add(a,t)]==responses[add(b,t)],'translation closure')
    # Same 25-state response, but a native named Hamilton re-marking guard
    # separates the five formerly forgotten common phases.
    paths=[tuple(range(15))+tuple(15+(4+b+i)%5 for i in range(5)) for b in range(5)]
    diag=[(i,i,i) for i in range(5)]
    guards=[[legal(hub(a),p) for p in paths] for a in diag]
    need(guards==[[i==j for j in range(5)] for i in range(5)],'native named guard separates common phase')
    complete={(rel(a),tuple(legal(hub(a),p) for p in paths)) for a in STATES}
    need(len(complete)==125,'full future observer restores125')
    # The native fixed-path complement is not global converse; even the
    # initial five-atom family is not closed under it.
    complement5=native_complement(T5,tuple(range(5)))
    need(complement5 is not None and sorted(x.bit_count() for x in complement5)!=[2]*5,'native complement leaves cyclic-five family')
    # Enumerate all linear subspaces of F5^3 via closure from generated spans.
    subspaces={frozenset({(0,0,0)})}
    frontier=list(subspaces)
    while frontier:
        H=frontier.pop()
        for v in STATES:
            if v in H: continue
            K=frozenset(add(h,tuple(t*x%5 for x in v)) for h in H for t in range(5))
            if K not in subspaces: subspaces.add(K); frontier.append(K)
    invariant=[H for H in subspaces if all(rotate(a) in H and converse(a) in H for a in H)]
    need(sorted(map(len,invariant))==[1,5,25,125],'all linear invariant kernels')
    # LCA reconstruction: arbitrary gain tree on five actual T5 cell charts.
    parent=[-1,0,0,1,1]; tree_checks=0
    for phases in product(range(5),repeat=5):
        gains=[0]+[(phases[i]-phases[parent[i]])%5 for i in range(1,5)]
        potentials=[0]*5
        for i in range(1,5): potentials[i]=(potentials[parent[i]]+gains[i])%5
        for i,j in combinations(range(5),2):
            need((potentials[j]-potentials[i])%5==(phases[j]-phases[i])%5,'LCA gain recovery')
            tree_checks+=1
    out={'status':'FINITE-EXACT','states':125,'named_single_vertex_probe_counts_by_active_modules':dict(sorted(probe_counts.items())),'unmarked_hub_quotient':25,'forgetful_fibres':5,'linear_subspaces':len(subspaces),'rotation_converse_invariant_kernel_sizes':sorted(map(len,invariant)),'invariant_quotient_sizes':[1,5,25,125],'strong_twenty_vertex_attachments_checked':125,'native_guard_paths':paths,'diagonal_guard_table':guards,'native_complement_T5_rows':complement5,'native_complement_T5_scores':sorted(x.bit_count() for x in complement5),'five_cell_tree_tuples':3125,'LCA_pair_checks':tree_checks,'checks':CHECKS}
    Path(__file__).with_name('kernel125.json').write_text(json.dumps(out,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(out))

if __name__=='__main__': main()
