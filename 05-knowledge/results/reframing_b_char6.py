def miss_mass(E, S):
    # measure of tau in [0,1) s.t. for all e in E, sector_of(e*tau) NOT in S
    E=sorted(set(E)); bps=set([F(0),F(1)])
    for e in E:
        if e==0: continue
        for m in range(0,7*e+1): bps.add(F(m,7*e))
    bps=sorted(bps); tot=F(0)
    Sset=set(S)
    for i in range(len(bps)-1):
        x0,x1=bps[i],bps[i+1]
        if x1<=x0: continue
        mid=(x0+x1)/2
        # the orbit sectors hit:
        hit=set(sector_of(e*mid) for e in E)
        # tau "misses" sector j if j NOT in hit. We want: all of S missed, i.e. S cap hit = empty
        if Sset.isdisjoint(hit):
            tot+=x1-x0
    return tot

