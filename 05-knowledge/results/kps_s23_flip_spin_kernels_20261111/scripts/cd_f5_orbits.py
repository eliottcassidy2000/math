"""cd_f5_orbits.py - step F5 with symmetry: the feasible sets of 5 odd planes of PG(3,2) fall into orbits of the
group generated by two linear maps (a Singer cycle and a transvection; whatever group they generate, the orbits
partition the sets, and the property searched for is invariant under every linear map because a linear map
permutes points, lines, planes and zero-sum 4-sets and relabels tournaments).  One representative per orbit is
searched exhaustively for other planes of defect exactly 2."""
import sys, itertools
from cd_more import F2System, planes, quads
from cd_min import Elim, plane_data, realizable, defect

S = F2System(4)
nv = len(S.var)
P = planes(4)
Q4 = quads(4)
PD = plane_data(S, P, Q4)
R = [realizable(rows, nv) for (qs, rows) in PD]
w2 = [[w for w in R[i] if defect(w) == 2] for i in range(15)]
pindex = {pl: i for i, pl in enumerate(P)}


def rows_with(i, w):
    return [(m, c ^ (w >> j & 1)) for j, (m, c) in enumerate(PD[i][1])]


def lin(images):
    """linear map given by the images of the basis vectors 1, 2, 4, 8."""
    def f(v):
        out = 0
        for b in range(4):
            if v >> b & 1:
                out ^= images[b]
        return out
    return f


singer = lin([2, 4, 8, 3])          # x -> x * t in F_16 = F_2[t]/(t^4 + t + 1): 1->t, t->t^2, t^2->t^3, t^3->t+1
transv = lin([3, 2, 4, 8])          # e1 -> e1 + e2
gens = []
for f in (singer, transv):
    assert sorted(f(v) for v in range(1, 16)) == list(range(1, 16))
    perm = [pindex[tuple(sorted(f(v) for v in pl))] for pl in P]
    gens.append(perm)

five = []
state = {}
for comb in itertools.combinations(range(15), 5):
    e = Elim()
    ok = True
    for i in comb:
        ok &= e.add_all(rows_with(i, 0))
    if ok:
        five.append(comb)
        state[comb] = e
fset = set(five)
seen = set()
orbits = []
for c in five:
    if c in seen:
        continue
    orb = {c}
    stack = [c]
    while stack:
        x = stack.pop()
        for g in gens:
            y = tuple(sorted(g[i] for i in x))
            assert y in fset
            if y not in orb:
                orb.add(y)
                stack.append(y)
    seen |= orb
    orbits.append((c, len(orb)))
print("feasible sets of 5 odd planes: %d in %d orbits, sizes %s" % (len(five), len(orbits), [n for c, n in orbits]))
sys.stdout.flush()
overall = 0
for comb, size in orbits:
    e = state[comb]
    others = [i for i in range(15) if i not in comb]
    levels = {1: 0, 2: 0, 3: 0, 4: 0}
    best = [0]

    def dfs(start, el, depth):
        for idx in range(start, len(others)):
            i = others[idx]
            for w in w2[i]:
                e2 = el.copy()
                if e2.add_all(rows_with(i, w)):
                    levels[depth + 1] += 1
                    if depth + 1 > best[0]:
                        best[0] = depth + 1
                    if depth + 1 < 4:
                        dfs(idx + 1, e2, depth + 1)
    dfs(0, e, 0)
    overall = max(overall, best[0])
    print("   orbit of %d sets, representative %s, rank %d: consistent additions of k planes of defect exactly 2: %s ; largest k = %d"
          % (size, comb, len(e.piv), sorted(levels.items()), best[0]))
    sys.stdout.flush()
print("largest number of planes of defect exactly 2 next to 5 odd planes:", overall)
