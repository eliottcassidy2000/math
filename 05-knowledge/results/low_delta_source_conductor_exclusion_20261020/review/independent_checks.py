#!/usr/bin/env python3
"""Independent finite-exact audit controls. Does not import producer code."""
from pathlib import Path
from itertools import combinations
import argparse
import hashlib
import json
import sympy as s

x, y, t, u, v, z = s.symbols('x y t u v z')
checks = {}
examples = []

def check(name, value):
    if not bool(value):
        raise RuntimeError('FAILED: ' + name)
    checks[name] = True

def zero(expr):
    return s.cancel(expr) == 0

def vector(poly, n):
    p = s.Poly(s.expand(poly), y)
    return s.Matrix([p.nth(i) for i in range(n)])

def quotient_matrix(poly, defining, n):
    return s.Matrix.hstack(*[vector(s.rem(s.expand(poly*y**j), defining, y), n)
                            for j in range(n)])

def residue_at_infinity(poly, conductor):
    m = s.degree(conductor, y)
    if m == 0:
        return s.Integer(0)
    remainder = s.Poly(s.rem(poly, conductor, y), y)
    return -remainder.nth(m-1)/s.LC(s.Poly(conductor, y))

def algebra_mod_conductor(f, g, c):
    """Compute the complete finite algebra generated by f,g modulo c."""
    m = int(s.degree(c, y))
    if not m:
        return [], []
    basis = [s.Integer(1)]
    mat = vector(1, m)
    while True:
        changed = False
        for b in list(basis):
            for h in (f, g):
                r = s.rem(b*h, c, y)
                col = vector(r, m)
                trial = mat.row_join(col)
                if trial.rank() > mat.cols:
                    mat = trial
                    basis.append(r)
                    changed = True
        if not changed:
            break
    # Reverse coefficient columns: pivots give exact attainable degrees.
    _, pivots = mat.T[:, ::-1].rref()
    degrees = sorted(m-1-j for j in pivots)
    return basis, degrees

def audit_pair(name, f, g, expected_gaps):
    n = int(s.degree(f, y))
    defining = f-u
    Y = quotient_matrix(y, defining, n)
    G = quotient_matrix(g, defining, n)
    R = s.expand(G.charpoly(v).as_expr())
    inclusion = s.Matrix.hstack(*[vector(s.rem(g**j, defining, y), n)
                                 for j in range(n)])
    index = s.factor(inclusion.det())
    check(name + ':primitive_power_basis', index != 0)
    check(name + ':equation', zero(R.subs({u:f, v:g})))
    rv = s.diff(R, v).subs({u:f, v:g})
    c = s.factor(s.cancel(rv/s.diff(f, y)))
    check(name + ':conductor_polynomial', s.denom(c) == 1)
    check(name + ':norm_square', zero(quotient_matrix(c, defining, n).det()-index**2))
    delta = int(s.degree(index, u))
    check(name + ':conductor_degree', s.degree(c, y) == 2*delta)
    if n == 1:
        resultant = 1
    else:
        U = s.cancel((f.subs(y,t)-f)/(t-y))
        V = s.cancel((g.subs(y,t)-g)/(t-y))
        # SymPy 1.14.0 can lose the swap sign when deg(U)<deg(V).
        # U is monic, so reducing V modulo U preserves its resultant exactly.
        reduced_V = s.rem(V,U,t)
        resultant = s.resultant(U,reduced_V,t)
    check(name + ':divided_difference', zero(resultant-c))
    # Independently certify cB is inside A by solving in its D-power basis.
    conductor_coordinates = inclusion.inv()*quotient_matrix(c, defining, n)
    check(name + ':conductor_module_membership',
          all(s.denom(s.cancel(q)) == 1 for q in conductor_coordinates))
    abar, degrees = algebra_mod_conductor(f, g, c)
    m = int(s.degree(c,y))
    gaps = [j for j in range(m) if j not in degrees]
    check(name + ':exact_degree_gaps', gaps == expected_gaps)
    check(name + ':index_vs_codimension', len(gaps) == delta)
    check(name + ':conductor_quotient_half_dimension', len(abar) == delta)
    if m:
        Amat = s.Matrix.hstack(*[vector(q,m) for q in abar])
        annihilators = s.Matrix.vstack(*[q.T for q in Amat.T.nullspace()])
        Yc = quotient_matrix(y,c,m)
        conductor_constraints = s.Matrix.vstack(*[annihilators*Yc**j for j in range(m)])
        check(name + ':no_larger_conductor_mod_c', conductor_constraints.rank() == m)
    else:
        check(name + ':no_larger_conductor_mod_c', c != 0)
    if delta:
        check(name + ':frobenius', max(gaps) == 2*delta-1)
        check(name + ':symmetry', all(((j in gaps) != ((2*delta-1-j) in gaps))
                                    for j in range(2*delta)))
        check(name + ':forbidden_residue', residue_at_infinity(y**(2*delta-1), c) != 0)
    # Actual field traces via inversion modulo f-u, checked against independent
    # interpolation traces computed by division in the g-variable.
    field = s.QQ.frac_field(u)
    modulus = s.Poly(defining,y,domain=field)
    inverse = s.invert(s.Poly(s.rem(s.diff(R,v).subs(v,g),defining,y),y,domain=field),modulus)
    ytraces = [s.trace(Y**j) for j in range(n)]
    for j in range(n+3):
        value = s.Poly(g**j,y,domain=field)*inverse
        value = value.rem(modulus)
        actual_trace = s.cancel(sum(value.nth(k)*ytraces[k] for k in range(n)))
        expected_trace = s.Poly(s.rem(v**j,R,v),v).nth(n-1)
        check(name + ':trace_interpolation_' + str(j), zero(actual_trace-expected_trace))
        check(name + ':polynomial_trace_' + str(j), s.denom(actual_trace) == 1)
        for i in range(3):
            a = s.expand(f**i*g**j)
            check(name + ':zero_residue_' + str(i) + '_' + str(j),
                  zero(residue_at_infinity(a,c)))
    examples.append({'name':name,'f':str(f),'g':str(g),'equation':str(R),
                     'conductor':str(c),'index':str(index),'delta':delta,'gaps':gaps})

PAIRS = [
 ('linear',y+2,y**3-y,[]),
 ('cusp',y**2,y**3,[1]),
 ('node',y**2,y*(y**2-1),[1]),
 ('two_nodes_translated',(y+1)**2+2,(y+1)*((y+1)**2-1)*((y+1)**2-4),[1,3]),
 ('tacnode',y**2,y*(y**2-1)**2,[1,3]),
 ('cusp_and_node',y**2,y**3*(y**2-1),[1,3]),
 ('quadratic_delta_three',y**2,y*(y**6+y**2+1),[1,3,5]),
 ('ordinary_triple',y**3,y**4+y,[1,2,5]),
 ('three_nodes',y**3-y,y**4,[1,2,5]),
 ('general_cubic_quartic',y**3+y+1,y**4+2*y**2+3*y+2,[1,2,5]),
 ('hidden_quadratic',y**3+y,(y**3+y)**2+y**2,[1]),
 ('nontrivial_cancellation',y**4,y**6+y,[1,2,3,5,9]),
]
for args in PAIRS:
    audit_pair(*args)

# All genus-at-most-three numerical semigroups; closure is checked far enough
# because every candidate gap is <= 5. No hidden infinite enumeration assertion.
semigroups=[]
for genus in range(4):
    for holes in combinations(range(1,6),genus):
        hs=set(holes)
        if all(i+j not in hs for i in range(6) for j in range(6)
               if i not in hs and j not in hs):
            if max(hs,default=-1)==2*genus-1:
                semigroups.append([genus,list(holes)])
check('low_genus_symmetric_classification',semigroups==[
    [0,[]],[1,[1]],[2,[1,3]],[3,[1,2,5]],[3,[1,3,5]]])

# Formal trace/residue compatibility for v=z^n, including negative exponents.
# Trace(z^q) is zero unless n | q, when it equals n*v^(q/n).
for n in range(1,9):
    for exponent in range(-25,26):
        q=exponent-n+1
        downstairs_residue = s.Integer(1) if q % n == 0 and q//n == -1 else s.Integer(0)
        upstairs_residue = s.Integer(1) if exponent == -1 else s.Integer(0)
        check('local_trace_residue_%d_%d'%(n,exponent),downstairs_residue==upstairs_residue)

# Regression guard: use the mathematical Sylvester determinant, not the
# library's direct lower-degree-first result, as the reference value.
guard_f,guard_g=t**3,t**5+1
cf=s.Poly(guard_f,t).all_coeffs();cg=s.Poly(guard_g,t).all_coeffs()
rows=[[0]*i+cf+[0]*(4-i) for i in range(5)]
rows += [[0]*i+cg+[0]*(2-i) for i in range(3)]
guard_det=s.Matrix(rows).det()
check('resultant_guard_sylvester_determinant',guard_det==1)
check('resultant_guard_monic_reduction',s.resultant(guard_f,s.rem(guard_g,guard_f,t),t)==guard_det)

# Nonplanar equalizer: same degree-four conductor and delta two do not suffice.
C=(y**2-1)*(y**2-4)
constraints=s.Matrix([[a**j-b**j for j in range(4)] for a,b in [(1,2),(-1,-2)]])
null=constraints.nullspace()
check('unequal_pair_equalizer_codimension_two',constraints.rank()==2 and len(null)==2)
h=y**3-7*y
check('unequal_pair_equalizer_contains_cubic',all(h.subs(y,a)==h.subs(y,b) for a,b in [(1,2),(-1,-2)]))
check('unequal_pair_equalizer_no_quadratic',constraints[:,1:3].det()!=0)
check('unequal_pair_equalizer_breaks_residue',residue_at_infinity(h,C)==-1)
for a,b in [(1,2),(-1,-2)]:
    for j in range(6):
        check('equalizer_conductor_membership_%s_%s'%(a,j),
              (C*y**j).subs(y,a)==(C*y**j).subs(y,b)==0)
# For fB inside the equalizer, f(a)=f(b) and af(a)=bf(b), so both vanish.
for a,b in [(1,2),(-1,-2)]:
    check('equalizer_conductor_necessity_'+str(a),s.Matrix([[1,-1],[a,-b]]).det()!=0)

# Necessity of generic primitivity: the inclusion determinant vanishes.
f=y**2;g=y**4+y**2
M=s.Matrix.hstack(vector(1,2),vector(s.rem(g,f-u,y),2))
check('nonprimitive_power_basis_fails',M.det()==0)

# Nonsaturation counter-control: S=C[x,xy²,y³], generic quadratic y².
# The map Q[x,u,v]/(u³-x³v²) -> Q[x,y] has u surviving in the abstract x=0
# quotient, although its specialization as a polynomial vanishes.
check('nonsaturated_relation',zero((u**3-x**3*v**2).subs({u:x*y**2,v:y**3})))
check('nonsaturated_fiber_relation',s.expand((u**3-x**3*v**2).subs(x,0))==u**3)
check('nonsaturated_fiber_extra_kernel',s.rem(u,u**3,u)==u and (x*y**2).subs(x,0)==0)
check('nonsaturated_y_squared_missing',not any(2*i+3*j==2 and i==0 for i in range(3) for j in range(3)))

# Sharper saturated non-Keller hostile with monic P and immersed birational slices.
f=y**3;g=x*y**2+y
R=v**3-3*x*u*v-x**3*u**2-u
c=x**2*y**2+x*y+1
check('saturated_hostile_equation',zero(R.subs({u:f,v:g})))
check('saturated_hostile_conductor',zero(s.cancel(s.diff(R,v).subs({u:f,v:g})/s.diff(f,y))-c))
check('saturated_hostile_jacobian',s.diff(f,x)*s.diff(g,y)-s.diff(f,y)*s.diff(g,x)==-3*y**4)
check('saturated_hostile_all_slice_immersion_witness',zero(s.diff(g,y)-2*x*y-1))
check('saturated_hostile_injective_zero_slice',g.subs(x,0)==y)
check('saturated_hostile_generic_quadratic',zero(g/x-y**2-y/x))
# Generic conductor roots constitute one distinct collision pair.
check('saturated_hostile_pair_sum',-s.Poly(c,y).nth(1)/s.LC(s.Poly(c,y))==-1/x)
check('saturated_hostile_pair_discriminant',s.discriminant(c,y)==-3*x**2)
check('saturated_hostile_pair_cubic_collision',zero((-1/x)**2-1/x**2))
check('saturated_hostile_pair_quadratic_collision',zero(x*(-1/x)+1))
check('saturated_hostile_quadratic_coefficient_pole',s.denom(1/x)==x)
check('saturated_hostile_even_degree_drop',s.degree(c,y)==2 and c.subs(x,0)==1)
# Its specialized image has degree pairs (3,2) for x != 0 and (3,1) at zero,
# so every slice is primitive; the exact monic relation has v-degree 3.
for a in [-3,-1,0,1,2,5]:
    ga=g.subs(x,a)
    check('saturated_hostile_slice_primitive_'+str(a),s.gcd(3,int(s.degree(ga,y)))==1)
    check('saturated_hostile_slice_immersed_'+str(a),s.gcd(s.diff(f,y),s.diff(ga,y))==1)
    Ga=quotient_matrix(ga,f-u,3)
    check('saturated_hostile_specialized_characteristic_'+str(a),
          zero(Ga.charpoly(v).as_expr()-R.subs(x,a)))

# Saturation removes a coefficient gcd but does not invert a primitive leading
# coefficient. The latter is the precise additional Keller/one-line step.
a0=(x-1)*(x+2);b0=(x-1)*(x**2+1)
d=s.gcd(a0,b0)
alpha=s.cancel(a0/d);beta=s.cancel(b0/d)
check('primitive_pair_gcd',s.gcd(alpha,beta)==1)
check('primitive_pair_nonzero_specialization',alpha.subs(x,-2)==0 and beta.subs(x,-2)==5)

# Both sharp delta-three curves are genuinely immersed; identify collision types.
for name,f,g in [('triple',y**3,y**4+y),('nodes',y**3-y,y**4)]:
    check(name+'_immersed',s.gcd(s.diff(f,y),s.diff(g,y))==1)
check('triple_conductor_three_double_roots',s.gcd(y**3+1,3*y**2)==1)
check('nodes_conductor_six_simple_roots',s.gcd((y*y-1)*(y**4+1),s.diff((y*y-1)*(y**4+1),y))==1)
ss,pp=s.symbols('ss pp')
D=3*(t*t)-1
D=D*4*y**3-(3*y*y-1)*4*t**3
check('node_tangent_identity',zero(D-4*(y-t)*(3*(t*y)**2-(y*y+y*t+t*t))))
for sv in (0,s.sqrt(2),-s.sqrt(2)):
    pv=sv**2-1
    check('node_pair_nonzero_discriminant_'+str(sv),s.simplify(sv**2-4*pv)!=0)
    check('node_pair_tangent_factor_'+str(sv),s.simplify(3*pv**2-1)==2)

payload={'status':'PASS: finite exact controls, not a universal proof',
         'check_count':len(checks),'pair_count':len(examples),'checks':checks,
         'resultant_regression':{'sympy_version':s.__version__,
          'direct_library_value':str(s.resultant(guard_f,guard_g,t)),
          'sylvester_value':str(guard_det),'reduced_value':str(s.resultant(guard_f,s.rem(guard_g,guard_f,t),t))},
         'examples':examples,'low_genus_symmetric_semigroups':semigroups,
         'new_boundary':'C[x,y^3,xy^2+y] is saturated and slice-immersed, but is not Keller and has no global monic quadratic.'}
parser=argparse.ArgumentParser()
parser.add_argument('--output')
args=parser.parse_args()
text=json.dumps(payload,indent=2,sort_keys=True)+'\n'
if args.output:
    Path(args.output).write_text(text)
else:
    print(text,end='')
