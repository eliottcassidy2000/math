"""window_configs.py -- mac-mini-2026-10-27-potentials

Exact closure search for THM-4812's window (strong S, tc(S) = 21, 13 <= n <= 20 or n = 22).
By THM-4812 (b)-(d): every Aut(S)-orbit induces K1, C3, R5 or P7, and G = Aut(S) is a subgroup of
P = prod_O Aut(S[O]) with transitive projections and |G| >= f(n)/21; only tc = 21 configurations survive and the index
[P : G] is 1 or 3.  Index-3 subgroups of the odd-order group P are normal (3 is the least prime divisor), i.e. kernels
of surjections P -> Z_3; they factor through P^ab = Z_3^(p+c) x Z_5^r.

This script lists, for every surviving configuration and every admissible G (index 1, and index 3 where allowed),
the G-orbitals on ordered pairs, and writes one job file per (config, G) for the C++ counter tc_window_scan.cpp:
  line 1: n, number of free orbital pairs K, |G|
  line 2: the orbits (dot-separated vertex lists)
  line 3: the fixed arcs (within orbits, a standard labelled copy of C3 / R5 / P7)
  then K lines, each the arc list of one orbital (its inverse is the other orientation).
"""
import itertools, os, sys

def f(n):
    k, r = divmod(n, 3)
    return 3 * 5 ** (k - 1) if r == 0 else (5 ** k if r == 1 else 9 * 5 ** (k - 1))

QR7 = {1, 2, 4}

def configs():
    out = []
    for n in [12]:
        tc = 21
        for (r, p) in [(0, 0), (1, 0), (2, 0), (0, 1)]:
            for c in range(0, n // 3 + 1):
                k1 = n - 3 * c - 5 * r - 7 * p
                if k1 < 0:
                    continue
                P = 3 ** c * 5 ** r * 21 ** p
                if P * tc < f(n):
                    continue
                I = P * tc // f(n)
                out.append((n, k1, c, r, p, P, I))
    return out

def build(n, k1, c, r, p):
    """Points: orbits listed P7 (if any), R5's, C3's, then K1's.  Returns (orbits, generators of P as permutations,
    the generator 'labels' used for homomorphisms to Z_3, fixed within-orbit arcs)."""
    orbits = []
    pos = 0
    def take(m):
        nonlocal pos
        o = list(range(pos, pos + m)); pos += m; return o
    P7 = [take(7) for _ in range(p)]
    R5 = [take(5) for _ in range(r)]
    C3 = [take(3) for _ in range(c)]
    K1 = [take(1) for _ in range(k1)]
    assert pos == n
    arcs = []
    for o in P7:
        for i in range(7):
            for d in QR7:
                arcs.append((o[i], o[(i + d) % 7]))
    for o in R5:
        for i in range(5):
            for d in (1, 2):
                arcs.append((o[i], o[(i + d) % 5]))
    for o in C3:
        for i in range(3):
            arcs.append((o[i], o[(i + 1) % 3]))
    # generators: for each P7: translation t (order 7) and multiplier m (x -> 2x, order 3); R5: translation; C3: rotation
    ident = list(range(n))
    gens = []   # (perm, z3_vector_index or None)
    z3_index = 0
    z3_coords = []
    for o in P7:
        t = ident[:]
        for i in range(7): t[o[i]] = o[(i + 1) % 7]
        gens.append((t, None))
        mlt = ident[:]
        for i in range(7): mlt[o[i]] = o[(2 * i) % 7]
        gens.append((mlt, z3_index)); z3_coords.append(('P7', o)); z3_index += 1
    for o in R5:
        t = ident[:]
        for i in range(5): t[o[i]] = o[(i + 1) % 5]
        gens.append((t, None))
    for o in C3:
        t = ident[:]
        for i in range(3): t[o[i]] = o[(i + 1) % 3]
        gens.append((t, z3_index)); z3_coords.append(('C3', o)); z3_index += 1
    return dict(P7=P7, R5=R5, C3=C3, K1=K1), gens, z3_index, arcs

def compose(a, b):   # a then b
    return tuple(b[a[x]] for x in range(len(a)))

def closure(gens, n):
    ident = tuple(range(n))
    G = {ident}
    frontier = [ident]
    gens = [tuple(g) for g in gens]
    while frontier:
        new = []
        for g in frontier:
            for h in gens:
                gh = compose(g, h)
                if gh not in G:
                    G.add(gh); new.append(gh)
        frontier = new
    return G

def subgroups(gens, z3dim, n, allow3, orbits):
    """Yield (name, generating set) for P itself and, if allow3, for each kernel of a nonzero functional phi on Z_3^z3dim
    (phi up to scalar).  A kernel is generated by: all generators with phi-value 0 (the P7 translations, R5 translations,
    and Z_3-generators e_i with phi_i = 0), plus products e_i e_j^(-phi_i/phi_j) for a fixed j with phi_j != 0."""
    yield ('P', [g for g, _ in gens])
    if not allow3:
        return
    z3gens = [(g, idx) for g, idx in gens if idx is not None]
    other = [g for g, idx in gens if idx is None]
    seen = set()
    for phi in itertools.product(range(3), repeat=z3dim):
        if not any(phi):
            continue
        lead = next(x for x in phi if x)
        norm = tuple((x * pow(lead, -1, 3)) % 3 for x in phi)
        if norm in seen:
            continue
        seen.add(norm)
        j = next(i for i, x in enumerate(norm) if x)
        gj = next(g for g, idx in z3gens if idx == j)
        kgens = list(other)
        for g, idx in z3gens:
            if idx == j:
                continue
            if norm[idx] == 0:
                kgens.append(g)
            else:
                # e_idx * e_j^(-phi_idx/phi_j): exponent e with norm[idx] + e*norm[j] = 0 mod 3
                e = (-norm[idx] * pow(norm[j], -1, 3)) % 3
                h = list(g)
                for _ in range(e):
                    h = [gj[h[x]] for x in range(n)]
                kgens.append(h)
        kgens.append([gj[gj[gj[x]]] for x in range(n)])   # e_j^3 (trivial for C3, for P7 multiplier also trivial)
        yield ('ker' + ''.join(map(str, norm)), kgens)

def transitive_on_orbits(G, orbits):
    for kind in ('P7', 'R5', 'C3'):
        for o in orbits[kind]:
            imgs = {g[o[0]] for g in G}
            if imgs != set(o):
                return False
    return True

def main(outdir):
    os.makedirs(outdir, exist_ok=True)
    jobs = 0
    for (n, k1, c, r, p, Psize, I) in configs():
        orbits, gens, z3dim, arcs = build(n, k1, c, r, p)
        allow3 = I >= 3
        for name, kg in subgroups(gens, z3dim, n, allow3, orbits):
            G = closure(kg, n)
            if len(G) * 21 < f(n):
                continue
            if not transitive_on_orbits(G, orbits):
                continue
            # the standard within-orbit arcs must be G-invariant
            arcset = set(arcs)
            assert all((g[u], g[v]) in arcset for g in G for (u, v) in arcs), "within-orbit structure not invariant"
            inorb = {}
            for kind in ('P7', 'R5', 'C3', 'K1'):
                for o in orbits[kind]:
                    for v in o: inorb[v] = tuple(o)
            # orbitals on ordered pairs between different orbits
            seen = {}
            orbitals = []
            for u in range(n):
                for v in range(n):
                    if u == v or inorb[u] == inorb[v] or (u, v) in seen:
                        continue
                    orb = sorted({(g[u], g[v]) for g in G})
                    for pr in orb: seen[pr] = len(orbitals)
                    orbitals.append(orb)
            pairs = []
            used = set()
            for t, orb in enumerate(orbitals):
                if t in used: continue
                u, v = orb[0]
                ti = seen[(v, u)]
                assert ti != t
                used.add(t); used.add(ti)
                pairs.append(orb)
            fn = os.path.join(outdir, f"n{n}_K{k1}_C{c}_R{r}_P{p}_{name}.job")
            with open(fn, 'w') as fh:
                fh.write(f"{n} {len(pairs)} {len(G)}\n")
                allorbs = [o for kind in ('P7', 'R5', 'C3', 'K1') for o in orbits[kind]]
                fh.write(' '.join('.'.join(map(str, o)) for o in allorbs) + "\n")
                fh.write(' '.join(f"{u},{v}" for u, v in arcs) + "\n")
                for orb in pairs:
                    fh.write(' '.join(f"{u},{v}" for u, v in orb) + "\n")
            jobs += 1
            print(f"n={n} K1={k1} C3={c} R5={r} P7={p} |P|={Psize} G={name} |G|={len(G)} free orbital pairs={len(pairs)}")
    print("jobs:", jobs)

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "window_jobs")
