import itertools as it, json

def require(x,msg):
 if not x: raise RuntimeError(msg)
B=[(16,1,3,7,14),(20,1,2,7,14)]
def paths(a,S):
 return sum(all(a[u]>>v&1 for u,v in zip(p,p[1:])) for p in it.permutations(S))
def parts(S):
 if not S:yield [];return
 x,*rest=S
 for p in parts(rest):
  yield [(x,)]+p
  for j in range(len(p)):yield p[:j]+[(x,)+p[j]]+p[j+1:]
profile_checks=0
for a in B:
 P={j:0 for j in range(1,6)}
 for partition in parts(list(range(5))):
  z=1
  for S in partition:z*=paths(a,S)
  P[len(partition)]+=z
 require(P=={1:9,2:33,3:31,4:10,5:1},'independent partition profile')
 for u in range(0,15):
  actual=0
  for j,count in P.items():
   z=1
   for t in range(j):z*=u-t
   actual+=count*z
  require(actual==u**5+6*u**3+2*u,'slot polynomial evaluation')
  profile_checks+=1
Q=[(16,33,35,39,46,1),(20,33,34,39,46,1)]
starts=[]
for a in Q:
 row=[]
 for start in range(6):
  row.append(sum(all(a[u]>>v&1 for u,v in zip(p,p[1:])) for tail in it.permutations([x for x in range(6) if x!=start]) for p in [(start,)+tail]))
 starts.append(row)
require(starts==[[1,2,4,8,1,1],[1,2,3,7,5,1]],'starting counts brute permutations')
# All affine functions on F2^3, independently generated by parity-dot evaluation.
words=[]
for c in range(2):
 for a in range(8):words.append(tuple(c^((a&x).bit_count()%2) for x in range(8)))
require(len(set(words))==16,'distinct affine words')
require(min(sum(u!=v for u,v in zip(x,y)) for x,y in it.combinations(words,2))==4,'code distance')
decode_checks=0
for w in words:
 for s in range(4):
  for erased in it.combinations(range(8),s):
   E=set(erased);visible=[i for i in range(8) if i not in E]
   for e in range((3-s)//2+1):
    for errors in it.combinations(visible,e):
     received=tuple(w[i]^(i in errors) for i in range(8))
     candidates=[v for v in words if sum(v[i]!=received[i] for i in visible)<=e]
     require(candidates==[w],'mixed error and erasure unique decoding')
     decode_checks+=1
# Sharpness at equality 2e+s=4: pair at distance four, erase all disagreements.
x,y=next((x,y) for x,y in it.combinations(words,2) if sum(u!=v for u,v in zip(x,y))==4)
D={i for i in range(8) if x[i]!=y[i]}
require(all(x[i]==y[i] for i in range(8) if i not in D),'threshold erasure ambiguity')
print(json.dumps({'status':'PASS','independent_partition_profile_checks':2,'slot_polynomial_checks':profile_checks,'brute_force_start_rows':starts,'mixed_error_erasure_decoding_checks':decode_checks,'equality_threshold_ambiguity':True},sort_keys=True,indent=2))
