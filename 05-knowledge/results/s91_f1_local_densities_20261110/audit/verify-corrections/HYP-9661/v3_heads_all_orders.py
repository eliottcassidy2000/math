#!/usr/bin/env python3
"""Verifier check for HYP-9661 (C): the heads of 11, 13, 47, 67 at EVERY order of the base.

Claim checked. Let (B, y) be a rooted tournament, y not a sink of B, and T = B + z (z -> y, every other vertex
of B -> z). Let R be the set of vertices of B reachable from y (y included), S = T[R + z], B' = B - R. Then
B' => S, S is strong of order >= 3, H(T) = H(B') H(S) and D = H(B) = H(B') H(S - z).
Consequence: if N = H(T) is prime then H(B') = 1 and H(S) = N, so S is a strong tournament with N paths (order
<= 8 for N <= 73, since f(9) = 75), and (S - z, y) is a rooted tournament with the same head N and the same D.

(1) the decomposition, on every rooted labelled tournament of order <= 5 with a root that is not a sink
    (own subset DP; no session code imported);
(2) every strong class S of order <= 8 with H(S) in {11, 13, 47, 67} (class representatives read from the
    committed reps_le8.npz, own decoder) and every vertex z of out-degree 1 in S: D = H(S - z) > N/3;
(3) a tail value is a head: H((B + s) + z) = D + 2 U_B(y) for a sink s appended to B (orders <= 4, literal U);
(4) if rooted_le9.npz is present (regenerated by census.py, not committed): the heads of 11, 13, 47, 67 at
    non-sink roots in the census of order <= 9 have exactly the D found in (2).
"""
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", "..", "..", ".."))
REPS = os.path.join(ROOT, "04-computation", "experiments", "s91_f1_local_densities_20261110", "rooted_spectrum",
                    "reps_le8.npz")
FAILS = []


def check(name, cond, detail=""):
    print(("PASS " if cond else "FAIL ") + name + (" : " + detail if detail else ""))
    if not cond:
        FAILS.append(name)


def decode(code, n):
    """out-masks; for i < j the bit j(j-1)/2 + i of the code is 1 iff i -> j"""
    out = [0] * n
    for j in range(1, n):
        base = j * (j - 1) // 2
        for i in range(j):
            if (code >> (base + i)) & 1:
                out[i] |= 1 << j
            else:
                out[j] |= 1 << i
    return out


def ham(out, verts):
    """number of Hamiltonian paths of the subtournament on the vertex list verts (1 for the empty list)"""
    k = len(verts)
    if k == 0:
        return 1
    idx = {v: i for i, v in enumerate(verts)}
    o = [sum(1 << idx[w] for w in verts if (out[v] >> w) & 1) for v in verts]
    f = [[0] * k for _ in range(1 << k)]
    for i in range(k):
        f[1 << i][i] = 1
    for mask in range(1, 1 << k):
        row = f[mask]
        for i in range(k):
            c = row[i]
            if c:
                nxt = o[i] & ~mask
                while nxt:
                    b = nxt & -nxt
                    f[mask | b][b.bit_length() - 1] += c
                    nxt ^= b
    return sum(f[(1 << k) - 1])


def reach(out, n, y):
    seen = 1 << y
    stack = [y]
    while stack:
        v = stack.pop()
        new = out[v] & ~seen & ((1 << n) - 1)
        while new:
            b = new & -new
            seen |= b
            stack.append(b.bit_length() - 1)
            new ^= b
    return seen


def is_strong(out, verts):
    if len(verts) == 1:
        return True
    full = sum(1 << v for v in verts)
    for v in verts:
        seen = 1 << v
        stack = [v]
        while stack:
            u = stack.pop()
            new = out[u] & full & ~seen
            while new:
                b = new & -new
                seen |= b
                stack.append(b.bit_length() - 1)
                new ^= b
        if seen != full:
            return False
    return True


# ---------------------------------------------------------------- (1) decomposition, orders <= 5
n_cases = 0
ok_dec = ok_strong = ok_join = True
for n in range(2, 6):
    npairs = n * (n - 1) // 2
    for code in range(1 << npairs):
        out = decode(code, n)
        D = ham(out, list(range(n)))
        for y in range(n):
            if out[y] == 0:
                continue                      # y is a sink of B
            # T = B + z, z = vertex n: z -> y, every other vertex -> z
            outT = out[:] + [1 << y]
            for v in range(n):
                if v != y:
                    outT[v] |= 1 << n
            R = reach(out, n, y)
            Rl = [v for v in range(n) if (R >> v) & 1]
            Bp = [v for v in range(n) if not (R >> v) & 1]
            S = Rl + [n]
            ok_join &= all((outT[w] >> v) & 1 for w in Bp for v in S)
            ok_strong &= is_strong(outT, S) and len(S) >= 3
            hT = ham(outT, list(range(n + 1)))
            ok_dec &= (hT == ham(out, Bp) * ham(outT, S)) and (D == ham(out, Bp) * ham(out, Rl))
            n_cases += 1
check("B' => S, S strong of order >= 3 [%d rooted labelled tournaments of order <= 5]" % n_cases, ok_join and ok_strong)
check("H(B + z) = H(B') H(S) and D = H(B') H(S - z)", ok_dec)

# ---------------------------------------------------------------- (2) strong classes with 11, 13, 47, 67 paths
TARGETS = (11, 13, 47, 67)
z = np.load(REPS)
found = {N: [] for N in TARGETS}
n_strong = {}
least = {}
for n in range(3, 9):
    cnt = 0
    for code in z["n%d" % n]:
        out = decode(int(code), n)
        verts = list(range(n))
        if not is_strong(out, verts):
            continue
        cnt += 1
        h = ham(out, verts)
        least[n] = min(least.get(n, h), h)
        if h in found:
            for zz in range(n):
                if bin(out[zz]).count("1") == 1:
                    y = out[zz].bit_length() - 1
                    rest = [v for v in verts if v != zz]
                    D = ham(out, rest)
                    # the base S - z with root y: y is not a sink of it, and all others beat z by out-degree 1
                    found[h].append((n, D))
    n_strong[n] = cnt
check("strong classes of orders 3..8: 1, 1, 6, 35, 353, 6008", [n_strong[n] for n in range(3, 9)] == [1, 1, 6, 35, 353, 6008],
      str(n_strong))
check("least H of a strong tournament of orders 3..8: 3, 5, 9, 15, 25, 45", [least[n] for n in range(3, 9)] == [3, 5, 9, 15, 25, 45])
for N in TARGETS:
    Ds = sorted(set(found[N]))
    print("     N = %d: (order of S, D = H(S - z)) over the vertices z of out-degree 1: %s" % (N, Ds))
    check("N = %d: every head at a non-sink root has D > N/3" % N, len(Ds) > 0 and all(3 * D > N for _, D in Ds))
check("the heads quoted in (C) occur: (5, 11), (5, 13), (17, 47), (33, 67)",
      all(any(D == d for _, D in found[N]) for N, d in ((11, 5), (13, 5), (47, 17), (67, 33))))

# ---------------------------------------------------------------- (3) a tail value is a head (one sink appended)
def slope_parts(out, n, y):
    """(U_even, U_odd): sum over directed paths R of B starting at y of H(B - V(R)), by parity of |V(R)|"""
    full = (1 << n) - 1
    tot = [0, 0]

    def rec(v, used, k):
        tot[k % 2] += ham(out, [w for w in range(n) if not (used >> w) & 1])
        nxt = out[v] & full & ~used
        while nxt:
            b = nxt & -nxt
            rec(b.bit_length() - 1, used | b, k + 1)
            nxt ^= b

    rec(y, 1 << y, 1)
    return tot[0], tot[1]


n_cases = 0
ok_head = ok_tail = ok_sink = True
for n in range(1, 5):
    npairs = n * (n - 1) // 2
    for code in range(1 << npairs):
        out = decode(code, n)
        D = ham(out, list(range(n)))
        for y in range(n):
            Ue, Uo = slope_parts(out, n, y)
            # head: B + z
            outT = out[:] + [1 << y]
            for v in range(n):
                if v != y:
                    outT[v] |= 1 << n
            ok_head &= ham(outT, list(range(n + 1))) == D + 2 * Ue
            # base with one sink s = vertex n appended, then the apex z = vertex n + 1 over y
            outS = [o | (1 << n) for o in out] + [0]
            Ue2, Uo2 = slope_parts(outS, n + 1, y)
            ok_sink &= (ham(outS, list(range(n + 1))) == D) and (Ue2 == Ue + Uo) and (Ue2 + Uo2 == 2 * (Ue + Uo))
            outZ = outS[:] + [1 << y]
            for v in range(n + 1):
                if v != y:
                    outZ[v] |= 1 << (n + 1)
            ok_tail &= ham(outZ, list(range(n + 2))) == D + 2 * (Ue + Uo)
            n_cases += 1
check("head law H(B + z) = D + 2 U_even [%d rooted labelled tournaments of order <= 4]" % n_cases, ok_head)
check("one appended sink: D unchanged, U doubles, U_even(B + s) = U(B)", ok_sink)
check("the tail value D + 2U of (B, y) is the head of (B + s, y): tails are heads with D <= N/3", ok_tail)

# ---------------------------------------------------------------- (4) the same D in the rooted census of order <= 9
# rooted_le9.npz is regenerated by census.py (not committed); rows (H(B), s, E, Yplus, U, d, strong, outdeg of root).
CENSUS = os.path.join(os.path.dirname(REPS), "rooted_le9.npz")
if os.path.exists(CENSUS):
    zc = np.load(CENSUS)
    expect = {11: [5], 13: [5], 47: [17, 23], 67: [29, 31, 33]}
    ok_c = True
    for N in TARGETS:
        Ds = set()
        orders = set()
        for mm in range(1, 10):
            rows = zc["m%d" % mm]
            x, e, ym = rows[:, 0], rows[:, 2], rows[:, 4]
            sel = ((x - e + ym) == N) & (e < x)
            if sel.any():
                orders.add(mm)
                Ds.update(int(d) for d in np.unique(x[sel]))
        print("     census, N = %d: D of the heads at a root that is not a sink: %s (base orders %d..%d)"
              % (N, sorted(Ds), min(orders), max(orders)))
        ok_c &= sorted(Ds) == expect[N]
    check("census of order <= 9: the heads of 11, 13, 47, 67 at non-sink roots have exactly the D of (2)", ok_c)
    rows = np.concatenate([zc["m%d" % mm] for mm in range(1, 10)], axis=0)
    x, e, ym = rows[:, 0], rows[:, 2], rows[:, 4]
    v = np.unique((x - e + ym)[((ym - e) >= 2 * x) & (e < x)])
    miss = np.setdiff1d(np.arange(1, 9153, 2), v[v < 9153]).tolist()
    check("census of order <= 9: heads with D <= N/3 at non-sink roots miss exactly 1, 7, 11, 13, 21, 47, 67 below 9153",
          miss == [1, 7, 11, 13, 21, 47, 67], str(miss))
else:
    print("     (4) skipped: rooted_le9.npz not present (regenerate it with census.py)")

print()
if FAILS:
    print("FAILED:", FAILS)
    sys.exit(1)
print("ALL VERIFIER CHECKS PASSED")
