#!/usr/bin/env python3
"""Independent full-type and sign audit, with no import of the census code.

All fixed objects are generated directly from permutations supplied in the
certificate. Isomorphism uses a separate constrained adjacency search. Full
automorphism groups are generated by a point-stabilizer chain, never by a twin
quotient. Thus even the empty graph is checked without listing n! elements.
"""
from collections import defaultdict
from itertools import combinations
from math import prod
from pathlib import Path
import json

CHECKS = 0

def require(ok, message):
    global CHECKS
    CHECKS += 1
    if not ok:
        raise RuntimeError(message)

def generated_group(generators, n):
    group = {tuple(range(n))}
    pending = list(group)
    while pending:
        p = pending.pop()
        for g in generators:
            q = tuple(g[p[i]] for i in range(n))
            if q not in group:
                group.add(q)
                pending.append(q)
    return group

def fixed_matrices(group, n, tournament):
    unseen = set(combinations(range(n), 2))
    orbits = []
    while unseen:
        u, v = min(unseen)
        directed = {(g[u], g[v]) for g in group}
        undirected = {tuple(sorted(e)) for e in directed}
        require(len(directed) == len(undirected), 'pair reversal in odd group')
        orbits.append(directed)
        unseen -= undirected
    for bits in range(1 << len(orbits)):
        A = [[0] * n for _ in range(n)]
        for k, orbit in enumerate(orbits):
            bit = (bits >> k) & 1
            for u, v in orbit:
                if tournament:
                    A[u][v], A[v][u] = bit, 1 - bit
                elif bit:
                    A[u][v] = A[v][u] = 1
        yield tuple(map(tuple, A))

def vertex_colors(A):
    n = len(A)
    degrees = [(sum(A[i]), sum(A[j][i] for j in range(n))) for i in range(n)]
    return [
        (degrees[i], tuple(sorted((A[i][j], A[j][i], degrees[j])
                                 for j in range(n) if i != j)))
        for i in range(n)
    ]

def fingerprint(A):
    return tuple(sorted(vertex_colors(A)))

def transporter(A, B, forced=None):
    n = len(A)
    ac, bc = vertex_colors(A), vertex_colors(B)
    if sorted(ac) != sorted(bc):
        return None
    f = dict(forced or {})
    if len(set(f.values())) != len(f):
        return None
    if any(ac[i] != bc[j] for i, j in f.items()):
        return None
    if any(A[i][k] != B[j][v] for i, j in f.items() for k, v in f.items()):
        return None
    used = set(f.values())

    def extend():
        if len(f) == n:
            return tuple(f[i] for i in range(n))
        candidates = []
        for i in range(n):
            if i in f:
                continue
            possible = [j for j in range(n) if j not in used and ac[i] == bc[j]
                        and all((A[i][u], A[u][i]) == (B[j][v], B[v][j])
                                for u, v in f.items())]
            if not possible:
                return None
            candidates.append((len(possible), i, possible))
        _, i, possible = min(candidates)
        for j in possible:
            f[i] = j
            used.add(j)
            answer = extend()
            if answer is not None:
                return answer
            used.remove(j)
            del f[i]
        return None
    return extend()

def full_types(matrices):
    buckets = defaultdict(list)
    for A in matrices:
        bucket = buckets[fingerprint(A)]
        if not any(transporter(A, B) is not None for B in bucket):
            bucket.append(A)
    return [A for bucket in buckets.values() for A in bucket]

def automorphism_audit(A):
    n = len(A)
    orbit_sizes, generators = [], []
    for i in range(n):
        fixed = {j: j for j in range(i)}
        orbit = 0
        for j in range(i, n):
            p = transporter(A, A, fixed | {i: j})
            if p is None:
                continue
            orbit += 1
            require(all(A[u][v] == A[p[u]][p[v]]
                        for u in range(n) for v in range(n)), 'invalid automorphism')
            generators.append(p)
        require(orbit > 0, 'identity absent from stabilizer orbit')
        orbit_sizes.append(orbit)
    signs = [(-1) ** sum(A[u][v] for u, v in combinations(range(n), 2)
                         if p[u] > p[v]) for p in generators]
    return prod(orbit_sizes), all(s == 1 for s in signs), len(generators)

def main():
    root = Path(__file__).parent
    source = json.loads((root / 'census.json').read_text())
    replay = json.loads((root / 'independent_replay.json').read_text())
    refs = {(r['n'], r['class']): r for r in replay['rows']}
    rows = []
    for row in source['rows']:
        n = row['n']
        H = generated_group(row['generators'], n)
        require(len(H) == row['order'], 'group order')
        tournaments = full_types(fixed_matrices(H, n, True))
        graphs = full_types(fixed_matrices(H, n, False))
        auts = [automorphism_audit(A) for A in graphs]
        even = sum(e for _, e, _ in auts)
        require(len(tournaments) == row['tau_T'], 'full tournament count')
        require(even == row['tau_E'], 'full sign-even graph count')
        require(len(graphs) == refs[n, row['class']]['direct_full_graph_types'],
                'all full graph types count')
        rows.append(dict(n=n, group=row['class'], tournament_types=len(tournaments),
                         graph_types=len(graphs), sign_even_graph_types=even,
                         stabilizer_chain_generators_tested=sum(g for _, _, g in auts),
                         largest_full_graph_automorphism_order=max(o for o, _, _ in auts)))
    print(json.dumps(dict(status='PASS', checks=CHECKS,
                          scope='All fixed graph and tournament types in the ten census rows; independent isomorphism and complete automorphism-generator sign test.',
                          rows=rows), indent=2, sort_keys=True))

if __name__ == '__main__':
    main()
