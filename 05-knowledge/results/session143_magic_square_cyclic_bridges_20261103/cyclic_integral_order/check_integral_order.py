def det(a):
    n=len(a)
    total=0
    for p in permutations(range(n)):
        term=(-1)**sum(p[i]>p[j] for i in range(n) for j in range(i+1,n))
        for i in range(n): term*=a[i][p[i]]
        total+=term
    return total

def transpose(a): return list(map(list,zip(*a)))
def mm(a,b): return [[sum(x*y for x,y in zip(row,col)) for col in zip(*b)] for row in a]
def mv(a,v): return [sum(x*y for x,y in zip(row,v)) for row in a]
def dot(a,b): return sum(x*y for x,y in zip(a,b))
def conv(a,b): return [sum(a[i]*b[(k-i)%5] for i in range(5)) for k in range(5)]
def powers(a,n,mul=conv,one=None):
    out=[one or [1,0,0,0,0]]
    for _ in range(n):out.append(mul(out[-1],a))
    return out

def lin(coeff,cols): return [sum(c*v[i] for c,v in zip(coeff,cols)) for i in range(len(cols[0]))]
def evalpoly(coeff,x):
    result=0
    for c in reversed(coeff):result=result*x+c
    return result

def polynomial_mul(a,b):
    out=[0]*(len(a)+len(b)-1)
    for i,x in enumerate(a):
        for j,y in enumerate(b):out[i+j]+=x*y
    return out

def reduce_poly(a,modulus):
    a=list(a)
    while len(a)>=len(modulus):
        lead=a[-1]; offset=len(a)-len(modulus)
        for j,c in enumerate(modulus):a[offset+j]-=lead*c
        a.pop()
    return a+[0]*(len(modulus)-1-len(a))

def cyclomul(a,b):return reduce_poly(polynomial_mul(a,b),[1,1,1,1,1])

def rank_mod(a,p):
    a=[[x%p for x in row] for row in a];rank=0
    for col in range(len(a[0])):
        row=next((r for r in range(rank,len(a)) if a[r][col]),None)
        if row is None:continue
        a[rank],a[row]=a[row],a[rank]
        inv=pow(a[rank][col],-1,p);a[rank]=[x*inv%p for x in a[rank]]
        for r in range(len(a)):
            if r!=rank:
                c=a[r][col];a[r]=[(x-c*y)%p for x,y in zip(a[r],a[rank])]
        rank+=1
    return rank

