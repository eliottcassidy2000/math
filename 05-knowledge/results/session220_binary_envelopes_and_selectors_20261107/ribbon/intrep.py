#!/usr/bin/env python3
"""intrep.py -- the observable integer quotient of the span-w ribbon transfer system.
Phi = the Z-module generated by the functionals phi.M_v (phi = final functional, v any word); it is a
sublattice of Z^d, invariant under right multiplication by every letter, of rank equal to the minimal
dimension over Q.  With an echelon Z-basis Psi (r x d), the reduced state y = Psi.x in Z^r determines
H(xv) for every suffix v, and y evolves by integer matrices A_a with Psi.M_a = A_a.Psi.
The module is generated by phi.M_v for |v| <= k once it stabilises and is letter-invariant (checked).
Writes span{w}_intrep.txt.  Usage: intrep.py w"""
import sys, itertools, random
from ribbon import transfer_system, letters, count_with_matrices

def echelon(gens, d):
    """integer echelon basis (rows with distinct, increasing pivot columns, positive pivots) of the
    Z-module generated by gens (lists of ints of length d)."""
    rows = [list(g) for g in gens if any(g)]
    basis = []
    col = 0
    while rows and col < d:
        # bring all rows with nonzero entry in column col to a single pivot by Euclid
        nz = [r for r in rows if r[col] != 0]
        rest = [r for r in rows if r[col] == 0]
        if not nz:
            col += 1; continue
        while len(nz) > 1:
            nz.sort(key=lambda r: abs(r[col]))
            p = nz[0]
            new = [p]
            for r in nz[1:]:
                q = r[col] // p[col]
                r2 = [x - q * y for x, y in zip(r, p)]
                if r2[col] != 0:
                    new.append(r2)
                elif any(r2):
                    rest.append(r2)
            nz = new
        p = nz[0]
        if p[col] < 0: p = [-x for x in p]
        basis.append(p)
        rows = rest
        col += 1
    return basis

def in_module_coeffs(basis, v):
    """coefficients of v in the echelon basis, or None if v is not in the module."""
    v = list(v); coeffs = []
    for row in basis:
        p = next(c for c, x in enumerate(row) if x != 0)
        q, rem = divmod(v[p], row[p])
        if rem != 0:
            return None
        coeffs.append(q)
        v = [x - q * y for x, y in zip(v, row)]
    if any(v):
        return None
    return coeffs

def vecmat(f, M, d):
    out = [0] * d
    for (j, i), m in M.items():
        if f[j]:
            out[i] += m * f[j]
    return out

def build(w, verbose=True):
    order, states, mats, final = transfer_system(w)
    d = len(order); L = letters(w)
    phi = [0] * d
    for j in final: phi[j] = 1
    gens = [phi]
    frontier = [phi]
    k = 0
    basis = echelon(gens, d)
    while True:
        k += 1
        frontier = [vecmat(f, mats[a], d) for f in frontier for a in L]
        gens = gens + frontier
        newbasis = echelon(gens, d)
        if verbose: print(f"  generator depth {k} (suffix functionals of length <= {k + 1} from the second round on): module rank {len(newbasis)}, generators {len(gens)}", flush=True)
        # invariance test: every basis row times every letter lies in the module
        invariant = all(in_module_coeffs(newbasis, vecmat(f, mats[a], d)) is not None for f in newbasis for a in L)
        same = (newbasis == basis)
        basis = newbasis
        # reduce generators to the basis to keep the list short
        gens = list(basis); frontier = [vecmat(f, mats[a], d) for f in basis for a in L]
        if invariant and same:
            break
        if k > 40:
            raise RuntimeError("module did not stabilise")
    r = len(basis)
    A = {a: [in_module_coeffs(basis, vecmat(f, mats[a], d)) for f in basis] for a in L}
    y0 = [f[0] for f in basis]
    hcoef = in_module_coeffs(basis, phi)
    return basis, A, y0, hcoef, order, states, mats, final

if __name__ == "__main__":
    w = int(sys.argv[1]) if len(sys.argv) > 1 else 2
    L = letters(w)
    basis, A, y0, hcoef, order, states, mats, final = build(w)
    r = len(basis); d = len(order)
    print(f"span {w}: profile states {d}, observable integer quotient of rank {r}")
    rng = random.Random(5)
    for t in range(500):
        n = rng.randint(1, 11)
        word = [rng.choice(L) for _ in range(n)]
        y = y0[:]
        for a in word:
            y = [sum(A[a][k][l] * y[l] for l in range(r)) for k in range(r)]
        H1 = sum(c * yk for c, yk in zip(hcoef, y))
        H2 = count_with_matrices(w, word, (order, states, mats, final))
        assert H1 == H2, (word, H1, H2)
    print("  reduced integer representation verified on 500 random words (n <= 11)")
    with open(f"span{w}_intrep.txt", "w") as f:
        f.write(f"{r} {len(L)}\n")
        f.write(" ".join(map(str, y0)) + "\n")
        f.write(" ".join(map(str, hcoef)) + "\n")
        for a in L:
            mask = sum(1 << (s - 1) for s in a)
            f.write(f"{mask}\n")
            for k in range(r):
                f.write(" ".join(map(str, A[a][k])) + "\n")
    print(f"  written span{w}_intrep.txt; largest |entry| {max(abs(x) for a in L for row in A[a] for x in row)}; y0 = {y0}; hcoef = {hcoef}")
