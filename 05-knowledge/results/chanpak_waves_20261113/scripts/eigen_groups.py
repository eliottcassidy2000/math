#!/usr/bin/env python3
"""Wave 23: eigenvalue groups of the triangularizable transfer systems (composition-factor characters).
For a simultaneously triangularizable family the eigenvalues of a word are products of the letters' diagonal
entries, so the multiplicative group generated by the letters' nonzero eigenvalues is the S-unit group of the
numeration.  Also prints, for the root-change blocks, the eigenvalue fields."""
import sympy as sp
import itertools
from rank_ladder import O4, Z4, J4, onehub_letters, twohub_letters, matmul

x = sp.symbols('x')
def eig(M):
    f = sp.Matrix(M).charpoly(x).as_expr()
    return sp.factor(f), sp.roots(sp.Poly(f, x))

fams = {'one-apex O/Z': {'O': O4, 'Z': Z4},
        'one-hub': {f'x={i}': M for i, M in enumerate(onehub_letters())},
        'two-hub': {f'(x,y)={a}{b}': M for (a, b), M in zip(itertools.product((0, 1), repeat=2), twohub_letters())},
        'root-change O/Z/J': {'O': O4, 'Z': Z4, 'J': J4}}
for name, letters in fams.items():
    print(f"== {name}")
    nz = set()
    for lab, M in letters.items():
        f, r = eig(M)
        print(f"   {lab:9s} charpoly = {f}")
        for root, mult in r.items():
            if root != 0:
                nz.add(root)
    print("   nonzero eigenvalues of letters:", sorted(nz, key=lambda t: complex(t).real))
# a word check for two-hub: eigenvalues of products are products of diagonal entries
L = twohub_letters()
W = matmul(matmul(L[0], L[3]), matmul(L[1], L[2]))
print("two-hub word (00)(11)(01)(10):", eig(W)[0])
