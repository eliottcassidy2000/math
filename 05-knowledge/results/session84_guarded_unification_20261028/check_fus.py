#!/usr/bin/env python3
"""Session84 F=U+S: independent exact divisor controls, no dependencies."""
from functools import lru_cache
from itertools import combinations
from math import gcd, isqrt, prod
import json

checks = 0

def require(condition, message):
    global checks
    checks += 1
    if not condition:
        raise RuntimeError(message)

@lru_cache(None)
def factors(n):
    if type(n) is not int or n < 1:
        raise ValueError('positive integer required')
    out = []
    p = 2
    while p*p <= n:
        if n % p == 0:
            a = 0
            while n % p == 0:
                n //= p
                a += 1
            out.append((p, a))
        p += 1
    if n > 1:
        out.append((n, 1))
    return tuple(out)

def observation(n):
    if type(n) is not int or n < 2:
        raise ValueError('FUS convention requires integer N>=2')
    fa = factors(n)
    r = len(fa)
    tau = prod(a+1 for _, a in fa)
    squarefree = all(a == 1 for _, a in fa)
    prime = r == 1 and fa[0][1] == 1
    F, U, S = tau-2, r-int(prime), 2**r-1-int(squarefree)
    sigma = prod(sum(p**j for j in range(a+1)) for p, a in fa)
    return dict(n=n, F=F, U=U, S=S, defect=F-U-S, tau=tau,
                sigma=sigma, prime=prime, squarefree=squarefree,
                factors=[list(z) for z in fa])

def is_square(n):
    return n >= 0 and isqrt(n)**2 == n

def sf(n):
    return prod(p for p, a in factors(n) if a % 2)

def promotion(n, p):
    observation(n)
    if type(p) is not int or factors(p) != ((p, 1),):
        raise ValueError('marked p must be prime')
    if dict(factors(n)).get(p) != 1:
        raise ValueError('marked prime must have exponent exactly one')
    return observation(n*p)

N = 10000
# Independent path: direct divisor addition, not the geometric-product formula.
divisors = [[] for _ in range(N+1)]
for d in range(1, N+1):
    for n in range(d, N+1, d):
        divisors[n].append(d)
prime_flags = [len(ds) == 2 for ds in divisors]
squarefree_flags = [True]*(N+1)
for p in range(2, isqrt(N)+1):
    if prime_flags[p]:
        for n in range(p*p, N+1, p*p):
            squarefree_flags[n] = False
rows = {}
for n in range(2, N+1):
    row = observation(n)
    ds = divisors[n][1:-1]
    direct = (len(ds), sum(prime_flags[d] for d in ds),
              sum(squarefree_flags[d] for d in ds), sum(divisors[n]))
    require(direct == (row['F'], row['U'], row['S'], row['sigma']),
            f'direct/formula mismatch {n}')
    profile = sorted(a for _, a in factors(n))
    require((row['defect'] == 0) == (profile in ([1], [3], [1, 1, 2])),
            f'balance classification {n}')
    rows[n] = row

existing_updates = 0
fresh_updates = 0
primes = [p for p in range(2, 48) if prime_flags[p]]
for n, row in rows.items():
    for p, a in factors(n):
        new = observation(p*n)
        increment = row['tau']//(a+1)-int(row['squarefree'])-int(row['prime'])
        require(new['defect']-row['defect'] == increment, f'exponent law {n},{p}')
        existing_updates += 1
    if n <= 500:
        for p in primes:
            if n % p:
                new = observation(p*n)
                rhs = 2*row['defect']+row['U']-int(row['squarefree'])-int(row['prime'])
                require(new['defect'] == rhs, f'fresh prime law {n},{p}')
                fresh_updates += 1

monotonic_pairs = 0
flat_pairs = []
for a, row in rows.items():
    if row['squarefree']:
        continue
    for b in range(2*a, N+1, a):
        require(rows[b]['defect'] >= row['defect'], f'monotonicity {a},{b}')
        expected_flat = (len(factors(a)) == 1 and factors(a)[0][1] == 2
                         and prime_flags[b//a] and gcd(a, b//a) == 1)
        require((rows[b]['defect'] == row['defect']) == expected_flat,
                f'flat boundary {a},{b}')
        if expected_flat:
            flat_pairs.append([a, b])
        if row['defect'] == 0:
            require(rows[b]['defect'] > 0, f'balanced antichain {a},{b}')
        monotonic_pairs += 1

# The strict-positive region is generated by four minimal divisibility profiles.
minimal_positive = []
positive_profiles = ((4,), (1, 3), (2, 2), (1, 1, 1, 2))
for n, row in rows.items():
    profile = tuple(sorted(a for _, a in factors(n)))
    exps = [a for _, a in factors(n)]
    contains_generator = (max(exps) >= 4
        or (max(exps) >= 3 and len(exps) >= 2)
        or sum(a >= 2 for a in exps) >= 2
        or (max(exps) >= 2 and len(exps) >= 4))
    require((row['defect'] > 0) == contains_generator, f'positive ideal {n}')
    direct_minimal = row['defect'] > 0 and not any(
        rows[d]['defect'] > 0 for d in divisors[n][1:-1])
    require(direct_minimal == (profile in positive_profiles), f'minimal positive {n}')
    if direct_minimal:
        minimal_positive.append(n)
require([rows[n]['defect'] for n in (4,12,24)] == [-1,-1,1], 'balance can be skipped')

square_promotions = []
for n, row in rows.items():
    if not is_square(row['sigma']):
        continue
    for p, a in factors(n):
        if a != 1:
            continue
        new = promotion(n, p)
        numerator, denominator = p*p+p+1, p+1
        require(gcd(numerator, denominator) == 1, f'coprime ratio {p}')
        require(p*p < numerator < (p+1)**2, f'between squares {p}')
        require(new['sigma']*denominator == row['sigma']*numerator,
                f'promotion ratio {n},{p}')
        require(not is_square(new['sigma']), f'square promotion hostile {n},{p}')
        square_promotions.append([n, p, new['n'], new['sigma']])

# Stronger theorem explicitly imports the inherited Ljunggren classification.
# Here we verify bounded prime steps and exact graph formulas independently.
def total_sigma(n):
    return prod(sum(p**j for j in range(a+1)) for p, a in factors(n))

def square_sigma_component(n):
    if not is_square(total_sigma(n)):
        raise ValueError('component source must have square sigma')
    a = dict(factors(n)).get(3, 0)
    if a == 0:
        return (n, 3*n)
    if a == 1:
        return (n//3, n)
    return (n,)

prime_step_tests = 0
square_sources = [1]+[n for n,r in rows.items() if is_square(r['sigma'])]
for n in square_sources:
    for p in sorted(set(primes) | {p for p,_ in factors(n)}):
        preserves = is_square(total_sigma(p*n))
        require(preserves == (p == 3 and n % 3 != 0), f'full prime step {n},{p}')
        prime_step_tests += 1
    component = square_sigma_component(n)
    for m in component:
        require(is_square(total_sigma(m)), f'component leaves vertex set {n},{m}')
        require(square_sigma_component(m) == component, f'component inverse {n},{m}')
    if len(component) == 2:
        lo, hi = component
        require(hi == 3*lo and lo % 3 != 0, f'component edge {component}')
    else:
        require(dict(factors(n)).get(3, 0) >= 2, f'isolated valuation {n}')
require(square_sigma_component(1) == (1,3), 'unit boundary component')
require(square_sigma_component(3) == (1,3), 'three boundary component')
require(tuple(x for x in square_sigma_component(3) if x > 1) == (3,), 'delete unit')
require(square_sigma_component(81) == (81,), '81 isolated')
require(square_sigma_component(343) == (343,1029), '343 component')
require(square_sigma_component(364) == (364,1092), '364 component')
require(total_sigma(1029) == 40**2 and total_sigma(1092) == 56**2, 'pair totals')

# The whole exponent-1-or-2 cube on the exact support {2,3,11}.
cube = []
for k in range(4):
    for selected in combinations((2,3,11), k):
        n = 66*prod(selected)
        row = observation(n)
        row['promoted_primes'] = list(selected)
        row['sigma_squarefree_kernel'] = sf(row['sigma'])
        require(is_square(row['sigma']) == (not selected), f'66 cube {n}')
        require((row['defect'] == 0) == (len(selected) == 1), f'66 balance cube {n}')
        cube.append(row)

balanced_square = [r for r in rows.values() if r['defect'] == 0 and is_square(r['sigma'])]
mixed = [r for r in balanced_square if len(r['factors']) == 3]
require(mixed[0]['n'] == 364, 'least mixed balanced square-sigma source')
require(observation(364)['sigma'] == 28**2, '364 positive control')
require(observation(820)['sigma'] == 42**2, '820 positive control')
require(observation(81)['defect'] == 1 and observation(81)['sigma'] == 11**2,
        '81 square sigma but not balanced')
require(observation(66)['defect'] == -3, '66 not balanced')
require(observation(60)['defect'] == 0 and not is_square(observation(60)['sigma']),
        '60 balanced but square-sigma false')
require((observation(12)['F'], observation(12)['U'], observation(12)['S']) ==
        (observation(18)['F'], observation(18)['U'], observation(18)['S']), 'count collision')
require(observation(24)['F'] != observation(36)['F'], 'marked operation loss')

rejected = 0
for n, p in [(1,2), (12,2), (12,4), (66,True), (66,5)]:
    try:
        promotion(n,p)
    except ValueError:
        rejected += 1
    else:
        raise RuntimeError(f'invalid promotion accepted {n},{p}')
require(rejected == 5, 'domain hostiles')

out = dict(status='PASS', source_bound=N, checks=checks,
           exact_integer_only=True, independent_divisor_observations=N-1,
           existing_prime_updates=existing_updates, fresh_prime_updates=fresh_updates,
           nonsquarefree_divisibility_pairs=monotonic_pairs,
           minimal_positive_defect_sources=minimal_positive,
           exceptional_flat_pairs_count=len(flat_pairs), exceptional_flat_pair_samples=flat_pairs[:8],
           square_source_promotions=len(square_promotions), rejected_domain_hostiles=rejected,
           full_prime_step_tests=prime_step_tests, square_component_sources=len(square_sources),
           prime_step_scope="square-sigma sources N<=10000; primes p<=47 and every prime divisor of N",
           graph_examples={str(n):list(square_sigma_component(n)) for n in (1,3,81,343,364)},
           support_2_3_11_cube=cube,
           balanced_square_sigma_sources=balanced_square,
           smallest_mixed_balanced_square_sigma=364,
           scope='Proofs and inherited theorem dependencies are stated in the companion note; finite checks are not universal proofs.')
print(json.dumps(out, indent=2, sort_keys=True))
