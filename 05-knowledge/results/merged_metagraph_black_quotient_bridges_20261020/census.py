#!/usr/bin/env python3
"""Independent HP-orbit census of the converse-merged antipodal metagraph.

No inherited tournament classifier. Every unlabelled tournament is encountered
among fixed-Hamiltonian-path tilings (Redei), and its entire tiling fibre is
generated by enumerating its directed Hamiltonian paths.

Uses explorer bit order: (x,y), y increasing, x decreasing; bit zero means
the arc follows the displayed n -> ... -> 1 base path.
"""
from collections import Counter, defaultdict
from itertools import permutations
from pathlib import Path
import argparse
import json
import math
import sys
import time


def schema(n):
    tiles = [(x, y) for y in range(1, n - 1) for x in range(n, y + 1, -1)]
    ix = {a: i for i, a in enumerate(tiles)}
    sigma = [ix[n + 1 - y, n + 1 - x] for x, y in tiles]
    return tiles, sigma


def reflection(t, sigma):
    return sum(((t >> i) & 1) << j for i, j in enumerate(sigma))


def tournament(t, n, tiles):
    adj = [0] * n
    for i in range(n - 1):
        adj[i] |= 1 << (i + 1)
    for k, (x, y) in enumerate(tiles):
        i, j = n - x, n - y
        if (t >> k) & 1:
            adj[j] |= 1 << i
        else:
            adj[i] |= 1 << j
    return adj


def hp_fibre(adj, n, tiles):
    full = (1 << n) - 1
    paths = []
    def visit(path, used):
        if used == full:
            paths.append(tuple(path))
            return
        options = (adj[path[-1]] if path else full) & (full ^ used)
        while options:
            b = options & -options
            options -= b
            visit(path + [b.bit_length() - 1], used | b)
    visit([], 0)
    fibre = set()
    for p in paths:
        t = 0
        for k, (x, y) in enumerate(tiles):
            if not ((adj[p[n - x]] >> p[n - y]) & 1):
                t |= 1 << k
        fibre.add(t)
    assert len(paths) % len(fibre) == 0
    return fibre, len(paths), len(paths) // len(fibre)


def graph_summary(vertices, edges):
    """All vertices retained, including isolated ones; loops count as one edge."""
    vertices = list(vertices)
    adj = {u: set() for u in vertices}
    for (u, v), count in edges.items():
        if count:
            adj[u].add(v)
            adj[v].add(u)
    components = []
    unseen = set(vertices)
    while unseen:
        root = min(unseen)
        todo, comp = [root], set()
        while todo:
            u = todo.pop()
            if u in comp:
                continue
            comp.add(u)
            unseen.discard(u)
            todo.extend(adj[u] - comp)
        e = sum(w for (u, v), w in edges.items() if u in comp)
        components.append({"vertices": sorted(comp), "edges": e,
                           "cycle_rank": e - len(comp) + 1})
    # Tarjan low-link search. Parallel edges rule out a literal multigraph
    # bridge even when their common underlying simple edge is a bridge.
    bridges = []
    discovery, low = {}, {}
    sys.setrecursionlimit(max(10000, 2*len(vertices)+100))
    def search(u, parent=None):
        discovery[u] = low[u] = len(discovery)
        for v in sorted(adj[u]):
            if u == v or v == parent:
                continue
            if v not in discovery:
                search(v,u)
                low[u] = min(low[u],low[v])
                pair=tuple(sorted((u,v)))
                if low[v] > discovery[u] and edges[pair] == 1:
                    bridges.append(list(pair))
            else:
                low[u] = min(low[u],discovery[v])
    for u in vertices:
        if u not in discovery:
            search(u)
    bridges.sort()
    return {"vertices": len(vertices), "edges": sum(edges.values()),
            "loops": sum(w for (u, v), w in edges.items() if u == v),
            "support_pairs": len(edges), "components": components,
            "component_count": len(components),
            "cycle_rank": sum(edges.values()) - len(vertices) + len(components),
            "bridges": bridges}


def run(n, outdir, direct_audit=False):
    start = time.time()
    tiles, sigma = schema(n)
    m, size = len(tiles), 1 << len(tiles)
    full = size - 1
    classmap = [-1] * size
    classes = []
    for t in range(size):
        if classmap[t] >= 0:
            continue
        adj = tournament(t, n, tiles)
        fibre, h, aut = hp_fibre(adj, n, tiles)
        ci = len(classes)
        assert min(fibre) == t
        assert all(classmap[s] == -1 for s in fibre)
        for s in fibre:
            classmap[s] = ci
        scores = [a.bit_count() for a in adj]
        c3 = math.comb(n, 3) - sum(math.comb(a, 2) for a in scores)
        classes.append({"class": ci, "representative": t, "mass": len(fibre),
                        "H": h, "aut": aut, "c3": c3, "scores": sorted(scores)})
        assert h % 2 and aut % 2 and len(fibre) % 2
    # Independent brute-force pairwise permutation orbit audit through n=5.
    if direct_audit:
        for rec in classes:
            adj = tournament(rec["representative"], n, tiles)
            got = set()
            for p in permutations(range(n)):
                if all((adj[p[i]] >> p[i + 1]) & 1 for i in range(n - 1)):
                    t = sum((1 - ((adj[p[n-x]] >> p[n-y]) & 1)) << k
                            for k, (x, y) in enumerate(tiles))
                    got.add(t)
            assert got == {i for i in range(size) if classmap[i] == rec["class"]}
    converse = [classmap[reflection(c["representative"], sigma)] for c in classes]
    for ci, cj in enumerate(converse):
        assert converse[cj] == ci
    merged_keys = sorted({min(ci, cj) for ci, cj in enumerate(converse)})
    rank = {k: u for u, k in enumerate(merged_keys)}
    pi = [rank[min(ci, converse[ci])] for ci in classmap]
    fibres = defaultdict(list)
    for t,u in enumerate(pi):
        fibres[u].append(t)
    nodes = []
    for u, k in enumerate(merged_keys):
        members = sorted({k, converse[k]})
        ts = fibres[u]
        blue = [t for t in ts if reflection(t, sigma) == t]
        mass, b = len(ts), len(blue)
        nodes.append({"node": u, "classes": members, "representative": min(ts),
                      "mass": mass, "blue": b, "reflection_pairs": (mass-b)//2,
                      "SC": len(members)==1, "c3": classes[k]["c3"],
                      "type": "PB" if b==mass else "MX" if b else "NS",
                      "quotient_black_charge": ((mass-b)//2) % 2})
        assert b % 2 == (len(members) == 1)
        assert (mass % 4 == 2) if not b else (mass % 2 == 1)
    blue_edges, black_edges = Counter(), Counter()
    defects = defaultdict(Counter)
    for t in range(size // 2):
        s = full ^ t
        pair = tuple(sorted((pi[t], pi[s])))
        rt = reflection(t, sigma)
        (blue_edges if rt == t else black_edges)[pair] += 1
        defects[t ^ rt][pair] += 1
    assert all(w % 2 == 0 for w in black_edges.values())
    assert all(w % 2 == 0 for d, cnt in defects.items() if d for w in cnt.values())
    quotient = Counter({pair: w // 2 for pair, w in black_edges.items()})
    degrees = Counter()
    for (u,v), w in quotient.items():
        degrees[u] += w
        degrees[v] += w
    assert all(degrees[u] == r["reflection_pairs"] for u,r in enumerate(nodes))
    for u, r in enumerate(nodes):
        assert r["type"] != "NS" or degrees[u] % 2 == 1
    summaries = {}
    for name, edges in [("blue",blue_edges), ("black",black_edges),
                        ("paired_black",quotient), ("combined",blue_edges+black_edges)]:
        summaries[name] = graph_summary(range(len(nodes)), edges)
    bk, q = summaries["black"], summaries["paired_black"]
    assert bk["cycle_rank"] == q["edges"] + q["cycle_rank"]
    for comp in q["components"]:
        assert sum(nodes[u]["quotient_black_charge"] for u in comp["vertices"]) % 2 == 0
    # Blue cycle parity: c3(u)-c3(v) is n-2 mod 2 on every blue edge.
    assert all((nodes[u]["c3"]-nodes[v]["c3"]) % 2 == (n-2) % 2 for u,v in blue_edges)
    data = {"n":n,"m":m,"tiles":tiles,"reflection_permutation":sigma,
            "classes":classes,"nodes":nodes,"pi":pi,"class_by_mask":classmap,
            "blue_edges":[[u,v,w] for (u,v),w in sorted(blue_edges.items())],
            "black_edges":[[u,v,w] for (u,v),w in sorted(black_edges.items())],
            "paired_black_edges":[[u,v,w] for (u,v),w in sorted(quotient.items())],
            "graphs":summaries}
    path = outdir / f"census_n{n}.json"
    path.write_text(json.dumps(data, separators=(",", ":")) + "\n")
    short = {"n":n, "tilings":size,"classes":len(classes),"merged":len(nodes),
             "SC":sum(r["SC"] for r in nodes),"types":dict(Counter(r["type"] for r in nodes)),
             "graphs":{name:{k:g[k] for k in ["edges","loops","support_pairs","component_count","cycle_rank","bridges"]}
                       for name,g in summaries.items()},
             "black_quotient_odd_SC":sum(r["SC"] and r["quotient_black_charge"] for r in nodes),
             "elapsed_seconds":round(time.time()-start,3)}
    print(json.dumps(short),flush=True)
    return short


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--min-n",type=int,default=3)
    p.add_argument("--max-n",type=int,default=7)
    p.add_argument("--output",type=Path,default=Path(__file__).resolve().parent)
    args=p.parse_args()
    args.output.mkdir(exist_ok=True,parents=True)
    rows=[run(n,args.output,n<=5) for n in range(args.min_n,args.max_n+1)]
    (args.output/"summary.json").write_text(json.dumps(rows,indent=2)+"\n")
