#!/usr/bin/env python3
"""Independent physical-label universe and rational-affine residual audit.

No producer code is imported. The only comparison input is its frozen receipt.
Source positions are generated by ceil(k*q/p)-1, not a floor-difference word.
Paths are generated by moving consecutive physical labels into zero neighbors.
Residues annotate already generated paths; they never select a path.
"""
from fractions import Fraction
from hashlib import sha256
from itertools import permutations
from math import factorial, gcd
from pathlib import Path
import json

F = Fraction
HERE = Path(__file__).resolve().parent
checks = 0


def check(value, label):
    global checks
    checks += 1
    if not value:
        raise RuntimeError(label)


def atanh_log(t, terms=48):
    power = t
    total = F(0)
    for j in range(terms):
        total += 2*power/(2*j+1)
        power *= t*t
    tail = 2*power/((2*terms+1)*(1-t*t))
    return total, total+tail


# log(3)=log(2)+log(3/2); t=1/5 for the second logarithm.
l2, u2 = atanh_log(F(1, 3))
l32, u32 = atanh_log(F(1, 5))
l3, u3 = l2+l32, u2+u32
lower_alpha, upper_alpha = l3/u2, u3/l2


def rational_cf_to_cutoff(x):
    numerator, denominator = x.numerator, x.denominator
    old_h, h, old_k, k = 0, 1, 1, 0
    digits, rows = [], []
    while denominator:
        a, remainder = divmod(numerator, denominator)
        digits.append(a)
        old_h, h = h, a*h+old_h
        old_k, k = k, a*k+old_k
        rows.append((k, h))
        if k >= 8000:
            return digits, rows
        numerator, denominator = denominator, remainder
    raise RuntimeError("logarithm interval endpoint terminated before cutoff")


left_digits, left_rows = rational_cf_to_cutoff(lower_alpha)
right_digits, right_rows = rational_cf_to_cutoff(upper_alpha)
check(left_digits == right_digits and left_rows == right_rows,
      "interval endpoints have distinct CF digits before cutoff")
convergents = [(p, q) for p, q in left_rows if 2 <= p < 8000 and p < q < 2*p]
check(left_rows[-1] == (15601, 24727), "unexpected terminal convergent")
N = 1 << 26
check(N == 8192**2 and 7999**2 < N, "Legendre denominator budget")
check(l2 > F(2, 3), "log2 lower bound")
check(F(3, 2*(3*N+2)) < F(1, 2*N), "negative minimum inequality")
check(l3 > F(13, 12), "log3 lower bound")
check(sum((F(29, 6)**k/factorial(k) for k in range(21)), F()) > 121,
      "log121 upper bound")
check(F(13, 12)-F(4*29, 6*20) == F(7, 60) > F(1, 9),
      "8000 large-range transfer")
check(8000 == 20**3, "cube threshold")


def affine_fixed_point(bits):
    scale, offset = F(1), F(0)
    for bit in bits:
        multiplier = F(3 if bit else 1, 2)
        scale *= multiplier
        offset = multiplier*offset+F(bit, 2)
    check(scale != 1, "zero clock")
    return offset/(1-scale), scale, offset


known_cycles = [[1, 2], [-1], [-5, -7, -10],
                [-17, -25, -37, -55, -82, -41, -61, -91, -136, -68, -34]]
known_shapes = []
for cycle in known_cycles:
    word = [x % 2 for x in cycle]
    fixed, _, _ = affine_fixed_point(word)
    check(fixed == cycle[0], "known-cycle affine positive control")
    for x, y in zip(cycle, cycle[1:]+cycle[:1]):
        check(((3*x+1)//2 if x % 2 else x//2) == y, "known-cycle branch edge")
    known_shapes.append((sum(word), len(word)))
check(known_shapes == [(1, 2), (1, 1), (2, 3), (7, 11)], "known cycle shapes")

shapes = sorted(set(convergents + [shape for shape in known_shapes
                                  if shape[0] >= 2 and shape[0] < shape[1] < 2*shape[0]]))
records = []
summary = []
cut_paths = 0
for p, q in shapes:
    check(gcd(p, q) == 1 and p < q < 2*p, "shape range")
    r = q-p
    positions = [(k*q+p-1)//p-1 for k in range(1, p+1)]
    check(len(set(positions)) == p, "source position distinctness")
    source = [0]*q
    source_labels = [None]*q
    for k, pos in enumerate(positions, start=1):
        source[pos] = 1
        source_labels[pos] = k % p
    # Independent check only; not used to generate the source.
    check(source == [((i+1)*p)//q-(i*p)//q for i in range(q)], "mechanical-word identity")
    D = pow(2, q)-pow(3, p)
    maximum, count = 0, 0
    seen = set()
    for index, x in enumerate(positions):
        y = positions[(index+1) % p]
        for direction in (1, -1):
            destination_x, destination_y = (x+direction) % q, (y+direction) % q
            if source[destination_x] or source[destination_y]:
                continue
            if {x, destination_x} & {y, destination_y}:
                continue
            check((y-x) % q == 2, "legal neighboring disjoint pair must have gap two")
            for ordered_moves in permutations(((x, destination_x), (y, destination_y))):
                labels = source_labels[:]
                edges = []
                for start, destination in ordered_moves:
                    check(labels[start] is not None and labels[destination] is None,
                          "physical move is not actual")
                    labels[start], labels[destination] = None, labels[start]
                    edges.append(start if direction == 1 else destination)
                key = tuple(edges)
                check(key not in seen, "duplicate physical ordered path")
                seen.add(key)
                bits = [int(label is not None) for label in labels]
                check(sum(bits) == p, "weight changed")
                fixed, scale, offset = affine_fixed_point(bits)
                B_fraction = offset*pow(2, q)
                check(B_fraction.denominator == 1, "affine carry failed to clear")
                B = B_fraction.numerator
                check(fixed == F(B, D), "affine fixed-point/clock identity")
                check(scale == F(pow(3, p), pow(2, q)), "affine multiplier identity")
                content = gcd(abs(D), B)
                check(fixed.denominator > 1 and content < abs(D), "integer output")
                check(fixed.denominator == abs(D)//content, "reduced denominator")
                # Labels/residues are retained solely to align the already found
                # physical records with the producer's serialization convention.
                residues = [(-source_labels[z]*r) % p for z in (x, y)]
                u = min(residues)
                check(sorted(residues) == [u, u+p-r], "neighbor residue identity")
                family = "plus" if direction == 1 else "minus"
                record = dict(p=p, q=q, r=r, family=family, u=u, edges=edges,
                              B=B, D=D, content=content, word="".join(map(str, bits)))
                initial_edge_label = source_labels[ordered_moves[0][0]]
                initial_residue = (-initial_edge_label*r) % p
                sort_key = (p, q, 0 if direction == 1 else 1, u,
                            0 if initial_residue == u else 1)
                records.append((sort_key, record))
                count += 1
                maximum = max(maximum, content)
                cut_paths += int(q-1 in edges)
    summary.append(dict(p=p, q=q, paths=count, maximum_content=maximum))

records.sort(key=lambda item: item[0])
serialized = b"".join(json.dumps(record, sort_keys=True, separators=(",", ":")).encode()+b"\n"
                      for _, record in records)
trace_digest = sha256(serialized).hexdigest()
(HERE/"independent_physical_records.jsonl").write_bytes(serialized)
producer_bytes = (HERE.parent/"candidates.receipt.json").read_bytes()
producer = json.loads(producer_bytes)
check(convergents == [(r["p"], r["q"]) for r in producer["small_convergent_shapes"]],
      "independent continued fractions disagree with producer")
check(left_digits == producer["continued_fraction_prefix"], "CF prefix mismatch")
check(trace_digest == producer["all_case_trace_sha256"], "full 740-record trace mismatch")
check(len(records) == 740 == producer["total_paths"], "total universe mismatch")
check(summary == [{key: row[key] for key in ("p", "q", "paths", "maximum_content")}
                  for row in producer["candidate_shapes"]], "summary mismatch")
check(not producer["integer_hits"], "producer integer hits")
print(json.dumps(dict(
    status="PASS: independent physical-label enumeration and rational-affine integrality",
    script_sha256=sha256(Path(__file__).read_bytes()).hexdigest(),
    comparison_receipt_sha256=sha256(producer_bytes).hexdigest(),
    checks=checks,
    logarithms="48 terms for log2 and log(3/2), with log3=log2+log(3/2)",
    continued_fraction_prefix=left_digits,
    terminal_convergent=dict(p=left_rows[-1][0], q=left_rows[-1][1]),
    small_convergents=[dict(p=p, q=q) for p, q in convergents],
    known_cycle_shapes=known_shapes,
    candidate_shapes=summary,
    total_paths=len(records),
    original_cut_crossing_paths=cut_paths,
    all_case_trace_sha256=trace_digest,
    all_integer_outputs_excluded=True,
    scope="Primitive q=p+r; same-direction disjoint moves of consecutive source ones only."
), indent=2))
