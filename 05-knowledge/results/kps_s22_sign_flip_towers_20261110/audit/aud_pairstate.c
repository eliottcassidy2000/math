/* aud_pairstate.c - auditor's own state counter (not derived from the session's pairstate.c).
 *
 * input (stdin), one record per line:   mode n out_0 ... out_{n-1} Omask
 *    out_i = bit mask of the out-neighbours of vertex i ; Omask = selected set O
 *    mode 0: subset recursion only            -> "n r M h E"
 *    mode 1: subset recursion + literal depth-first enumeration (no memo, every path generated one by one)
 *                                             -> "n r M h E | r M h E"
 *    mode 2: H only (subset recursion)        -> "n H"
 *
 * Subset recursion ("pull" form): endat[S][v] = sum over x in S-v, x->v of endat[S-v][x]; same for startat.
 * Literal enumeration:
 *    h  = number of Hamiltonian paths, generated by extension along arcs;
 *    E  = those ending in O (generated backwards from the last vertex);
 *    M  = for every path P2 (any length) starting in O: number of Hamiltonian paths of the rest (1 if no rest);
 *    W  = for every path P2 starting at f in O, not covering everything: Hamiltonian paths of the rest ending in O.
 *    (the last vertex of P1 and the first of P2 are automatically distinct.)
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
typedef unsigned long long u64;
typedef __int128 i128;

static int n;
static unsigned outm[24], inm[24], FULL, OM;

static void pr(i128 x) {
    if (x < 0) { putchar('-'); x = -x; }
    char b[64]; int k = 0;
    if (x == 0) b[k++] = '0';
    while (x > 0) { b[k++] = '0' + (int)(x % 10); x /= 10; }
    while (k--) putchar(b[k]);
}

/* ---------- literal enumeration ---------- */
static u64 extf(unsigned rem, int v) {          /* extend forwards from v through all of rem */
    if (!rem) return 1;
    u64 c = 0; unsigned nx = outm[v] & rem;
    while (nx) { int u = __builtin_ctz(nx); nx &= nx - 1; c += extf(rem & ~(1u << u), u); }
    return c;
}
static u64 extb(unsigned rem, int v) {          /* extend backwards from v through all of rem */
    if (!rem) return 1;
    u64 c = 0; unsigned nx = inm[v] & rem;
    while (nx) { int u = __builtin_ctz(nx); nx &= nx - 1; c += extb(rem & ~(1u << u), u); }
    return c;
}
static u64 ham(unsigned S) {                    /* Hamiltonian paths of the sub-tournament on S (1 if empty) */
    if (!S) return 1;
    u64 c = 0; unsigned t = S;
    while (t) { int v = __builtin_ctz(t); t &= t - 1; c += extf(S & ~(1u << v), v); }
    return c;
}
static u64 ham_end_in_O(unsigned S) {
    u64 c = 0; unsigned t = S & OM;
    while (t) { int v = __builtin_ctz(t); t &= t - 1; c += extb(S & ~(1u << v), v); }
    return c;
}
static i128 litM, litW;
static void walkP2(unsigned used, int v) {      /* P2 = a path with vertex set `used`, currently ending at v */
    unsigned rem = FULL & ~used;
    litM += ham(rem);
    if (rem) {
        litW += ham_end_in_O(rem);
        unsigned nx = outm[v] & rem;
        while (nx) { int u = __builtin_ctz(nx); nx &= nx - 1; walkP2(used | (1u << u), u); }
    }
}

int main(void) {
    int mode;
    while (scanf("%d %d", &mode, &n) == 2) {
        if (n > 22 && mode != 3) { fprintf(stderr, "order too large\n"); return 1; }
        if (n > 30) { fprintf(stderr, "order too large\n"); return 1; }
        for (int i = 0; i < n; i++) { if (scanf("%u", &outm[i]) != 1) return 1; inm[i] = 0; }
        if (scanf("%u", &OM) != 1) return 1;
        FULL = (n == 32) ? 0xffffffffu : ((1u << n) - 1);
        if (mode == 3) {           /* mode 3: H only, by literal generation of every Hamiltonian path (no tables) */
            for (int i = 0; i < n; i++) for (int j = 0; j < n; j++) if (outm[i] >> j & 1) inm[j] |= 1u << i;
            printf("%d ", n); pr((i128)ham(FULL)); putchar('\n'); fflush(stdout); continue;
        }
        /* sanity: tournament */
        for (int i = 0; i < n; i++) {
            if (outm[i] >> i & 1) { fprintf(stderr, "loop\n"); return 1; }
            for (int j = i + 1; j < n; j++)
                if (((outm[i] >> j) & 1) + ((outm[j] >> i) & 1) != 1) { fprintf(stderr, "not a tournament\n"); return 1; }
        }
        for (int i = 0; i < n; i++) for (int j = 0; j < n; j++) if (outm[i] >> j & 1) inm[j] |= 1u << i;
        size_t NS = (size_t)1 << n;
        u64 *endat = calloc(NS * (size_t)n, sizeof(u64));
        u64 *startat = (mode == 2) ? NULL : calloc(NS * (size_t)n, sizeof(u64));
        u64 *tot = calloc(NS, sizeof(u64));
        if (!endat || !tot || (mode != 2 && !startat)) { fprintf(stderr, "memory\n"); return 1; }
        tot[0] = 1;
        for (size_t S = 1; S < NS; S++) {
            u64 sum = 0;
            if ((S & (S - 1)) == 0) {
                int v = __builtin_ctzll(S);
                endat[S * n + v] = 1; if (startat) startat[S * n + v] = 1; sum = 1;
            } else {
                unsigned t = (unsigned)S;
                while (t) {
                    int v = __builtin_ctz(t); t &= t - 1;
                    size_t R = S ^ ((size_t)1 << v);
                    u64 c = 0; unsigned xs = (unsigned)R & inm[v];
                    while (xs) { int x = __builtin_ctz(xs); xs &= xs - 1; c += endat[R * n + x]; }
                    endat[S * n + v] = c; sum += c;
                    if (startat) {
                        c = 0; unsigned ys = (unsigned)R & outm[v];
                        while (ys) { int y = __builtin_ctz(ys); ys &= ys - 1; c += startat[R * n + y]; }
                        startat[S * n + v] = c;
                    }
                }
            }
            tot[S] = sum;
        }
        i128 h = tot[NS - 1];
        if (mode == 2) { printf("%d ", n); pr(h); putchar('\n'); fflush(stdout); free(endat); free(tot); continue; }
        i128 E = 0, M = 0, W = 0;
        for (int o = 0; o < n; o++) if (OM >> o & 1) E += endat[(NS - 1) * n + o];
        for (size_t S = 0; S < NS - 1; S++) {            /* S = vertex set of P1, R = rest = vertex set of P2 */
            size_t R = (NS - 1) ^ S;
            i128 sR = 0; unsigned t = (unsigned)R & OM;
            while (t) { int o = __builtin_ctz(t); t &= t - 1; sR += startat[R * n + o]; }
            if (sR == 0) continue;
            M += (i128)tot[S] * sR;
            if (S) {
                i128 eS = 0; t = (unsigned)S & OM;
                while (t) { int o = __builtin_ctz(t); t &= t - 1; eS += endat[S * n + o]; }
                W += eS * sR;
            }
        }
        printf("%d ", n); pr(h - W); putchar(' '); pr(M); putchar(' '); pr(h); putchar(' '); pr(E);
        if (mode == 1) {
            i128 lh = ham(FULL), lE = ham_end_in_O(FULL);
            litM = 0; litW = 0;
            unsigned t = OM;
            while (t) { int f = __builtin_ctz(t); t &= t - 1; walkP2(1u << f, f); }
            printf(" | "); pr(lh - litW); putchar(' '); pr(litM); putchar(' '); pr(lh); putchar(' '); pr(lE);
        }
        putchar('\n'); fflush(stdout);
        free(endat); free(startat); free(tot);
    }
    return 0;
}
