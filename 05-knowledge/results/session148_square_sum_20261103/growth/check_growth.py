#!/usr/bin/env python3
"""Independent finite tests; explicit failures survive python -O."""
from math import isqrt
from collections import defaultdict

def require(ok, what):
    if not ok: raise RuntimeError(what)

def degree(n):
    return isqrt(2*n-1)-isqrt(n)

def edges_formula(n):
    k, m = isqrt(n), isqrt(2*n-1)
    twelve = (12*(m-k)*n-12*k + 2*k*(k+1)*(2*k+1)
              - m*(m+1)*(2*m+1) + 6*((m+1)//2))
    require(twelve % 12 == 0, ('not integral',n,twelve))
    return twelve//12

def ceilroot(x):
    y=isqrt(x)
    return y+(y*y!=x)

def threshold(k):
    a=k-2+ceilroot(2*(k-1)**2+3)
    return a, max(a*a, (a+k)**2//2+1)

def square(t): return isqrt(t)**2 == t

def paths_dp(n):
    adj=[0]*n
    for i in range(n):
        for j in range(n):
            if i!=j and square(i+j+2): adj[i] |= 1<<j
    dp={}
    # states map mask to endpoint counts, generated by appending vertices
    levels=[{} for _ in range(n+1)]
    for v in range(n): levels[1][1<<v] = {v:1}
    for count in range(1,n):
        for mask, ends in levels[count].items():
            for v,c in ends.items():
                choices=adj[v]&~mask
                while choices:
                    bit=choices&-choices; choices-=bit
                    dest=bit.bit_length()-1
                    e=levels[count+1].setdefault(mask|bit,{})
                    e[dest]=e.get(dest,0)+c
    for level in levels[1:]: dp.update(level)
    return adj,dp

def total(dp,mask): return sum(dp.get(mask,{}).values())

# G14 is a connected tree; three leaves certify no Hamilton path.
adj14,_ = paths_dp(14)
seen=1
while True:
    expansion=seen
    for i in range(14):
        if seen>>i & 1: expansion |= adj14[i]
    if expansion==seen: break
    seen=expansion
require(seen==(1<<14)-1 and sum(x.bit_count() for x in adj14)==26, 'G14 tree')
require([i+1 for i,x in enumerate(adj14) if x.bit_count()==1]==[8,9,10], 'G14 leaves')

edge_running=0
for n in range(1,10001):
    brute=sum(square(n+j) for j in range(1,n))
    require(degree(n)==brute,('degree',n,degree(n),brute))
    edge_running+=brute
    require(edges_formula(n)==edge_running,('edge',n))
    a=isqrt(n)
    for k in range(1,degree(n)+3):
        block=(max(a*a,(a+k)**2//2+1)<=n<=(a+1)**2-1)
        require((degree(n)>=k)==block,('block',n,k))
    if n>=2:
        birth=int(square(2*n-2) or square(2*n-1))
        drop=int(square(n))
        require(degree(n)-degree(n-1)==birth-drop,('difference',n))
        if birth and drop:
            r=isqrt(n)
            s=isqrt(2*n-2) if square(2*n-2) else isqrt(2*n-1)
            require((s%2==0 and r*r-2*(s//2)**2==1) or
                    (s%2==1 and s*s-2*r*r==-1),('pell',n,r,s))

for k in range(1,101):
    a,t=threshold(k)
    require(degree(t)>=k,('threshold fails',k,a,t))
    require(all(degree(n)<k for n in range(1,t)),('earlier threshold',k,a,t))

for n in range(1,19):
    adj,dp=paths_dp(n); full=(1<<n)-1
    nxt=n+1
    neighbor=0
    for i in range(n):
        if square((i+1)+nxt): neighbor |= 1<<i
    A=2*sum(c for v,c in dp.get(full,{}).items() if neighbor>>v&1)
    C=0
    for mask,ends in dp.items():
        other=full^mask
        if not other: continue
        left=sum(c for v,c in ends.items() if neighbor>>v&1)
        right=sum(c for v,c in dp.get(other,{}).items() if neighbor>>v&1)
        C+=left*right
    _,next_dp=paths_dp(n+1)
    exact=total(next_dp,(1<<(n+1))-1)
    require(A+C==exact,('paths recurrence',n,A,C,exact))
    if n==14: require(total(dp,full)==0 and A==0 and C==2, ('G14 to G15',A,C))
    if n+1 in (15,16,17,18):
        require(exact=={15:2,16:2,17:2,18:0}[n+1],('known paths',n+1,exact))

print('PASS degrees/blocks/edge totals n<=10000; first thresholds k<=100; Pell indicators n<=10000; path recurrence n<=18; no assert-dependent checks')
