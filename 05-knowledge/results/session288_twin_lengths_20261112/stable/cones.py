def twinquot(rows,O):
 n=len(rows);adj=[set() for _ in rows]
 for a,b in combinations(range(n),2):
  if O>>a&1 or O>>b&1:continue
  if all(bool(rows[a]>>v&1)==bool(rows[b]>>v&1) for v in range(n) if v not in (a,b)):adj[a].add(b);adj[b].add(a)
 comps=[];seen=set()
 for v in range(n):
  if v in seen:continue
  todo=[v];cc=set()
  while todo:
   x=todo.pop()
   if x in cc:continue
   cc.add(x);todo.extend(adj[x]-cc)
  seen|=cc;comps.append(sorted(cc))
 q=[sum(1<<j for j,B in enumerate(comps) if rows[A[0]]>>B[0]&1) for A in comps]
 o=sum(1<<i for i,A in enumerate(comps) if O>>A[0]&1)
 for A in comps:
  need(sorted(sum(bool(rows[v]>>w&1) for w in A) for v in A)==list(range(len(A))),'transitive component')
  need(all(len({bool(rows[v]>>w&1) for v in A})==1 for w in range(n) if w not in A),'module')
 return q,o,comps

def maps(rows,O):
 cells=defaultdict(list)
 for v,r in enumerate(rows):cells[(bool(O>>v&1),r.bit_count(),(r&O).bit_count())].append(v)
 best=None;ps=[]
 for parts in product(*(permutations(cells[k]) for k in sorted(cells))):
  p=sum(parts,());rr=tuple(sum(1<<j for j,w in enumerate(p) if rows[v]>>w&1) for v in p);key=(sum(1<<j for j,v in enumerate(p) if O>>v&1),rr)
  if best is None or key<best:best=key;ps=[p]
  elif key==best:ps.append(p)
 return best,ps

def meet(a,b):
 out=[]
 for x,y in zip(a,b):
  if x and y and x!=y:return None
  out.append(x or y)
 return tuple(out)
def contains(a,b):return all(not x or x==y for x,y in zip(a,b))
def union_terms(cones):
 out={}
 for cone in sorted(cones):
  updates=Counter({cone:1})
  for c,m in out.items():
   d=meet(c,cone)
   if d is not None:updates[d]-=m
  for c,m in updates.items():
   out[c]=out.get(c,0)+m
   if not out[c]:del out[c]
 return out

def expand(q,O,lengths):
 typ=[v for v,m in enumerate(lengths) for _ in range(m)]
 rows=[sum(1<<j for j,w in enumerate(typ) if (v==w and i<j) or q[v]>>w&1) for i,v in enumerate(typ)]
 sel=sum(1<<j for j,v in enumerate(typ) if O>>v&1)
 ports=[]
 for v,m in enumerate(lengths):
  if m==1 and not O>>v&1:ports.append(typ.index(v))
 return rows,sel,typ

