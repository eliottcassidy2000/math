#!/usr/bin/env python3
"""Exact hostile audit for the GMC equal-mass two-rung collision lemma.

The intended application is a three-charge Laurent face.  Its balanced
semigroup is required to be freely generated by two primitive rays of the
same mass.  This is stronger than merely asking the two extreme rays to have
equal mass: the charge triple (1, 6, -4) is the smallest hostile below and
has a third channel on the first equal-mass slice.

This is the exact referee artifact for THM-2639.
"""

from fractions import Fraction
from math import comb, factorial, gcd


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def gcd_many(values):
    result = 0
    for value in values:
        result = gcd(result, abs(value))
    return result


def multinomial(parts):
    result = factorial(sum(parts))
    for part in parts:
        result //= factorial(part)
    return result


def add_vectors(left, right):
    return tuple(x + y for x, y in zip(left, right))


def scale_vector(scale, vector):
    return tuple(scale * value for value in vector)


def cross(left, right):
    return (
        left[1] * right[2] - left[2] * right[1],
        left[2] * right[0] - left[0] * right[2],
        left[0] * right[1] - left[1] * right[0],
    )


def compositions_three(total):
    for first in range(total + 1):
        for second in range(total - first + 1):
            yield (first, second, total - first - second)


def balanced_channels(charge, mass):
    return tuple(
        vector
        for vector in compositions_three(mass)
        if sum(q * value for q, value in zip(charge, vector)) == 0
    )


def poly_add(left, right):
    result = dict(left)
    for monomial, coefficient in right.items():
        result[monomial] = result.get(monomial, 0) + coefficient
        if result[monomial] == 0:
            del result[monomial]
    return result


def poly_scale(scale, polynomial):
    if scale == 0:
        return {}
    return {
        monomial: scale * coefficient
        for monomial, coefficient in polynomial.items()
        if scale * coefficient != 0
    }


def poly_mul(left, right):
    result = {}
    for left_monomial, left_coefficient in left.items():
        for right_monomial, right_coefficient in right.items():
            monomial = add_vectors(left_monomial, right_monomial)
            result[monomial] = (
                result.get(monomial, 0)
                + left_coefficient * right_coefficient
            )
    return {key: value for key, value in result.items() if value != 0}


def two_rung_weights(a, b, c, d):
    """Weights for v=(a,0,c), w=(0,b,d), with equal mass."""
    ell = a + c
    require(ell == b + d, "the two rays do not have equal mass")
    return (
        comb(ell, a),
        comb(ell, b),
        comb(2 * ell, 2 * a),
        multinomial((a, b, c + d)),
        comb(2 * ell, 2 * b),
    )


def delta_value(a, b, c, d):
    A, B, C, D, E = two_rung_weights(a, b, c, d)
    return C * B * B - D * A * B + E * A * A


def verify_bezout_identity(A, B, C, D, E):
    """Verify the universal identity in Z[x,y] by sparse arithmetic."""
    x = {(1, 0): 1}
    y = {(0, 1): 1}
    first = poly_add(poly_scale(A, x), poly_scale(B, y))
    second = poly_add(
        poly_add(
            poly_scale(C, poly_mul(x, x)),
            poly_scale(D, poly_mul(x, y)),
        ),
        poly_scale(E, poly_mul(y, y)),
    )
    multiplier = poly_add(
        poly_scale(E * B, y),
        poly_scale(D * B - E * A, x),
    )
    left = poly_add(
        poly_scale(B * B, second),
        poly_scale(-1, poly_mul(multiplier, first)),
    )
    delta = C * B * B - D * A * B + E * A * A
    require(left == {(2, 0): delta}, "two-rung Bezout identity failed")


def verify_positive_tuple(a, b, c, d):
    """Verify Delta<0 and every exact identity used in its all-range proof."""
    require(min(a, b, c, d) > 0, "ray coordinates must be positive")
    require(a + c == b + d, "ray masses differ")
    require(a != b, "the injective-charge boundary a != b is missing")

    A, B, C, D, E = two_rung_weights(a, b, c, d)
    delta = C * B * B - D * A * B + E * A * A
    verify_bezout_identity(A, B, C, D, E)

    # Orient so a<b.  Swapping rays sends (a,b,c,d) to (b,a,d,c)
    # and leaves Delta invariant.
    if a > b:
        ao, bo, co, do = b, a, d, c
    else:
        ao, bo, co, do = a, b, c, d
    require(ao < bo and co > do, "oriented equal-mass order failed")
    require(delta_value(ao, bo, co, do) == delta, "Delta is not ray-swap invariant")

    Ao, Bo, Co, Do, Eo = two_rung_weights(ao, bo, co, do)
    ell = ao + co
    central = comb(2 * ell, ell)
    middle = comb(co + do, co)
    first_denominator = comb(2 * ao, ao) * comb(2 * co, co)
    second_denominator = comb(2 * bo, bo) * comb(2 * do, do)

    # The three normalized channel identities.
    require(Co * first_denominator == Ao * Ao * central,
            "pure-v normalized coefficient identity failed")
    require(Do * middle == Ao * Bo * central,
            "mixed normalized coefficient identity failed")
    require(Eo * second_denominator == Bo * Bo * central,
            "pure-w normalized coefficient identity failed")

    normalized_delta = Fraction(delta, Ao * Ao * Bo * Bo)
    normalized_bracket = central * (
        Fraction(1, first_denominator)
        - Fraction(1, middle)
        + Fraction(1, second_denominator)
    )
    require(normalized_delta == normalized_bracket,
            "normalized Delta identity failed")

    # Full-range strict sign proof.  Put h=b-a=c-d>0.
    h = bo - ao
    require(h == co - do and h > 0, "equal-mass gap identity failed")

    large_ratio = Fraction(comb(2 * co, co), middle)
    large_product = Fraction(1)
    for index in range(1, h + 1):
        factor = Fraction(2 * do + h + index, do + index)
        require(factor >= 2, "large-side product factor dropped below two")
        large_product *= factor
    require(large_ratio == large_product and large_ratio >= 2 ** h,
            "large-side product bound failed")

    small_ratio = Fraction(middle, comb(2 * do, do))
    small_product = Fraction(1)
    for index in range(1, h + 1):
        factor = Fraction(2 * do + index, do + index)
        require(factor < 2, "small-side product factor reached two")
        small_product *= factor
    require(small_ratio == small_product and small_ratio < 2 ** h,
            "small-side product bound failed")

    require(comb(2 * ao, ao) >= 2 ** ao,
            "first central-binomial lower bound failed")
    require(comb(2 * bo, bo) > 2 ** bo,
            "strict second central-binomial lower bound failed")
    require(first_denominator >= 4 * middle,
            "first reciprocal is not at most 1/(4M)")
    require(second_denominator > 2 * middle,
            "second reciprocal is not below 1/(2M)")
    require(
        Fraction(1, first_denominator) + Fraction(1, second_denominator)
        < Fraction(1, middle),
        "strict reciprocal inequality failed",
    )
    require(delta < 0, "Delta is not strictly negative")
    return delta


def tuple_census(max_mass):
    count = 0
    closest = None
    closest_tuple = None
    for ell in range(2, max_mass + 1):
        for a in range(1, ell):
            c = ell - a
            for b in range(1, ell):
                if a == b:
                    continue
                d = ell - b
                delta = verify_positive_tuple(a, b, c, d)
                count += 1
                if closest is None or delta > closest:
                    closest = delta
                    closest_tuple = (a, b, c, d)
    return count, closest_tuple, closest


def primitive_ray_census(bound):
    equal_mass = 0
    unimodular = 0
    nonunimodular = 0
    first_hostile = None
    for negative_magnitude in range(1, bound + 1):
        for first_positive in range(1, bound + 1):
            for second_positive in range(first_positive + 1, bound + 1):
                charge = (first_positive, second_positive, -negative_magnitude)
                if gcd_many(charge) != 1:
                    continue
                first_gcd = gcd(first_positive, negative_magnitude)
                second_gcd = gcd(second_positive, negative_magnitude)
                v = (
                    negative_magnitude // first_gcd,
                    0,
                    first_positive // first_gcd,
                )
                w = (
                    0,
                    negative_magnitude // second_gcd,
                    second_positive // second_gcd,
                )
                if sum(v) != sum(w):
                    continue
                equal_mass += 1
                ell = sum(v)
                index = gcd_many(cross(v, w))
                first_level = balanced_channels(charge, ell)
                require(len(first_level) == index + 1,
                        "equal-mass slice/index census changed")
                require(v in first_level and w in first_level,
                        "an extreme ray left its equal-mass slice")
                if index == 1:
                    unimodular += 1
                    require(set(first_level) == {v, w},
                            "unimodular first slice has an extra channel")
                    second_level = balanced_channels(charge, 2 * ell)
                    expected_second = {
                        scale_vector(2, v),
                        add_vectors(v, w),
                        scale_vector(2, w),
                    }
                    require(set(second_level) == expected_second,
                            "unimodular second slice is not the free two-ray slice")
                    verify_positive_tuple(v[0], w[1], v[2], w[2])
                else:
                    nonunimodular += 1
                    extras = tuple(
                        vector for vector in first_level if vector not in (v, w)
                    )
                    require(extras, "nonunimodular hostile has no extra first-slice channel")
                    if first_hostile is None:
                        first_hostile = (charge, v, w, ell, index, first_level)
    return equal_mass, unimodular, nonunimodular, first_hostile


def affine_face_identity():
    """The exact (6,-2,-18) affine-Wick-face ideal certificate."""
    first = {
        (1, 3, 0): 4,
        (3, 0, 1): 4,
    }
    second = {
        (2, 6, 0): 28,
        (4, 3, 1): 280,
        (6, 0, 2): 28,
    }
    # 7*a*(a^2*c+9*b^3)
    multiplier = {
        (3, 0, 1): 7,
        (1, 3, 0): 63,
    }
    difference = poly_add(second, poly_scale(-1, poly_mul(multiplier, first)))
    require(difference == {(2, 6, 0): -224},
            "affine-face two-rung ideal certificate failed")
    return difference


def canonical_hostile_counts():
    # (1,9,-3) is the primitive reordered charge triple of (6,-2,-18).
    charge = (1, 9, -3)
    counts = tuple(len(balanced_channels(charge, mass)) for mass in range(1, 49))
    expected = tuple(0 if mass % 4 else mass // 4 + 1 for mass in range(1, 49))
    require(counts == expected, "canonical free two-ray Hilbert function changed")
    return counts


def boundary_controls():
    # If injectivity is dropped, a=b=1 and c=d gives Delta=0 identically.
    zero_family = tuple(delta_value(1, 1, c, c) for c in range(1, 21))
    require(zero_family == (0,) * 20,
            "equal-charge Delta-zero hostile changed")
    # Equal a=b>=2 is still negative, but such rows have repeated charges and
    # are not an exact injectively indexed Laurent support.
    negative_controls = tuple(delta_value(a, a, 3, 3) for a in range(2, 9))
    require(all(value < 0 for value in negative_controls),
            "equal-charge negative boundary control changed")
    return zero_family, negative_controls


