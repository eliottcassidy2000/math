"""Silent-move GROUP structure for signed-LRC AP_n.  monad-explorer-S708.

Hypothesis (to test): the collision class of a cut eps is the orbit under a 2-group G_eps
generated by the individually-silent half-system flips H_d, d|C a prime-power divisor >1.
=> |G_eps| = 2^{s(eps)}, s(eps)=#{prime-power divisors d>1 : flipping H_d is silent at eps}.

For each prime-power divisor d|C (d>1), K_d=<C/d> (order-d subgroup of Z/C).
Flipping H_d = negate every runner i in K_d \ {0} that lies in the chosen half-system; but for the
PURPOSE of detecting silence we use the equivalent test (THM-417, generalized):
  flipping the K_d-half-system is silent at cut eps  <=>  A_t := sum_{i not in K_d} eps_i sin(2pi t i/C)=0
  for all t with d nmid t   (the non-K_d signed points form full K_d-cosets).
We DIRECTLY realize the move on the sign vector and test Phi^2 invariance, the ground truth.

Output: for each composite C, verify every class size == 2^{s(eps)} and tabulate N(H_d), joint counts.
"""
import numpy as np
import math
from collections import Counter, defaultdict


def is_prime(C):
    return C > 1 and all(C % d for d in range(2, int(C**0.5) + 1))


def factor_str(C):
    f, m, d = [], C, 2
    while d * d <= m:
        while m % d == 0:
            f.append(d); m //= d
        d += 1
    if m > 1:
        f.append(m)
    return "x".join(map(str, f))


def prime_power_divisors(C):
    """All d>1 with d|C and d a prime power."""
    res = []
    m = C
    d = 2
    primes = []
    while d * d <= m:
        if m % d == 0:
            primes.append(d)
            while m % d == 0:
                m //= d
        d += 1
    if m > 1:
        primes.append(m)
    # recover full factorization exponents
    out = []
    for p in primes:
        e = 0
        cc = C
        while cc % p == 0:
            e += 1; cc //= p
        for k in range(1, e + 1):
            out.append(p ** k)
    return sorted(out)


def halfsystem(C, d):
    """Half-system of K_d \\ {0}: representatives of {K_d \\ 0} mod negation, as residues in 1..C-1.
    K_d = <C/d>. Its nonzero elements pair as {x, C-x}; take the one in 1..(C-1)/2."""
    g = C // d
    Kd = set((g * j) % C for j in range(d))
    half = set()
    for x in Kd:
        if x == 0:
            continue
        if x <= C // 2:
            half.add(x)
    return half  # residues; some may be > n-1 (n-1=(C-1)/2 so all <=(C-1)/2 are runners)


def analyze(C):
    n1 = (C - 1) // 2          # number of runners = n-1, speeds 1..n1
    H = np.arange(1, n1 + 1)
    S = np.sin(2 * math.pi * np.outer(H, H) / C)  # S[t-1,i-1]
    nfree = n1 - 1
    total = 1 << nfree
    ppd = prime_power_divisors(C)
    # half-systems as index masks over runners 1..n1 (0-based index i-1)
    hs_masks = {}
    for d in ppd:
        hs = halfsystem(C, d)
        mask = np.zeros(n1, dtype=bool)
        for x in hs:
            if 1 <= x <= n1:
                mask[x - 1] = True
        hs_masks[d] = mask

    # build all cuts (eps_0=+1 fixed)
    eps = np.ones((n1, total), dtype=np.int8)
    idx = np.arange(total, dtype=np.uint64)
    for b in range(nfree):
        bit = ((idx >> np.uint64(b)) & np.uint64(1)).astype(np.int8)
        eps[b + 1, :] = np.where(bit == 1, 1, -1)
    Phi2 = np.round((S @ eps) ** 2, 6)  # (n1,total)

    # class id per cut
    sig = {}
    classid = np.empty(total, dtype=np.int64)
    for j in range(total):
        key = Phi2[:, j].tobytes()
        cid = sig.get(key)
        if cid is None:
            cid = len(sig); sig[key] = cid
        classid[j] = cid
    csize = Counter(classid.tolist())
    class_size_of_cut = np.array([csize[classid[j]] for j in range(total)])

    # for each cut, which H_d are silent: realize flip, compare Phi2 column
    silent_count = np.zeros(total, dtype=np.int64)
    Nd = {}
    per_cut_silent = [[] for _ in range(total)]
    for d in ppd:
        mask = hs_masks[d]
        flip = np.where(mask[:, None], -1, 1).astype(np.int8)  # (n1,1)
        eps_f = eps * flip
        Phi2_f = np.round((S @ eps_f) ** 2, 6)
        same = np.all(np.abs(Phi2_f - Phi2) < 1e-4, axis=0)
        # exclude trivial (mask empty or flip == global which is quotiented): a real move must change eps
        changed = np.any(eps_f != eps, axis=0)
        sil = same & changed
        Nd[d] = int(sil.sum())
        silent_count += sil.astype(np.int64)
        for j in np.nonzero(sil)[0]:
            per_cut_silent[j].append(d)

    # test: class_size == 2^{silent_count} ?
    pred_size = 2 ** silent_count
    grouptest = bool(np.all(pred_size == class_size_of_cut))

    # joint counts: # cuts where exactly the set was silent (size>=2 means a combined move)
    a_by_s = Counter(silent_count.tolist())  # s -> #cuts
    # pairwise joint
    pair_joint = defaultdict(int)
    for j in range(total):
        ds = per_cut_silent[j]
        if len(ds) >= 2:
            for a in range(len(ds)):
                for b in range(a + 1, len(ds)):
                    pair_joint[(ds[a], ds[b])] += 1

    defic = total - len(sig)
    # formula deficiency from silent_count: sum (1 - 2^{-s})
    defic_formula = sum(c * (1 - 2.0 ** (-s)) for s, c in a_by_s.items())
    return dict(C=C, total=total, ppd=ppd, Nd=Nd, defic=defic,
                defic_formula=defic_formula, grouptest=grouptest,
                a_by_s=dict(a_by_s), pair_joint=dict(pair_joint),
                hist={int(s): int(c) for s, c in sorted(Counter(csize.values()).items())})


for C in [9, 15, 21, 25, 27, 33, 35, 39, 45, 49]:
    r = analyze(C)
    print(f"C={C} ({factor_str(C)}) total={r['total']} defic={r['defic']} "
          f"defic_formula={r['defic_formula']:.3f} GROUPTEST={r['grouptest']}")
    print(f"   prime-power divisors {r['ppd']}   N(H_d)={r['Nd']}")
    print(f"   class-size hist={r['hist']}   #cuts by s(silent count)={r['a_by_s']}")
    if r['pair_joint']:
        print(f"   pairwise joint (both silent) = {r['pair_joint']}")
    print(flush=True)
