    mR=meas(Rsafe); mQ=meas(Qlon); mB=meas(intersect(Rsafe,Qlon))
    baseline=mR*mQ; bf=float(baseline)
    SPEC_exact=float(mB-baseline)
    Rprime=float(mB/baseline) if baseline>0 else 1.0

    print("="*90)
    print(f"  ({label})  R={R}  Q={Q}")
    print(f"  baseline={bf:.6f}  SPEC={SPEC_exact:+.6f}  R'={Rprime:.5f}")
    print("="*90)
    # Verify representation-sum identity for chat at a few n=14N, and split diag/off.
    print(f"  VERIFY chat(14N) = representation sum; SPEC diag-diag vs rest (kmax={kmax}):")
    L1=0.0; SPEC_rep=0.0; SPEC_dd=0.0; maxerr=0.0; bad=0
    for N in range(1,Nres+1):
        n=14*N
        cn_exact=coeff_arcs(Rsafe,n)
        cn_rep,cn_diag,cn_off=rep_coeff(R,n,kmax=kmax)
        gn_exact=coeff_arcs(Qlon,n)
        gn_rep,gn_diag,gn_off=rep_coeff([14*m for m in Q], n, kmax=kmax)
        err_c=abs(cn_exact-cn_rep); err_g=abs(gn_exact-gn_rep)
        maxerr=max(maxerr,err_c,err_g)
        if err_c>5e-3 or err_g>5e-3: bad+=1
        term=2.0*(cn_exact*gn_exact.conjugate()).real
        SPEC_rep += term
        L1 += 2.0*abs(cn_exact)*abs(gn_exact)
        # diagonal-diagonal contribution to SPEC (both single-relation = divisor terms)
        SPEC_dd += 2.0*(cn_diag*gn_diag.conjugate()).real
