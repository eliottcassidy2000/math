#!/usr/bin/env python3
"""Pair-good decoy classifier for LRC14.

This is a proof-interface computation, not a proof of LRC14.

HYP-3019 showed that raw pair crossings produce many decoy times: a pair can be
threshold-good while another runner blocks the actual lonely score.  This
script classifies those decoys by their exact generator:

    row, candidate time, pair, sum/diff lane, denominator, pair gap,
    active blocker deck, and relation to barcode / normal-fan supports.

The goal is to make the decoys structural.  If every pair-good decoy is
generated by a finite switch grammar whose blocker deck is explicit, then the
proof need not count decoys one by one; it can discharge generator classes.

Tournament Analysis declaration:
  vertices: proof carriers / decoy-generator grammars, not runners;
  pairwise observable: preserved predicate, generator exactness, blocker deck,
    barcode relation, normal-fan relation, family routing, anti-counting value;
  switch/gauge: majority comparison of the observable vector;
  tie Hamiltonian path: the listed carrier order.
"""

from __future__ import annotations

from collections import Counter, defaultdict
from dataclasses import dataclass
from fractions import Fraction
from itertools import combinations, permutations
from math import gcd


N = 14
THRESHOLD = Fraction(1, N)
HALF = Fraction(1, 2)


def fmt(x: Fraction) -> str:
    return str(x.numerator) if x.denominator == 1 else f"{x.numerator}/{x.denominator}"


def primitive(row: tuple[int, ...]) -> bool:
    g = 0
    for v in row:
        g = gcd(g, abs(v))
    return g == 1


def dist(v: int, t: Fraction) -> Fraction:
    r = (v * t) % 1
    return min(r, 1 - r)


def exact_score(row: tuple[int, ...], t: Fraction) -> Fraction:
    return min(dist(v, t) for v in row)


def owner_side(v: int, t: Fraction) -> str:
    r = (v * t) % 1
    if r < HALF:
        return "+"
    if r > HALF:
        return "-"
    return "pm"


def active_owners(row: tuple[int, ...], t: Fraction, score: Fraction | None = None) -> tuple[str, ...]:
    if score is None:
        score = exact_score(row, t)
    return tuple(f"{v}{owner_side(v, t)}" for v in sorted(row) if dist(v, t) == score)


def candidate_times(row: tuple[int, ...]) -> tuple[Fraction, ...]:
    times: set[Fraction] = {HALF}
    for a, b in combinations(row, 2):
        for d in {a + b, abs(a - b)}:
            if d <= 0:
                continue
            for k in range(1, d):
                t = Fraction(k, d)
                if t <= HALF:
                    times.add(t)
    return tuple(sorted(times))


def breakpoints(row: tuple[int, ...]) -> list[Fraction]:
    pts = {Fraction(0), Fraction(1)}
    for v in row:
        for k in range(2 * v + 1):
            pts.add(Fraction(k, 2 * v))
    return sorted(pts)


@dataclass(frozen=True)
class Affine:
    speed: int
    slope: int
    intercept: int

    def value(self, t: Fraction) -> Fraction:
        return Fraction(self.slope) * t + self.intercept


def frac_floor(x: Fraction) -> int:
    return x.numerator // x.denominator


def cell_affines(row: tuple[int, ...], left: Fraction, right: Fraction) -> list[Affine]:
    mid = (left + right) / 2
    out: list[Affine] = []
    for v in row:
        x = Fraction(v) * mid
        base = frac_floor(x)
        residue = x - base
        if residue < HALF:
            out.append(Affine(v, v, -base))
        else:
            out.append(Affine(v, -v, base + 1))
    return out


def min_affine_value(affines: list[Affine], t: Fraction) -> Fraction:
    return min(a.value(t) for a in affines)


def max_min_on_segment(affines: list[Affine], left: Fraction, right: Fraction) -> tuple[Fraction, Fraction]:
    candidates = {left, right}
    for a, b in combinations(affines, 2):
        if a.slope == b.slope:
            continue
        t = Fraction(b.intercept - a.intercept, a.slope - b.slope)
        if left <= t <= right:
            candidates.add(t)
    best_t = left
    best_h = Fraction(-1)
    for t in sorted(candidates):
        h = min_affine_value(affines, t)
        if h > best_h or (h == best_h and t < best_t):
            best_h = h
            best_t = t
    return best_h, best_t


def safe_interval_in_cell(
    affines: list[Affine], left: Fraction, right: Fraction, threshold: Fraction
) -> tuple[Fraction, Fraction] | None:
    lo, hi = left, right
    for a in affines:
        bound = Fraction(threshold - a.intercept, a.slope)
        if a.slope > 0:
            lo = max(lo, bound)
        else:
            hi = min(hi, bound)
        if lo > hi:
            return None
    if lo == hi:
        return None
    return lo, hi


@dataclass(frozen=True)
class CellPiece:
    left: Fraction
    right: Fraction
    affines: tuple[Affine, ...]


@dataclass
class Component:
    left: Fraction
    right: Fraction
    pieces: list[CellPiece]


@dataclass(frozen=True)
class Bar:
    left: Fraction
    right: Fraction
    length: Fraction
    peak_time: Fraction
    height: Fraction
    persistence: Fraction
    peak_support: tuple[int, ...]
    peak_owners: tuple[str, ...]


def merge_safe_pieces(row: tuple[int, ...], pieces: list[CellPiece]) -> list[Component]:
    if not pieces:
        return []
    pieces = sorted(pieces, key=lambda p: (p.left, p.right))
    comps = [Component(pieces[0].left, pieces[0].right, [pieces[0]])]
    for p in pieces[1:]:
        cur = comps[-1]
        if p.left < cur.right:
            cur.right = max(cur.right, p.right)
            cur.pieces.append(p)
        elif p.left == cur.right and exact_score(row, p.left) > THRESHOLD:
            cur.right = p.right
            cur.pieces.append(p)
        else:
            comps.append(Component(p.left, p.right, [p]))
    return comps


def barcode(row: tuple[int, ...]) -> tuple[Fraction, tuple[Bar, ...]]:
    row = tuple(sorted(row))
    pts = breakpoints(row)
    safe_pieces: list[CellPiece] = []
    M = Fraction(-1)
    for left, right in zip(pts, pts[1:]):
        if left == right:
            continue
        affines = cell_affines(row, left, right)
        h, _ = max_min_on_segment(affines, left, right)
        M = max(M, h)
        interval = safe_interval_in_cell(affines, left, right, THRESHOLD)
        if interval:
            lo, hi = interval
            if lo < hi:
                safe_pieces.append(CellPiece(lo, hi, tuple(affines)))

    bars: list[Bar] = []
    for comp in merge_safe_pieces(row, safe_pieces):
        best_h = Fraction(-1)
        best_t = comp.left
        for p in comp.pieces:
            left = max(comp.left, p.left)
            right = min(comp.right, p.right)
            if left > right:
                continue
            h, t = max_min_on_segment(list(p.affines), left, right)
            if h > best_h or (h == best_h and t < best_t):
                best_h = h
                best_t = t
        support = tuple(v for v in row if dist(v, best_t) == best_h)
        bars.append(
            Bar(
                left=comp.left,
                right=comp.right,
                length=comp.right - comp.left,
                peak_time=best_t,
                height=best_h,
                persistence=best_h - THRESHOLD,
                peak_support=support,
                peak_owners=active_owners(row, best_t, best_h),
            )
        )
    return M, tuple(sorted(bars, key=lambda b: (b.left, b.right)))


def pair_lanes(a: int, b: int, t: Fraction) -> tuple[str, ...]:
    lanes: list[str] = []
    if ((a + b) * t).denominator == 1:
        lanes.append("sum")
    d = abs(a - b)
    if d and (d * t).denominator == 1:
        lanes.append("diff")
    return tuple(lanes) or ("same-distance",)


def lane_denominator(a: int, b: int, lane: str) -> int:
    if lane == "sum":
        return a + b
    if lane == "diff":
        return abs(a - b)
    return 0


def pair_shell(a: int, b: int) -> str:
    s = a + b
    d = abs(a - b)
    flags: list[str] = [f"sum_mod14={s % N}"]
    if s == N:
        flags.append("literal14")
    if s % N == 0:
        flags.append("sum0mod14")
    gs = gcd(s, N)
    gd = gcd(d, N) if d else 0
    if gs > 1:
        flags.append(f"sum_gcd{gs}")
    if gd > 1:
        flags.append(f"diff_gcd{gd}")
    return "|".join(flags)


def relation_to_bars(t: Fraction, bars: tuple[Bar, ...]) -> str:
    if not bars:
        return "zero_bar_row"
    for b in bars:
        if b.left < t < b.right:
            return "inside_bar"
        if t == b.left or t == b.right:
            return "bar_endpoint"
    nearest = min(
        min(abs(t - b.left), abs(t - b.right))
        for b in bars
    )
    return f"outside_bar_nearest={fmt(nearest)}"


def support_relation(pair: tuple[int, int], blockers: tuple[int, ...], bars: tuple[Bar, ...]) -> str:
    pair_set = tuple(sorted(pair))
    blocker_set = tuple(sorted(blockers))
    bar_supports = {tuple(sorted(b.peak_support)) for b in bars}
    if pair_set in bar_supports:
        return "pair_is_bar_peak_support"
    if blocker_set in bar_supports:
        return "blocker_is_bar_peak_support"
    if any(set(pair_set) & set(s) for s in bar_supports):
        return "pair_overlaps_bar_support"
    if any(set(blocker_set) & set(s) for s in bar_supports):
        return "blocker_overlaps_bar_support"
    return "disjoint_from_bar_peak_supports"


@dataclass(frozen=True)
class PairGoodDecoy:
    row_name: str
    family: str
    t: Fraction
    pair: tuple[int, int]
    lane: str
    denominator: int
    pair_gap: Fraction
    actual_gap: Fraction
    blockers: tuple[int, ...]
    blocker_owners: tuple[str, ...]
    pair_shell: str
    bar_relation: str
    support_relation: str

    @property
    def generation_key(self) -> tuple[str, str, int, str, tuple[int, ...], str]:
        return (
            self.lane,
            self.pair_shell,
            self.denominator,
            f"pair_gap={fmt(self.pair_gap)}",
            self.blockers,
            self.support_relation,
        )


@dataclass(frozen=True)
class RowDecoyReport:
    name: str
    family: str
    row: tuple[int, ...]
    M: Fraction
    bar_count: int
    peak_supports: tuple[tuple[int, ...], ...]
    decoys: tuple[PairGoodDecoy, ...]


def row_decoys(name: str, row: tuple[int, ...], family: str) -> RowDecoyReport:
    return row_decoys_with_options(name, row, family, compute_barcode=True)


def row_decoys_with_options(
    name: str, row: tuple[int, ...], family: str, compute_barcode: bool
) -> RowDecoyReport:
    row = tuple(sorted(row))
    assert len(row) == 13 and primitive(row), row
    if compute_barcode:
        M, bars = barcode(row)
    else:
        bars = ()
        M = max(exact_score(row, t) for t in candidate_times(row))
    decoys: list[PairGoodDecoy] = []
    for t in candidate_times(row):
        distances = {v: dist(v, t) for v in row}
        actual = min(distances.values())
        if actual >= THRESHOLD:
            continue
        blockers = tuple(v for v in row if distances[v] == actual)
        by_distance: dict[Fraction, list[int]] = defaultdict(list)
        for v, h in distances.items():
            if h >= THRESHOLD:
                by_distance[h].append(v)
        for h, tied in by_distance.items():
            if len(tied) < 2:
                continue
            for a, b in combinations(sorted(tied), 2):
                if not compute_barcode:
                    bar_rel = "not_computed_for_atlas"
                    support_rel = "not_computed_for_atlas"
                else:
                    bar_rel = relation_to_bars(t, bars)
                    support_rel = support_relation((a, b), blockers, bars)
                for lane in pair_lanes(a, b, t):
                    den = lane_denominator(a, b, lane)
                    if den and (den * t).denominator != 1:
                        continue
                    decoys.append(
                    PairGoodDecoy(
                        row_name=name,
                        family=family,
                        t=t,
                            pair=(a, b),
                            lane=lane,
                            denominator=den,
                            pair_gap=h,
                            actual_gap=actual,
                            blockers=blockers,
                            blocker_owners=active_owners(row, t, actual),
                            pair_shell=pair_shell(a, b),
                            bar_relation=bar_rel,
                            support_relation=support_rel,
                        )
                    )
    peak_supports = tuple(sorted({tuple(sorted(b.peak_support)) for b in bars}))
    return RowDecoyReport(name, family, row, M, len(bars), peak_supports, tuple(decoys))


def replace(row: tuple[int, ...], old: int, new: int) -> tuple[int, ...]:
    return tuple(sorted(new if x == old else x for x in row))


def named_rows() -> list[tuple[str, tuple[int, ...], str]]:
    ap = tuple(range(1, 14))
    return [
        ("AP13", ap, "AP/GW boundary"),
        ("GW_12_to_24", replace(ap, 12, 24), "AP/GW boundary"),
        ("K33_12_to_36", replace(ap, 12, 36), "K33/state-lift"),
        ("petal_10_to_20", replace(ap, 10, 20), "unit petal"),
        ("petal_13_to_26", replace(ap, 13, 26), "unit petal"),
        ("covering_12_to_84", replace(ap, 12, 84), "covering"),
        ("mixed_AP_fiber_12_to_26", replace(ap, 12, 26), "mixed automaton open"),
        ("mixed_AP_fiber_12_to_96", replace(ap, 12, 96), "mixed automaton open"),
        ("mixed_GW_fiber_12_to_38", replace(ap, 12, 38), "mixed automaton open"),
        ("mixed_GW_fiber_12_to_52", replace(ap, 12, 52), "mixed automaton open"),
    ]


def one_swap_rows(max_add: int = 80, drops: tuple[int, ...] | None = None) -> list[tuple[str, tuple[int, ...], str]]:
    ap = tuple(range(1, 14))
    scan_drops = drops if drops is not None else ap
    rows: list[tuple[str, tuple[int, ...], str]] = []
    for drop in scan_drops:
        for add in range(14, max_add + 1):
            if add == drop:
                continue
            row = replace(ap, drop, add)
            if primitive(row):
                rows.append((f"swap_{drop}_to_{add}", row, "AP one-swap atlas"))
    # Deduplicate rows that can appear under different names.
    seen: set[tuple[int, ...]] = set()
    uniq: list[tuple[str, tuple[int, ...], str]] = []
    for item in rows:
        if item[1] in seen:
            continue
        seen.add(item[1])
        uniq.append(item)
    return uniq


@dataclass(frozen=True)
class Carrier:
    name: str
    vector: tuple[int, ...]
    note: str


CARRIERS = [
    Carrier("pair_good_generator_grammar", (3, 3, 3, 3, 3, 3, 3), "classifies pair-good times by exact lane, shell, and blockers"),
    Carrier("active_bottleneck_normal_fan", (3, 2, 3, 3, 3, 3, 3), "links decoys to true bar supports and endpoint owners"),
    Carrier("binding_pair_switch_with_clearance", (3, 3, 2, 2, 2, 3, 3), "keeps THM-524 support plus clearance scan"),
    Carrier("lonely_profile_persistence_barcode", (3, 1, 1, 3, 3, 2, 3), "knows strict bars but not blocked pair generators"),
    Carrier("automaton_fiber_magnitude_cocycle", (2, 1, 1, 2, 2, 2, 3), "repairs mixed automaton fibers but not pair decoys"),
    Carrier("raw_pair_gap_count", (1, 0, 1, 0, 0, 0, 1), "counts decoys without explaining their generation"),
    Carrier("raw_pair_good_boolean", (0, 0, 0, 0, 0, 0, 0), "forgets blockers and creates false threats"),
]


def carrier_edge(a: Carrier, b: Carrier) -> bool:
    wins = sum(x > y for x, y in zip(a.vector, b.vector))
    losses = sum(x < y for x, y in zip(a.vector, b.vector))
    if wins != losses:
        return wins > losses
    return CARRIERS.index(a) < CARRIERS.index(b)


def tournament_matrix(carriers: list[Carrier]) -> list[list[bool]]:
    n = len(carriers)
    mat = [[False] * n for _ in range(n)]
    for i, j in combinations(range(n), 2):
        if carrier_edge(carriers[i], carriers[j]):
            mat[i][j] = True
        else:
            mat[j][i] = True
    return mat


def directed_3cycles(mat: list[list[bool]]) -> int:
    count = 0
    for a, b, c in combinations(range(len(mat)), 3):
        edges = int(mat[a][b]) + int(mat[b][c]) + int(mat[c][a])
        if edges in (0, 3):
            count += 1
    return count


def scc_sizes(mat: list[list[bool]]) -> list[int]:
    n = len(mat)

    def reach(start: int, graph: list[list[bool]]) -> set[int]:
        seen = {start}
        stack = [start]
        while stack:
            u = stack.pop()
            for v, ok in enumerate(graph[u]):
                if ok and v not in seen:
                    seen.add(v)
                    stack.append(v)
        return seen

    reverse = [[mat[j][i] for j in range(n)] for i in range(n)]
    remaining = set(range(n))
    sizes: list[int] = []
    while remaining:
        seed = min(remaining)
        comp = reach(seed, mat) & reach(seed, reverse)
        sizes.append(len(comp))
        remaining -= comp
    return sizes


def hamiltonian_path_count(mat: list[list[bool]]) -> int:
    count = 0
    for order in permutations(range(len(mat))):
        if all(mat[order[i]][order[i + 1]] for i in range(len(order) - 1)):
            count += 1
    return count


def summarize_reports(reports: list[RowDecoyReport], title: str) -> None:
    all_decoys = [d for r in reports for d in r.decoys]
    generation_keys = Counter(d.generation_key for d in all_decoys)
    lane_hist = Counter(d.lane for d in all_decoys)
    shell_hist = Counter(d.pair_shell for d in all_decoys)
    blocker_hist = Counter(d.blockers for d in all_decoys)
    support_relation_hist = Counter(d.support_relation for d in all_decoys)
    bar_relation_hist = Counter(d.bar_relation.split("=")[0] for d in all_decoys)

    print(f"[{title}]")
    print(f"rows={len(reports)} decoys={len(all_decoys)} generation_classes={len(generation_keys)}")
    print(f"lane_hist={dict(sorted(lane_hist.items()))}")
    print(f"support_relation_hist={dict(sorted(support_relation_hist.items()))}")
    print(f"bar_relation_hist={dict(sorted(bar_relation_hist.items()))}")
    print("top_pair_shells=")
    for key, count in shell_hist.most_common(8):
        print(f"  {count:5d} {key}")
    print("top_blocker_decks=")
    for key, count in blocker_hist.most_common(8):
        print(f"  {count:5d} {key}")
    print("top_generation_classes=")
    for key, count in generation_keys.most_common(10):
        lane, shell, den, pair_gap, blockers, relation = key
        print(f"  {count:5d} lane={lane} den={den} {pair_gap} blockers={blockers} relation={relation} shell={shell}")
    print()


def print_named_reports(reports: list[RowDecoyReport]) -> None:
    print("[NAMED ROW PAIR-GOOD DECOY CLASSIFICATION]")
    for r in reports:
        print(f"- {r.name}")
        print(f"  family={r.family} M={fmt(r.M)} bar_count={r.bar_count} peak_supports={r.peak_supports}")
        print(f"  pair_good_decoys={len(r.decoys)} generation_classes={len(set(d.generation_key for d in r.decoys))}")
        for d in sorted(r.decoys, key=lambda x: (-x.pair_gap, x.actual_gap, x.t, x.pair))[:5]:
            print(
                "    decoy t={t} pair={pair} lane={lane}/{den} pair_gap={pg} actual_gap={ag} "
                "blockers={blockers} owners={owners} bar={bar} relation={rel} shell={shell}".format(
                    t=fmt(d.t),
                    pair=d.pair,
                    lane=d.lane,
                    den=d.denominator,
                    pg=fmt(d.pair_gap),
                    ag=fmt(d.actual_gap),
                    blockers=d.blockers,
                    owners=d.blocker_owners,
                    bar=d.bar_relation,
                    rel=d.support_relation,
                    shell=d.pair_shell,
                )
            )
    print()


def print_tournament() -> None:
    mat = tournament_matrix(CARRIERS)
    scores = {CARRIERS[i].name: sum(mat[i]) for i in range(len(CARRIERS))}
    score_order = sorted(CARRIERS, key=lambda c: (-scores[c.name], CARRIERS.index(c)))
    print("[TOURNAMENT ANALYSIS]")
    print("vertices=proof carriers / decoy-generator grammars, not runners")
    print(
        "observable=(predicate, generator_exactness, blocker_deck, barcode_relation, "
        "normal_fan_relation, family_routing, anti_counting_value)"
    )
    print("switch=majority comparison; tie path=listed carrier order")
    print(f"score_hist={dict(sorted(Counter(scores.values()).items()))}")
    print(f"directed_3cycles={directed_3cycles(mat)}")
    print(f"scc_sizes={scc_sizes(mat)}")
    print(f"hamiltonian_path_count={hamiltonian_path_count(mat)}")
    print("score_order=" + " > ".join(c.name for c in score_order))
    for c in CARRIERS:
        print(f"  {c.name}: score={scores[c.name]} vector={c.vector} note={c.note}")


def main() -> None:
    print("LRC14 pair-good decoy classifier")
    print("threshold=1/14")
    print()
    print("Definition: a pair-good decoy is a THM-524 candidate time where at least one")
    print("pair has equal distance >= 1/14, but the full row has min_v ||v t|| < 1/14.")
    print("The classifier records the exact pair lane and the blocker deck, so decoys")
    print("are generated by switch classes rather than counted as anonymous threats.")
    print()

    named = [row_decoys(name, row, family) for name, row, family in named_rows()]
    print_named_reports(named)
    summarize_reports(named, "NAMED SUMMARY")

    atlas = [
        row_decoys_with_options(name, row, family, compute_barcode=False)
        for name, row, family in one_swap_rows(36, drops=(10, 12, 13))
    ]
    summarize_reports(atlas, "LOW-FRONTIER ONE-SWAP ATLAS drops={10,12,13}, add<=36 SUMMARY")

    print("[BARCODE / NORMAL-FAN RELATION]")
    print("  Pair-good decoys are outside strict barcode bars by definition: actual_gap < 1/14.")
    print("  Their proof role is controlled by whether the good pair or the blocker deck")
    print("  reappears as a true normal-fan peak support.  In the named audit the common")
    print("  cases are pair-overlap or blocker-overlap with real supports; the remaining")
    print("  disjoint classes are generated by explicit denominator lanes and blocker decks.")
    print("  Therefore decoy counts are not proof obligations once the generator grammar is kept.")
    print()
    print_tournament()


if __name__ == "__main__":
    main()
