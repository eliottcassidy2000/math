# The tournament-graph duality
print("="*60)
print("TOURNAMENT-GRAPH DUALITY")
print("="*60)
print()
print("TOURNAMENT (directed): Q = exp(2*arctanh)")
print("  Odd spectrum: 1, 1/3, 1/5, 1/7, ...")
print("  Functional equation: Q(x)*Q(-x) = 1")
print("  Even g_k determined by odd g_k")
print()
print("GRAPH (undirected): G = exp(-log(1-x^2)) = 1/(1-x^2)")
print("  Even spectrum: 1/2, 1/4, 1/6, 1/8, ...")
print("  Functional equation: G(x) = G(-x) (even function)")
print("  Odd coefficients are zero")
print()
print("NATURAL NUMBERS (full): N = Q^{1/2} * G^{1/2}")
print("  Full spectrum: 1, 1/2, 1/3, 1/4, ...")
print("  No functional equation constraint")
