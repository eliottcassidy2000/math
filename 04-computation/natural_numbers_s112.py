#!/usr/bin/env python3
"""natural_numbers_s112.py — What are the natural numbers?"""
from fractions import Fraction
from math import comb

print("THREE FUNDAMENTAL SERIES")
print("="*60)
print()
print("  ALL reciprocals: 1 + 1/2 + 1/3 + 1/4 + ... = -log(1-x)")
print("    exp -> 1/(1-x)")
print()
print("  ODD reciprocals: 1 + 1/3 + 1/5 + 1/7 + ... = arctanh(x)")
print("    exp(2*.) -> (1+x)/(1-x) = Q(x) [TOURNAMENT]")
print()
print("  EVEN reciprocals: 1/2 + 1/4 + 1/6 + ... = -(1/2)log(1-x^2)")
print("    exp(2*.) -> 1/(1-x^2) [GRAPH]")
print()
print("  KEY IDENTITY: -log(1-x) = arctanh(x) - (1/2)log(1-x^2)")
print("  => 1/(1-x) = sqrt(Q(x)) * sqrt(1/(1-x^2))")
print("  => 1/(1-x) = sqrt(Q(x)/(1-x^2)) = sqrt((1+x)/(1-x)^3)... hmm")
print()
print("  Actually: exp(-log(1-x)) = 1/(1-x)")
print("  exp(arctanh(x)) = sqrt((1+x)/(1-x))")
print("  exp(-(1/2)log(1-x^2)) = 1/sqrt(1-x^2)")
print("  Product: sqrt((1+x)/(1-x)) / sqrt(1-x^2)")
print("  = sqrt((1+x)/(1-x)) / sqrt((1-x)(1+x))")
print("  = 1/(1-x). CHECK!")
print()

# The m-th power comparison
print("="*60)
print("m-TH POWERS: TOURNAMENTS vs MULTISETS")
print("="*60)
print()
print("Tournament: Q^m  = ((1+x)/(1-x))^m = 1 + 2*sum g_k(m)*x^k")
print("Multiset:   S^m  = (1/(1-x))^m = sum C(m+k-1,k)*x^k")
print()
print("Q^m counts DIRECTED weighted matchings (Delannoy)")
print("S^m counts UNDIRECTED multisets (stars-and-bars)")
print()

for m in [3, 5]:
    print(f"m={m}:")
    for k in range(1, 8):
        qk = 2*sum(Fraction(comb(k-1,j-1)*comb(m,j))*2**(j-1)
                    for j in range(1, min(k,m)+1))
        sk = comb(m+k-1, k)
        ratio = Fraction(qk, sk)
        print(f"  k={k}: Q^m={qk:>6}, S^m={sk:>6}, Q/S={ratio}")
    print()

print("The ratio Q^m/S^m = the DIRECTED FRACTION of all orderings.")
print("As k grows: this ratio -> 2^k * k! / m^k (approximately)")
print("The directed content GROWS with interaction order k.")
print()

# The decomposition
print("="*60)
print("DECOMPOSITION: NATURAL = DIRECTED + UNDIRECTED")
print("="*60)
print()
print("(1/(1-x))^m = Q(x)^{m/2} * (1/(1-x^2))^{m/2}")
print()
print("In the tournament context:")
print("  FULL structure (1/(1-x)^m):")
print("    = ALL interactions at all scales")
print("    = directed + undirected together")
print()
print("  DIRECTED part (Q^{m/2}):")
print("    = interactions sensitive to ARC DIRECTION")
print("    = generated by ODD harmonics 1, 1/3, 1/5, ...")
print("    = the tournament-specific contribution")
print()
print("  UNDIRECTED part (1/(1-x^2))^{m/2}:")
print("    = interactions INSENSITIVE to direction")
print("    = generated by EVEN harmonics 1/2, 1/4, 1/6, ...")
print("    = the graph-like (symmetric) contribution")
print()

# What does this mean for the natural numbers?
print("="*60)
print("WHAT IS A NATURAL NUMBER?")
print("="*60)
print()
print("In our framework, 1/n is the weight of the n-th interaction scale:")
print()
for n in range(1, 13):
    parity = "ODD (directed, tournament)" if n % 2 == 1 else "EVEN (undirected, graph)"
    examples = {
        1: "pairwise comparison itself",
        2: "whether a unit step occurred (either direction)",
        3: "3-way directed consistency (triangle orientation)",
        4: "2 unit steps co-occurring (undirected pair)",
        5: "5-way directed cluster (pentagon interaction)",
        6: "3 unit steps or 2 triples (mixed undirected)",
        7: "7-way directed cluster",
        8: "4 unit steps or 2 quads",
    }
    desc = examples.get(n, "...")
    print(f"  n={n:2d}: weight 1/{n}, {parity}")
    if n <= 8:
        print(f"         meaning: {desc}")

print()
print("The NATURAL NUMBER n is the SCALE of the n-th interaction.")
print("Its reciprocal 1/n is the STRENGTH of that interaction.")
print()
print("The harmonic series sum 1/n diverges: CRITICALITY.")
print("All scales contribute; no scale is negligible.")
print()
print("The tournament selects only the ODD scales (1, 3, 5, 7, ...)")
print("because arc direction breaks the even symmetry.")
print()

