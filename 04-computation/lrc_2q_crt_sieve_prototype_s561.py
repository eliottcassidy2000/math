    # work per tuple: brute uses (q-1)^2 pairs * k runners, mod-2q ops;
    # tier1 uses (q-1)^2 pairs * (k-1) runners, mod-q ops. Report ratio of
    # (modulus * runners): proxy for inner-loop cost.
    brute_cost = (m) * k
    tier1_cost = (q) * (k - 1)
