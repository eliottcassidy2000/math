def build_n5():
    n = 5
    num_arcs = comb(n, 2)
    perms = list(permutations(range(n)))
    def adj(mask):
        A = [[0]*n for _ in range(n)]
        idx = 0
        for i in range(n):
            for j in range(i+1, n):
                if (mask >> idx) & 1: A[i][j] = 1
                else: A[j][i] = 1
                idx += 1
        return A
    def canon(A):
        best = None
        for p in perms:
            s = tuple(A[p[i]][p[j]] for i in range(n) for j in range(n))
            if best is None or s < best: best = s
        return best
    canon_map = {}; classes = []; t_class = [0]*(2**num_arcs)
    for mask in range(2**num_arcs):
        c = canon(adj(mask))
        if c not in canon_map:
            canon_map[c] = len(classes); classes.append(c)
        t_class[mask] = canon_map[c]
    nc = len(classes)
    sizes = [0]*nc
    for ci in t_class: sizes[ci] += 1
    F = np.zeros((nc, nc), dtype=int)
    for mask in range(2**num_arcs):
        ci = t_class[mask]
        for bit in range(num_arcs):
            F[ci][t_class[mask ^ (1 << bit)]] += 1
    T = np.zeros((nc, nc))
    for ci in range(nc):
        for cj in range(nc):
            T[ci][cj] = F[ci][cj] / (sizes[ci] * num_arcs)
    return T, nc

def matrix_exp(M, terms=30):
    result = np.eye(M.shape[0])
    power = np.eye(M.shape[0])
    for k in range(1, terms):
        power = power @ M / k
        result += power
        if np.max(np.abs(power)) < 1e-15:
            break
    return result

def matrix_exp_trace(M, terms=30):
    n = M.shape[0]
    result = float(n)
    power = np.eye(n)
    for k in range(1, terms):
        power = power @ M / k
        result += np.trace(power)
        if np.max(np.abs(power)) < 1e-15:
            break
    return result

