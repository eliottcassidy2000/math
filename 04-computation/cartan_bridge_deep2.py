# INVESTIGATION D: What DOES distinguish H classes within DRT?
# ============================================================

def investigate_H_discriminant(n=7):
    """
    If all regular n=7 tournaments have S_T^2 = -7I+J and the same
    eigenvalue spectrum {0, +/-i*sqrt(7)}, what distinguishes the three
    H classes (171, 175, 189)?

    Answer: the EIGENVECTOR structure must differ. The eigenspaces of S_T
    (3-dimensional eigenspace for +i*sqrt(7), 3-dim for -i*sqrt(7))
    have different orientations relative to the vertex basis.

    We can detect this via: higher cycle counts, the "signature" of
    the eigenvector matrix, or the commutant of S_T.
    """
    print("\n" + "=" * 70)
    print(f"INVESTIGATION D: WHAT DISTINGUISHES H CLASSES? (n={n})")
    print("=" * 70)

    m = n * (n - 1) // 2
    total = 1 << m

    by_H = defaultdict(list)

    for bits in range(total):
        A = binary_to_tournament(bits, n)
        scores = A.sum(axis=1)
        if not all(s == (n - 1) // 2 for s in scores):
            continue

        H = count_ham_paths(A)
        S = signed_adjacency(A).astype(float)

        # Higher cycle counts via traces of powers
        traces = []
        Sk = S.copy()
        for k in range(1, n + 1):
            traces.append(round(np.real(np.trace(Sk)), 4))
            Sk = Sk @ S

        # Count directed 3-cycles and 5-cycles
        c3 = 0
        c5 = 0
        for triple in combinations(range(n), 3):
            a, b, c = triple
            if A[a][b] and A[b][c] and A[c][a]:
                c3 += 1
            if A[a][c] and A[c][b] and A[b][a]:
                c3 += 1
        for quint in combinations(range(n), 5):
            for perm in permutations(quint[1:]):
                path = [quint[0]] + list(perm)
                is_cycle = True
                for k2 in range(5):
                    if not A[path[k2]][path[(k2 + 1) % 5]]:
                        is_cycle = False
                        break
                if is_cycle:
                    c5 += 1

        # Commutant dimension: dim of {X : XS = SX}
        # Build commutant equations: (S tensor I - I tensor S^T) vec(X) = 0
        S_kron = np.kron(S, np.eye(n)) - np.kron(np.eye(n), S.T)
        comm_dim = n * n - np.linalg.matrix_rank(S_kron, tol=0.01)

        by_H[H].append({
            'bits': bits, 'c3': c3, 'c5': c5,
            'traces': traces, 'comm_dim': comm_dim
        })

    print(f"\nH class characteristics:")
    print(f"  {'H':>5s} {'count':>6s} {'c3':>5s} {'c5':>5s} "
          f"{'comm_dim':>9s} {'tr(S^4)':>10s} {'tr(S^6)':>10s}")

    for H in sorted(by_H.keys()):
        group = by_H[H]
        rep = group[0]
        print(f"  {H:5d} {len(group):6d} {rep['c3']:5d} {rep['c5']:5d} "
              f"{rep['comm_dim']:9d} {rep['traces'][3]:10.1f} "
              f"{rep['traces'][5]:10.1f}")

    # Key: cycle counts should distinguish them
    print(f"\nCycle counts are the DISCRIMINANT between iso-spectral classes.")
    print(f"Since tr(S^k) is the same for all (same eigenvalues),")
    print(f"the distinction must come from the eigenvector structure,")
    print(f"which is captured by the non-trace invariants of S^k.")


