def investigate_distinguishing_power(n=7):
    """
    For regular n=7 tournaments, S_T^2 is the same for all.
    At what power k does S_T^k first distinguish the three H classes?

    The three classes have H = 171, 175, 189 (from our established results).
    """
    print("=" * 70)
    print(f"INVESTIGATION A: DISTINGUISHING POWER OF S_T^k (n={n})")
    print("=" * 70)

    m = n * (n - 1) // 2
    total = 1 << m

    # Collect regular tournaments grouped by H
    by_H = defaultdict(list)

    for bits in range(total):
        A = binary_to_tournament(bits, n)
        scores = sorted(A.sum(axis=1))
        if not all(s == (n - 1) // 2 for s in scores):
            continue
        H = count_ham_paths(A)
        S = signed_adjacency(A).astype(float)
        by_H[H].append(S)

    print(f"\nRegular tournament classes:")
    for H in sorted(by_H.keys()):
        print(f"  H={H}: {len(by_H[H])} tournaments")

    H_values = sorted(by_H.keys())

    # For each power k, check if trace(S^k) distinguishes the classes
    print(f"\nPower traces by H class:")
    print(f"  {'k':>3s}", end="")
    for H in H_values:
        print(f"  {'H=' + str(H):>12s}", end="")
    print(f"  {'distinct?':>10s}")

    for k in range(1, 2 * n + 1):
        traces = {}
        for H in H_values:
            S = by_H[H][0]  # representative
            Sk = np.linalg.matrix_power(S, k)
            traces[H] = round(np.real(np.trace(Sk)), 4)

        trace_vals = list(traces.values())
        is_distinct = len(set(trace_vals)) == len(trace_vals)
        print(f"  {k:3d}", end="")
        for H in H_values:
            print(f"  {traces[H]:12.1f}", end="")
        print(f"  {'YES' if is_distinct else 'no':>10s}")

    # Also check the FULL matrix S^k, not just trace
    print(f"\nFull matrix signature by H class (using sorted eigenvalues of S^k):")
    for k in [3, 4, 5, 6, 7]:
        sigs = {}
        for H in H_values:
            S = by_H[H][0]
            Sk = np.linalg.matrix_power(S, k)
            # Use sorted absolute values of eigenvalues as signature
            eigvals = sorted(np.abs(np.linalg.eigvals(Sk)))
            sigs[H] = tuple(round(e, 2) for e in eigvals)

        all_same = len(set(sigs.values())) == 1
        print(f"  k={k}: {'ALL SAME' if all_same else 'DIFFERENT'}")
        if not all_same:
            for H in H_values:
                print(f"    H={H}: {sigs[H]}")
            break

    # Check off-diagonal entries of S^k
    print(f"\nOff-diagonal uniqueness of S^k by H class:")
    for k in range(1, 2 * n + 1):
        off_diag_sigs = {}
        for H in H_values:
            S = by_H[H][0]
            Sk = np.linalg.matrix_power(S, k)
            # Sorted off-diagonal entries (as tuple)
            off = sorted(round(np.real(Sk[i][j]), 2)
                         for i in range(n) for j in range(n) if i != j)
            off_diag_sigs[H] = tuple(off)

        distinct = len(set(off_diag_sigs.values()))
        if distinct > 1:
            print(f"  k={k}: {distinct} distinct off-diagonal patterns "
                  f"-- FIRST DISTINCTION!")
            for H in H_values:
                vals = set(off_diag_sigs[H])
                print(f"    H={H}: unique off-diag values = {sorted(vals)}")
            break
        else:
            print(f"  k={k}: all same")


