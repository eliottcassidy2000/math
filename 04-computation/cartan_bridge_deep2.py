# INVESTIGATION C: Matrix algebra dimension of S_T
# ============================================================

def investigate_algebra_dimension(n=7):
    """
    The algebra Alg(S_T) = span{I, S_T, S_T^2, ...} has dimension
    equal to the degree of the minimal polynomial of S_T.

    For Paley T_7: min poly = x(x^2+7), degree 3, Alg dim = 3.
    For non-Paley regular: min poly might be different.

    The algebra dimension tells us the minimal information needed
    to reconstruct all of S_T's "directed structure."

    If dim(Alg(S_T)) = d, then d real numbers suffice to encode
    the tournament (up to the information preserved by powers).
    """
    print("\n" + "=" * 70)
    print(f"INVESTIGATION C: ALGEBRA DIMENSION OF S_T (n={n})")
    print("=" * 70)

    m = n * (n - 1) // 2
    total = 1 << m

    dim_by_H = defaultdict(list)
    minpoly_by_H = defaultdict(list)

    for bits in range(total):
        A = binary_to_tournament(bits, n)
        scores = sorted(A.sum(axis=1))
        if not all(s == (n - 1) // 2 for s in scores):
            continue

        H = count_ham_paths(A)
        S = signed_adjacency(A).astype(float)

        # Compute algebra dimension = rank of [I, S, S^2, ..., S^{n-1}]
        basis = []
        Sk = np.eye(n)
        for k in range(n):
            basis.append(Sk.flatten())
            Sk = Sk @ S

        basis_matrix = np.array(basis)
        rank = np.linalg.matrix_rank(basis_matrix, tol=0.01)
        dim_by_H[H].append(rank)

        # Minimal polynomial: find smallest k such that S^k is in span{I,...,S^{k-1}}
        for k in range(1, n + 1):
            test_basis = np.array([np.linalg.matrix_power(S, j).flatten()
                                   for j in range(k)])
            Sk_flat = np.linalg.matrix_power(S, k).flatten()
            # Check if S^k is in span of {I, S, ..., S^{k-1}}
            try:
                coeffs, res, rk, sv = np.linalg.lstsq(test_basis.T, Sk_flat, rcond=None)
                reconstruction = test_basis.T @ coeffs
                error = np.linalg.norm(Sk_flat - reconstruction)
                if error < 0.01:
                    minpoly_by_H[H].append(k)
                    break
            except:
                pass

    print(f"\nAlgebra dimension by H class:")
    for H in sorted(dim_by_H.keys()):
        dims = dim_by_H[H]
        dim_set = sorted(set(dims))
        print(f"  H={H}: dim(Alg(S_T)) = {dim_set} ({len(dims)} tournaments)")

    print(f"\nMinimal polynomial degree by H class:")
    for H in sorted(minpoly_by_H.keys()):
        degs = minpoly_by_H[H]
        deg_set = sorted(set(degs))
        print(f"  H={H}: min poly degree = {deg_set}")

    # For each H class, extract the minimal polynomial
    print(f"\nMinimal polynomial coefficients (representative per class):")
    for H in sorted(dim_by_H.keys()):
        # Get a representative
        found = False
        for bits in range(total):
            A = binary_to_tournament(bits, n)
            scores = sorted(A.sum(axis=1))
            if not all(s == (n - 1) // 2 for s in scores):
                continue
            if count_ham_paths(A) != H:
                continue

            S = signed_adjacency(A).astype(float)

            # Find minimal polynomial via Cayley-Hamilton
            # S satisfies char poly. Find all factors.
            char_poly = np.round(np.real(np.poly(S)), 2)
            eigvals = np.linalg.eigvals(S)

            print(f"\n  H={H}:")
            print(f"    Eigenvalues: ", end="")
            for ev in sorted(eigvals, key=lambda x: (abs(x), x.real)):
                if abs(ev.imag) < 0.001:
                    print(f"{ev.real:.3f}", end=" ")
                else:
                    print(f"({ev.real:.3f}+{ev.imag:.3f}i)", end=" ")
            print()
            print(f"    Char poly coefficients: {char_poly}")

            # Check if min poly is x(x^2+n) = x^3 + nx
            S3 = np.linalg.matrix_power(S, 3)
            check = S3 + n * S
            err = np.max(np.abs(check))
            print(f"    S^3 + {n}*S = 0? error = {err:.4f} "
                  f"({'YES' if err < 0.01 else 'NO'}")

            if err > 0.01:
                # Try other minimal polynomials
                # S^3 + a*S^2 + b*S + c*I = 0
                # Build system: each entry gives an equation
                # S^3[i,j] + a*S^2[i,j] + b*S[i,j] + c*I[i,j] = 0
                S2 = S @ S
                entries = []
                for i in range(n):
                    for j in range(n):
                        entries.append([S2[i,j], S[i,j],
                                       float(i == j), -S3[i,j]])
                entries = np.array(entries)
                try:
                    sol, _, _, _ = np.linalg.lstsq(entries[:, :3],
                                                    entries[:, 3], rcond=None)
                    a, b, c = sol
                    print(f"    Min poly: x^3 + {a:.2f}*x^2 + {b:.2f}*x + {c:.2f}")
                except:
                    print(f"    Could not find degree-3 min poly")

            found = True
            break


