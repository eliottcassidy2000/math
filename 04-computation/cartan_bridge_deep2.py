# INVESTIGATION E: The Cartan bridge for the attention algebra
# ============================================================

def investigate_attention_algebra():
    """
    For a transformer attention matrix A (continuous, row-stochastic),
    the matrix algebra generated by A_anti (the tournament part)
    has finite dimension. This dimension is the key quantity:

    - dim = 1: trivial attention (A_anti = 0, pure similarity)
    - dim = 2: binary attention (one eigenvalue pair)
    - dim = n: generic attention (all eigenvalues distinct)

    For TRAINED attention, we expect dim < n (structured attention).
    For RANDOM attention, we expect dim = n (generic).

    The "Cartan bridge complexity" = dim(Alg(A_anti)) / dim(Alg(A_sym))
    measures the relative complexity of directed vs undirected structure.
    """
    print("\n" + "=" * 70)
    print("INVESTIGATION E: ATTENTION ALGEBRA DIMENSIONS")
    print("=" * 70)

    np.random.seed(42)

    for n in [5, 7, 11]:
        print(f"\nn = {n}:")

        # Random attention
        dims_anti = []
        dims_sym = []
        for trial in range(100):
            logits = np.random.randn(n, n)
            exp_l = np.exp(logits - logits.max(axis=1, keepdims=True))
            A = exp_l / exp_l.sum(axis=1, keepdims=True)

            A_anti = (A - A.T) / 2
            A_sym = (A + A.T) / 2

            # Algebra dimension = number of distinct eigenvalues
            # (for diagonalizable matrices)
            eigvals_anti = np.linalg.eigvals(A_anti)
            eigvals_sym = np.linalg.eigvals(A_sym)

            # Count distinct eigenvalues (up to conjugation for complex)
            # Group by |lambda|
            mags_anti = sorted(set(round(abs(e), 4) for e in eigvals_anti))
            mags_sym = sorted(set(round(abs(e), 4) for e in eigvals_sym))

            dims_anti.append(len(mags_anti))
            dims_sym.append(len(mags_sym))

        print(f"  Random attention (100 trials):")
        print(f"    Anti spectral diversity: "
              f"mean={np.mean(dims_anti):.1f}, "
              f"range=[{min(dims_anti)}, {max(dims_anti)}]")
        print(f"    Sym spectral diversity:  "
              f"mean={np.mean(dims_sym):.1f}, "
              f"range=[{min(dims_sym)}, {max(dims_sym)}]")

        # Paley attention
        if n in [7, 11, 13] and all(n % i != 0 for i in range(2, int(n**0.5)+1)):
            qr = set()
            for k in range(1, n):
                qr.add((k * k) % n)
            A_paley = np.zeros((n, n))
            for i in range(n):
                for j in range(n):
                    if i != j and (j - i) % n in qr:
                        A_paley[i][j] = 1.0
            row_sums = A_paley.sum(axis=1, keepdims=True)
            A_paley = A_paley / np.maximum(row_sums, 1e-10)

            A_anti = (A_paley - A_paley.T) / 2
            A_sym = (A_paley + A_paley.T) / 2

            mags_anti = sorted(set(round(abs(e), 4)
                                   for e in np.linalg.eigvals(A_anti)))
            mags_sym = sorted(set(round(abs(e), 4)
                                  for e in np.linalg.eigvals(A_sym)))

            print(f"  Paley T_{n} attention:")
            print(f"    Anti spectral diversity: {len(mags_anti)} "
                  f"(values: {mags_anti})")
            print(f"    Sym spectral diversity:  {len(mags_sym)} "
                  f"(values: {mags_sym})")
            print(f"    Paley has MINIMAL spectral diversity = "
                  f"MAXIMAL symmetry")


