# INVESTIGATION B: Does S^2 universality hold at other n?
# ============================================================

def investigate_S2_universality():
    """
    Check if S_T^2 = -n*I + J for ALL regular tournaments at various n.

    For doubly regular tournaments: d = (n-3)/4 must be a non-negative integer.
    This requires n = 3 mod 4. So n = 3, 7, 11, 15, 19, 23, ...

    For n NOT = 3 mod 4: d is not an integer, so no DRT exists,
    and S_T^2 should vary among regular tournaments.
    """
    print("\n" + "=" * 70)
    print("INVESTIGATION B: S_T^2 UNIVERSALITY FOR REGULAR TOURNAMENTS")
    print("=" * 70)

    for n in [3, 5, 7, 9]:
        m = n * (n - 1) // 2
        total = 1 << m

        if total > 5000000:
            print(f"\nn={n}: too many tournaments ({total}), skipping")
            continue

        d_expected = (n - 3) / 4.0
        is_int = d_expected == int(d_expected)

        target = -n * np.eye(n) + np.ones((n, n))

        regular_count = 0
        drt_count = 0  # matches S^2 = -nI + J

        H_by_drt = {'yes': [], 'no': []}

        for bits in range(total):
            A = binary_to_tournament(bits, n)
            scores = A.sum(axis=1)
            if not all(s == (n - 1) // 2 for s in scores):
                continue

            regular_count += 1
            S = signed_adjacency(A).astype(float)
            S2 = S @ S

            if np.max(np.abs(S2 - target)) < 0.01:
                drt_count += 1
                H_by_drt['yes'].append(count_ham_paths(A))
            else:
                H_by_drt['no'].append(count_ham_paths(A))

        print(f"\nn={n}: d_expected = {d_expected} "
              f"({'integer' if is_int else 'NOT integer'})")
        print(f"  Regular tournaments: {regular_count}")
        print(f"  With S^2 = -nI+J (DRT): {drt_count} ({100*drt_count/max(regular_count,1):.1f}%)")

        if H_by_drt['yes']:
            print(f"  DRT H values: {sorted(set(H_by_drt['yes']))}")
        if H_by_drt['no']:
            print(f"  Non-DRT H values: {sorted(set(H_by_drt['no']))}")

        if regular_count == drt_count:
            print(f"  *** ALL regular n={n} tournaments are DRT! ***")
        elif drt_count == 0:
            print(f"  *** NO regular n={n} tournaments are DRT ***")


