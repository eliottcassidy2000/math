import numpy as np
from itertools import combinations, permutations
from collections import defaultdict


def binary_to_tournament(bits, n):
    A = np.zeros((n, n), dtype=int)
    pos = 0
    for i in range(n):
        for j in range(i+1, n):
            if bits & (1 << pos):
                A[i][j] = 1
            else:
                A[j][i] = 1
            pos += 1
    return A


def signed_adjacency(A):
    n = A.shape[0]
    S = np.zeros((n, n), dtype=int)
    for i in range(n):
        for j in range(n):
            if i != j:
                S[i][j] = 2 * A[i][j] - 1
    return S


def count_ham_paths(A):
    n = A.shape[0]
    dp = defaultdict(int)
    for v in range(n):
        dp[(1 << v, v)] = 1
    for mask in range(1, 1 << n):
        for v in range(n):
            if not (mask & (1 << v)):
                continue
            if dp[(mask, v)] == 0:
                continue
            for w in range(n):
                if mask & (1 << w):
                    continue
                if A[v][w]:
                    dp[(mask | (1 << w), w)] += dp[(mask, v)]
    full = (1 << n) - 1
    return sum(dp[(full, v)] for v in range(n))


def paley_tournament(p):
    qr = set()
    for k in range(1, p):
        qr.add((k * k) % p)
    A = np.zeros((p, p), dtype=int)
    for i in range(p):
        for j in range(p):
            if i != j and (j - i) % p in qr:
                A[i][j] = 1
    return A


