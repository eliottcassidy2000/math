# CLAIM 4: realizable set = multiplicative semigroup of strong-H atoms?
# ------------------------------------------------------------------
def claim4(R, strongH):
    print("\n" + "=" * 70)
    print("CLAIM 4: R_n as multiplicative closure of strong-tournament H atoms")
    print("=" * 70)
    # atoms: strong-tournament H-values for m=1..7.
    # m=1 (single vertex) is strong by convention, H=1 -> multiplicative identity.
    # build atom list with their vertex sizes
    atoms = {1: {1}}            # m=1 -> H=1
    # m=2 is NOT strong (no strong tournament on 2 vertices); skip
    for m in range(3, 8):
        atoms[m] = set(strongH[m])
    print("  Strong-H atom sets:")
    for m in sorted(atoms):
        print(f"    m={m}: {sorted(atoms[m])}")

    # multiplicative closure: products of strong-H values where the TOTAL vertex
    # count (sum of m's) <= N. A tournament on n vertices decomposes uniquely into
    # strong components in a transitive order (condensation is transitive), and H
    # is multiplicative over them (Claim 1). So R_n should equal the set of products
    # h_{m1}*...*h_{mk} with m1+...+mk = n, each h_{mi} a strong-H value on mi verts
    # (mi=1 contributes factor 1; mi>=3 contributes a strong-H atom; mi=2 impossible
    #  as a strong component).
    def closure_for_n(N):
        # dp over vertex budget: reachable[v] = set of products achievable using
        # strong components summing to exactly v
        reach = {0: {1}}
        for v in range(1, N + 1):
            s = set()
            # last strong component has size c (c=1, or c>=3)
            for c in list([1]) + list(range(3, v + 1)):
                if c not in atoms:
                    continue
                if (v - c) in reach:
                    for p in reach[v - c]:
                        for a in atoms[c]:
                            s.add(p * a)
            if s:
                reach[v] = s
        return reach.get(N, set())

    print("\n  Compare closure(n) vs R_n for n=3..7 (sanity, should match exactly):")
    for n in range(3, 8):
        cl = closure_for_n(n)
        print(f"    n={n}: closure==R_n ? {cl==R[n]}   "
              f"(closure {sorted(cl)[:12]}{'...' if len(cl)>12 else ''})")

    # Now the real test: R_8 interior via closure (we cannot easily gentourng n=8
    # iso classes = 6880, but we CAN: 6880 is fine. Let's actually compute R_8 directly
    # too for a hard check, plus closure.)
    print("\n  Building R_8 directly via gentourng (6880 classes) ...")
    R8 = set()
    cnt = 0
    for beats in gen_iso_tournaments(8):
        R8.add(H_dp(beats))
        cnt += 1
    print(f"    enumerated {cnt} classes; R_8 = {sorted(R8)}")
    cl8 = closure_for_n(8)
    print(f"    closure(8) = {sorted(cl8)}")
    print(f"    closure(8) == R_8 ? {cl8 == R8}")
    if cl8 != R8:
        print(f"      in R_8 not in closure: {sorted(R8 - cl8)}")
        print(f"      in closure not in R_8: {sorted(cl8 - R8)}")

    # permanent gaps: which odd numbers never appear?
    # Gather all realizable up to n=8
    allR = set()
    for n in R:
        allR |= R[n]
    allR |= R8
    maxv = max(allR)
    odd_gaps = sorted(set(range(1, maxv + 1, 2)) - allR)
    print(f"\n  All realizable H up to n=8: {sorted(allR)}")
    print(f"  Max realizable (n<=8): {maxv}")
    print(f"  Odd gaps below max (n<=8): {odd_gaps}")
    print(f"  Are 7 and 21 the only gaps that look permanent? "
          f"{set([g for g in odd_gaps if g<=21])}")
    return R8, cl8


