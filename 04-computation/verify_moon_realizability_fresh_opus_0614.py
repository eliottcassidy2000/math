import sys, subprocess, itertools
from math import comb

GEN = "/opt/homebrew/bin/gentourng"


# ------------------------------------------------------------------
# gentourng decoding (independent implementation)
# ------------------------------------------------------------------
def gen_iso_tournaments(n, strong_only=False):
    """Yield 'beats' adjacency as list of int bitmasks: beats[i] has bit j set if i->j.
    Decoded from gentourng default ascii upper-triangle row-by-row output."""
    args = [GEN]
    if strong_only:
        args.append("-c")
    args.append(str(n))
    out = subprocess.run(args, capture_output=True, text=True)
    pairs = list(itertools.combinations(range(n), 2))   # (0,1),(0,2),...,(0,n-1),(1,2),...
    L = len(pairs)
    for line in out.stdout.split():
        bits = line.strip()
        if len(bits) != L:
            continue
        beats = [0] * n
        for (i, j), b in zip(pairs, bits):
            if b == '1':
                beats[i] |= (1 << j)   # i -> j
            else:
                beats[j] |= (1 << i)   # j -> i
        yield beats


# ------------------------------------------------------------------
# Hamiltonian path counter -- METHOD A: brute force over permutations
# ------------------------------------------------------------------
def H_bruteforce(beats):
    n = len(beats)
    cnt = 0
    for perm in itertools.permutations(range(n)):
        ok = True
        for a in range(n - 1):
            u, v = perm[a], perm[a + 1]
            if not (beats[u] >> v) & 1:   # need arc u->v
                ok = False
                break
        if ok:
            cnt += 1
    return cnt


# ------------------------------------------------------------------
# Hamiltonian path counter -- METHOD B: bitmask DP (independent code)
# count directed Ham paths in a tournament = sum over all (start,end) of paths
# dp[mask][v] = number of directed paths covering exactly vertices in mask, ending at v.
# ------------------------------------------------------------------
def H_dp(beats):
    n = len(beats)
    full = (1 << n) - 1
    # incoming[v] = bitmask of u with u->v
    incoming = [0] * n
    for u in range(n):
        bm = beats[u]
        v = 0
        while bm:
            if bm & 1:
                incoming[v] |= (1 << u)
            bm >>= 1
            v += 1
    dp = [[0] * n for _ in range(1 << n)]
    for v in range(n):
        dp[1 << v][v] = 1
    for mask in range(1, 1 << n):
        row = dp[mask]
        for v in range(n):
            if not (mask >> v) & 1:
                continue
            cv = row[v]
            if cv == 0:
                continue
            # extend by w with v->w (w not in mask)
            succ = beats[v] & ~mask & full
            w = 0
            s = succ
            while s:
                if s & 1:
                    dp[mask | (1 << w)][w] += cv
                s >>= 1
                w += 1
    return sum(dp[full])


# ------------------------------------------------------------------
# Dominance join T1 => T2 (every vertex of T1 beats every vertex of T2)
# ------------------------------------------------------------------
def dominance_join(beats1, beats2):
    n1, n2 = len(beats1), len(beats2)
    n = n1 + n2
    beats = [0] * n
    # T1 vertices 0..n1-1 keep their internal arcs
    for i in range(n1):
        beats[i] = beats1[i]
    # T2 vertices shifted by n1
    for i in range(n2):
        bm = beats2[i]
        shifted = 0
        v = 0
        while bm:
            if bm & 1:
                shifted |= (1 << (v + n1))
            bm >>= 1
            v += 1
        beats[n1 + i] = shifted
    # every T1 vertex beats every T2 vertex
    t2mask = 0
    for j in range(n1, n):
        t2mask |= (1 << j)
    for i in range(n1):
        beats[i] |= t2mask
    return beats


