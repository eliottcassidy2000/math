# CLAIM 3: strong-tournament minimum H = 3,5,9,15,23 ; formula m^2-5m+9
# ------------------------------------------------------------------
def claim3():
    print("\n" + "=" * 70)
    print("CLAIM 3: strong-tournament min H per m, formula m^2-5m+9")
    print("=" * 70)
    minH = {}
    strongH = {}
    for m in range(3, 8):
        vals = set()
        for beats in gen_iso_tournaments(m, strong_only=True):
            vals.add(H_dp(beats))
        strongH[m] = vals
        minH[m] = min(vals)
        formula = m * m - 5 * m + 9
        print(f"  m={m}: minH={minH[m]:>4}  formula(m^2-5m+9)={formula:>4}  "
              f"{'OK' if minH[m]==formula else 'MISMATCH'}   strongH set={sorted(vals)}")
    seq = [minH[m] for m in range(3, 8)]
    print(f"  minH sequence m=3..7: {seq}  expected [3,5,9,15,23]? {seq==[3,5,9,15,23]}")
    return strongH


