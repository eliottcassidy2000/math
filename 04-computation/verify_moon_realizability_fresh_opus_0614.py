# CLAIM 2: Realizable sets, gaps, 7/21 forbidden, 49 realizable
# ------------------------------------------------------------------
def claim2():
    print("\n" + "=" * 70)
    print("CLAIM 2: Realizable sets R_n, gaps, 7/21 forbidden, 49 realizable")
    print("=" * 70)
    R = {}
    for n in range(1, 8):
        vals = set()
        if n <= 2:
            vals.add(H_dp(trivial(n)) if n >= 1 else 0)
            # n=1 -> 1 path (single vertex), n=2 -> 1 path
        else:
            for beats in gen_iso_tournaments(n):
                vals.add(H_dp(beats))
        R[n] = vals
        print(f"  R_{n} = {sorted(vals)}")
    print()
    print(f"  R_5 == {{1,3,5,9,11,13,15}} ? {sorted(R[5]) == [1,3,5,9,11,13,15]}")
    # 7 only odd gap below 15 in R_5
    odds_below_15 = set(range(1, 16, 2))
    gaps5 = sorted(odds_below_15 - R[5])
    print(f"  odd gaps below 15 in R_5: {gaps5}  (7 only? {gaps5==[7]})")
    # 7 and 21 not realizable at any n<=7
    seven_any = any(7 in R[n] for n in R)
    twentyone_any = any(21 in R[n] for n in R)
    print(f"  7 realizable at any n<=7? {seven_any}")
    print(f"  21 realizable at any n<=7? {twentyone_any}")
    # 49 realizable at n=7
    print(f"  49 in R_7? {49 in R[7]}")
    # is 49 a strong-tournament H value directly?
    strongH7 = set()
    for beats in gen_iso_tournaments(7, strong_only=True):
        strongH7.add(H_dp(beats))
    print(f"  49 a STRONG-tournament H value at n=7 (not a product)? {49 in strongH7}")
    return R


