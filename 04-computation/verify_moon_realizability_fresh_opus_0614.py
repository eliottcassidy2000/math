# CLAIM 1: Moon multiplicativity
# ------------------------------------------------------------------
def claim1():
    print("=" * 70)
    print("CLAIM 1: MOON multiplicativity H(T1=>T2)=H(T1)H(T2)")
    print("=" * 70)
    # cross-check the two counters on all iso tournaments n=3..6 first
    print("\n[1a] Cross-check brute-force vs DP counter, all iso classes n=3..6:")
    mismatch = 0
    for n in range(3, 7):
        for beats in gen_iso_tournaments(n):
            hb = H_bruteforce(beats) if n <= 7 else None
            hd = H_dp(beats)
            if hb is not None and hb != hd:
                mismatch += 1
                print(f"  MISMATCH n={n}: brute={hb} dp={hd}")
        print(f"  n={n}: OK (both counters agree on all {sum(1 for _ in gen_iso_tournaments(n))} classes)")
    print(f"  total mismatches: {mismatch}")

    # Now multiplicativity: take ALL iso classes T1 of size a, T2 of size b,
    # form join, check H(join)==H(T1)*H(T2). Use a,b up to total <=7.
    print("\n[1b] H(T1=>T2)=H(T1)*H(T2) over iso classes, |T1|+|T2|<=7:")
    fails = 0
    tested = 0
    for a in range(1, 7):
        for b in range(1, 7):
            if a + b > 7:
                continue
            T1s = list(gen_iso_tournaments(a)) if a >= 3 else [trivial(a)]
            T2s = list(gen_iso_tournaments(b)) if b >= 3 else [trivial(b)]
            for beats1 in T1s:
                for beats2 in T2s:
                    h1 = H_dp(beats1)
                    h2 = H_dp(beats2)
                    j = dominance_join(beats1, beats2)
                    hj = H_dp(j)
                    tested += 1
                    if hj != h1 * h2:
                        fails += 1
                        print(f"  FAIL a={a} b={b}: H1={h1} H2={h2} prod={h1*h2} Hjoin={hj}")
    print(f"  tested {tested} join pairs, failures: {fails}")

    # explicit examples
    print("\n[1c] Explicit examples:")
    examples = []
    c3 = list(gen_iso_tournaments(3))   # cyclic (H=3) and transitive (H=1)
    for beats in c3:
        examples.append((3, beats, H_dp(beats)))
    # pick the 3-cycle (H=3) and transitive (H=1)
    cyc3 = [b for _, b, h in examples if h == 3][0]
    tr3 = [b for _, b, h in examples if h == 1][0]
    for (name1, t1, h1), (name2, t2, h2) in [
        (("C3", cyc3, 3), ("C3", cyc3, 3)),
        (("C3", cyc3, 3), ("Tr3", tr3, 1)),
        (("Tr3", tr3, 1), ("C3", cyc3, 3)),
    ]:
        j = dominance_join(t1, t2)
        hj = H_dp(j)
        print(f"  H({name1}=>{name2}) = {hj}, H1*H2 = {h1*h2}  {'OK' if hj==h1*h2 else 'FAIL'}")
    return fails == 0 and mismatch == 0


def trivial(a):
    """trivial/transitive tournament on a vertices as beats list (i beats j iff i<j gives a path);
    for a=1 single vertex, a=2 single arc."""
    beats = [0] * a
    for i in range(a):
        for j in range(i + 1, a):
            beats[i] |= (1 << j)
    return beats


