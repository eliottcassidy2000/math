#!/usr/bin/env python3
"""Exact target-degree-three one-bracket gate for THM-3686.

For the ``y=0`` target subalgebra generated by A,B,C, enumerate every
nonconstant target monomial of total target degree at most N (N=2,3).  Put
arbitrary coefficients on two such target polynomials P,Q and compute the
coefficient ideal of ``{P,Q}-1`` in Q[x,z].  A reduced Groebner basis [1]
proves that no Darboux pair exists in the stated finite universe.

The independent linear-wedge rank is a positive control: one already lies
in the linear span of pairwise brackets for N=3, so the Groebner obstruction
detects failure of decomposability as one bracket, not failure of additive
span.
"""

from __future__ import annotations

from itertools import combinations

import sympy as sp


def require(condition: bool, detail: object) -> None:
    if not condition:
        raise RuntimeError(detail)


def bracket(first: sp.Expr, second: sp.Expr, x: sp.Symbol, z: sp.Symbol) -> sp.Expr:
    return sp.expand(sp.diff(first, x) * sp.diff(second, z) - sp.diff(first, z) * sp.diff(second, x))


def coefficient_matrix(polynomials: list[sp.Expr], x: sp.Symbol, z: sp.Symbol) -> tuple[sp.Matrix, tuple[tuple[int, int], ...]]:
    supports = sorted(
        {
            monomial
            for polynomial in polynomials
            for monomial, _coefficient in sp.Poly(polynomial, x, z).terms()
        }
    )
    matrix = sp.Matrix(
        [
            [sp.Poly(polynomial, x, z).coeff_monomial(x**power_x * z**power_z) for polynomial in polynomials]
            for power_x, power_z in supports
        ]
    )
    return matrix, tuple(supports)


def target_basis(
    maximum_degree: int,
    A: sp.Expr,
    B: sp.Expr,
    C: sp.Expr,
    x: sp.Symbol,
    z: sp.Symbol,
) -> tuple[tuple[tuple[int, int, int], ...], list[sp.Expr]]:
    labels: list[tuple[int, int, int]] = []
    pullbacks: list[sp.Expr] = []
    for total_degree in range(1, maximum_degree + 1):
        for power_a in range(total_degree + 1):
            for power_b in range(total_degree - power_a + 1):
                power_c = total_degree - power_a - power_b
                labels.append((power_a, power_b, power_c))
                pullbacks.append(sp.expand(A**power_a * B**power_b * C**power_c))
    matrix, _support = coefficient_matrix(pullbacks, x, z)
    pivots = matrix.rref()[1]
    independent_labels = tuple(labels[index] for index in pivots)
    independent_pullbacks = [pullbacks[index] for index in pivots]
    return independent_labels, independent_pullbacks


def run_gate(maximum_degree: int, A: sp.Expr, B: sp.Expr, C: sp.Expr, x: sp.Symbol, z: sp.Symbol) -> tuple[object, ...]:
    labels, monomials = target_basis(maximum_degree, A, B, C, x, z)
    expected_dimension = sp.binomial(maximum_degree + 3, 3) - 1
    require(len(monomials) == expected_dimension, ("unexpected target dependence", maximum_degree, len(monomials), expected_dimension))

    number = len(monomials)
    first_coefficients = sp.symbols(f"a0:{number}")
    second_coefficients = sp.symbols(f"b0:{number}")
    first = sum(coefficient * monomial for coefficient, monomial in zip(first_coefficients, monomials))
    second = sum(coefficient * monomial for coefficient, monomial in zip(second_coefficients, monomials))
    error = sp.Poly(bracket(first, second, x, z) - 1, x, z)
    equations = error.coeffs()

    variables = (*first_coefficients, *second_coefficients)
    basis = sp.groebner(equations, *variables, order="grevlex")
    require(list(basis) == [1], ("one-bracket ideal was not unit", maximum_degree, list(basis)[:5]))

    wedge_polynomials = [bracket(monomials[left], monomials[right], x, z) for left, right in combinations(range(number), 2)]
    wedge_matrix, wedge_support = coefficient_matrix([*wedge_polynomials, sp.Integer(1)], x, z)
    linear_matrix = wedge_matrix[:, :-1]
    augmented_matrix = wedge_matrix
    linear_rank = linear_matrix.rank()
    augmented_rank = augmented_matrix.rank()
    if maximum_degree == 3:
        require((linear_rank, augmented_rank) == (75, 75), ("linear-span control", linear_rank, augmented_rank))
    else:
        require((linear_rank, augmented_rank) == (26, 27), ("degree-two negative control", linear_rank, augmented_rank))

    wedge_count = len(wedge_polynomials)
    return (
        maximum_degree,
        number,
        len(equations),
        len(variables),
        tuple(basis),
        len(wedge_support),
        wedge_count,
        linear_rank,
        augmented_rank,
        wedge_count - linear_rank,
        labels,
    )


def main() -> None:
    x, z = sp.symbols("x z")
    t = x**2 * z
    A = sp.expand(3 * z * (2 - t))
    B = sp.expand(2 * x * z * (2 - t))
    C = sp.expand(x * (1 - t))

    rows = [run_gate(maximum_degree, A, B, C, x, z) for maximum_degree in (2, 3)]

    print("theorem=THM-3686-y0-target-degree3-one-bracket-no-go")
    print(f"sympy_version={sp.__version__}")
    print("universe=P,Q_are_arbitrary_C-linear_combinations_of_nonconstant_A^iB^jC^k_with_i+j+k<=N;constants_irrelevant")
    for row in rows:
        degree, number, equation_count, variable_count, basis, support_size, wedge_count, rank, augmented_rank, nullity, labels = row
        print(
            f"N={degree};target_basis={number};coefficient_variables={variable_count};"
            f"xz_equations={equation_count};groebner={basis};wedge_support={support_size};"
            f"wedge_columns={wedge_count};wedge_rank={rank};augmented_rank={augmented_rank};wedge_nullity={nullity}"
        )
        print(f"N={degree};labels={labels}")
    print("consequence=no_single_bracket_equals_1_through_total_target_degree_3")
    print("linear_controls=N2_absent_from_bracket_span;N3_present_in_bracket_span_but_not_as_one_decomposable_wedge")
    print("scope=finite_exact_target_degree_gate;arbitrary_mixed_weight_one_bracket_remains_open")
    print("commands=python3 -B 04-computation/jacobian_y0_target_degree3_one_bracket_no_go_thm3686.py;python3 -B -O 04-computation/jacobian_y0_target_degree3_one_bracket_no_go_thm3686.py")


if __name__ == "__main__":
    main()
