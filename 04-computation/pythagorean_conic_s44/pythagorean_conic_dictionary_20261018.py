def kuratowski_views(d):
    """Search equivariant identifications for (a) Petersen - P ~ K3,3 and (b) Petersen / M ~ K5."""
    p, pts, conic, inte, Gi, group, idx = d['p'], d['pts'], d['conic'], d['inte'], d['Gi'], d['group'], d['idx']
    duad, edge_to_ext = d['duad'], d['edge_to_ext']
    # perfect matchings of Petersen
    edges = list(Gi.edges())
    pms = []
    for comb in itertools.combinations(edges, 5):
        vs = set()
        for e in comb:
            vs |= set(e)
        if len(vs) == 10:
            pms.append(frozenset(frozenset(e) for e in comb))
    assert len(pms) == 6
    def act(g, v):
        return pts[g[idx[v]]]
    # (b) matching -> conic point with equal stabilizers
    def stab_point(x):
        return frozenset(g for g in group if act(g, x) == x)
    def stab_pm(M):
        return frozenset(g for g in group if frozenset(frozenset(act(g, v) for v in e) for e in M) == M)
    match_to_point = {}
    for M in pms:
        s = stab_pm(M)
        cands = [x for x in conic if stab_point(x) == s]
        assert len(cands) == 1, cands
        match_to_point[M] = cands[0]
    # duads of the matching edges
    report_b = []
    for M, x in match_to_point.items():
        ds = [duad[edge_to_ext[e]] for e in M]
        contains_x = sum(1 for dd in ds if x in dd)
        # contract M and identify vertices of K5 with the 5 matching edges
        H = nx.contracted_nodes  # unused, explicit construction below
        rep = {}
        for e in M:
            for v in e:
                rep[v] = e
        K = nx.Graph()
        K.add_nodes_from(M)
        for u, v in Gi.edges():
            if frozenset((u, v)) not in M:
                K.add_edge(rep[u], rep[v])
        isK5 = nx.is_isomorphic(K, nx.complete_graph(5)) and K.number_of_edges() == 10
        # label K5 vertices by conic points: the matching edge e has duad duad[edge_to_ext[e]]
        lab = {e: duad[edge_to_ext[e]] for e in M}
        # relation between a non-matching edge f=(u,v) and the labels of the two K5 vertices it joins
        rel = Counter()
        for u, v in Gi.edges():
            f = frozenset((u, v))
            if f in M:
                continue
            df = duad[edge_to_ext[f]]
            a, b = lab[rep[u]], lab[rep[v]]
            rel[(len(df & a), len(df & b), len(a & b), x in df)] += 1
        report_b.append({'matching_edges_whose_duad_contains_x': contains_x, 'contraction_is_K5': isK5,
                         'relation_hist': {str(k): v for k, v in rel.items()}})
    print(f"[p=5 Kuratowski b] 6 perfect matchings <-> 6 conic points (equal stabilizers, order "
          f"{len(stab_point(conic[0]))}); per matching: " + str([r['matching_edges_whose_duad_contains_x'] for r in report_b])
          + f"; contractions are K5: {all(r['contraction_is_K5'] for r in report_b)}")
    print(f"   relation histogram (|d(f)&a|,|d(f)&b|,|a&b|, x in d(f)) for matching 0: {report_b[0]['relation_hist']}")
    # (a) delete interior point P -> subdivided K3,3 on the 6 distance-2 vertices
    report_a = []
    for P in inte:
        dist = nx.single_source_shortest_path_length(Gi, P)
        far = [v for v in inte if dist[v] == 2]
        nb = [v for v in inte if dist[v] == 1]
        # K3,3: far vertices, edges = edges among far + suppressed paths through neighbours
        K = nx.Graph()
        K.add_nodes_from(far)
        for u, v in Gi.subgraph(far).edges():
            K.add_edge(u, v)
        for N in nb:
            ends = [w for w in Gi[N] if w != P]
            K.add_edge(*ends)
        isK33 = nx.is_isomorphic(K, nx.complete_bipartite_graph(3, 3))
        sides = nx.bipartite.sets(K)
        # stabilizer of P acting on far vertices and on conic points: search equivariant bijections
        stabP = [g for g in group if act(g, P) == P]
        def orbit_sig(objs, actf):
            return sorted(len([g for g in stabP if actf(g, o) == o]) for o in objs)
        sig_far = orbit_sig(far, act)
        sig_con = orbit_sig(conic, act)
        bij_ok = []
        for perm in itertools.permutations(conic):
            phi = dict(zip(far, perm))
            if all(phi[act(g, f)] == act(g, phi[f]) for g in stabP for f in far):
                bij_ok.append(phi)
        split_from_K = None
        splits = []
        for phi in bij_ok:
            s0 = frozenset(phi[v] for v in sides[0])
            s1 = frozenset(phi[v] for v in sides[1])
            splits.append(frozenset((s0, s1)))
        # canonical split of P: the 3+3 split of conic points with the same stabilizer as P
        stabP_set = frozenset(stabP)
        canon = []
        for T in itertools.combinations(conic, 3):
            T = frozenset(T)
            Tc = frozenset(conic) - T
            spl = frozenset((T, Tc))
            st = frozenset(g for g in group if frozenset((frozenset(act(g, x) for x in T),
                                                           frozenset(act(g, x) for x in Tc))) == spl)
            if st == stabP_set:
                canon.append(spl)
        canon = list(set(canon))
        report_a.append({'isK33': isK33, 'equivariant_bijections': len(bij_ok), 'sig_far': sig_far, 'sig_conic': sig_con,
                         'canonical_splits': len(canon),
                         'K33_bipartition_maps_to_canonical_split': [s in canon for s in splits]})
    r0 = report_a[0]
    print(f"[p=5 Kuratowski a] Petersen - P suppressed is K3,3 for all P: {all(r['isK33'] for r in report_a)}; "
          f"Stab(P) orbit signatures far {r0['sig_far']} conic {r0['sig_conic']}; equivariant bijections far->conic: "
          f"{r0['equivariant_bijections']}; canonical splits per P: {r0['canonical_splits']}; bipartition -> canonical split: "
          f"{r0['K33_bipartition_maps_to_canonical_split']}")
    OUT['kuratowski'] = {'a': report_a, 'b': report_b}


def p7_dictionary():
    p = 7
    pts, conic, ext, inte = classify(p)
    Gi, Ge = conj_graph(inte, p), conj_graph(ext, p)
    cox = coxeter_graph()
    iso_cox = nx.is_isomorphic(Ge, cox)
    LH = nx.line_graph(nx.heawood_graph())
    iso_lh = nx.is_isomorphic(Gi, LH)
    print(f"[p=7] |conic|={len(conic)} |ext|={len(ext)} |int|={len(inte)}; G_ext ~ Coxeter graph: {iso_cox} "
          f"(girth {girth(Ge)}, Coxeter girth {girth(cox)}); G_int ~ L(Heawood): {iso_lh}")
    group, gens, idx = berggren_group_perm(p, pts)
    print(f"[p=7] Berggren group mod 7 on PG(2,7): order {len(group)} (|PGL(2,7)| = 336)")
    OUT['p7'] = {'Gext_is_Coxeter': iso_cox, 'Gint_is_LHeawood': iso_lh, 'berggren_group_order': len(group),
                 'girth_ext': girth(Ge)}


def survey(primes=(3, 5, 7, 11, 13)):
    rows = []
    for p in primes:
        pts, conic, ext, inte = classify(p)
        row = {'p': p}
        for name, vs in (('int', inte), ('ext', ext)):
            G = conj_graph(vs, p)
            degs = sorted(set(dict(G.degree()).values()))
            conn = nx.is_connected(G) if len(G) else None
            g = girth(G)
            ham = None
            if conn and len(G) <= 12:
                ham = exhaustive_hamiltonian(G)
            elif conn:
                ham = hamiltonian_cycle(G) is not None or None
            row[name] = {'order': len(G), 'degree': degs, 'connected': conn, 'girth': g, 'hamiltonian': ham}
        group, _, _ = berggren_group_perm(p, pts)
        row['berggren_group_order'] = len(group)
        row['PGL2_order'] = p * (p * p - 1)
        rows.append(row)
        print(f"[survey p={p}] int {row['int']}  ext {row['ext']}  Berggren image {len(group)} vs |PGL(2,p)| {p*(p*p-1)}")
    OUT['survey'] = rows


