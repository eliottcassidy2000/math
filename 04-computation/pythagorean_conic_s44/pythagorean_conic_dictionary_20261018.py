#!/usr/bin/env python3
"""The Pythagorean form x^2 + y^2 - z^2 over F_p: conic graphs, Petersen, K5, K6, K3,3, Coxeter (S44).

Objects (all exact, finite).
  - PG(2,p), p an odd prime, with the conic C: x^2 + y^2 - z^2 = 0 (the reduction of the Pythagorean light cone).
    A non-conic point P is EXTERIOR if its polar line meets C in 2 points, INTERIOR if in 0 points.
  - G_int(p), G_ext(p): conjugacy graphs (B(P,Q) = 0) on interior / exterior points.
  - The Berggren matrices A, B, C (generators of the ternary tree of primitive Pythagorean triples from (3,4,5))
    reduced mod p, acting on PG(2,p).
Checks.
  1. Berggren matrices preserve the form; the tree from (3,4,5) lists every primitive triple with hypotenuse <= X
     exactly once (X = 2000).
  2. p = 5: G_int ~ Petersen; G_ext ~ 5 K3 (the 5 self-polar exterior triangles); exterior points <-> edges of K6 on
     the 6 conic points (tangency duads); interior points <-> synthemes (perfect matchings of the 6 conic points cut out
     by the 3 secants through the point) and, equivariantly, <-> 3+3 splits; the group generated by the Berggren
     matrices mod 5 acts on G_int as a subgroup of order 60; the full automorphism group has order 120.
     Correction (clock_duality-20261018j): the original expectation of equality was already refuted by this script
     in f09f8097d1; its exact receipt correctly reports acts_as_Aut_Petersen = false.
  3. Kuratowski views of Petersen in conic language: deleting an interior point gives a subdivided K3,3; contracting a
     perfect matching gives K5. Equivariant identifications with conic data are searched for exhaustively.
  4. p = 7: G_ext ~ Coxeter graph (built independently as KG(7,3) minus the 7 lines of a Fano plane); G_int ~ the
     line graph of the Heawood graph.
  5. p = 3, 11, 13: parameters (order, degree, girth, connectivity) of G_int, G_ext; Hamiltonicity search.
Usage: python pythagorean_conic_dictionary_20261018.py
"""
import itertools, json, sys, os, random
from collections import Counter, defaultdict
import networkx as nx

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = {}

A = ((1, -2, 2), (2, -1, 2), (2, -2, 3))
B = ((1, 2, 2), (2, 1, 2), (2, 2, 3))
C = ((-1, 2, 2), (-2, 1, 2), (-2, 2, 3))
J = ((1, 0, 0), (0, 1, 0), (0, 0, -1))


def mat_mul(X, Y, p=None):
    Z = tuple(tuple(sum(X[i][k] * Y[k][j] for k in range(3)) for j in range(3)) for i in range(3))
    if p:
        Z = tuple(tuple(z % p for z in row) for row in Z)
    return Z


def mat_vec(X, v, p=None):
    w = tuple(sum(X[i][k] * v[k] for k in range(3)) for i in range(3))
    return tuple(x % p for x in w) if p else w


def transpose(X):
    return tuple(tuple(X[j][i] for j in range(3)) for i in range(3))


def det3(X):
    a, b, c = X
    return (a[0] * (b[1] * c[2] - b[2] * c[1]) - a[1] * (b[0] * c[2] - b[2] * c[0])
            + a[2] * (b[0] * c[1] - b[1] * c[0]))


# ------------------------------------------------------------------ 1. the integral tree
def check_tree(X=2000):
    for M in (A, B, C):
        assert mat_mul(mat_mul(transpose(M), J), M) == J
    dets = [det3(M) for M in (A, B, C)]
    seen = Counter()
    stack = [(3, 4, 5)]
    while stack:
        t = stack.pop()
        if t[2] > X:
            continue
        seen[(min(t[0], t[1]), max(t[0], t[1]), t[2])] += 1
        for M in (A, B, C):
            stack.append(mat_vec(M, t))
    from math import gcd, isqrt
    truth = set()
    for c in range(5, X + 1):
        for a in range(1, c):
            b2 = c * c - a * a
            b = isqrt(b2)
            if b * b == b2 and a < b and gcd(a, b) == 1:
                truth.add((a, b, c))
    ok = set(seen) == truth and all(v == 1 for v in seen.values())
    OUT['tree'] = {'X': X, 'dets': dets, 'triples': len(truth), 'exact_once': ok}
    print(f"[tree] Berggren dets {dets}; primitive triples with c <= {X}: {len(truth)}; tree lists each exactly once: {ok}")
    assert ok


# ------------------------------------------------------------------ 2. PG(2,p) and the conic
def points(p):
    pts = []
    for x in range(p):
        for y in range(p):
            for z in range(p):
                v = (x, y, z)
                if v == (0, 0, 0):
                    continue
                f = next(c for c in v if c)
                if f == 1:
                    pts.append(v)
    return pts


def normalize(v, p):
    f = next(c for c in v if c % p)
    inv = pow(f, -1, p)
    return tuple(c * inv % p for c in v)


def Bform(u, v, p):
    return (u[0] * v[0] + u[1] * v[1] - u[2] * v[2]) % p


def classify(p):
    pts = points(p)
    conic = [v for v in pts if Bform(v, v, p) == 0]
    ext, inte = [], []
    for v in pts:
        if Bform(v, v, p) == 0:
            continue
        k = sum(1 for c in conic if Bform(v, c, p) == 0)
        (ext if k == 2 else inte).append(v)
        assert k in (0, 2)
    return pts, conic, ext, inte


def conj_graph(vs, p):
    G = nx.Graph()
    G.add_nodes_from(vs)
    for u, v in itertools.combinations(vs, 2):
        if Bform(u, v, p) == 0:
            G.add_edge(u, v)
    return G


def girth(G):
    best = None
    for s in G:
        dist = {s: 0}
        par = {s: None}
        q = [s]
        for u in q:
            for w in G[u]:
                if w not in dist:
                    dist[w] = dist[u] + 1
                    par[w] = u
                    q.append(w)
                elif par[u] != w:
                    L = dist[u] + dist[w] + 1
                    if best is None or L < best:
                        best = L
    return best


def berggren_group_perm(p, pts):
    """Permutation group on points generated by A, B, C mod p (closure by BFS on group elements)."""
    idx = {v: i for i, v in enumerate(pts)}
    def perm(M):
        return tuple(idx[normalize(mat_vec(M, v, p), p)] for v in pts)
    gens = [perm(M) for M in (A, B, C)]
    ident = tuple(range(len(pts)))
    group = {ident}
    frontier = [ident]
    while frontier:
        new = []
        for g in frontier:
            for s in gens:
                h = tuple(s[g[i]] for i in range(len(pts)))
                if h not in group:
                    group.add(h)
                    new.append(h)
        frontier = new
    return group, gens, idx


def automorphism_count(G, limit=10 ** 6):
    GM = nx.algorithms.isomorphism.GraphMatcher(G, G)
    n = 0
    for _ in GM.isomorphisms_iter():
        n += 1
        if n >= limit:
            break
    return n


def coxeter_graph():
    """KG(7,3) minus the 7 lines of a Fano plane (an independent construction of the Coxeter graph)."""
    lines = [frozenset(((i) % 7, (i + 1) % 7, (i + 3) % 7)) for i in range(7)]
    verts = [frozenset(s) for s in itertools.combinations(range(7), 3) if frozenset(s) not in lines]
    G = nx.Graph()
    G.add_nodes_from(verts)
    for u, v in itertools.combinations(verts, 2):
        if not (u & v):
            G.add_edge(u, v)
    return G


def hamiltonian_cycle(G, tries=200, seed=1):
    """Randomized DFS with restarts; returns a Hamiltonian cycle or None (None is NOT a proof of non-existence)."""
    rng = random.Random(seed)
    nodes = list(G)
    n = len(nodes)
    sys.setrecursionlimit(10000)
    for t in range(tries):
        start = rng.choice(nodes)
        path = [start]
        onpath = {start}
        budget = [20000]
        def dfs():
            budget[0] -= 1
            if budget[0] < 0:
                return False
            if len(path) == n:
                return start in G[path[-1]]
            nbrs = [w for w in G[path[-1]] if w not in onpath]
            rng.shuffle(nbrs)
            nbrs.sort(key=lambda w: sum(1 for x in G[w] if x not in onpath))
            for w in nbrs:
                path.append(w); onpath.add(w)
                if dfs():
                    return True
                path.pop(); onpath.discard(w)
            return False
        if dfs():
            return list(path)
    return None


def exhaustive_hamiltonian(G):
    """Exact Hamiltonicity test by DFS from a fixed vertex (small graphs only)."""
    nodes = list(G)
    n = len(nodes)
    s = nodes[0]
    path = [s]
    on = {s}
    def dfs():
        if len(path) == n:
            return s in G[path[-1]]
        for w in G[path[-1]]:
            if w not in on:
                path.append(w); on.add(w)
                if dfs():
                    return True
                path.pop(); on.discard(w)
        return False
    return dfs()


def p5_dictionary():
    p = 5
    pts, conic, ext, inte = classify(p)
    Gi, Ge = conj_graph(inte, p), conj_graph(ext, p)
    pet = nx.petersen_graph()
    iso_pet = nx.is_isomorphic(Gi, pet)
    comps = [len(c) for c in nx.connected_components(Ge)]
    tri = all(nx.is_isomorphic(Ge.subgraph(c), nx.complete_graph(3)) for c in nx.connected_components(Ge))
    print(f"[p=5] |conic|={len(conic)} |ext|={len(ext)} |int|={len(inte)}; G_int ~ Petersen: {iso_pet}; "
          f"G_ext components {sorted(comps)} all triangles: {tri}")
    # self-polar triangles
    selfpolar = []
    nonconic = ext + inte
    for a, b, c in itertools.combinations(nonconic, 3):
        if Bform(a, b, p) == Bform(a, c, p) == Bform(b, c, p) == 0:
            selfpolar.append((a, b, c))
    types = Counter(sum(1 for x in t if x in inte) for t in selfpolar)
    print(f"[p=5] self-polar triangles: {len(selfpolar)}; by number of interior vertices: {dict(types)}")
    # tangency duads of exterior points
    duad = {E: frozenset(c for c in conic if Bform(E, c, p) == 0) for E in ext}
    assert len(set(duad.values())) == 15
    # syntheme of interior points: pair x with the second conic point on line P x
    def line_points(u, v):
        out = set()
        for s in range(p):
            for t in range(p):
                if (s, t) != (0, 0):
                    out.add(normalize(tuple((s * a + t * b) % p for a, b in zip(u, v)), p))
        return out
    synth = {}
    for P in inte:
        pairs = set()
        for x in conic:
            L = line_points(P, x)
            others = [c for c in conic if c in L and c != x]
            assert len(others) == 1
            pairs.add(frozenset((x, others[0])))
        assert len(pairs) == 3
        synth[P] = frozenset(pairs)
    # synthemes from exterior self-polar triangles
    ext_tris = [t for t in selfpolar if all(x in ext for x in t)]
    synth_ext = [frozenset(duad[x] for x in t) for t in ext_tris]
    all15 = set(synth.values()) | set(synth_ext)
    print(f"[p=5] interior synthemes distinct: {len(set(synth.values()))}; exterior-triangle synthemes: "
          f"{len(set(synth_ext))}; together all 15 synthemes of K6: {len(all15) == 15}")
    # Petersen edge {P,Q} -> third vertex S (exterior) of the self-polar triangle
    edge_to_ext = {}
    for P, Q in Gi.edges():
        S = [x for x in ext if Bform(x, P, p) == 0 and Bform(x, Q, p) == 0]
        assert len(S) == 1
        edge_to_ext[frozenset((P, Q))] = S[0]
    assert len(set(edge_to_ext.values())) == 15
    # group
    group, gens, idx = berggren_group_perm(p, pts)
    OUT['p5_group_order'] = len(group)
    # restriction to interior points; test whether it is all of Aut(G_int)
    ii = [idx[v] for v in inte]
    pos = {idx[v]: k for k, v in enumerate(inte)}
    restr = set()
    for g in group:
        restr.add(tuple(pos[g[i]] for i in ii))
    autos = automorphism_count(Gi)
    all_auto = all(all(Gi.has_edge(inte[pos[g[ii[a]]]], inte[pos[g[ii[b]]]])
                       for a, b in [(inte.index(u), inte.index(v)) for u, v in Gi.edges()]) for g in group)
    print(f"[p=5] Berggren group mod 5 acting on PG(2,5): order {len(group)}; on interior points: {len(restr)} "
          f"distinct permutations, all automorphisms of G_int: {all_auto}; |Aut(Petersen)| = {autos}")
    OUT['p5'] = {'conic': len(conic), 'ext': len(ext), 'int': len(inte), 'Gint_is_Petersen': iso_pet,
                 'Gext_components': sorted(comps), 'Gext_triangles': tri, 'selfpolar_types': dict(types),
                 'synthemes_all15': len(all15) == 15, 'berggren_group_order': len(group),
                 'acts_as_Aut_Petersen': all_auto and len(restr) == autos}
    return dict(p=p, pts=pts, conic=conic, ext=ext, inte=inte, Gi=Gi, Ge=Ge, duad=duad, synth=synth,
                edge_to_ext=edge_to_ext, group=group, idx=idx, selfpolar=selfpolar)


