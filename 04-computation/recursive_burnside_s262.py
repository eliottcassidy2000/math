        """Class of tournament restricted to vertices [1..n-2]."""
        overlap_pairs = [(i,j) for i in range(1, n-1) for j in range(i+1, n-1)]
        if not overlap_pairs:
            return 0  # n=3: no overlap
        n2 = n - 2
        op = [(i-1, j-1) for (i,j) in overlap_pairs]
