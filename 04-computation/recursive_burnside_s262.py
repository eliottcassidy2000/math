    for bits in range(2**m):
        oc = overlap_class(bits)
        fc = tc[bits]
        apex_val = (bits >> k_apex) & 1
        by_overlap[oc].append((fc, apex_val, bits))

    # For each overlap group: how many distinct edges come from apex flips?
    edges_by_overlap = defaultdict(set)
