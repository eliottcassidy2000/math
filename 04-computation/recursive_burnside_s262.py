# For the apex arc at (0, n-1):
# Reversing it changes the tournament from "0 beats n-1" to "n-1 beats 0".
# The rest of the tournament is UNCHANGED.
# So the class of T^{apex} depends on:
# 1. The class of T (which determines the overlap + boundary structure)
# 2. How swapping the apex direction changes the iso class

# THE KEY: at the apex, the recursive decomposition gives:
# T = bottom(n-1) ∪ top(n-1) ∪ {apex}
# T^{apex} = same bottom ∪ same top ∪ {reversed apex}

# So class(T) → class(T^{apex}) depends ONLY on:
# - The isomorphism class of T|_{bottom} = T\{n-1}
# - The isomorphism class of T|_{top} = T\{0}
# - The class of T|_{overlap} = T\{0, n-1}
# - Whether the apex goes 0→(n-1) or (n-1)→0

# THE RECURSIVE FORMULA:
# E(G_n) = #{distinct class pairs (C, D) : ∃T ∈ C with T^{apex} ∈ D, C ≠ D}

