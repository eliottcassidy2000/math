def dist(x): x%=1; return min(x,1-x)
def M_exact(V):
    # max_t min_i ||v_i t||, optimum at t=m/(v_i±v_j)
    ds=set(V)
    from itertools import combinations
    for a,b in combinations(V,2): ds.add(a+b); ds.add(abs(a-b))
    ds.discard(0); best=F(-1)
    for d in ds:
        for m in range(0,d):
            t=F(m,d); val=min(dist(v*t) for v in V)
            if val>best: best=val
    return best
def orbits(mod, gens):
    seen=set(); orbs=[]
    for x in range(1,mod):
        if x in seen: continue
        orb=set(); stack=[x]
        while stack:
            y=stack.pop()
            if y in seen or y==0: 
                if y!=0: seen.add(y)
                continue
            seen.add(y); orb.add(y)
            for g in gens:
                stack.append((g*y)%mod)
        if orb: orbs.append(sorted(orb))
    return orbs
