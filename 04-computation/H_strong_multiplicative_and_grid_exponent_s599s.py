"""WHY 7,21 are impossible (structural): H is MULTIPLICATIVE over strong components (Moon):
H(T)=prod H(C_i). So achievable H = multiplicative semigroup generated by H-values of STRONGLY
CONNECTED tournaments. 7 impossible <=> no strong tournament has H=7 (7 prime => not a product).
Compute strong-tournament H-spectra (m=3..6), the generated semigroup, confirm gaps.
Also: the unit-GRID disproof exponent (most-popular-distance), hunting ~1.014. opus-2026-06-03-S599s."""
from itertools import combinations, product
def Hcount(n,adj):
    size=1<<n; dp=[[0]*n for _ in range(size)]
    for v in range(n): dp[1<<v][v]=1
    for mask in range(size):
        row=dp[mask]
        for v in range(n):
            c=row[v]
            if not c: continue
            av=adj[v]
            for w in range(n):
                if not(mask>>w&1) and av>>w&1: dp[mask|1<<w][w]+=c
    return sum(dp[size-1][v] for v in range(n))
def is_strong(n,adj):
    # 0 reaches all (forward) and all reach 0 (forward in reverse)
    def reach(start, nb):
        seen={start}; st=[start]
        while st:
            x=st.pop()
            for y in range(n):
                if y not in seen and nb(x,y): seen.add(y); st.append(y)
        return len(seen)==n
    fwd=lambda x,y: adj[x]>>y&1
    rev=lambda x,y: adj[y]>>x&1
    return reach(0,fwd) and reach(0,rev)
def main():
    print("STRONG-tournament H-spectra (the multiplicative 'primes'):")
    strongvals={}
    for m in range(3,7):
        sv=set()
        for bits in product((0,1),repeat=m*(m-1)//2):
            adj=[0]*m
            for (i,j),b in zip(combinations(range(m),2),bits):
                if b: adj[i]|=1<<j
                else: adj[j]|=1<<i
            if is_strong(m,adj): sv.add(Hcount(m,adj))
        strongvals[m]=sv
        print(f"  m={m}: strong H-values = {sorted(sv)}")
    primes=set().union(*strongvals.values())  # the multiplicative generators (plus 1)
    print(f"\n strong-tournament H-values (all m≤6) = {sorted(primes)}")
    print(f"  is 7 a strong value? {7 in primes}  is 21? {21 in primes}  is 63? {63 in primes}")
    # generated multiplicative semigroup up to bound
    B=200; ach={1}
    changed=True
    while changed:
        changed=False
        for a in list(ach):
            for g in primes:
                if a*g<=B and a*g not in ach: ach.add(a*g); changed=True
    gaps=[h for h in range(1,B+1,2) if h not in ach]
    print(f" achievable (semigroup, ≤{B}) gaps among odds: {gaps[:25]}")
    print(f" => 7 impossible: {7 not in ach}; 21 impossible: {21 not in ach}")
    print("\nUNIT-GRID disproof exponent: k×k grid, most-popular squared-distance count; exponent=log(U)/log(n)")
    import math
    for k in (8,16,32,64,128,256):
        from collections import defaultdict
        cnt=defaultdict(int)
        for a in range(-k+1,k):
            for b in range(0,k):       # b>=0 half, handle b=0 a>0 to avoid double count of pairs
                if a==0 and b==0: continue
                d=a*a+b*b
                w=(k-abs(a))*(k-abs(b))
                cnt[d]+=w
        U=max(cnt.values())//1   # ordered-ish; relative scale only -> exponent
        n=k*k
        print(f"  k={k:3d} n={n:5d}: maxdist-count U={U}; exponent log(U)/log(n) = {math.log(U)/math.log(n):.4f}")
if __name__=='__main__': main()
