def S_full(p, q, P):
    A, B = normP(p, P), normP(q, P)
    if A == 0 or B == 0:
        return 0
    C = normP(p * q, P)
    return (2 * A * B * (P - A) * (P - B) + 2 * C * (P - C)) // P


def symmetry_group(P):
    """find the subgroup of PGL_2(F_P) acting on slope z=p/q that preserves S_P.
    Represent state as residue pair (p%P,q%P) up to overall scaling (homogeneous)."""
    # enumerate PGL_2(F_P) as matrices [[a,b],[c,d]] mod P, det!=0, mod scalars.
    elems = []
    seen = set()
    for a in range(P):
        for b in range(P):
            for c in range(P):
                for d in range(P):
                    if (a * d - b * c) % P == 0:
                        continue
                    # normalize by first nonzero entry to factor scalars
                    for s in (a, b, c, d):
                        if s % P != 0:
                            inv = pow(s, -1, P)
                            break
                    key = tuple((x * inv) % P for x in (a, b, c, d))
                    if key in seen:
                        continue
                    seen.add(key)
                    elems.append((a, b, c, d))
    # which preserve S_P on all residue pairs (p,q), p,q in 0..P-1 not both 0?
    def preserves(M):
        a, b, c, d = M
        for p in range(P):
            for q in range(P):
                if p == 0 and q == 0:
                    continue
                np_, nq = (a * p + b * q) % P, (c * p + d * q) % P
                if S_full(np_, nq, P) != S_full(p, q, P):
                    return False
        return True
    G = [M for M in elems if preserves(M)]
    return G, len(elems)


