def ham_count(n, A):
    dp = [[0]*n for _ in range(1 << n)]
    for v in range(n):
        dp[1 << v][v] = 1
    for mask in range(1 << n):
        for last in range(n):
            c = dp[mask][last]
            if not c: continue
            for nxt in range(n):
                if mask & (1 << nxt): continue
                if A[last][nxt]:
                    dp[mask | (1 << nxt)][nxt] += c
    full = (1 << n) - 1
    return sum(dp[full][v] for v in range(n))

