def study_projection_algebra(n):
    """Study the algebra generated by arc projections for n-vertex tournaments."""
    m = n*(n-1)//2  # number of arcs
    dim = 2**m       # dimension of Boolean cube

    print(f"n={n}: m={m} arcs, dim=2^{m}={dim}")

    # Each tournament T is a point in {0,1}^m
    # H(T) = number of Hamiltonian paths

    # The "Hamiltonian path vector" |Phi>:
    # |Phi> = sum over all permutations sigma of |T_sigma>
    # where T_sigma is the tournament encoding the total order sigma

    # Actually: H(T) = sum over sigma of product_{consecutive pairs} T[sigma(i)][sigma(i+1)]
    # This is a MULTILINEAR function of the T[i][j] variables.

    # For each permutation sigma, define the "path indicator":
    # I_sigma(T) = product_{k=0}^{n-2} T[sigma(k)][sigma(k+1)]
    # Then H(T) = sum_sigma I_sigma(T)

    # I_sigma is a MONOMIAL in the T[i][j] variables of degree n-1.
    # H(T) is a sum of n! such monomials.

    # The FOURIER TRANSFORM: each T[i][j] in {0,1} can be written as
    # T[i][j] = (1 + x_{ij})/2 where x_{ij} in {-1,+1}
    # Then I_sigma = product (1 + x_{sigma(k),sigma(k+1)})/2
    # = (1/2^{n-1}) product (1 + x_e) for edges e in sigma

    # H(T) = (1/2^{n-1}) sum_sigma product_{e in sigma} (1 + x_e)
    # = (1/2^{n-1}) sum_sigma sum_{S subset of edges(sigma)} product_{e in S} x_e
    # = (1/2^{n-1}) sum_S c(S) * product_{e in S} x_e
    # where c(S) = #{sigma : S is a subset of edges(sigma)}

    # The FOURIER COEFFICIENT H_hat(S) = c(S) / 2^{n-1}
    # and H_hat(empty) = n!/2^{n-1} = E[H]

    # For |S| = 2k: H_hat(S) counts paths containing all edges in S.
    # The ENERGY E_{2k} = sum_{|S|=2k} H_hat(S)^2

    if n > 5:
        print("  (skipping enumeration for n > 5)")
        return

    # Enumerate all tournaments and compute H
    H_vals = []
    for bits in range(dim):
        T = [[0]*n for _ in range(n)]
        idx = 0
        for i in range(n):
            for j in range(i+1, n):
                if (bits >> idx) & 1:
                    T[i][j] = 1
                else:
                    T[j][i] = 1
                idx += 1

        H = 0
        for sigma in permutations(range(n)):
            ok = True
            for k in range(n-1):
                if T[sigma[k]][sigma[k+1]] != 1:
                    ok = False
                    break
            if ok:
                H += 1
        H_vals.append(H)

    # Compute E[H], Var[H], E[H^2]
    E_H = Fraction(sum(H_vals), dim)
    E_H2 = Fraction(sum(h*h for h in H_vals), dim)
    Var_H = E_H2 - E_H*E_H
    CV2 = Var_H / (E_H * E_H)

    print(f"  E[H] = {E_H} = {float(E_H):.4f}")
    print(f"  Var[H] = {float(Var_H):.4f}")
    print(f"  CV^2 = {CV2} = {float(CV2):.6f}")

    # Compare to Delannoy formula
    cv2_del = Fraction(0)
    for k in range(1, (n-1)//2 + 1):
        mm = n - 2*k
        if mm < 1: continue
        gk = sum(Fraction(comb(k-1,j-1)*comb(mm,j)) * 2**(j-1)
                 for j in range(1, min(k,mm)+1))
        ff = Fraction(1)
        for i in range(2*k):
            ff *= (n-i)
        cv2_del += 2*gk/ff

    print(f"  CV^2 (Delannoy) = {cv2_del} = {float(cv2_del):.6f}")
    print(f"  Match: {CV2 == cv2_del}")

    return H_vals

