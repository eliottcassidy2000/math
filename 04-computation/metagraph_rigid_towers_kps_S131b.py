def stack(A, B):
    na, nb = len(A), len(B)
    n = na + nb
    M = [[0] * n for _ in range(n)]
    for i in range(na):
        Ai = A[i]
        Mi = M[i]
        for j in range(na):
            Mi[j] = Ai[j]
        for j in range(nb):
            Mi[na + j] = 1
    for i in range(nb):
        Bi = B[i]
        Mi = M[na + i]
        for j in range(nb):
            Mi[na + j] = Bi[j]
    return M

def c3(A, B, C):
    parts = [A, B, C]
    sizes = [len(p) for p in parts]
    off = [0, sizes[0], sizes[0] + sizes[1]]
    n = sum(sizes)
    M = [[0] * n for _ in range(n)]
    for b, P in enumerate(parts):
        for i in range(sizes[b]):
            for j in range(sizes[b]):
                M[off[b] + i][off[b] + j] = P[i][j]
    for b in range(3):
        nb = (b + 1) % 3
        for i in range(sizes[b]):
            for j in range(sizes[nb]):
                M[off[b] + i][off[nb] + j] = 1
    return M

def wl_colors(n, A, rounds=3):
    col = [sum(A[i]) for i in range(n)]
    for _ in range(rounds):
        nxt = []
        for i in range(n):
            outs = tuple(sorted(col[j] for j in range(n) if A[i][j]))
            ins = tuple(sorted(col[j] for j in range(n) if j != i and not A[i][j]))
            nxt.append(hash((col[i], outs, ins)))
        uniq = {c: k for k, c in enumerate(sorted(set(nxt)))}
        col = [uniq[c] for c in nxt]
    return col

def fingerprint(n, A):
    col = wl_colors(n, A)
    return (n, tuple(sorted(zip(col, [sum(A[i]) for i in range(n)]))))

def iso_map(n, A, B):
    ca, cb = wl_colors(n, A), wl_colors(n, B)
    if sorted(ca) != sorted(cb):
        return False
    cand = [[j for j in range(n) if cb[j] == ca[i]] for i in range(n)]
    order = sorted(range(n), key=lambda i: len(cand[i]))
    mapping = [-1] * n
    used = [False] * n
    def bt(k):
        if k == n:
            return True
        i = order[k]
        for j in cand[i]:
            if used[j]:
                continue
            ok = True
            for k2 in range(k):
                i2 = order[k2]
                if A[i][i2] != B[j][mapping[i2]] or A[i2][i] != B[mapping[i2]][j]:
                    ok = False
                    break
            if ok:
                mapping[i] = j; used[j] = True
                if bt(k + 1):
                    return True
                used[j] = False; mapping[i] = -1
        return False
    return bt(0)

def aut_size(n, A):
    col = wl_colors(n, A)
    cand = [[j for j in range(n) if col[j] == col[i]] for i in range(n)]
    order = sorted(range(n), key=lambda i: len(cand[i]))
    mapping = [-1] * n
    used = [False] * n
    cnt = 0
    def bt(k):
        nonlocal cnt
        if k == n:
            cnt += 1
            return
        i = order[k]
        for j in cand[i]:
            if used[j]:
                continue
            ok = True
            for k2 in range(k):
                i2 = order[k2]
                if A[i][i2] != A[j][mapping[i2]] or A[i2][i] != A[mapping[i2]][j]:
                    ok = False
                    break
            if ok:
                mapping[i] = j; used[j] = True
                bt(k + 1)
                used[j] = False; mapping[i] = -1
    bt(0)
    return cnt

def ham(n, A):
    full = (1 << n) - 1
    dp = [[0] * n for _ in range(1 << n)]
    for i in range(n):
        dp[1 << i][i] = 1
    for mask in range(1 << n):
        row = dp[mask]
        for last in range(n):
            c = row[last]
            if not c:
                continue
            Al = A[last]
            for nx in range(n):
                if Al[nx] and not (mask >> nx) & 1:
                    dp[mask | (1 << nx)][nx] += c
    return sum(dp[full][i] for i in range(n))

def is_sc(n, A):
    Aop = [[A[j][i] for j in range(n)] for i in range(n)]
    return iso_map(n, A, Aop)

N = 10
gen = {1: [[[0]]]}
