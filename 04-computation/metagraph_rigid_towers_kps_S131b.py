    buckets = {}
    out = []
    def add(M):
        fp = fingerprint(n, M)
        lst = buckets.setdefault(fp, [])
        for X in lst:
            if iso_map(n, M, X):
                return
        lst.append(M)
        out.append(M)
    for a in range(1, n):
        for A in gen[a]:
            for B in gen[n - a]:
                add(stack(A, B))
