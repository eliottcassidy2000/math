def require(condition, payload):
    if not condition:
        raise RuntimeError(payload)


def prime_factors(n):
    factors = []
    d = 2
    while d * d <= n:
        if n % d == 0:
            factors.append(d)
            while n % d == 0:
                n //= d
        d += 1
    if n > 1:
        factors.append(n)
    return tuple(factors)


def ff_mul(p, nonsquare, x, y):
    a, b = x
    c, d = y
    return ((a * c + nonsquare * b * d) % p,
            (a * d + b * c) % p)


def ff_pow(p, nonsquare, x, n):
    value = (1, 0)
    while n:
        if n & 1:
            value = ff_mul(p, nonsquare, value, x)
        x = ff_mul(p, nonsquare, x, x)
        n //= 2
    return value


def ff_order(p, nonsquare, x):
    if x == (0, 0):
        return 0
    order = p * p - 1
    for ell in prime_factors(order):
        while order % ell == 0 and ff_pow(
                p, nonsquare, x, order // ell) == (1, 0):
            order //= ell
    return order


def mat_mul(p, a, b):
    return ((a[0] * b[0] + a[1] * b[2]) % p,
            (a[0] * b[1] + a[1] * b[3]) % p,
            (a[2] * b[0] + a[3] * b[2]) % p,
            (a[2] * b[1] + a[3] * b[3]) % p)


def mat_det(p, a):
    return (a[0] * a[3] - a[1] * a[2]) % p


def mat_inv(p, a):
    determinant = mat_det(p, a)
    require(determinant != 0, ("singular matrix", p, a))
    inverse = pow(determinant, p - 2, p)
    return ((a[3] * inverse) % p, (-a[1] * inverse) % p,
            (-a[2] * inverse) % p, (a[0] * inverse) % p)


def matrix_order(p, a):
    identity = (1, 0, 0, 1)
    value = identity
    for order in range(1, p * p * p * p + 1):
        value = mat_mul(p, value, a)
        if value == identity:
            return order
    raise RuntimeError(("matrix order bound", p, a))


def group_closure(p, generators):
    identity = (1, 0, 0, 1)
    moves = tuple(generators) + tuple(mat_inv(p, g) for g in generators)
    seen = {identity}
    queue = deque([identity])
    while queue:
        current = queue.popleft()
        for move in moves:
            child = mat_mul(p, current, move)
            if child not in seen:
                seen.add(child)
                queue.append(child)
    return frozenset(seen)


def normalized_line(p, vector):
    x, y = vector
    require((x, y) != (0, 0), ("zero line vector", p))
    if x:
        inverse = pow(x, p - 2, p)
        return (1, y * inverse % p)
    return (0, 1)


def fixed_line(p, transvection):
    a = ((transvection[0] - 1) % p, transvection[1] % p,
         transvection[2] % p, (transvection[3] - 1) % p)
    if a[0] or a[1]:
        vector = (a[1], -a[0] % p)
    else:
        vector = (a[3], -a[2] % p)
    return normalized_line(p, vector)


def scalar_order(p, value):
    require(value % p, ("zero scalar", p, value))
    running = value % p
    for order in range(1, p):
        if running == 1:
            return order
        running = running * value % p
    raise RuntimeError(("scalar order", p, value))


def prime_row(p):
    nonsquare = next(d for d in range(2, p)
                     if pow(d, (p - 1) // 2, p) == p - 1)
    primitive = next((a, b)
                     for a in range(p)
                     for b in range(p)
                     if ff_order(p, nonsquare, (a, b)) == p * p - 1)
    a, b = primitive
    singer = (a, nonsquare * b % p, b, a)
    # This is rho(0,-1,0) in THM-2779's standard affine action
    # (r,w) -> (r,w+r).
    transvection = (1, 0, 1, 1)
    identity = (1, 0, 0, 1)

    require(matrix_order(p, singer) == p * p - 1,
            ("Singer order", p, primitive, singer))
    determinant = mat_det(p, singer)
    require(scalar_order(p, determinant) == p - 1,
            ("Singer determinant", p, determinant))

    scalar_step = identity
    for _ in range(p + 1):
        scalar_step = mat_mul(p, scalar_step, singer)
    require(scalar_step[1] == scalar_step[2] == 0
            and scalar_step[0] == scalar_step[3],
            ("radial Singer step", p, scalar_step))
    require(scalar_order(p, scalar_step[0]) == p - 1,
            ("radial order", p, scalar_step))

    singer_inverse = mat_inv(p, singer)
    power = identity
    inverse_power = identity
    lines = set()
    for _ in range(p + 1):
        conjugate = mat_mul(
            p, mat_mul(p, power, transvection), inverse_power)
        lines.add(fixed_line(p, conjugate))
        power = mat_mul(p, power, singer)
        inverse_power = mat_mul(p, singer_inverse, inverse_power)
    require(len(lines) == p + 1, ("projective line orbit", p, lines))

    generated = group_closure(p, (singer, transvection))
    gl_order = (p * p - 1) * (p * p - p)
    require(len(generated) == gl_order,
            ("linear closure", p, len(generated), gl_order))

    moved_line = fixed_line(
        p, mat_mul(p, mat_mul(p, singer, transvection), singer_inverse))
    require(moved_line != fixed_line(p, transvection),
            ("Singer falsely normalizes transvection line", p))

    # The standard H_p action contains every translation.  Its orbit of zero
    # is therefore the whole affine plane, and the central z-translation is
    # visible on every point.
