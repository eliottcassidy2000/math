"""Exact scratch audit of the THM-2825 Schur/scale boundary.

This script deliberately reuses only the public reconstruction functions of
the primary THM-2825 companion.  It checks three claims not printed there:

1. the signed semantic-parity symbol has an explicit norm-one gamma_2
   factorization and is a Schur tripotent;
2. exact half-step offsets partition the relation into pairwise Schur-
   orthogonal partial matchings;
3. the algebra generated by cell and semantic-colour masks cannot contain
   either metric collar, while ordinary matrix composition of the two collar
   matchings produces a rank-587 common-side partial translation.

No Python ``assert`` is used.
"""

from collections import Counter, defaultdict
from hashlib import sha256
from pathlib import Path
