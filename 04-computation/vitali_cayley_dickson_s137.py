def tournament_adj(n, bits):
    adj = [[0]*n for _ in range(n)]
    idx = 0
    for i in range(n):
        for j in range(i+1, n):
            if bits & (1 << idx):
                adj[i][j] = 1
            else:
                adj[j][i] = 1
            idx += 1
    return adj

def H_dp(adj, n):
    dp = [0]*((1<<n)*n)
    for v in range(n): dp[(1<<v)*n+v] = 1
    for S in range(1, 1<<n):
        for v in range(n):
            if not (S&(1<<v)): continue
            val = dp[S*n+v]
            if val == 0: continue
            for u in range(n):
                if S&(1<<u): continue
                if adj[v][u]: dp[(S|(1<<u))*n+u] += val
    full = (1<<n)-1
    return sum(dp[full*n+v] for v in range(n))

def lambda_graph(adj, n):
    """Compute lambda(u,v) = # 3-cycle witnesses for each pair."""
    lam = {}
    for u in range(n):
        for v in range(u+1, n):
            count = 0
            for w in range(n):
                if w == u or w == v: continue
                # w witnesses 3-cycle through u,v iff
                # there's a directed 3-cycle on {u,v,w}
                # directed cycles: u→v→w→u or u→w→v→u
                if (adj[u][v] and adj[v][w] and adj[w][u]) or \
                   (adj[u][w] and adj[w][v] and adj[v][u]):
                    count += 1
            lam[(u,v)] = count
    return lam

def score_seq(adj, n):
    return tuple(sorted(sum(adj[i]) for i in range(n)))

