#!/usr/bin/env python3
"""S91 helper (g20_local), part B(iii): the reduction modulo p of the minimal representation of G(2,0).

For each prime p (default 3, 5, 7, 11, 13):
  A. the invariant set.  l(w) mod p lies in S = union over the last letter j of w (empty word: class 0) of the affine
     subspaces S_j = b_j + D_j; computed from words of length <= 5 and certified letter-invariant
     (D_j A_c inside D_c, b_j A_c - b_c in D_c).  |S| = sum_j p^(dim D_j) if the S_j are pairwise disjoint.
  B. distinct left vectors modulo p among the words of length <= 8 (= the 4^8 words of length exactly 8, because a
     leading 0 does not change the left vector) and of length exactly 10, 12; compared with 4^n (no collision), with
     |S|, and with the number expected for uniform sampling from S.
  C. the orbit O (all words).
       p = 3: exhaustive breadth-first closure on a bitmap of (Z/3)^17.
       p >= 5: every letter restricted to a class is an affine BIJECTION S_j -> S_c (checked), so the monoid of return
       maps to S_0 is a finite group G_0 of affine maps of F_p^d (d = dim D_0), generated by the 16 loops
       tau_j phi_(j->c) tau_c^(-1).  Translations in G_0 are harvested from iterated commutators (derived series) and
       closed under conjugation: a subspace W.  If W = F_p^d then G_0 is transitive, hence O = S (PROVED for that p).
       Otherwise the orbit is a union of W-cosets and is counted exactly by breadth-first search on F_p^d / W.
  D. consequence when O = S and the maps are bijections: the walk "append a uniform random letter" on S is doubly
     stochastic, irreducible and aperiodic (letter 0 fixes l(empty)), so the law of l(w) mod p over the words of length
     n tends to the uniform law on S; if FIN is not constant on any S_j the law of H mod p tends to the uniform law.

Usage: python3 orbit_modp.py [p ...]
"""
import itertools
import math
import random
import sys
import time

import numpy as np
from numba import njit

import minrep

R = 17


def rref_mod(mat, p):
    A = np.array(mat, dtype=np.int64) % p
    if A.ndim == 1:
        A = A.reshape(1, -1)
    m, n = A.shape
    piv = []
    r = 0
    for c in range(n):
        if r == m:
            break
        nz = np.nonzero(A[r:, c])[0]
        if nz.size == 0:
            continue
        i = r + int(nz[0])
        if i != r:
            A[[r, i]] = A[[i, r]]
        A[r] = (A[r] * pow(int(A[r, c]), p - 2, p)) % p
        for k in range(m):
            if k != r and A[k, c]:
                A[k] = (A[k] - A[k, c] * A[r]) % p
        piv.append(c)
        r += 1
    return A[:r].copy(), piv


def in_span(E, piv, v, p):
    """coordinates of v in the RREF basis E (pivot columns piv), or None"""
    v = np.array(v, dtype=np.int64) % p
    co = v[piv] if len(piv) else np.zeros(0, dtype=np.int64)
    rec = (co @ E) % p if len(piv) else np.zeros_like(v)
    if np.array_equal(rec, v):
        return co
    return None


def inv_mod(Mx, p):
    n = Mx.shape[0]
    A = np.concatenate([Mx % p, np.eye(n, dtype=np.int64)], axis=1)
    for c in range(n):
        nz = np.nonzero(A[c:, c])[0]
        if nz.size == 0:
            raise ValueError("singular")
        i = c + int(nz[0])
        if i != c:
            A[[c, i]] = A[[i, c]]
        A[c] = (A[c] * pow(int(A[c, c]), p - 2, p)) % p
        for k in range(n):
            if k != c and A[k, c]:
                A[k] = (A[k] - A[k, c] * A[c]) % p
    return A[:, n:].copy()


@njit(cache=True)
def nb_codes_exact_length(n, A, L0, p):
    """codes (base-p digits) of l(w) mod p for all 4^n words of length n"""
    Rr = L0.shape[0]
    out = np.empty(4 ** n, dtype=np.int64)
    st = np.zeros((n + 1, Rr), dtype=np.int64)
    for j in range(Rr):
        st[0, j] = L0[j]
    pw = np.ones(Rr, dtype=np.int64)
    for j in range(1, Rr):
        pw[j] = pw[j - 1] * p
    if n == 0:
        c0 = 0
        for j in range(Rr):
            c0 += st[0, j] * pw[j]
        out[0] = c0
        return out
    letter = np.zeros(n + 1, dtype=np.int64)
    d = 0
    pos = 0
    while True:
        if letter[d] == 4:
            d -= 1
            if d < 0:
                break
            letter[d] += 1
            continue
        c = letter[d]
        for j in range(Rr):
            acc = 0
            for i in range(Rr):
                acc += st[d, i] * A[c, i, j]
            st[d + 1, j] = acc % p
        if d + 1 == n:
            code = 0
            for j in range(Rr):
                code += st[n, j] * pw[j]
            out[pos] = code
            pos += 1
            letter[d] += 1
        else:
            d += 1
            letter[d] = 0
    return out


@njit(cache=True)
def nb_closure_bitmap(A, L0, p, cap):
    """exhaustive orbit of L0 under the four maps v -> v A_c mod p; returns the list of codes (or -1 size if > cap)"""
    Rr = L0.shape[0]
    size = 1
    for _ in range(Rr):
        size *= p
    seen = np.zeros(size, dtype=np.uint8)
    queue = np.empty(cap, dtype=np.int64)
    pw = np.ones(Rr, dtype=np.int64)
    for j in range(1, Rr):
        pw[j] = pw[j - 1] * p
    code0 = 0
    for j in range(Rr):
        code0 += L0[j] * pw[j]
    seen[code0] = 1
    queue[0] = code0
    head = 0
    tail = 1
    v = np.zeros(Rr, dtype=np.int64)
    while head < tail:
        code = queue[head]
        head += 1
        x = code
        for j in range(Rr):
            v[j] = x % p
            x //= p
        for c in range(4):
            nc = 0
            for j in range(Rr):
                acc = 0
                for i in range(Rr):
                    acc += v[i] * A[c, i, j]
                nc += (acc % p) * pw[j]
            if seen[nc] == 0:
                seen[nc] = 1
                if tail >= cap:
                    return queue[:0], -1
                queue[tail] = nc
                tail += 1
    return queue[:tail].copy(), tail


@njit(cache=True)
def nb_orbit_tables(sc, A, FIN, p):
    """for the sorted orbit codes sc: next-state indices under the four letters and H mod p"""
    n = sc.size
    Rr = A.shape[1]
    nxt = np.empty((4, n), dtype=np.int32)
    hval = np.empty(n, dtype=np.int8)
    pw = np.ones(Rr, dtype=np.int64)
    for j in range(1, Rr):
        pw[j] = pw[j - 1] * p
    v = np.zeros(Rr, dtype=np.int64)
    for idx in range(n):
        x = sc[idx]
        h = 0
        for j in range(Rr):
            v[j] = x % p
            x //= p
            h += v[j] * FIN[j]
        hval[idx] = h % p
        for c in range(4):
            nc = 0
            for j in range(Rr):
                acc = 0
                for i in range(Rr):
                    acc += v[i] * A[c, i, j]
                nc += (acc % p) * pw[j]
            lo = 0
            hi = n
            while lo < hi:
                mid = (lo + hi) // 2
                if sc[mid] < nc:
                    lo = mid + 1
                else:
                    hi = mid
            nxt[c, idx] = lo
    return nxt, hval


@njit(cache=True)
def nb_walk_step(dist, nxt, new):
    n = dist.size
    for i in range(n):
        new[i] = 0.0
    for c in range(4):
        for i in range(n):
            new[nxt[c, i]] += 0.25 * dist[i]


@njit(cache=True)
def nb_class_hist(dist, hval, p):
    out = np.zeros(p)
    for i in range(dist.size):
        out[hval[i]] += dist[i]
    return out


def analyse(p, rep, out):
    ok = True

    def check(name, cond):
        nonlocal ok
        print(("   PASS  " if cond else "   FAIL  ") + name)
        ok &= bool(cond)

    A_int, L0_int, FIN_int = rep["A"], rep["L0"], rep["FIN"]
    A = np.array([[[A_int[c][i][j] % p for j in range(R)] for i in range(R)] for c in range(4)], dtype=np.int64)
    L0 = np.array([x % p for x in L0_int], dtype=np.int64)
    FIN = np.array([x % p for x in FIN_int], dtype=np.int64)
    print(f"p = {p}")
    # A. invariant set
    pts = {0: [L0.copy()], 1: [], 2: [], 3: []}
    cur = [((), L0)]
    for n in range(1, 6):
        nxt = []
        for w, v in cur:
            for c in range(4):
                v2 = (v @ A[c]) % p
                nxt.append((w + (c,), v2))
                pts[c].append(v2)
        cur = nxt
    base = {0: L0.copy()}
    for j in (1, 2, 3):
        base[j] = (L0 @ A[j]) % p
    E, PIV = {}, {}
    for j in range(4):
        diffs = np.array([(v - base[j]) % p for v in pts[j]], dtype=np.int64)
        E[j], PIV[j] = rref_mod(diffs, p)
    dims = [len(PIV[j]) for j in range(4)]
    stable = True
    for j in range(4):
        for c in range(4):
            img = (E[j] @ A[c]) % p
            for row in img:
                stable &= in_span(E[c], PIV[c], row, p) is not None
            stable &= in_span(E[c], PIV[c], (base[j] @ A[c] - base[c]) % p, p) is not None
    check(f"S = union of b_j + D_j is letter-invariant and contains l(empty); dims {dims}", stable)
    same_dir = all(np.array_equal(E[j], E[0]) for j in range(4))
    disjoint = True
    for i in range(4):
        for j in range(i + 1, 4):
            # b_i + D_i and b_j + D_j meet iff b_j - b_i lies in D_i + D_j
            Es, Ps = rref_mod(np.vstack([E[i], E[j]]), p)
            if in_span(Es, Ps, (base[j] - base[i]) % p, p) is not None:
                disjoint = False
    sizeS = sum(p ** d for d in dims) if disjoint else None
    print(f"   direction spaces equal: {same_dir}; classes pairwise disjoint: {disjoint}; |S| = {sizeS}"
          f" = {sizeS / p ** R:.3e} of p^17")
    fin_nonconst = all(bool(((E[j] @ FIN) % p).any()) for j in range(4))
    print(f"   H = l . FIN is non-constant on every S_j: {fin_nonconst}")
    out["dims"] = dims
    out["sizeS"] = sizeS
    # B. distinct left vectors among short words
    rows = []
    for n in (8, 10, 12):
        codes = nb_codes_exact_length(n, A, L0, p)
        nd = int(np.unique(codes).size)
        N = 4 ** n
        exp_unif = sizeS * (1 - math.exp(-N / sizeS)) if sizeS else float("nan")
        rows.append((n, N, nd, exp_unif))
        print(f"   words of length {n:2d}: {N:9d} words, {nd:9d} distinct left vectors mod {p}"
              f" (uniform sampling from S would give {exp_unif:12.1f})")
    out["distinct"] = rows
    # C. the orbit
    if p == 3:
        t0 = time.time()
        codes, size = nb_closure_bitmap(A, L0, p, 40_000_000)
        print(f"   exhaustive closure: |O| = {size}  ({time.time() - t0:.1f} s); |S| = {sizeS}; "
              f"|O| / |S| = {size / sizeS:.6f}")
        out["orbit"] = int(size)
        # class of each orbit point (chunked)
        sc = np.sort(codes)
        cnts = [0, 0, 0, 0]
        chunk = 1_000_000
        for a in range(0, sc.size, chunk):
            x = sc[a:a + chunk].copy()
            digs = np.zeros((x.size, R), dtype=np.int64)
            for j in range(R):
                digs[:, j] = x % p
                x //= p
            for j in range(4):
                dd = (digs - base[j]) % p
                co = dd[:, PIV[j]]
                rec = (co @ E[j]) % p
                cnts[j] += int((rec == dd).all(axis=1).sum())
        print(f"   orbit points per class: {cnts} (each S_j has {p ** dims[0]} points)")
        # ranks of the letters on the direction spaces
        rk = [[len(rref_mod((E[j] @ A[c]) % p, p)[1]) for c in range(4)] for j in range(4)]
        print(f"   rank of letter c on D_j (rows j, columns c): {rk}")
        out["class_counts"] = cnts
        # law of the walk on O and the limit law of H mod 3 (power iteration, float64)
        nxt, hval = nb_orbit_tables(sc, A, FIN, p)
        pw = p ** np.arange(R, dtype=np.int64)
        start = int(np.searchsorted(sc, int(L0 @ pw)))
        dist = np.zeros(sc.size)
        dist[start] = 1.0
        new = np.zeros(sc.size)
        walk = []
        for n in range(1, 161):
            nb_walk_step(dist, nxt, new)
            dist, new = new, dist
            if n in (8, 12, 16, 17, 24, 32, 48, 64, 96, 128, 160):
                f = p * nb_class_hist(dist, hval, p)
                walk.append((n, [float(x) for x in f]))
                print(f"   walk on O after {n:3d} letters: class factors of H mod 3 = "
                      + " ".join(f"{x:.10f}" for x in f) + f"; max and min state weight * |O| = "
                      f"{dist.max() * sc.size:.6f}, {dist.min() * sc.size:.6f}")
        out["walk3"] = walk
        return ok
    # p >= 5: bijections and the return group
    d = dims[0]
    bij = disjoint and all(dd == d for dd in dims)
    Lam = {}
    tr = {}
    for j in range(4):
        for c in range(4):
            img = (E[j] @ A[c]) % p
            Lam[(j, c)] = img[:, PIV[c]] % p
            tr[(j, c)] = ((base[j] @ A[c] - base[c]) % p)[PIV[c]]
            bij &= len(rref_mod(Lam[(j, c)], p)[1]) == d
    check("every letter is an affine bijection S_j -> S_c (16 maps of rank dim D)", bij)
    if not bij:
        return ok

    def aff(Lm, t):
        Mx = np.zeros((d + 1, d + 1), dtype=np.int64)
        Mx[:d, :d] = Lm
        Mx[d, :d] = t
        Mx[d, d] = 1
        return Mx

    def mul(X, Y):
        return (X @ Y) % p

    def ainv(X):
        Li = inv_mod(X[:d, :d], p)
        t = (-(X[d, :d] @ Li)) % p
        return aff(Li, t)

    phi = {k: aff(Lam[k], tr[k]) for k in Lam}
    tau = {0: np.eye(d + 1, dtype=np.int64)}
    for j in (1, 2, 3):
        tau[j] = phi[(0, j)]
    gens = []
    for j in range(4):
        for c in range(4):
            g = mul(mul(tau[j], phi[(j, c)]), ainv(tau[c]))
            if not np.array_equal(g, np.eye(d + 1, dtype=np.int64)):
                gens.append(g)
    ginv = [ainv(g) for g in gens]
    allg = gens + ginv
    I = np.eye(d, dtype=np.int64)
    # translations from iterated commutators
    rng = random.Random(1000 + p)
    Wrows = np.zeros((0, d), dtype=np.int64)
    Wpiv = []

    def add_translation(vec):
        nonlocal Wrows, Wpiv
        if not vec.any():
            return
        Wrows, Wpiv = rref_mod(np.vstack([Wrows, vec.reshape(1, -1)]), p)

    def close_W():
        nonlocal Wrows, Wpiv
        while True:
            before = len(Wpiv)
            if before == 0 or before == d:
                return
            stack = [Wrows]
            for g in allg:
                stack.append((Wrows @ g[:d, :d]) % p)
            Wrows, Wpiv = rref_mod(np.vstack(stack), p)
            if len(Wpiv) == before:
                return

    def comm(x, y):
        return mul(mul(ainv(x), ainv(y)), mul(x, y))

    level = list(allg)
    pool = list(allg)
    harvested = 0
    for depth in range(1, 9):
        new = []
        pairs = [(a, b) for a in range(len(level)) for b in range(len(level)) if a < b]
        rng.shuffle(pairs)
        for (a, b) in pairs[:400]:
            cm = comm(level[a], level[b])
            if np.array_equal(cm[:d, :d], I):
                if cm[d, :d].any():
                    add_translation(cm[d, :d].copy())
                    harvested += 1
            else:
                new.append(cm)
        # also commutators with the generators (stay in the same term of the derived series)
        for x in list(new)[:60]:
            for g in allg[:8]:
                cm = comm(x, g)
                if np.array_equal(cm[:d, :d], I):
                    if cm[d, :d].any():
                        add_translation(cm[d, :d].copy())
                        harvested += 1
                else:
                    new.append(cm)
        close_W()
        print(f"   derived depth {depth}: {len(new)} non-translation elements kept, translations harvested so far "
              f"{harvested}, dim W = {len(Wpiv)} of {d}")
        if len(Wpiv) == d or not new:
            break
        rng.shuffle(new)
        level = new[:60]
        pool += new[:400]
    # refinement: W is normal (invariant under every linear part), so the orbit is a union of W-cosets and G_0 acts
    # on F_p^d / W; an element whose linear part is the identity modulo W acts there as a translation by its t, so
    # t can be added to W (the orbit is then a union of cosets of the larger subspace).  Repeat until stable.
    rounds = 0
    while len(Wpiv) < d:
        grew = False
        for g in pool:
            if len(Wpiv) == d:
                break
            diff = (g[:d, :d] - I) % p
            if len(Wpiv) == 0:
                triv = not diff.any()
            else:
                red = (diff - diff[:, Wpiv] @ Wrows) % p
                triv = not red.any()
            if triv:
                t = g[d, :d].copy()
                if len(Wpiv):
                    t = (t - t[Wpiv] @ Wrows) % p
                if t.any():
                    add_translation(g[d, :d].copy())
                    close_W()
                    grew = True
        rounds += 1
        if not grew:
            break
    print(f"   after {rounds} refinement rounds over {len(pool)} group elements: dim W = {len(Wpiv)} of {d}")
    dW = len(Wpiv)
    out["dimW"] = dW
    if dW == d:
        check(f"the return group G_0 contains all translations of F_p^{d}: O = S, |O| = {sizeS}", True)
        out["orbit"] = sizeS
        return ok
    # count the orbit on the quotient F_p^d / W
    free = [c for c in range(d) if c not in Wpiv]
    dq = d - dW
    if p ** dq > 60_000_000:
        print(f"   quotient too large for an exhaustive search (p^{dq}); orbit size not determined")
        out["orbit"] = None
        return ok

    def reduce_q(Y):
        """canonical representatives modulo W of the rows of Y: zero at the pivot columns of W"""
        if dW:
            Y = (Y - Y[:, Wpiv] @ Wrows) % p
        return Y[:, free]

    pwq = p ** np.arange(dq, dtype=np.int64)
    seen = np.zeros(p ** dq, dtype=bool)
    y0 = np.zeros((1, d), dtype=np.int64)
    fr = reduce_q(y0)
    seen[int(fr[0] @ pwq)] = True
    frontier = fr
    while frontier.shape[0]:
        full = np.zeros((frontier.shape[0], d), dtype=np.int64)
        full[:, free] = frontier
        nxt_codes = []
        for g in gens:
            img = (full @ g[:d, :d] + g[d, :d]) % p
            q = reduce_q(img)
            nxt_codes.append(q @ pwq)
        codes = np.unique(np.concatenate(nxt_codes))
        codes = codes[~seen[codes]]
        seen[codes] = True
        frontier = np.zeros((codes.size, dq), dtype=np.int64)
        x = codes.copy()
        for j in range(dq):
            frontier[:, j] = x % p
            x //= p
    orbq = int(seen.sum())
    size = 4 * orbq * p ** dW
    print(f"   orbit of G_0 on F_p^{d} / W: {orbq} of {p ** dq} cosets; |O| = {size}; |S| = {sizeS}")
    out["orbit"] = size
    check("O = S", size == sizeS)
    return ok


def main():
    primes = [int(x) for x in sys.argv[1:]] or [3, 5, 7, 11, 13]
    rep = minrep.build()
    ok = True
    summary = {}
    for p in primes:
        summary[p] = {}
        ok &= analyse(p, rep, summary[p])
    print("summary: p, dims of the classes, |S|, |O|, distinct left vectors among the 4^8 words of length <= 8")
    for p in primes:
        s = summary[p]
        print(f"   p = {p:2d}: dims {s.get('dims')}, |S| = {s.get('sizeS')}, |O| = {s.get('orbit')}, "
              f"distinct(8) = {s['distinct'][0][2]} of {s['distinct'][0][1]}")
    print("ALL CHECKS PASSED" if ok else "CHECK FAILED")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
