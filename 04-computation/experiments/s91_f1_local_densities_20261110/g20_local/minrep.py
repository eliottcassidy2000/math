#!/usr/bin/env python3
"""S91 helper (g20_local): the minimal Z-representation of the Hamiltonian-path series of the two-apex grammar G(2,0).

Construction (exact integers; Hankel / Schuetzenberger / Fliess reduction over Z):
  * Lambda_reach = Z-span of the 36-dimensional state rows e M_w (closure under the four letters, breadth first);
  * Lambda_obs   = Z-span of the columns M_w f;
  * G = pairing matrix of the two echelon bases; rank_Q G is the Hankel rank; the elementary divisors of G are those of
    the infinite Hankel matrix (H(uv))_{u,v}, so the Hankel rank modulo p is #{elementary divisors prime to p};
  * Lambda_L = Z-span of the rows L(w) = (e M_w) Bobs^T; in an echelon basis of Lambda_L every word has an integer
    coordinate vector l(w) in Z^R, the letters act by integer matrices A_c (l(wc) = l(w) A_c), and
    H(uv) = l(u) . r(v) with integer right vectors r(v); l(empty) = L0, r(empty) = FIN.

build() returns a dict with everything; `python3 minrep.py` prints the summary and runs the checks.
"""
import itertools
import sys
from fractions import Fraction

import g20_core as g
from lattice_tools import Lattice, smith_diagonal, rank_mod, rank_q, solve_q

NS = g.NS
Mnp = g.letter_matrices()
M = [[[int(Mnp[c][s][t]) for t in range(NS)] for s in range(NS)] for c in range(4)]
E0 = [int(x) for x in g.INIT]
F0 = [int(x) for x in g.ACC]


def row_step(v, c):
    out = [0] * NS
    for s in range(NS):
        x = v[s]
        if x:
            for k in range(g.T_CNT[c, s]):
                out[g.T_TO[c, s, k]] += x
    return out


def col_step(u, c):
    """(M_c u)(s) = sum_t M_c[s][t] u[t]"""
    return [sum(u[g.T_TO[c, s, k]] for k in range(g.T_CNT[c, s])) for s in range(NS)]


def closure(start, step):
    lat = Lattice(NS)
    lat.add(start)
    gens = [((), start)]
    frontier = [((), start)]
    while frontier:
        nxt = []
        for w, v in frontier:
            for c in range(4):
                v2 = step(v, c)
                if lat.add(v2):
                    nxt.append((w + (c,), v2))
        gens += nxt
        frontier = nxt
    # stability certificate: every letter image of every basis row lies in the lattice
    for b in lat.rows():
        for c in range(4):
            assert lat.contains(step(b, c)), "lattice not letter-stable"
    return lat, gens


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def build():
    reach, reach_gens = closure(E0, row_step)
    obs, obs_gens = closure(F0, col_step)
    Br = reach.rows()
    Bo = obs.rows()
    G = [[dot(r, o) for o in Bo] for r in Br]
    hankel_rank = rank_q(G)
    eldiv = smith_diagonal(G)
    # left lattice with tracked preimages in the state space
    nobs = len(Bo)
    aug = Lattice(nobs)
    for r in Br:
        aug.add([dot(r, o) for o in Bo] + list(r))
    rows = aug.rows()
    R = len(rows)
    left = Lattice(nobs)
    for row in rows:
        left.add(row[:nobs])
    pre = [row[nobs:] for row in rows]          # state-space preimages of the basis vectors of Lambda_L

    def lcoords_state(v):
        return left.coords([dot(v, o) for o in Bo])

    A = []
    for c in range(4):
        A.append([lcoords_state(row_step(pre[i], c)) for i in range(R)])
    L0 = lcoords_state(E0)
    Bmat = left.rows()                            # R x nobs
    phi = obs.coords(F0)
    FIN = [dot(Bmat[i], phi) for i in range(R)]

    def rvec_state(u):                            # right vector of a column u in Lambda_obs
        cu = obs.coords(u)
        return [dot(Bmat[i], cu) for i in range(R)]

    Ac = [[[A[c][i][j] for i in range(R)] for j in range(R)] for c in range(4)]  # transposes, for right action

    def l_of(word):
        v = L0
        for c in word:
            v = [sum(v[i] * A[c][i][j] for i in range(R)) for j in range(R)]
        return v

    def r_of(word):
        u = FIN
        for c in reversed(word):
            u = [sum(A[c][i][j] * u[j] for j in range(R)) for i in range(R)]
        return u

    return dict(reach=reach, obs=obs, Br=Br, Bo=Bo, G=G, hankel_rank=hankel_rank, eldiv=eldiv, R=R, A=A, L0=L0,
                FIN=FIN, l_of=l_of, r_of=r_of, reach_gens=reach_gens, obs_gens=obs_gens, rvec_state=rvec_state,
                lcoords_state=lcoords_state)


def main():
    ok = True

    def check(name, cond):
        nonlocal ok
        print(("PASS  " if cond else "FAIL  ") + name)
        ok &= bool(cond)

    rep = build()
    R = rep["R"]
    A, L0, FIN = rep["A"], rep["L0"], rep["FIN"]
    print(f"reachable lattice rank {rep['reach'].rank} (generated by words of length <= "
          f"{max(len(w) for w, _ in rep['reach_gens'])}), observable lattice rank {rep['obs'].rank} "
          f"(suffixes of length <= {max(len(w) for w, _ in rep['obs_gens'])})")
    print(f"Hankel rank over Q = {rep['hankel_rank']}; dimension of the minimal Z-representation = {R}")
    print("elementary divisors of the Hankel matrix:", rep["eldiv"])
    check("Hankel rank over Q is 17 (Session 191, THM-4878 (3))", rep["hankel_rank"] == 17 and R == 17)
    for p in (2, 3, 5, 7, 11, 13, 17, 19, 23):
        rp = rank_mod(rep["G"], p)
        want = sum(1 for d in rep["eldiv"] if d % p != 0)
        print(f"   Hankel rank modulo {p:2d} = {rp}")
        check(f"rank mod {p} agrees with the elementary divisors", rp == want)
    # the representation reproduces H: all words of length <= 6 as l(w).FIN, and H(uv) = l(u).r(v) for |u|,|v| <= 3
    bad = 0
    for n in range(0, 7):
        for w in itertools.product(range(4), repeat=n):
            if dot(rep["l_of"](w), FIN) != g.H_word(w):
                bad += 1
    check("l(w) . FIN = H(w) for all words of length <= 6", bad == 0)
    bad = 0
    words3 = [w for n in range(0, 4) for w in itertools.product(range(4), repeat=n)]
    lv = {w: rep["l_of"](w) for w in words3}
    rv = {w: rep["r_of"](w) for w in words3}
    for u in words3:
        for v in words3:
            if dot(lv[u], rv[v]) != g.H_word(u + v):
                bad += 1
    check("H(uv) = l(u) . r(v) for all u, v of length <= 3 (7,225 pairs)", bad == 0)
    # left vectors generate Z^R; right vectors generate a sublattice of index prod(eldiv)
    latl = Lattice(R)
    for w in words3:
        latl.add(lv[w])
    idx = 1
    for j in sorted(latl.basis):
        idx *= abs(latl.basis[j][j])
    check("the left vectors of words of length <= 3 generate Z^17 (index 1)", latl.rank == R and idx == 1)
    latr = Lattice(R)
    for w in words3:
        latr.add(rv[w])
    idxr = 1
    for j in sorted(latr.basis):
        idxr *= abs(latr.basis[j][j])
    prod = 1
    for d in rep["eldiv"]:
        prod *= d
    print(f"index of the lattice of right vectors in Z^17: {idxr}; product of elementary divisors: {prod}")
    check("index of the right lattice = product of the elementary divisors", idxr == prod)
    # constant functionals
    rho = solve_q([lv[w] for w in words3], [1] * len(words3))
    tau = solve_q([rv[w] for w in words3], [1] * len(words3))
    check("there is rho with l(w) . rho = 1 on all words of length <= 3", rho is not None)
    check("there is tau with tau . r(v) = 1 on all suffixes of length <= 3", tau is not None)
    if rho is not None:
        inv = all([sum(A[c][i][j] * rho[j] for j in range(R)) for i in range(R)] == rho for c in range(4))
        check("A_c rho = rho for the four letters and l(empty) . rho = 1: l(w) . rho = 1 for EVERY word (PROVED)",
              inv and dot(L0, rho) == 1)
        print("   rho =", [str(x) for x in rho])
    if tau is not None:
        inv = all([sum(tau[i] * A[c][i][j] for i in range(R)) for j in range(R)] == tau for c in range(4))
        check("tau A_c = tau for the four letters and tau . r(empty) = 1: tau . r(v) = 1 for EVERY suffix (PROVED)",
              inv and dot(tau, FIN) == 1)
        print("   tau =", [str(x) for x in tau])
    if rho is not None and tau is not None:
        print("   tau . rho =", dot(tau, rho))
    print("ALL CHECKS PASSED" if ok else "CHECK FAILED")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
