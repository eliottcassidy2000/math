# ---------------------------------------------------------------- orbit labelling
def orbit_minima(q, gens):
    """For the group generated by gens (units mod q) acting on Z/q by multiplication:
    returns (label, omin) arrays: label[a] = orbit id of residue a, omin[id] = min(a, q-a) over the orbit."""
    label = [-1] * q
    omin = []
    for s in range(q):
        if label[s] != -1:
            continue
        oid = len(omin)
        stack = [s]; label[s] = oid; best = min(s, q - s)
        while stack:
            a = stack.pop()
            for g in gens:
                b = (g * a) % q
                if label[b] == -1:
                    label[b] = oid; stack.append(b)
                    d = b if b <= q - b else q - b
                    if d < best: best = d
        omin.append(best)
    return label, omin

def I_values(q, cache):
    """I(m/q) for all m prime to q, as Fractions; q arbitrary (2,3 allowed)."""
    e = 0; f = 0; qq = q
    while qq % 2 == 0: qq //= 2; e += 1
    while qq % 3 == 0: qq //= 3; f += 1
    qp = qq
    # <2,3>-orbit minima at q'
    if qp == 1:
        base = None
    else:
        key = ('23', qp)
        if key not in cache: cache[key] = orbit_minima(qp, (2 % qp, 3 % qp) if qp > 1 else ())
        base = cache[key]
    # <3>-orbit minima at 2^e' q' (e' = 1..e) and <2>-orbit minima at 3^f' q' (f' = 1..f)
    threes = []
    for ep in range(1, e + 1):
        D = (1 << ep) * qp
        key = ('3', D)
        if key not in cache: cache[key] = orbit_minima(D, (3 % D,))
        threes.append((D, cache[key]))
    twos = []
    for fp in range(1, f + 1):
        D = (3 ** fp) * qp
        key = ('2', D)
        if key not in cache: cache[key] = orbit_minima(D, (2 % D,))
        twos.append((D, cache[key]))
    res = {}
    for m in range(1, q):
        if math.gcd(m, q) != 1: continue
        best = Fraction(1, 2)
        # single points m/(2^e' 3^f' q') for e'>=1, f'>=1 (the orbit before either prime is exhausted)
        for ep in range(1, e + 1):
            for fp in range(1, f + 1):
                D = (1 << ep) * (3 ** fp) * qp
                r = m % D
                d = Fraction(min(r, D - r), D)
                if d < best: best = d
        for D, (lab, om) in threes:
            d = Fraction(om[lab[m % D]], D)
            if d < best: best = d
        for D, (lab, om) in twos:
            d = Fraction(om[lab[m % D]], D)
            if d < best: best = d
        if base is not None:
            lab, om = base
            d = Fraction(om[lab[m % qp]], qp)
            if d < best: best = d
        else:
            best = Fraction(0)
        res[m] = best
    return res

def phi(q):
    r, n, p = q, q, 2
    while p * p <= n:
        if n % p == 0:
            while n % p == 0: n //= p
            r -= r // p
        p += 1
    if n > 1: r -= r // n
    return r

def is_prime(n):
    if n < 2: return False
    if n % 2 == 0: return n == 2
    r = int(n ** 0.5)
    for p in range(3, r + 1, 2):
        if n % p == 0: return False
    return True

