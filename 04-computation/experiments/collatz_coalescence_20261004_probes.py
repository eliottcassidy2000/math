def probe_E(KMAX=24):
    P("=" * 78)
    P("Probe E: the powers of three against bounded-depth coefficient-descent certificates")
    P("=" * 78)
    # which cycle points are in the closure of <3> in Z_2^x = {u : u = 1 or 3 mod 8}
    cyc = {-1: [-1], -5: [-5, -7], -17: [-17, -25, -37, -55, -41, -61, -91], 1: [1]}
    for x0, pts in cyc.items():
        ins = [x for x in pts if x % 8 in (1, 3)]
        P(f"  cycle of {x0}: points {pts}; in the closure of <3> (1 or 3 mod 8): {ins}")
    # 2-adic digits of log_3(-5): a_k with 3^(a_k) = -5 mod 2^k
    digs = []
    a = 0
    for k in range(3, 40):
        mod = 1 << k
        # extend a mod 2^(k-2): try a and a + 2^(k-3)
        if k == 3:
            a = 1  # 3^1 = 3 = -5 mod 8
        else:
            if pow(3, a, mod) != (mod - 5) % mod:
                a += 1 << (k - 3)
            assert pow(3, a, mod) == (mod - 5) % mod, (k, a)
        digs.append(a)
    P(f"  log_3(-5) in Z_2: a mod 2^(k-2) for k = 3..39: {digs[:12]} ... {digs[-1]} (mod 2^37)")
    P(f"  in particular a = {digs[0]} mod 2, {digs[1]} mod 4, {digs[2]} mod 8 (codex's residual class 3 mod 8 is this -5 shadow), {digs[6]} mod 128, {digs[8]} mod 512")
    if np is None:
        P("  numpy unavailable; skipping the Bad_k scan"); return
    omax = [0] * (KMAX + 1)
    for j in range(1, KMAX + 1):
        o = 0
        while 3 ** (o + 1) < 2 ** j: o += 1
        omax[j] = o  # descent at step j iff o_j <= omax[j]  (3^o < 2^j)
    share_hist = []
    for k in range(4, KMAX + 1):
        mod = 1 << k
        r = np.arange(1, mod, 2, dtype=np.int64)
        x = r.copy(); o = np.zeros_like(r); alive = np.ones(r.shape, dtype=bool)
        for j in range(1, k + 1):
            odd = (x & 1) == 1
            x = np.where(odd, (3 * x + 1) >> 1, x >> 1)
            o = o + odd
            alive &= (o > omax[j])
        bad = r[alive]
        in3 = (bad % 8 == 1) | (bad % 8 == 3)   # the subgroup <3> of the odd residues mod 2^k (index 2) = {1,3 mod 8}
        n3 = int(in3.sum()); nb = int(bad.size)
        # exponent classes: a mod 2^(k-2) with 3^a in Bad_k  <=> number of Bad_k residues in <3> (3 is a bijection a -> 3^a)
        share = n3 / nb
        share_hist.append((k, nb, n3, share))
        P(f"  k={k:2d}: |Bad_k| = {nb:8d}   |Bad_k cap <3>| = {n3:7d}   share = {share:.4f}   (resisting exponent classes a mod 2^(k-2): {n3} of {1 << (k-2)})")
    P("  heuristics for the limiting share: plain critical tilt 1 - log_3 2 = 0.3691 (third letter 0 vs 1 under the zero-drift tilt);")
    P("  the survivors are a ballot-conditioned walk, which biases the third letter toward 1, so the limit should sit BELOW 0.369.")
    # E2: the share to large k by the (j, o) dynamic programme (the condition 3^o_j > 2^j depends on (j, o_j) only;
    # residues mod 2^k <-> words bijectively, Terras), in float64 normalised by 2^-j (fair-coin probabilities).
    P("-" * 78)
    P("  E2: share s_k = W_k(110)/W_k by the (j,o) dynamic programme (exact condition; float64 probabilities), and a 1/k extrapolation")
    KBIG = 6000
    omax2 = [0] * (KBIG + 1)
    for j in range(1, KBIG + 1):
        o = 0
        while 3 ** (o + 1) < 2 ** j: o += 1
        omax2[j] = o
    # state: probability vector over o (number of ones so far), two copies: prefix 110 and prefix 111
    def run(prefix):
        # after 3 letters
        o0 = sum(prefix)
        p = np.zeros(KBIG + 2); p[o0] = 0.125
        hist = {}
        for j in range(4, KBIG + 1):
            q = np.zeros_like(p)
            q[1:] += 0.5 * p[:-1]   # letter 1
            q += 0.5 * p            # letter 0
            q[:omax2[j] + 1] = 0.0  # kill descents: need o_j > omax2[j]
            p = q
            if j in (24, 50, 100, 200, 400, 800, 1600, 3200, 6000):
                hist[j] = p.sum()
        return hist
    h0 = run((1, 1, 0)); h1 = run((1, 1, 1))
    ks = sorted(h0)
    shares = {}
    for k in ks:
        shares[k] = h0[k] / (h0[k] + h1[k])
        P(f"    k={k:5d}: W_k(110)/2^k = {h0[k]:.4e}  W_k(111)/2^k = {h1[k]:.4e}  share s_k = {shares[k]:.5f}")
    # Richardson-type extrapolation assuming s_k = s_inf + c/k
    for (k1, k2) in ((400, 800), (800, 1600), (1600, 3200), (3200, 6000)):
        s_inf = (k2 * shares[k2] - k1 * shares[k1]) / (k2 - k1)
        P(f"    1/k extrapolation from k = {k1}, {k2}: s_inf = {s_inf:.5f}")
    P("  (the (j,o) programme reproduces the exact counts above: compare W_24(110)/2^24 with 51280/2^24 = %.4e)" % (51280 / 2 ** 24))

