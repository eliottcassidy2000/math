def probe_F(NMAX=20):
    P("=" * 78)
    P("Probe F: the sheet involution is a half-turn 3-adically and a coset swap 2-adically")
    P("=" * 78)
    for n in range(2, NMAX + 1):
        L = 2 * 3 ** (n - 1)
        assert pow(2, L // 2, 3 ** n) == 3 ** n - 1
    P(f"  2^(L/2) = -1 mod 3^n for 2 <= n <= {NMAX}, L = 2*3^(n-1): -1 is in <2> (the half-turn of the unit cycle, THM-4521(2))")
    for n in range(3, NMAX + 1):
        mod = 1 << n
        x = 1; found = False
        for a in range(1 << (n - 2)):
            if x == mod - 1: found = True; break
            x = (3 * x) % mod
        assert not found
    P(f"  -1 is not in <3> mod 2^n for 3 <= n <= {NMAX}: <3> = {{1, 3 mod 8}} has index 2 and the sheet swaps the two cosets")

