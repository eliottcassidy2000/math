def arch_class(p, a, q=3):
    """perigee classification (gates lane, Belaga 2003): 'none' = no rational cycle of the clock has
    least point >= 1 (so no integral word), 'all' = every word's cycle has least point >= 1, else
    'transition'.  Dyadic G>0: x_min <= 1/(2^(p/a) - q) and x_min >= c_min/G with
    c_min = q^a - 2^a (ones in front).  q-adic G<0: y_min >= c_min/|G|."""
    G = gate(p, a, q)
    M = abs(G)
    cmin = sum(q ** (a - 1 - i) * 2 ** i for i in range(a))
    if G > 0:
        if 2 ** p > (q + 1) ** a:
            return "none"
        if cmin >= G:
            return "all"
        return "transition"
    if 2 ** p < (q - 1) ** a:
        return "none"
    if cmin >= M:
        return "all"
    return "transition"


def gate_row(p, a, q=3):
    """all local/global data of one gate (exact), for all words and for PRIMITIVE words.
    Requires |D| < 2^62.  Necklace units: L = #primitive necklaces = Cp/p."""
    import sympy
    G = gate(p, a, q)
    M = abs(G)
    C = math.comb(p, a)
    L = lyndon_count(p, a)
    Cp = p * L
    row = dict(p=p, a=a, q=q, D=G, C=C, L=L, arch=arch_class(p, a, q))
    if M == 1:
        row.update(fac={}, pp=[], N_D=C, N_Dp=Cp, local={}, localp={}, glue=[], primes={})
        return row
    fac = {int(k): int(v) for k, v in sympy.factorint(M).items()}
    pp = sorted(qq ** e for qq, e in fac.items())
    local = {m: count_zero_mod(p, a, m, q) for m in pp}
    localp = {m: count_zero_prim(p, a, m, q) for m in pp}
    N_D = local[M] if M in local else count_zero_mod(p, a, M, q)
    N_Dp = localp[M] if M in localp else count_zero_prim(p, a, M, q)
    primes = {}
    for qq, e in fac.items():
        o2, o3 = mult_order(2, qq), mult_order(q, qq)
        Nq = local[qq] if qq in local else count_zero_mod(p, a, qq, q)
        Nqp = localp[qq] if qq in localp else count_zero_prim(p, a, qq, q)
        primes[qq] = dict(e=e, o2=o2, o3=o3, H=o2 * o3 // math.gcd(o2, o3), Nq=Nq, Nqp=Nqp)
    glue = []
    m = 1
    pred = float(Cp)
    for r, x in enumerate(pp, start=1):
        m *= x
        pred *= localp[x] / Cp if Cp else 0.0
        if r >= 2:
            Nm = N_Dp if m == M else count_zero_prim(p, a, m, q)
            glue.append((r, m, Nm, pred))
    row.update(fac=fac, pp=pp, N_D=N_D, N_Dp=N_Dp, local=local, localp=localp, glue=glue, primes=primes)
    return row


def lam_loc(row):
    """local-product prediction for the number of primitive integral NECKLACES:
    (Cp/p) * prod_{q^e || D} nu_{q^e},  nu = (primitive local count)/Cp."""
    Cp = row["p"] * row["L"]
    if Cp == 0:
        return 0.0
    lam = float(Cp)
    for m, n in row["localp"].items():
        lam *= n / Cp
    return lam / row["p"]


def classify(row):
    """GLOBAL (a primitive cycle) / REPEAT (only repetitions of smaller cycles) / ARCH (perigee: no
    eligible word) / PRIME-GATE (|D| a prime power: local = global) / LOCAL (a proper prime-power
    divisor already has no primitive solution) / HASSE (every prime power has primitive solutions,
    the full gate has none).  Suffix '!' = surprising: the necklace-Poisson expectation of the
    missing solutions is >= 3."""
    if row["N_Dp"] > 0:
        return "GLOBAL"
    if row["N_D"] > 0:
        return "REPEAT"
    if row["arch"] == "none":
        return "ARCH"
    L = row["L"]
    zeros = [m for m, n in row["localp"].items() if n == 0]
    if len(row["pp"]) == 1:
        return "PRIME-GATE" + ("!" if zeros and L / zeros[0] >= 3 else "")
    if zeros:
        return "LOCAL" + ("!" if any(L / m >= 3 for m in zeros) else "")
    return "HASSE" + ("!" if lam_loc(row) >= 3 else "")


def density_dp(p, a, m, q=3):
    """nu_m = #{w : c_w = 0 mod m} / C(p,a) for large p, by the residue DP in float64 with
    per-step max-normalisation (relative error ~1e-15 per entry; no cancellation)."""
    dp = np.zeros((a + 1, m), dtype=np.float64)
    dp[0, 0] = 1.0
    for s in range(p - 1, -1, -1):
        t2 = pow(2, s, m)
        lo = max(0, a - s - 1)  # rows that can still reach a ones
        for c in range(min(a - 1, p - 1 - s), lo - 1, -1):
            w = (pow(q, c, m) * t2) % m
            dp[c + 1] += np.roll(dp[c], w)
        mx = dp.max()
        if mx > 1e100:
            dp /= mx
    row = dp[a]
    return float(row[0] / row.sum())


def convergent_gates(pmax):
    """(p, a) for the convergents and semiconvergents of log_2 3 with p <= pmax (p/a ~ log2 3)."""
    import fractions
    x = math.log2(3)
    out = []
    for a in range(1, pmax):
        for p in (math.floor(a * x), math.ceil(a * x)):
            if 2 <= p <= pmax:
                out.append((p, a))
    # keep best approximations: |p - a x| smaller than for every smaller a (either side)
    best = []
    rec = 10.0
    for p, a in sorted(set(out), key=lambda t: (t[1], t[0])):
        e = abs(p - a * x)
        if e < rec - 1e-15:
            best.append((p, a))
            rec = e
    return best
