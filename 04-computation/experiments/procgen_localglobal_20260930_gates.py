def mobius(n):
    r, m, d = 1, n, 2
    while d * d <= m:
        if m % d == 0:
            m //= d
            if m % d == 0:
                return 0
            r = -r
        d += 1
    return -r if m > 1 else r


def lyndon_count(p, a):
    g = math.gcd(p, a)
    return sum(mobius(d) * math.comb(p // d, a // d) for d in range(1, g + 1) if g % d == 0) // p


def count_zero_prim(p, a, m, q=3):
    """#{PRIMITIVE (aperiodic) words w in W(p,a) : c_w = 0 mod m}.  A d-fold repetition u^d has
    c_{u^d} = c_u * cof_d with cof_d = D(p,a)/D(p/d,a/d) (geometric sum), so it is 0 mod m iff
    c_u = 0 mod m/gcd(m, cof_d); Moebius inversion over d | gcd(p,a) removes the repetitions."""
    g = math.gcd(p, a)
    tot = 0
    for d in range(1, g + 1):
        if g % d or mobius(d) == 0:
            continue
        if d == 1:
            n = count_zero_mod(p, a, m, q)
        else:
            Dd = gate(p // d, a // d, q)
            cof = gate(p, a, q) // Dd
            assert cof * Dd == gate(p, a, q)
            mm = m // math.gcd(m, abs(cof))
            n = count_zero_mod(p // d, a // d, mm, q) if mm > 1 else math.comb(p // d, a // d)
        tot += mobius(d) * n
    return tot


