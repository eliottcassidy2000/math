#!/usr/bin/env python3
"""procgen_localglobal_20260930_gates.py -- Collatz side of the local/global lane (helpers).

Words w of length p with a ones at s_0 < ... < s_{a-1}; carry c_w = sum_i 3^{a-1-i} 2^{s_i};
gate D = 2^p - 3^a.  The rational periodic point of T(x) = x/2, (3x+1)/2 with word w is c_w/D, so an
integer cycle with shape (p,a) exists iff some c_w = 0 mod |D|.

  count_zero_mod(p, a, m)   N_m = #{w : c_w = 0 mod m}, exact, by meet-in-the-middle over a split of
                            the positions; residues are kept in int64 (m < 2^62 is required, true
                            for every gate with p <= 40).  O(2^(p/2)) time and memory per modulus.
  count_zero_dp(p, a, m)    the same count by a residue DP, O(p a m) -- for small m and any p.
  brute(p, a)               all carries (for cross-checks, small p).
stdout only.
"""
import math
from itertools import combinations

import numpy as np


def gate(p, a, q=3):
    return 2 ** p - q ** a


def brute(p, a, q=3):
    out = []
    for S in combinations(range(p), a):
        out.append(sum(q ** (a - 1 - i) * 2 ** s for i, s in enumerate(S)))
    return out


def _left(p, a, h, m, q=3):
    """residues (mod m) of sum_{i<j} q^{a-1-i} 2^{s_i} over words on positions [0,h) with j ones."""
    A = {0: np.zeros(1, dtype=np.int64)}
    for s in range(h):
        new = {}
        for c, arr in A.items():
            new.setdefault(c, []).append(arr)
            if c < a:
                w = (pow(q, a - 1 - c, m) * pow(2, s, m)) % m
                x = arr + np.int64(w)
                x[x >= m] -= np.int64(m)
                new.setdefault(c + 1, []).append(x)
        A = {c: np.concatenate(v) for c, v in new.items()}
    return A


def _right(p, a, h, m, q=3):
    """residues (mod m) of sum_{i'} q^{r-1-i'} 2^{s'_{i'}} over words on positions [h,p) with r ones."""
    B = {0: np.zeros(1, dtype=np.int64)}
    for s in range(p - 1, h - 1, -1):
        new = {}
        for c, arr in B.items():
            new.setdefault(c, []).append(arr)
            if c < a:
                w = (pow(q, c, m) * pow(2, s, m)) % m
                x = arr + np.int64(w)
                x[x >= m] -= np.int64(m)
                new.setdefault(c + 1, []).append(x)
        B = {c: np.concatenate(v) for c, v in new.items()}
    return B


def count_zero_mod(p, a, m, q=3, h=None):
    """exact #{w in W(p,a) : c_w = 0 mod m}."""
    if m == 1:
        return math.comb(p, a)
    assert m < (1 << 62)
    if h is None:
        h = p // 2
    A = _left(p, a, h, m, q)
    B = _right(p, a, h, m, q)
    N = 0
    for j, arr in A.items():
        r = a - j
        if r not in B:
            continue
        Bs = np.sort(B[r])
        t = (np.int64(m) - arr) % np.int64(m)
        N += int((np.searchsorted(Bs, t, "right") - np.searchsorted(Bs, t, "left")).sum())
    return N


def count_zero_dp(p, a, m, q=3):
    """exact #{w : c_w = 0 mod m} by the residue DP over positions (state = ones placed, residue).
    Works for any p; cost O(p * a * m)."""
    # process positions from the END: suffix with c ones has value sum 3^{c'} 2^{s} (c' = rank from end)
    dp = np.zeros((a + 1, m), dtype=object if math.comb(p, a) >= 2 ** 62 else np.int64)
    dp[0, 0] = 1
    for s in range(p - 1, -1, -1):
        t2 = pow(2, s, m)
        new = dp.copy()
        for c in range(min(a - 1, p - 1 - s), -1, -1):
            w = (pow(q, c, m) * t2) % m
            new[c + 1] += np.roll(dp[c], w)
        dp = new
    return int(dp[a, 0])


def count_residues_dp(p, a, m, q=3):
    """full residue histogram of c_w mod m (exact), for small m."""
    dp = np.zeros((a + 1, m), dtype=object if math.comb(p, a) >= 2 ** 62 else np.int64)
    dp[0, 0] = 1
    for s in range(p - 1, -1, -1):
        t2 = pow(2, s, m)
        new = dp.copy()
        for c in range(min(a - 1, p - 1 - s), -1, -1):
            w = (pow(q, c, m) * t2) % m
            new[c + 1] += np.roll(dp[c], w)
        dp = new
    return dp[a]


def mult_order(x, n):
    x %= n
    if math.gcd(x, n) != 1:
        return None
    from sympy.ntheory import n_order
    return int(n_order(x, n))


def subgroup_23_size(q):
    """|<2,3>| in (Z/q)^* for q coprime to 6 (q prime power or any modulus), by BFS (q <= ~10^7)."""
    seen = bytearray(q)
    frontier = [1]
    seen[1] = 1
    n = 1
    while frontier:
        nxt = []
        for x in frontier:
            for y in ((2 * x) % q, (3 * x) % q):
                if not seen[y]:
                    seen[y] = 1
                    n += 1
                    nxt.append(y)
        frontier = nxt
    return n


def subgroup_23_size_prime(q):
    """|<2,3>| mod a prime q: lcm-type formula via orders: |<2,3>| = (q-1)/gcd-index, computed as
    the order of the subgroup generated by g^{(q-1)/o2} and g^{(q-1)/o3}: = lcm(o2, o3) in a cyclic group."""
    o2 = mult_order(2, q)
    o3 = mult_order(3, q)
    return o2 * o3 // math.gcd(o2, o3)


