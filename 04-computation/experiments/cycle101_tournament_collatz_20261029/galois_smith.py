"""Smith-form test of THM-4848 (multiplier descent for run observers of circulant tournaments).

For a circulant tournament T(S) on Z_q (q an odd prime) with multiplier stabiliser H = {m : mS = S}, translations
act freely on ordered k-tuples, so over Z_(p) (p != q) coker M_k(T) = coker(B_0) + X_p, where B_0 is the
trivial-character block and X_p is the cokernel of B_1 over Z_(p)[zeta_q].  Multipliers m in H conjugate B_1 to
sigma_m(B_1) by a monomial matrix, so the elementary divisors of B_1 agree at a prime P of Q(zeta_q) and at its
H-translates.  Prediction: for every p != q and every e >= 1, the number of Z/p^e summands of X_p is divisible by
|H<p>| (the subgroup of Z_q^* generated by H and p).  Also checked: sigma_h(det B_1) == det B_1 for a generator h of H,
and det M_k = det B_0 * N(det B_1).

Cases: Paley P7 (k = 2, 3), P11 (k = 2), the four <3>-invariant circulants on Z_13 (k = 2), and the controls with
H = 1: the rotational tournaments R7 (k = 2) and R11 (k = 2).
usage: python3 galois_smith.py [names]    (writes out/galois_smith.out, out/galois_smith.json)
Large elementary divisors are not fully factored: a gcd-free basis is formed, primes below 10^7 are split off, and
each remaining coprime 'bundle' is tested against the weaker law (multiplicities divisible by |H|), which every
prime inside it must satisfy.
"""
import sys, itertools, json
from math import gcd
sys.path.insert(0, '../growth_gf_runs_fermat_20261029')
from fast_runs import m2_fast
from runs import circulant, run_matrix, gp_batch, gp_matrix, parse_vec


def observer(q, S, k):
    A = circulant(q, S)
    if k == 2:
        T, _ = m2_fast(A)
        tuples = [(a, b) for a in range(q) for b in range(q) if a != b]
        M = [[int(T[s[0], s[1], t[0], t[1]]) for t in tuples] for s in tuples]
        return tuples, M
    tuples = list(itertools.permutations(range(q), k))
    return run_matrix(A, k, tuples)


def stabiliser(q, S):
    return sorted(m for m in range(1, q) if {(m * s) % q for s in S} == set(S))


def subgroup(q, gens):
    G = {1}
    while True:
        new = {(g * h) % q for g in G for h in gens} | G
        if new == G:
            return G
        G = new


def val(n, p):
    e = 0
    while n % p == 0:
        n //= p
        e += 1
    return e


def analyse(q, S, k, name):
    tuples, M = observer(q, S, k)
    idx = {t: i for i, t in enumerate(tuples)}
    shift = lambda t, s: tuple((x + s) % q for x in t)
    reps, seen = [], set()
    for t in tuples:
        if t not in seen:
            seen.update(shift(t, s) for s in range(q))
            reps.append(t)
    B0 = [[sum(M[idx[r]][idx[shift(rp, s)]] for s in range(q)) for rp in reps] for r in reps]
    H = stabiliser(q, S)
    h = next((m for m in H if len(subgroup(q, [m])) == len(H)), 1)

    def b1_entry(r, rp):
        terms = ['%d*z^%d' % (M[idx[r]][idx[shift(rp, s)]], s) for s in range(q) if M[idx[r]][idx[shift(rp, s)]]]
        return '(' + ('+'.join(terms) if terms else '0') + ')'
    B1 = 'Mat([' + ';'.join(','.join(b1_entry(r, rp) for rp in reps) for r in reps) + '])'
    P = 'polcyclo(%d, z)' % q
    cmds = ['matsnf(%s)' % gp_matrix(M), 'matsnf(%s)' % gp_matrix(B0),
            'my(d=lift(Mod(matdet(%s), %s))); [lift(Mod(subst(d, z, z^%d), %s)) == d, norm(Mod(d, %s))]'
            % (B1, P, h, P, P),
            'matdet(%s)' % gp_matrix(M)]
    out = gp_batch(cmds, timeout=7200)
    snfM = [abs(x) for x in parse_vec(out[0])]
    snfB = [abs(x) for x in parse_vec(out[1])]
    inv, nrm = out[2].strip('[]').split(',')
    invariant = inv.strip() == '1'
    nrm = int(nrm)
    detM = int(out[3])
    detB0 = 1
    for x in snfB:
        detB0 *= x
    sign_ok = abs(detM) == abs(detB0) * abs(nrm)
    # gcd-free basis of the elementary divisors (no full factorisation needed), then split off primes < 10^7
    vals = sorted({x for x in snfM + snfB if x > 1})
    base = []
    for x in vals:
        todo = [x]
        while todo:
            y = todo.pop()
            if y == 1:
                continue
            for i, b in enumerate(base):
                g = gcd(y, b)
                if g > 1:
                    base.pop(i)
                    todo += [g, b // g, y // g]
                    break
            else:
                base.append(y)
    units = []                      # (u, is_prime): primes, or unfactored coprime bundles
    if base:
        fac = gp_batch(['my(f=factor(%d, 10^7)); [f[,1]~, vector(#f[,1], i, ispseudoprime(f[i,1]))]' % b
                        for b in base], timeout=3600)
        for line in fac:
            ps, flags = line.strip()[1:-1].split('], [')
            ps = [int(t) for t in ps.strip('[').split(',')]
            flags = [int(t) for t in flags.strip(']').split(',')]
            units += [(u, bool(fl)) for u, fl in zip(ps, flags)]
    units = sorted(set(units))
    report = []
    ok_all = True
    for p, isprime in units:
        if p == q:
            continue
        cM, cB = {}, {}
        for src, dst in ((snfM, cM), (snfB, cB)):
            for x in src:
                if x:
                    e = val(x, p)
                    if e:
                        dst[e] = dst.get(e, 0) + 1
        X = {e: cM.get(e, 0) - cB.get(e, 0) for e in set(cM) | set(cB)}
        X = {e: c for e, c in X.items() if c}
        if isprime:
            g = len(subgroup(q, H + [p % q]))
            f = len(subgroup(q, [p % q]))
        else:                       # a bundle: every prime in it obeys at least the |H| law
            g, f = len(H), None
        neg = any(c < 0 for c in X.values())
        ok = (not neg) and all(c % g == 0 for c in X.values())
        ok_all &= ok
        if X or cB:
            report.append({'p': p if isprime else 'bundle(%d digits)' % len(str(p)), 'p_mod_q': p % q if isprime else None,
                           'f': f, '|H<p>|': g, 'B0': cB, 'X': X, 'ok': ok})
    return {'name': name, 'q': q, 'S': sorted(S), 'k': k, 'H': H, 'size': len(tuples),
            'det_B1_fixed_by_H': invariant, 'det_factorisation_ok': sign_ok, 'all_multiplicities_ok': ok_all,
            'kernel_M': snfM.count(0), 'primes': report}


cases = [(7, {1, 2, 4}, 2, 'P7'), (7, {1, 2, 4}, 3, 'P7'), (11, {1, 3, 4, 5, 9}, 2, 'P11'),
         (13, {1, 3, 9, 2, 5, 6}, 2, 'Z13 <3> A'), (13, {1, 3, 9, 7, 8, 11}, 2, 'Z13 <3> B'),
         (13, {4, 10, 12, 2, 5, 6}, 2, 'Z13 <3> C'), (13, {4, 10, 12, 7, 8, 11}, 2, 'Z13 <3> D'),
         (7, {1, 2, 3}, 2, 'R7 control'), (11, {1, 2, 3, 4, 5}, 2, 'R11 control')]
if len(sys.argv) > 1:
    cases = [c for c in cases if c[3].split()[0] in sys.argv[1:]]
results = []
with open('out/galois_smith.out', 'w') as fo:
    for q, S, k, name in cases:
        r = analyse(q, S, k, name)
        results.append(r)
        lines = ['%s (q=%d, S=%s, k=%d, H=%s, %dx%d): det B_1 fixed by H: %s; det M = det B_0 * N(det B_1): %s; '
                 'kernel dim %d; multiplicity law: %s' % (name, q, sorted(S), k, r['H'], r['size'], r['size'],
                 r['det_B1_fixed_by_H'], r['det_factorisation_ok'], r['kernel_M'], r['all_multiplicities_ok'])]
        for e in r['primes']:
            lines.append('    p=%s (p mod q = %s, f = %s, required multiplicity divisor %d): trivial block %s, nontrivial part %s -> %s'
                         % (e['p'], e['p_mod_q'], e['f'], e['|H<p>|'], e['B0'], e['X'], 'ok' if e['ok'] else 'FAIL'))
        fo.write('\n'.join(lines) + '\n')
        fo.flush()
        print('\n'.join(lines), flush=True)
json.dump(results, open('out/galois_smith.json', 'w'), indent=1, default=str)
