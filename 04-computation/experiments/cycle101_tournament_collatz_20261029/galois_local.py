"""Local (p-adic) Smith data of the four-run observer of Paley P7 at the split primes found by chirality_more.py.

M_4(P7) is 840 x 840 and its determinant is huge, so the p-part of coker M_4 and of coker B_0 is read off from
the Smith form of the lattice generated by M and p^N * I (PARI mathnfmodid), whose elementary divisors are
gcd(e_i, p^N) = p^(v_p(e_i)) once p^N exceeds every p-power that occurs.  THM-4848 (iii): in the nontrivial part
X_p every Z/p^e has multiplicity divisible by |H<p>| = |QR_7 <p>|, which is 3 for p = 1, 2, 4 (mod 7).
Non-trivial instances (f = 1 < 3): p = 71 and p = 2843 (both = 1 mod 7).  Also p = 79, 151, 7529 (f = 3).
"""
import sys, itertools, json
sys.path.insert(0, '../growth_gf_runs_fermat_20261029')
from runs import circulant, run_matrix, gp_batch, gp_matrix, parse_vec

q, k = 7, 4
QR = {1, 2, 4}
A = circulant(q, QR)
tuples, M = run_matrix(A, k, list(itertools.permutations(range(q), k)))
idx = {t: i for i, t in enumerate(tuples)}
shift = lambda t, s: tuple((x + s) % q for x in t)
reps, seen = [], set()
for t in tuples:
    if t not in seen:
        seen.update(shift(t, s) for s in range(q))
        reps.append(t)
B0 = [[sum(M[idx[r]][idx[shift(rp, s)]] for s in range(q)) for rp in reps] for r in reps]
res = {}
for p, N in ((71, 12), (2843, 8), (79, 8), (151, 8), (7529, 8)):
    d = p ** N
    out = gp_batch(['matsnf(mathnfmodid(%s, %d))' % (gp_matrix(M), d), 'matsnf(mathnfmodid(%s, %d))' % (gp_matrix(B0), d)],
                   timeout=7200)
    def counts(line):
        c = {}
        for x in parse_vec(line):
            x = abs(x)
            e = 0
            while x and x % p == 0:
                x //= p
                e += 1
            assert e < N, 'precision too low'
            if e:
                c[e] = c.get(e, 0) + 1
        return c
    cM, cB = counts(out[0]), counts(out[1])
    X = {e: cM.get(e, 0) - cB.get(e, 0) for e in set(cM) | set(cB)}
    X = {e: c for e, c in X.items() if c}
    ok = all(c % 3 == 0 for c in X.values()) and all(c > 0 for c in X.values())
    res[p] = {'M': cM, 'B0': cB, 'X': X, 'law_ok': ok}
    print('P7 k=4, p=%d (p mod 7 = %d): coker M_4 %s ; trivial block %s ; nontrivial part %s ; multiplicities divisible by 3: %s'
          % (p, p % 7, cM, cB, X, ok), flush=True)
json.dump({str(p): {kk: {str(e): c for e, c in v.items()} if isinstance(v, dict) else v for kk, v in r.items()}
           for p, r in res.items()}, open('out/galois_local.json', 'w'), indent=1)
