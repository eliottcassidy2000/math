#!/usr/bin/env python3
"""Runner for the four-vertex / Redei lane (procgen_tourn_20260924).
Runs the three scripts one after another (one heavy process at a time) and writes
05-knowledge/results/procgen_tourn_20260924.out.  Total about 1 minute, peak memory < 500 MB.
"""
import os
import platform
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "05-knowledge", "results", "procgen_tourn_20260924.out")
SCRIPTS = ["procgen_tourn_20260924_four_vertex.py", "procgen_tourn_20260924_windows.py",
           "procgen_tourn_20260924_redei.py"]
failed = False
with open(OUT, "w") as fo:
    fo.write("# procgen_tourn_20260924 -- generated by %s (python %s, numpy %s)\n"
             % (os.path.basename(__file__), platform.python_version(), __import__("numpy").__version__))
    for s in SCRIPTS:
        t0 = time.time()
        fo.write("\n##### %s\n" % s)
        fo.flush()
        r = subprocess.run([sys.executable, os.path.join(HERE, s)], capture_output=True, text=True)
        fo.write(r.stdout)
        if r.returncode != 0:
            failed = True
            fo.write("\n!!! exit code %d\n%s\n" % (r.returncode, r.stderr[-3000:]))
        fo.write("##### %s: exit %d\n" % (s, r.returncode))
        fo.flush()
        print("%s: exit %d, %.0f s" % (s, r.returncode, time.time() - t0), flush=True)
print("wrote", OUT)
sys.exit(1 if failed else 0)
