#!/usr/bin/env python3
"""Read-only, solver-free check of all saved 375x11 branch witnesses.
Verifies EVERY original CNF clause on the minimal support/sumset closure
induced by the saved colours, then verifies each named branch directly.
No SAT verdict is trusted. Source CNF is generated by the exact field script.
"""
import argparse,gzip,hashlib,json
from pathlib import Path
from pysat.formula import CNF

def need(ok,msg):
    if not ok:raise RuntimeError(msg)

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--cnf',type=Path,required=True);ap.add_argument('--geometry',type=Path,required=True);ap.add_argument('--witnesses',type=Path,required=True);ap.add_argument('--out',type=Path,required=True);a=ap.parse_args()
    d=json.loads(gzip.decompress(a.witnesses.read_bytes()));geo=json.loads(a.geometry.read_text());F=CNF(from_file=str(a.cnf))
    need(hashlib.sha256(a.cnf.read_bytes()).hexdigest()==d['cnf_sha256'],'CNF hash')
    sizes=d['coordinate_sizes'];end=6*sum(sizes)
    # Decode all base clauses: the producer only uses colour one-hot/edge/gauge,
    # forward Horn support and sumset rules, and final forbidden-pair clauses.
    negative=[];horn={};units=[];positive=[]
    for C in F.clauses:
        pos=[x for x in C if x>0];neg=[-x for x in C if x<0]
        if not pos:negative.append(neg)
        elif len(pos)==1 and neg:
            need(pos[0]>end and len(neg)==2,'unexpected Horn shape')
            need(all(t<pos[0] for t in neg),'non-forward Horn dependency')
            horn.setdefault(pos[0],[]).append(neg)
        elif len(C)==1:units.append(C[0])
        else:
            need(not neg and len(pos)==6 and max(pos)<=end,'unknown clause type');positive.append(pos)
    checked=0
    for key,col in d['witnesses'].items():
        flat=sum(col,[]);need([len(t) for t in col]==sizes,'original vertices')
        need(hashlib.sha256(bytes(flat)).hexdigest()==key,'witness digest')
        truth=bytearray(F.nv+1)
        for k,c in enumerate(flat):need(0<=c<6,'colour');truth[6*k+c+1]=1
        for v,rules in sorted(horn.items()):truth[v]=any(truth[x] and truth[y] for x,y in rules)
        need(all(truth[u] for u in units),'gauge')
        need(all(any(truth[v] for v in row) for row in positive),'one-hot existence')
        need(all(not all(truth[v] for v in row) for row in negative),'forbidden clause')
        checked+=1
    groups=[g for g in geo['support_groups'] if g['family']=='u_times_v_square'];branches=0
    for result,group in zip(d['groups'],groups):
        need(len(result['branches'])==375,'375 cover')
        expected={(i,p,r,j,q,s) for i in range(6) for j in range(i+1,6) for p in (2,3) for r in range(p) for q in (2,3) for s in range(q)}
        need({tuple(b['branch']) for b in result['branches']}==expected,'complete local universe')
        for row in result['branches']:
            need(row['status']=='SAT','unexpected unsolved branch');col=d['witnesses'][row['witness']]
            i,p,r,j,q,s=row['branch']
            for pos,mod,res in ((i,p,r),(j,q,s)):
                axis,pairs=group['factors'][pos]
                need(all((col[axis][v]-col[axis][u])%mod==res for u,v in pairs),'branch congruence')
            branches+=1
    need(len(d['groups'])==len(groups)==11 and branches==4125,'all groups')
    out={'status':'FINITE-EXACT solver-free certificate replay','witnesses':checked,'branches':branches,'clauses_per_witness':len(F.clauses),'total_original_clause_checks':checked*len(F.clauses),'original_vertices_per_witness':sum(sizes),'cnf_sha256':d['cnf_sha256']}
    a.out.write_text(json.dumps(out,indent=2)+'\n');print(out)
if __name__=='__main__':main()
