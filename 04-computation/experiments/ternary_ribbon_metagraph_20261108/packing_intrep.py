#!/usr/bin/env python3
"""packing_intrep.py w x -- the observable integer quotient of the span-w odd-cycle packing automaton evaluated at
x (an integer base): the Z-module generated by the functionals phi.M_v (phi = the empty-state functional, v any
suffix) is a letter-invariant sublattice of Z^d of rank r = the minimal dimension over Q of the series u -> H_x(u);
with an echelon (or, if its entries are large, LLL-reduced) Z-basis Psi, the reduced state y = Psi.state in Z^r
determines H_x(u v) for every suffix v, and y evolves by integer matrices A_a.  Writes pk{x}_span{w}_intrep.txt in
the format of intrep.py (r nletters / y0 / hcoef / per letter: mask then r rows) for ribbon_levels_mod.c."""
import sys, os, random
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'ribbon_spectrum_20261104'))
from intrep import echelon, in_module_coeffs, vecmat
from ribbon import letters
from ribbon_packing import packing_system, value_with_matrices

def build(w, x, verbose=True):
    order, states, mats, init, final = packing_system(w)
    d = len(order); L = letters(w)
    matsx = {a: {k: c0 + c1 * x for k, (c0, c1) in mats[a].items()} for a in L}
    phi = [0] * d; phi[final] = 1
    gens = [phi]; frontier = [phi]; basis = echelon(gens, d); k = 0
    while True:
        k += 1
        frontier = [vecmat(f, matsx[a], d) for f in frontier for a in L]
        gens = gens + frontier
        newbasis = echelon(gens, d)
        if verbose: print(f"  depth {k}: module rank {len(newbasis)}, generators {len(gens)}", flush=True)
        invariant = all(in_module_coeffs(newbasis, vecmat(f, matsx[a], d)) is not None for f in newbasis for a in L)
        same = (newbasis == basis); basis = newbasis
        gens = list(basis); frontier = [vecmat(f, matsx[a], d) for f in basis for a in L]
        if invariant and same: break
        if k > 60: raise RuntimeError("module did not stabilise")
    r = len(basis)
    big = max(abs(v) for row in basis for v in row)
    if big > 10**6:
        from sympy.polys.matrices import DomainMatrix
        from sympy import ZZ, Matrix
        if verbose: print(f"  echelon entries up to {big}: LLL-reducing", flush=True)
        dm = DomainMatrix([[ZZ(v) for v in row] for row in basis], (r, d), ZZ).lll()
        rows = [[int(v) for v in row] for row in dm.to_Matrix().tolist()]
        Bm = Matrix(rows); BBt_inv = (Bm * Bm.T).inv()
        def coeffs(v):
            c = BBt_inv * (Bm * Matrix(v))
            assert all(q.q == 1 for q in c) and Bm.T * c == Matrix(v), "not in module"
            return [int(q) for q in c]
        basis = rows
    else:
        coeffs = lambda v: in_module_coeffs(basis, v)
    A = {a: [coeffs(vecmat(f, matsx[a], d)) for f in basis] for a in L}
    y0 = [f[init] for f in basis]
    hcoef = coeffs(phi)
    return basis, A, y0, hcoef, (order, states, mats, init, final), matsx

if __name__ == "__main__":
    w = int(sys.argv[1]) if len(sys.argv) > 1 else 2
    x = int(sys.argv[2]) if len(sys.argv) > 2 else 3
    L = letters(w)
    basis, A, y0, hcoef, sysw, matsx = build(w, x)
    r = len(basis); d = len(sysw[0])
    print(f"span {w}, base x = {x}: packing states {d}, observable integer quotient of rank {r}")
    rng = random.Random(11)
    for t in range(400):
        n = rng.randint(1, 11)
        word = [rng.choice(L) for _ in range(n)]
        y = y0[:]
        for a in word:
            y = [sum(A[a][k][l] * y[l] for l in range(r)) for k in range(r)]
        v1 = sum(c * yk for c, yk in zip(hcoef, y))
        v2 = value_with_matrices(w, word, x, sysw)
        assert v1 == v2, (word, v1, v2)
    print("  reduced integer representation verified on 400 random words (n <= 11)")
    name = f"pk{x}_span{w}_intrep.txt"
    with open(name, "w") as f:
        f.write(f"{r} {len(L)}\n"); f.write(" ".join(map(str, y0)) + "\n"); f.write(" ".join(map(str, hcoef)) + "\n")
        for a in L:
            mask = sum(1 << (s - 1) for s in a); f.write(f"{mask}\n")
            for k in range(r): f.write(" ".join(map(str, A[a][k])) + "\n")
    print(f"  written {name}; largest |entry| {max(abs(v) for a in L for row in A[a] for v in row)}; y0 = {y0}; hcoef = {hcoef}")
