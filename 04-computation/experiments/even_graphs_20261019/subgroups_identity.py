#!/usr/bin/env python3
"""tau(H) = # tournament types whose automorphism group contains a conjugate of H, eps(H) = same for even graphs,
for every odd-order subgroup H <= S_n (n <= NMAX). Subgroups are identified up to S_n-conjugacy by the invariant
(order, multiset of cycle types); for n <= 7 the invariant is verified to separate conjugacy classes by brute force."""
import sys, subprocess, itertools
import networkx as nx
from networkx.algorithms.isomorphism import GraphMatcher, DiGraphMatcher
from collections import Counter, defaultdict
NMAX = int(sys.argv[1]) if len(sys.argv) > 1 else 7
def geng(n):
    out = subprocess.run(['geng', '-q', str(n)], capture_output=True, text=True).stdout.split()
    return [nx.from_graph6_bytes(s.encode()) for s in out]
def gentourng(n):
    out = subprocess.run(['gentourng', '-q', str(n)], capture_output=True, text=True).stdout.split()
    Ts = []
    for line in out:
        D = nx.DiGraph(); D.add_nodes_from(range(n)); k = 0
        for i in range(n):
            for j in range(i + 1, n):
                D.add_edge(i, j) if line[k] == '1' else D.add_edge(j, i); k += 1
        Ts.append(D)
    return Ts
def cycle_type(g):
    n = len(g); seen = [False] * n; ct = []
    for i in range(n):
        if not seen[i]:
            L = 0; j = i
            while not seen[j]: seen[j] = True; j = g[j]; L += 1
            ct.append(L)
    return tuple(sorted(ct, reverse=True))
def mul(a, b): return tuple(a[b[i]] for i in range(len(a)))
def inv(a):
    r = [0] * len(a)
    for i, x in enumerate(a): r[x] = i
    return tuple(r)
def sign(edges, g):
    s = 0
    for u, v in edges:
        if g[u] > g[v]: s ^= 1
    return -1 if s else 1
def closure(gens, n):
    idt = tuple(range(n)); S = {idt}; frontier = [idt]
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = mul(g, x)
            if y not in S: S.add(y); frontier.append(y)
    return frozenset(S)
def odd_subgroups(A, n):
    """all odd-order subgroups of A generated by <= 2 elements (enough for n <= 8), as frozensets"""
    idt = tuple(range(n))
    odd = [g for g in A if g != idt and all(L % 2 for L in cycle_type(g))]
    subs = set()
    cyc = {}
    for g in odd:
        c = closure([g], n); subs.add(c); cyc[g] = c
    for g, h in itertools.combinations(odd, 2):
        if h in cyc[g]: continue
        c = closure([g, h], n)
        if len(c) % 2 == 1: subs.add(c)
    return subs
def invariant(H):
    return (len(H), tuple(sorted(Counter(cycle_type(g) for g in H).items())))

for n in range(3, NMAX + 1):
    Gs = geng(n); Ts = gentourng(n)
    tau = Counter(); eps = Counter(); odd_types = Counter()
    reps = {}
    for T in Ts:
        A = {tuple(m[i] for i in range(n)) for m in DiGraphMatcher(T, T).isomorphisms_iter()}
        invs = set()
        for H in odd_subgroups(A, n):
            iv = invariant(H); invs.add(iv); reps.setdefault(iv, set()).add(H)
        for iv in invs: tau[iv] += 1
    for G in Gs:
        edges = [(min(u, v), max(u, v)) for u, v in G.edges()]
        A = {tuple(m[i] for i in range(n)) for m in GraphMatcher(G, G).isomorphisms_iter()}
        even = all(sign(edges, g) == 1 for g in A)
        invs = set()
        for H in odd_subgroups(A, n):
            iv = invariant(H); invs.add(iv); reps.setdefault(iv, set()).add(H)
        for iv in invs:
            if even: eps[iv] += 1
            else: odd_types[iv] += 1
    # verify that the invariant separates conjugacy classes (n <= 7): all H with the same invariant are conjugate
    if n <= 7:
        perms = list(itertools.permutations(range(n)))
        for iv, Hs in reps.items():
            Hs = list(Hs)
            if len(Hs) > 1:
                H0 = Hs[0]
                for H in Hs[1:]:
                    assert any(frozenset(mul(mul(h, g), inv(h)) for g in H) == H0 for h in perms), ("non-conjugate same invariant", iv)
        print(f"n = {n}: invariant separates conjugacy classes of the odd-order subgroups met (verified)")
    print(f"n = {n}: odd-order subgroup classes H: tau(H) [tournaments] / eps(H) [even graphs] / odd graphs with H")
    for iv in sorted(set(tau) | set(eps), key=lambda x: (x[0], x[1])):
        flag = "" if tau[iv] == eps[iv] else "  <-- DIFFER"
        print(f"  |H|={iv[0]} types {iv[1]}: {tau[iv]} / {eps[iv]} / {odd_types[iv]}{flag}")
