#!/usr/bin/env python3
"""Mechanism behind t_lambda = e_lambda. For each odd cycle type lambda and n <= NMAX:
 t_lambda = # tournament types with an automorphism of type lambda; e_lambda = same for even graphs;
 clT = sum over tournament types of the number of Aut(T)-conjugacy classes of elements of type lambda;
 clE = same over even graphs; clOdd* = over odd graphs X, classes of k of type lambda such that sgn_X is trivial on the
 centraliser C_{Aut X}(k) (the signed-Burnside identity predicts clT = clE + clOdd*);
 sgT/sgE = classes of cyclic SUBGROUPS generated by elements of type lambda."""
import sys, subprocess, itertools
import networkx as nx
from networkx.algorithms.isomorphism import GraphMatcher, DiGraphMatcher
from collections import Counter, defaultdict
sys.path.insert(0, '.')
NMAX = int(sys.argv[1]) if len(sys.argv) > 1 else 7

def geng(n):
    out = subprocess.run(['geng', '-q', str(n)], capture_output=True, text=True).stdout.split()
    return [nx.from_graph6_bytes(s.encode()) for s in out]
def gentourng(n):
    out = subprocess.run(['gentourng', '-q', str(n)], capture_output=True, text=True).stdout.split()
    Ts = []
    for line in out:
        D = nx.DiGraph(); D.add_nodes_from(range(n)); k = 0
        for i in range(n):
            for j in range(i + 1, n):
                D.add_edge(i, j) if line[k] == '1' else D.add_edge(j, i); k += 1
        Ts.append(D)
    return Ts
def cycle_type(g):
    n = len(g); seen = [False] * n; ct = []
    for i in range(n):
        if not seen[i]:
            L = 0; j = i
            while not seen[j]: seen[j] = True; j = g[j]; L += 1
            ct.append(L)
    return tuple(sorted(ct, reverse=True))
def mul(a, b): return tuple(a[b[i]] for i in range(len(a)))   # (a*b)(i) = a(b(i))
def inv(a):
    r = [0] * len(a)
    for i, x in enumerate(a): r[x] = i
    return tuple(r)
def sign(edges, g):
    s = 0
    for u, v in edges:
        if g[u] > g[v]: s ^= 1
    return -1 if s else 1
def analyse(A, edges, n):
    """A: set of automorphisms (tuples). returns dict lambda -> (classes of elements, classes of subgroups, classes with
    centraliser-trivial sign) and the evenness."""
    idt = tuple(range(n))
    sg = {g: sign(edges, g) for g in A} if edges is not None else {g: 1 for g in A}
    even = all(v == 1 for v in sg.values())
    seen = set(); res = defaultdict(lambda: [0, 0, 0]); seen_sub = set()
    for k in A:
        if k == idt or k in seen: continue
        lam = cycle_type(k)
        if any(L % 2 == 0 for L in lam): continue
        cls = {mul(mul(a, k), inv(a)) for a in A}
        seen |= cls
        res[lam][0] += 1
        cent = [a for a in A if mul(a, k) == mul(k, a)]
        if all(sg[a] == 1 for a in cent): res[lam][2] += 1
        # subgroup generated by k
        sub = set(); x = k
        while x not in sub: sub.add(x); x = mul(k, x)
        sub = frozenset(sub)
        if sub not in seen_sub:
            orbit_sub = {frozenset(mul(mul(a, s), inv(a)) for s in sub) for a in A}
            seen_sub |= orbit_sub
            res[lam][1] += 1
    return res, even

for n in range(3, NMAX + 1):
    Gs = geng(n); Ts = gentourng(n)
    tot = defaultdict(lambda: Counter())
    for G in Gs:
        edges = [(min(u, v), max(u, v)) for u, v in G.edges()]
        A = {tuple(m[i] for i in range(n)) for m in GraphMatcher(G, G).isomorphisms_iter()}
        res, even = analyse(A, edges, n)
        for lam, (c, s, cc) in res.items():
            if even:
                tot[lam]['e_types'] += 1; tot[lam]['clE'] += c; tot[lam]['sgE'] += s
            else:
                tot[lam]['oddX_types'] += 1; tot[lam]['clOdd'] += c; tot[lam]['clOdd*'] += cc; tot[lam]['sgOdd'] += s
    for T in Ts:
        A = {tuple(m[i] for i in range(n)) for m in DiGraphMatcher(T, T).isomorphisms_iter()}
        res, _ = analyse(A, None, n)
        for lam, (c, s, cc) in res.items():
            tot[lam]['t_types'] += 1; tot[lam]['clT'] += c; tot[lam]['sgT'] += s
    print(f"\n=== n = {n} ===")
    print("lambda | t_types e_types | clT = clE + clOdd* ? | sgT sgE | odd-graph types with lambda, clOdd, sgOdd")
    for lam in sorted(tot, key=lambda c: (-max(c), c)):
        d = tot[lam]
        ok = (d['clT'] == d['clE'] + d['clOdd*'])
        print(f"  {lam}: {d['t_types']} {d['e_types']} | {d['clT']} = {d['clE']} + {d['clOdd*']} {'OK' if ok else 'FAIL'} | "
              f"{d['sgT']} {d['sgE']} | {d['oddX_types']} {d['clOdd']} {d['sgOdd']}")
