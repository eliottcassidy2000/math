#!/usr/bin/env python3
"""Runner for lane procgen_repunit_20260924 (digits, rotations and repunits).

Runs the four parts one after another (one heavy process at a time) and writes
05-knowledge/results/procgen_repunit_20260924.out:
  Part 1  procgen_repunit_20260924_primes.py        consecutive-prime digit transitions to 10^11 (LO-S)
  Part 2  procgen_repunit_20260924_collatz.py       exact Haar digit chains of U and T vs orbits
  Part 3  procgen_repunit_20260924_repunits.py      rotation algebra, circular/permutable primes, repunit primes
  Part 4  procgen_repunit_20260924_dictionary.py    Collatz repunit dictionary, B-L fixed points, exponent tests
C helpers: procgen_repunit_20260924_{primes,collatz,circular,collatz_repunits}.c (the last needs GMP).
Total ~ 12-15 minutes on the mac-mini; peak memory < 700 MB (the 10^9 bitset sieve uses 63 MB).
Every check raises on failure; a failing part is reported with its exit code.
"""
import os, subprocess, sys, time, platform

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "05-knowledge", "results", "procgen_repunit_20260924.out")
SCRIPTS = ["procgen_repunit_20260924_primes.py", "procgen_repunit_20260924_collatz.py",
           "procgen_repunit_20260924_repunits.py", "procgen_repunit_20260924_dictionary.py"]

with open(OUT, "w") as fo:
    fo.write(f"# procgen_repunit_20260924 -- generated by {os.path.basename(__file__)} on {time.strftime('%Y-%m-%d %H:%M')}"
             f" (python {platform.python_version()}, {platform.system()} {platform.machine()})\n")
    for s in SCRIPTS:
        t0 = time.time()
        fo.write(f"\n##### {s}\n")
        fo.flush()
        r = subprocess.run([sys.executable, os.path.join(HERE, s)], capture_output=True, text=True)
        fo.write(r.stdout)
        if r.returncode != 0:
            fo.write(f"\n!!! exit code {r.returncode}\n{r.stderr[-4000:]}\n")
        fo.write(f"##### {s}: exit {r.returncode}, {time.time() - t0:.0f} s\n")
        fo.flush()
        print(f"{s}: exit {r.returncode}, {time.time() - t0:.0f} s", flush=True)
print("wrote", OUT)
