#!/usr/bin/env python3
"""procgen_sources_20260923_run.py -- run the four procgen_sources_20260923 scripts in sequence
(one process at a time) and write 05-knowledge/results/procgen_sources_20260923.out.

Usage (from the repository root):  python3 04-computation/experiments/procgen_sources_20260923_run.py
Total: about 30 seconds; peak resident memory about 600 MB (the base-2, 20-round log table).
"""
import datetime
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SCRIPTS = ['procgen_sources_20260923_moonshine.py', 'procgen_sources_20260923_hexagons.py',
           'procgen_sources_20260923_logdigits.py', 'procgen_sources_20260923_interplay.py']
OUT = os.path.join(ROOT, '05-knowledge', 'results', 'procgen_sources_20260923.out')


def main():
    parts = [f'# procgen_sources_20260923.out -- generated by procgen_sources_20260923_run.py\n'
             f'# python {sys.version.split()[0]}; scripts: {", ".join(SCRIPTS)}\n']
    for s in SCRIPTS:
        path = os.path.join(ROOT, '04-computation', 'experiments', s)
        r = subprocess.run([sys.executable, path], capture_output=True, text=True, cwd=ROOT)
        parts.append(f'\n########## {s} (exit {r.returncode})\n')
        parts.append(r.stdout)
        if r.returncode != 0:
            parts.append('STDERR:\n' + r.stderr)
    with open(OUT, 'w') as fh:
        fh.write(''.join(parts))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
