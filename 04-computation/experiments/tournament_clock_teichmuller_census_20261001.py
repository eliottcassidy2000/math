#!/usr/bin/env python3
"""Extended Teichmuller-clock census for the Tournament Clock Prime Collatz note (2026-10-01).

For a prime p >= 5 the p-th power clock mod p^2 is {0} together with the Teichmuller lifts omega(x) = x^p mod p^2.
A unit triangle omega(1) + omega(t) = omega(1 + t) is a root t != 0, -1 of ((1+t)^p - 1 - t^p)/p mod p, i.e. a solution
of x^p + y^p = z^p (mod p^2) with p not dividing xyz.  The roots are permuted by the S3 generated by t -> 1/t and
t -> -1 - t, so #roots = 2[p = 1 mod 3] + 3[p Wieferich base 2] + 6j.  This script checks, for every prime 5 <= p < P_MAX,
that the root set is invariant under both maps, that it contains the Eisenstein pair (primitive cube roots of unity)
iff p = 1 mod 3, and that it contains t = 1 iff 2^(p-1) = 1 (mod p^2) (tested directly).  It then tabulates j (the
number of generic 6-orbits) separately for p = 1 and p = 2 mod 3, and compares with the Poisson(1/6) heuristic.

Reproduce: python3 04-computation/experiments/tournament_clock_teichmuller_census_20261001.py   (about 6 minutes)
"""
import math
import sys
from collections import Counter

P_MAX = 150000
spf = list(range(P_MAX + 1))
for i in range(2, math.isqrt(P_MAX) + 1):
    if spf[i] == i:
        for j in range(i * i, P_MAX + 1, i):
            if spf[j] == j:
                spf[j] = i


def prime_factors(n):
    s = set()
    while n > 1:
        p = spf[n]
        s.add(p)
        while n % p == 0:
            n //= p
    return s


def primitive_root(p):
    qs = prime_factors(p - 1)
    return next(g for g in range(2, p) if all(pow(g, (p - 1) // q, p) != 1 for q in qs))


orbits = {1: Counter(), 2: Counter()}
wieferich, bad, record = [], [], []
by_range = {}  # (class, range index) -> [primes, total j], ranges of width 25000
for p in range(5, P_MAX):
    if spf[p] != p:
        continue
    g, p2 = primitive_root(p), p * p
    W = pow(g, p, p2)
    om = [0] * p
    x, w = 1, 1
    for _ in range(p - 1):
        om[x] = w
        x, w = x * g % p, w * W % p2
    roots = [t for t in range(1, p - 1) if (om[t + 1] - 1 - om[t]) % p2 == 0]
    R = set(roots)
    cls = 1 if p % 3 == 1 else 2
    wief = pow(2, p - 1, p2) == 1
    if wief:
        wieferich.append(p)
    eis = {pow(g, (p - 1) // 3, p), pow(g, 2 * (p - 1) // 3, p)} if cls == 1 else set()
    rest = len(roots) - len(eis) - (3 if wief else 0)
    if (R != {pow(t, -1, p) for t in R} or R != {(-1 - t) % p for t in R} or not eis <= R
            or (1 in R) != wief or rest < 0 or rest % 6):
        bad.append(p)
    orbits[cls][rest // 6] += 1
    cell = by_range.setdefault((cls, p // 25000), [0, 0])
    cell[0] += 1
    cell[1] += rest // 6
    if rest // 6 >= 3:
        record.append((p, rest // 6))

print("primes 5 <= p < %d; base-2 Wieferich primes (each has t = 1 as a root): %s; orbit-law violations: %s" % (P_MAX, wieferich, bad))
lam = 1 / 6
size, total = {}, {}
for cls in (1, 2):
    C = orbits[cls]
    N = sum(C.values())
    size[cls], total[cls] = N, sum(j * c for j, c in C.items())
    mean = total[cls] / N
    print("p = %d mod 3: %d primes; generic 6-orbits j: %s" % (cls, N, sorted(C.items())))
    print("   share with j = 0: %.4f (Poisson(1/6): %.4f); mean j: %.4f (1/6 = %.4f, standard error %.4f)"
          % (C[0] / N, math.exp(-lam), mean, lam, math.sqrt(lam / N)))
N = size[1] + size[2]
pooled = (total[1] + total[2]) / N
print("pooled: %d primes, mean j %.4f, z = %.2f against 1/6" % (N, pooled, (pooled - lam) / math.sqrt(lam / N)))
diff = total[2] / size[2] - total[1] / size[1]
print("class difference (p = 2 minus p = 1 mod 3): %.4f, z = %.2f" % (diff, diff / math.sqrt(lam * (1 / size[1] + 1 / size[2]))))
print("primes with j >= 3: %s" % record)
for cls in (1, 2):
    print("p = %d mod 3, mean j by range of 25000: %s" % (cls, ", ".join(
        "%.4f" % (by_range[(cls, i)][1] / by_range[(cls, i)][0]) for i in range(P_MAX // 25000))))
ok = not bad and wieferich == [1093, 3511]
print("ALL CHECKS PASSED" if ok else "FAILED")
sys.exit(0 if ok else 1)
