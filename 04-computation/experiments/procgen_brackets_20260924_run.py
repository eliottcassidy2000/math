#!/usr/bin/env python3
"""Runner for the brackets / pairings / square-sum lane (procgen_brackets_20260924).
Runs the five scripts one after another (one heavy process at a time) and writes
05-knowledge/results/procgen_brackets_20260924.out.  Total ~7 minutes, peak memory < 700 MB.
"""
import os, subprocess, sys, time, platform

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "05-knowledge", "results", "procgen_brackets_20260924.out")
SCRIPTS = ["procgen_brackets_20260924_escape_sets.py", "procgen_brackets_20260924_pairings.py",
           "procgen_brackets_20260924_provable_rung.py", "procgen_brackets_20260924_square_sum.py",
           "procgen_brackets_20260924_legendre.py"]
with open(OUT, "w") as fo:
    fo.write(f"# procgen_brackets_20260924 -- generated by {os.path.basename(__file__)} on {time.strftime('%Y-%m-%d %H:%M')}"
             f" (python {platform.python_version()}, {platform.system()})\n")
    for s in SCRIPTS:
        t0 = time.time()
        fo.write(f"\n##### {s}\n"); fo.flush()
        r = subprocess.run([sys.executable, os.path.join(HERE, s)], capture_output=True, text=True)
        fo.write(r.stdout)
        if r.returncode != 0:
            fo.write(f"\n!!! exit code {r.returncode}\n{r.stderr[-3000:]}\n")
        fo.write(f"##### {s}: {time.time()-t0:.0f} s\n"); fo.flush()
        print(f"{s}: exit {r.returncode}, {time.time()-t0:.0f} s", flush=True)
print("wrote", OUT)
