"""Icosahedral group checks: element orders of I and I_h, and a tetrahedral subgroup acting regularly on the 12 vertices."""
import itertools
import numpy as np
phi = (1 + 5 ** 0.5) / 2
V = []
for s1 in (1, -1):
    for s2 in (1, -1):
        V += [(0, s1, s2 * phi), (s1, s2 * phi, 0), (s2 * phi, 0, s1)]
V = np.array(V, dtype=float)
def key(M): return tuple(np.round(M, 6).flatten())
# generate rotation group from two rotations mapping vertex set to itself
def rot(axis, ang):
    a = np.array(axis, float); a /= np.linalg.norm(a); x, y, z = a; c, s = np.cos(ang), np.sin(ang)
    return np.array([[c + x*x*(1-c), x*y*(1-c) - z*s, x*z*(1-c) + y*s],
                     [y*x*(1-c) + z*s, c + y*y*(1-c), y*z*(1-c) - x*s],
                     [z*x*(1-c) - y*s, z*y*(1-c) + x*s, c + z*z*(1-c)]])
g1 = rot(V[0], 2 * np.pi / 5)
f = (V[0] + V[1] + V[2]) / 3  # check it's a face
g2 = rot((1, 1, 1), 2 * np.pi / 3)
G = {key(np.eye(3)): np.eye(3)}; frontier = [np.eye(3)]
while frontier:
    new = []
    for M in frontier:
        for g in (g1, g2):
            P = g @ M; k = key(P)
            if k not in G: G[k] = P; new.append(P)
    frontier = new
def order(M):
    P = M.copy(); n = 1
    while not np.allclose(P, np.eye(3), atol=1e-6): P = P @ M; n += 1
    return n
I = list(G.values())
print("|I| =", len(I), " element orders of I:", sorted({order(M) for M in I}))
Ih = I + [-M for M in I]
print("|I_h| =", len(Ih), " element orders of I_h:", sorted({order(M) for M in Ih}))
# vertex set preserved?
vs = {tuple(np.round(v, 6)) for v in V}
print("I preserves vertices:", all({tuple(np.round(M @ v, 6)) for v in V} == vs for M in I))
# tetrahedral subgroup: elements of order <= 3 generated by g2 and a conjugate order-2 element commuting structure
inv = [M for M in I if order(M) == 2]
T = None
for a in inv:
    H = {key(np.eye(3)): np.eye(3)}; fr = [np.eye(3)]
    while fr:
        new = []
        for M in fr:
            for g in (g2, a):
                P = g @ M; k = key(P)
                if k not in H: H[k] = P; new.append(P)
        fr = new
    if len(H) == 12: T = list(H.values()); break
print("found subgroup of order 12:", T is not None, " element orders:", sorted({order(M) for M in T}))
free = all(not np.allclose(M @ v, v, atol=1e-6) for M in T if not np.allclose(M, np.eye(3)) for v in V)
orbit = {tuple(np.round(M @ V[0], 6)) for M in T}
print("A4 acts freely on vertices:", free, " orbit size of a vertex:", len(orbit), "(regular iff 12)")
