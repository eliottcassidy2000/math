#!/usr/bin/env python3
"""Pair actions of Collatz-type affine groups {x -> s x + c : s in S} on Z/N.

Checks, by brute-force orbit computation on unordered pairs:
  (A) the classification theorem for primes p >= 5 and S in {<2,3>, <3>, <2>, <3/2>}:
        transitive  <=>  S * <-1> = F_p^*
        regular     <=>  S = squares and p = 3 mod 4
  (B) non-transitivity for every composite N (gcd(N,6)=1) up to a bound;
  (C) the golden family R_n = Z[phi]/(phi^n - 1), G_n = <x+1, phi x>, n = 3..12 (paper's Theorem D);
  (D) 2-adic levels: <x+1, 3x> on Z/2^K, odd-difference pairs;
  (E) p-adic lifts at 11 and 23 (Wieferich obstruction);
  (F) cycle denominators |2^A - 3^r| and Ellison exceptions: which subgroups act transitively/regularly.
"""
import sys
from math import gcd
from sympy import isprime, factorint, n_order, primerange

def pair_orbits(N, mults, unit_diff_only=False):
    """Orbits of <x+1, s x (s in mults)> on unordered pairs {x<y} of Z/N.
    Returns list of orbit sizes.  If unit_diff_only, restrict to pairs with gcd(y-x, N) = 1."""
    seen = {}
    sizes = []
    def norm(a, b):
        a %= N; b %= N
        return (a, b) if a < b else (b, a)
    pairs = []
    for x in range(N):
        for y in range(x + 1, N):
            if unit_diff_only and gcd(y - x, N) != 1:
                continue
            pairs.append((x, y))
    for p0 in pairs:
        if p0 in seen:
            continue
        stack = [p0]; seen[p0] = True; cnt = 0
        while stack:
            a, b = stack.pop(); cnt += 1
            nxt = [norm(a + 1, b + 1)] + [norm(s * a, s * b) for s in mults]
            for q in nxt:
                if q not in seen:
                    seen[q] = True; stack.append(q)
        sizes.append(cnt)
    return sizes

def subgroup(N, gens):
    S = {1}; frontier = [1]
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = (x * g) % N
            if y not in S:
                S.add(y); frontier.append(y)
    return S

def classify_prime(p, gens):
    """Theoretical prediction for S = <gens> mod p."""
    S = subgroup(p, gens)
    full = (p - 1)
    Spm = S | {(-s) % p for s in S}
    trans = (len(Spm) == full)
    sq = {(x * x) % p for x in range(1, p)}
    regular = (S == sq) and (p % 4 == 3)
    return len(S), trans, regular

GROUPS = {
    '<2,3>': lambda N: [2 % N, 3 % N],
    '<3>':   lambda N: [3 % N],
    '<2>':   lambda N: [2 % N],
    '<3/2>': lambda N: [(3 * pow(2, -1, N)) % N],
}

def check_A(P=200):
    bad = 0; rows = []
    for p in primerange(5, P):
        for name, g in GROUPS.items():
            gens = g(p)
            sizes = pair_orbits(p, gens)
            npairs = p * (p - 1) // 2
            ordS, trans_pred, reg_pred = classify_prime(p, gens)
            Gord = p * ordS
            trans = (len(sizes) == 1)
            regular = trans and (Gord == npairs)
            if trans != trans_pred or regular != reg_pred:
                bad += 1
                print('MISMATCH', p, name, sizes[:5], trans, trans_pred, regular, reg_pred)
            if trans:
                stab = Gord // npairs
                assert Gord % npairs == 0
                assert stab in (1, 2), (p, name, stab)
                assert (stab == 1) == regular
    print(f'(A) brute-force pair orbits for primes 5..{P}, 4 subgroups: {bad} mismatches with the classification')

def check_B(Nmax=130):
    bad = 0; checked = 0
    for N in range(5, Nmax):
        if isprime(N) or gcd(N, 6) != 1:
            continue
        for name, g in GROUPS.items():
            sizes = pair_orbits(N, g(N))
            checked += 1
            if len(sizes) == 1:
                bad += 1; print('composite transitive?!', N, name)
    print(f'(B) composite N < {Nmax} coprime to 6: {checked} (N,group) cases, transitive cases = {bad}')

def phi_rep(n):
    """Return (N_n, residue of phi) when R_n = Z[phi]/(phi^n-1) is cyclic of order N_n with phi -> root r;
    else None.  Uses Smith form via explicit search: R_n cyclic iff some r in Z/N has r^2=r+1, r^n=1 and the map
    m+k phi -> m+k r has kernel (phi^n-1).  We just brute-force check: the subgroup generated by 1 and phi ..."""
    # phi^n = F_{n-1} + F_n phi
    F = [0, 1]
    for _ in range(n + 2):
        F.append(F[-1] + F[-2])
    a, b = F[n - 1] - 1, F[n]    # phi^n - 1 = a + b phi
    # multiplication-by-(a+b phi) matrix on basis (1, phi): columns images of 1, phi
    # (a + b phi)*1 = a + b phi ; (a + b phi)*phi = b + (a + b) phi
    M = [[a, b], [b, a + b]]   # columns
    det = abs(a * (a + b) - b * b)
    return a, b, det

def golden_Gn_pairs(n):
    """Brute-force G_n = <x+1, phi x> on R_n = O/(phi^n - 1), represented as Z^2/L with L spanned by
    (a,b) and (b,a+b).  Canonical reps via Hermite normal form."""
    a, b, det = phi_rep(n)
    # lattice L generated by v1=(a,b), v2=(b,a+b) (coordinates (m,k) for m + k phi)
    # compute HNF: find basis (d1, 0), (e, d2) style lower triangular
    v1 = (a, b); v2 = (b, a + b)
    D = a * (a + b) - b * b  # signed det
    def reduce(m, k):
        s = ((a + b) * m - b * k) // D
        t = (-b * m + a * k) // D
        return (m - s * a - t * b, k - s * b - t * (a + b))
    # enumerate representatives
    reps = set()
    span = abs(D) + abs(a) + abs(b) + 5
    for m in range(-span, span):
        for k in range(-span, span):
            reps.add(reduce(m, k))
        if len(reps) == abs(D):
            pass
    reps = sorted(reps)
    assert len(reps) == abs(D), (n, len(reps), D)
    idx = {r: i for i, r in enumerate(reps)}
    N = len(reps)
    def add1(r):
        return reduce(r[0] + 1, r[1])
    def mulphi(r):
        m, k = r
        return reduce(k, m + k)   # (m + k phi) phi = k + (m+k) phi
    # group order: N * order of phi
    r = (1, 0); d = 0
    while True:
        r = mulphi(r); d += 1
        if r == reduce(1, 0):
            break
    Gord = N * d
    # orbits on unordered pairs
    seen = set(); sizes = []
    def norm(x, y):
        return (x, y) if idx[x] < idx[y] else (y, x)
    for i in range(N):
        for j in range(i + 1, N):
            p0 = (reps[i], reps[j])
            if p0 in seen:
                continue
            st = [p0]; seen.add(p0); c = 0
            while st:
                x, y = st.pop(); c += 1
                for q in (norm(add1(x), add1(y)), norm(mulphi(x), mulphi(y))):
                    if q not in seen:
                        seen.add(q); st.append(q)
            sizes.append(c)
    npairs = N * (N - 1) // 2
    return N, d, Gord, npairs, sizes

def check_C():
    print('(C) golden family R_n = O/(phi^n-1), G_n = <x+1, phi x>:')
    print('    n  |R_n|  ord(phi) |G_n|  #pairs  #orbits  transitive regular')
    for n in range(3, 13):
        N, d, Gord, npairs, sizes = golden_Gn_pairs(n)
        trans = len(sizes) == 1
        reg = trans and Gord == npairs
        print(f'   {n:2d} {N:5d} {d:6d} {Gord:7d} {npairs:7d} {len(sizes):7d}   {trans!s:5}   {reg!s:5}')

def check_D(Kmax=11):
    print('(D) 2-adic: <x+1, 3x> on Z/2^K, unordered pairs by v_2(difference):')
    for K in range(3, Kmax + 1):
        N = 2 ** K
        ord3 = n_order(3, N)
        Gord = N * ord3
        # orbits restricted to odd-difference pairs
        sizes = pair_orbits(N, [3], unit_diff_only=True)
        nodd = N * (N // 2) // 2
        # all pairs: count orbits by valuation
        allsizes = pair_orbits(N, [3]) if K <= 9 else None
        line = f'   K={K:2d} |G|={Gord:8d} odd-diff pairs={nodd:8d} orbits={len(sizes)} regular={len(sizes)==1 and Gord==nodd}'
        if allsizes is not None:
            line += f' | all pairs: {len(allsizes)} orbits, sizes(desc)={sorted(allsizes, reverse=True)[:K]}'
        print(line)

def check_E():
    print('(E) p-adic lifts: unit-difference pairs mod p^2')
    for p, gens, label in [(11, [3], '<3> mod 121'), (23, [2], '<2> mod 529'), (23, [3], '<3> mod 529'),
                           (7, [2], '<2> mod 49'), (23, [2, 3], '<2,3> mod 529')]:
        N = p * p
        S = subgroup(N, gens)
        Spm = S | {(-s) % N for s in S}
        units = sum(1 for x in range(1, N) if x % p)
        reg = (len(Spm) == units) and (len(Spm) == 2 * len(S))
        print(f'   {label:14s}: |S|={len(S):4d}  |S u -S|={len(Spm):4d}  units={units:4d}  '
              f'transitive on unit-diff pairs={len(Spm)==units}  regular={reg}')
    # golden at 11: phi -> lift of 4 mod 121 (root of x^2-x-1)
    N = 121
    roots = [x for x in range(N) if (x * x - x - 1) % N == 0]
    for r in roots:
        S = subgroup(N, [r])
        Spm = S | {(-s) % N for s in S}
        print(f'   golden phi -> {r:3d} mod 121 (= {r%11} mod 11): |<phi>|={len(S)}  |S u -S|={len(Spm)}  units=110  '
              f'regular on unit-diff pairs={len(Spm)==110 and len(Spm)==2*len(S)}')
    print('   Wieferich checks: 3^5 mod 121 =', pow(3, 5, 121), '; 2^11 mod 529 =', pow(2, 11, 529),
          '; 3^11 mod 529 =', pow(3, 11, 529), '; 2^3 mod 49 =', pow(2, 3, 49))

def subgroup_report(p):
    out = {}
    for name, g in GROUPS.items():
        gens = g(p)
        ordS, t, r = classify_prime(p, gens)
        out[name] = ('REG' if r else ('TRANS' if t else '-'), ordS)
    return out

def check_F():
    print('(F) cycle denominators D=|2^A-3^r| (r>=1, 3^r<2^(A+1)), prime factors and pair actions on F_p:')
    seen = set()
    rows = []
    for A in range(1, 31):
        for r in range(1, A + 1):
            D = abs(2 ** A - 3 ** r)
            # only "near" pairs: 2^(A-1) < 3^r < 2^(A+1)
            if not (2 ** (A - 1) < 3 ** r < 2 ** (A + 1)):
                continue
            rows.append((A, r, D))
    for A, r, D in rows:
        if D in (0,):
            continue
        fac = factorint(D) if D > 1 else {}
        tags = []
        for p in sorted(fac):
            if p < 5:
                tags.append(f'{p}:n/a')
                continue
            rep = subgroup_report(p)
            s = ','.join(f'{k}={v[0]}' for k, v in rep.items() if v[0] != '-')
            tags.append(f'{p}[{s or "none"}]')
        sign = '+' if 2 ** A > 3 ** r else '-'
        print(f'   A={A:2d} r={r:2d} 2^A-3^r={sign}{D}: ' + ' '.join(tags))

def check_G():
    print('(G) least regular primes per subgroup (p < 400):')
    for name, g in GROUPS.items():
        regs = [p for p in primerange(5, 400) if classify_prime(p, g(p))[2]]
        trans = [p for p in primerange(5, 120) if classify_prime(p, g(p))[1] and not classify_prime(p, g(p))[2]]
        print(f'   {name:6s} regular: {regs[:18]}')
        print(f'   {name:6s} transitive non-regular (p<120): {trans}')
    # density heuristics: fraction of primes < 10^5 regular for <2,3>
    tot = 0; reg = 0; trans = 0
    for p in primerange(5, 100000):
        tot += 1
        _, t, r = classify_prime_fast(p, [2, 3])
        reg += r; trans += t
    print(f'   <2,3>: primes 5..1e5: {tot}, transitive {trans} ({trans/tot:.4f}), regular {reg} ({reg/tot:.4f})')

def classify_prime_fast(p, gens):
    # order of subgroup generated by gens = (p-1)/index; compute via orders: |<2,3>| = lcm-type; use generator g
    from sympy import primitive_root, discrete_log
    g = primitive_root(p)
    exps = [discrete_log(p, x % p, g) for x in gens]
    d = p - 1
    for e in exps:
        d = gcd(d, e)
    ordS = (p - 1) // d          # subgroup = <g^d>
    minus1_in = ((p - 1) // 2) % d == 0
    trans = (d == 1) or (d == 2 and not minus1_in)
    regular = (d == 2) and (p % 4 == 3)
    return ordS, trans, regular

