#!/usr/bin/env python3
"""
chessboard_weave_20261006_hp_blocking_exhaustive.py

HYP-9168 (beta(T) = hall(T)) exhaustively over ALL isomorphism classes of tournaments
with 3 <= N <= NMAX (default 10), generated by nauty's gentourng.

For every class the C engine (chessboard_weave_20261006_hp_blocking_engine.c, mode bnbq):
  * computes hall(T) by the Konig formula min_{|A|+|B|=N+2} e(A,B),
  * checks that the optimal (A,B) obstruction really kills every HP (exact subset DP) and
    leaves no 1-path-cycle factor (bipartite matching <= N-2),
  * proves by branch and bound that NO set of hall(T)-1 arcs kills every HP
    (HP-guided branching with protection, packing lower bound; validated against brute
    force subset enumeration in chessboard_weave_20261006_hp_blocking_run.py).
Hence beta(T) = hall(T) for every class, unless a COUNTEREXAMPLE line is printed.

N = 10 is split into 2 gentourng res/mod pieces run in parallel (2 threads max).
"""
import os
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "chessboard_weave_20261006_hp_blocking_engine.c")
BIN = os.path.join(tempfile.gettempdir(), "chessboard_weave_20261006_hp_blocking_exh_%d.bin" % os.getpid())
NMAX = int(sys.argv[1]) if len(sys.argv) > 1 else 10
NSPLIT = 2


def build():
    subprocess.run(["clang", "-O3", "-march=native", "-o", BIN, SRC], check=True)


def run_piece(n, res=None, mod=None):
    gen = ["gentourng", str(n)] + ([f"{res}/{mod}"] if mod else [])
    g = subprocess.Popen(gen, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
    e = subprocess.Popen([BIN, "bnbq"], stdin=g.stdout, stdout=subprocess.PIPE, text=True)
    g.stdout.close()
    return e


def parse_summary(lines):
    d = {}
    hist = {}
    other = []
    for ln in lines:
        if ln.startswith("SUMMARY"):
            for tok in ln.split():
                if "=" in tok:
                    k, v = tok.split("=", 1)
                    d[k] = v
            # max_nodes tournament in parentheses
            d["max_tour"] = ln.split("(")[1].split(")")[0]
        elif ln.startswith("HALL_HISTOGRAM"):
            for tok in ln.split()[1:]:
                k, v = tok.split(":")
                hist[int(k)] = hist.get(int(k), 0) + int(v)
        elif ln.strip():
            other.append(ln.rstrip())
    return d, hist, other


def main():
    build()
    print(__doc__.strip())
    print()
    grand_ok = True
    for n in range(3, NMAX + 1):
        t0 = time.time()
        if n < 10:
            procs = [run_piece(n)]
        else:
            procs = [run_piece(n, r, NSPLIT) for r in range(NSPLIT)]
        outs = [p.communicate()[0].splitlines() for p in procs]
        tot = {"tournaments": 0, "total_nodes": 0, "max_nodes": 0, "hall_lt_sigma": 0,
               "obstruction_fail": 0, "aborted": 0, "counterexamples": 0}
        hist = {}
        others = []
        maxtour = ""
        for o in outs:
            d, h, oth = parse_summary(o)
            for k in tot:
                if k == "max_nodes":
                    if int(d[k]) > tot[k]:
                        tot[k] = int(d[k])
                        maxtour = d["max_tour"]
                else:
                    tot[k] += int(d[k])
            for k, v in h.items():
                hist[k] = hist.get(k, 0) + v
            others += oth
        ok = tot["obstruction_fail"] == 0 and tot["aborted"] == 0 and tot["counterexamples"] == 0
        grand_ok &= ok
        print(f"N={n}: classes={tot['tournaments']} beta=hall for all: {ok}  "
              f"hall<sigma classes={tot['hall_lt_sigma']}  B&B nodes total={tot['total_nodes']} "
              f"max={tot['max_nodes']} ({maxtour})  time={time.time() - t0:.1f}s")
        print("   hall histogram: " + " ".join(f"{k}:{hist[k]}" for k in sorted(hist)))
        for ln in others:
            print("   " + ln)
        sys.stdout.flush()
    print()
    print("ALL CLASSES N <= %d: beta = hall %s" % (NMAX, "CONFIRMED" if grand_ok else "NOT CONFIRMED (see above)"))


if __name__ == "__main__":
    main()
