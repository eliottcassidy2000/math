#!/usr/bin/env python3
"""The Nagata automorphism N = (x - 2y(xz+y^2) - z(xz+y^2)^2, y + z(xz+y^2), z) is equivariant for the mixed weights (3,1,-1)
(invariant ring k[xz + y^2, ... ]: weight-0 monomials x^a y^b z^c with 3a + b = c: generated by xz^3? no: z x z... check),
det JN = 1, and it is wild (Shestakov-Umirbaev); the quotient by the (3,1,-1) action has invariants xz^3, yz, (xz + y^2) z^2."""
import sympy as sp
x, y, z, lam = sp.symbols('x y z lambda')
w = x*z + y**2
N = sp.Matrix([x - 2*y*w - z*w**2, y + z*w, z])
print("det JN =", sp.expand(N.jacobian([x, y, z]).det()))
Nl = N.subs({x: lam**3*x, y: lam*y, z: z/lam}, simultaneous=True)
print("equivariant for weights (3,1,-1):", [sp.simplify(Nl[i]/lam**e - N[i]) == 0 for i, e in enumerate((3, 1, -1))])
# invariants of weights (3,1,-1): monomials x^a y^b z^c with 3a + b - c = 0, generated by yz, xz^3; (xz+y^2) z^2 = xz^3 + (yz)^2
print("w z^2 = x z^3 + (y z)^2:", sp.expand(w*z**2 - (x*z**3 + (y*z)**2)) == 0)
# quotient map on (a, b) = (yz, xz^3): N preserves z and w, so a' = (y + z w) z = a + z^2 w = a + b + a^2, b' = (x - 2yw - zw^2) z^3
a, b = sp.symbols('a b')
Na = sp.expand(N[1]*N[2]); Nb = sp.expand(N[0]*N[2]**3)
def desc(e):
    r = sp.expand(e.subs({y: a/z, x: b/z**3}, simultaneous=True)); assert sp.simplify(sp.diff(r, z)) == 0; return sp.expand(r)
print("Nagata on the quotient (a, b) = (yz, xz^3):", (sp.factor(desc(Na)), sp.factor(desc(Nb))))
