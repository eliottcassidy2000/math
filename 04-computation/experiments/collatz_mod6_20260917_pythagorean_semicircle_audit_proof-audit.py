def is_sq(n):
    return n >= 0 and isqrt(n) ** 2 == n


def brute_ppts(cmax):
    """(odd leg a, even leg b, c) for all PPTs with c<=cmax, by brute force."""
    out = []
    for c in range(5, cmax + 1):
        for a in range(1, c):
            b2 = c * c - a * a
            if b2 <= 0:
                break
            b = isqrt(b2)
            if b * b == b2 and a < b and gcd(a, b) == 1:
                x, y = (a, b) if a % 2 else (b, a)
                out.append((x, y, c))
    return out


def phi(n):
    return sum(1 for k in range(1, n + 1) if gcd(k, n) == 1)


def omega(n):
    c, p = 0, 2
    while p * p <= n:
        if n % p == 0:
            c += 1
            while n % p == 0:
                n //= p
        p += 1
    return c + (n > 1)


