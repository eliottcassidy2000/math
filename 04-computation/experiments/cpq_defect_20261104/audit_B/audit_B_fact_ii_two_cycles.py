#!/usr/bin/env python3
"""audit_B_fact_ii_two_cycles.py -- audit B of THM-4871 statement 7, fact (ii) "two overlapping cycles".

Claim: if c, c' are cycles of the same prime length r with distinct overlapping supports O, O', then K = <c, c'>
is 2-transitive on Delta = O u O'.
Test: c = (0 1 ... r-1); for every overlap size j = 1..r-1, every j-subset S of O and EVERY r-cycle c' on
O' = S u {r, ..., 2r-j-1} (all (r-1)! cyclic orders), check 2-transitivity by the orbit of an ordered pair under
<c, c'> (BFS on ordered pairs of Delta; 2-transitive iff the orbit has size m(m-1), m = |Delta|).
Exhaustive for r = 3, 5, 7 (every overlapping pair of r-cycles is Sym-conjugate to one of these); random sample
for r = 11, 13.  For r = 3, 5 the group order is also computed with sympy and compared with |A_m|, |S_m|
(Jordan: m >= r + 3 forces A_m <= K; for m = r + 1, r + 2 the group is listed).
"""
import sys, time, itertools, random
from collections import Counter

def orbit_pairs(gens, pts):
    """orbit of the ordered pair (pts[0], pts[1]) under the group generated by gens (dicts)."""
    start = (pts[0], pts[1])
    seen = {start}; stack = [start]
    while stack:
        (a, b) = stack.pop()
        for g in gens:
            x = (g[a], g[b])
            if x not in seen:
                seen.add(x); stack.append(x)
    return seen

def orbit_points(gens, pt):
    seen = {pt}; stack = [pt]
    while stack:
        a = stack.pop()
        for g in gens:
            x = g[a]
            if x not in seen:
                seen.add(x); stack.append(x)
    return seen

def check(r, S, order):
    """S: j-subset of O (sorted tuple); order: tuple listing O' in cyclic order (c' maps order[i] -> order[i+1])."""
    O = list(range(r)); j = len(S)
    Oprime = list(S) + list(range(r, 2 * r - j))
    Delta = sorted(set(O) | set(Oprime))
    c = {x: x for x in Delta}
    for i in range(r):
        c[i] = (i + 1) % r
    cp = {x: x for x in Delta}
    for i in range(r):
        cp[order[i]] = order[(i + 1) % r]
    m = len(Delta)
    trans = len(orbit_points([c, cp], Delta[0])) == m
    two = len(orbit_pairs([c, cp], Delta)) == m * (m - 1)
    return m, trans, two, c, cp, Delta

def main():
    t0 = time.time()
    print("audit B / fact (ii): two overlapping r-cycles generate a 2-transitive group on their union")
    for r in (3, 5, 7):
        total = 0; fails = 0; by_m = Counter()
        orders = Counter()
        use_sympy = r <= 5
        if use_sympy:
            from sympy.combinatorics import Permutation, PermutationGroup
        for j in range(1, r):
            for S in itertools.combinations(range(r), j):
                Oprime = list(S) + list(range(r, 2 * r - j))
                first = Oprime[0]
                for rest in itertools.permutations(Oprime[1:]):
                    order = (first,) + rest
                    m, trans, two, c, cp, Delta = check(r, S, order)
                    total += 1; by_m[m] += 1
                    if not (trans and two):
                        fails += 1
                        if fails <= 5:
                            print("  FAIL r=%d S=%s order=%s m=%d transitive=%s 2-transitive=%s" % (r, S, order, m, trans, two))
                    if use_sympy:
                        idx = {x: i for i, x in enumerate(Delta)}
                        g1 = Permutation([idx[c[x]] for x in Delta]); g2 = Permutation([idx[cp[x]] for x in Delta])
                        G = PermutationGroup([g1, g2])
                        import math
                        o = G.order(); fm = math.factorial(m)
                        tag = "S_m" if o == fm else ("A_m" if 2 * o == fm else "order %d" % o)
                        orders[(m, tag)] += 1
        print("r=%d: %d pairs (c, c') tested, |Delta| distribution %s, failures of 2-transitivity: %d  (%.1fs)"
              % (r, total, dict(sorted(by_m.items())), fails, time.time() - t0))
        if use_sympy:
            print("      group orders by (m, type): %s" % dict(sorted(orders.items())))
    # sampled larger primes
    random.seed(20261104)
    for r, samples in ((11, 3000), (13, 1500)):
        fails = 0; by_m = Counter()
        for _ in range(samples):
            j = random.randint(1, r - 1)
            S = tuple(sorted(random.sample(range(r), j)))
            Oprime = list(S) + list(range(r, 2 * r - j))
            rest = Oprime[1:]; random.shuffle(rest)
            order = (Oprime[0],) + tuple(rest)
            m, trans, two, _, _, _ = check(r, S, order)
            by_m[m] += 1
            if not (trans and two):
                fails += 1
        print("r=%d: %d random pairs, |Delta| distribution %s, failures: %d  (%.1fs)" % (r, samples, dict(sorted(by_m.items())), fails, time.time() - t0))
    # the block-argument special cases m = r+1 and m = r+2, exhaustive for r = 11 with S the j = r-1 and r-2 subsets
    for r in (11,):
        for j in (r - 1, r - 2):
            fails = 0; total = 0
            for S in itertools.combinations(range(r), j):
                Oprime = list(S) + list(range(r, 2 * r - j))
                for _ in range(40):
                    rest = Oprime[1:]; random.shuffle(rest)
                    order = (Oprime[0],) + tuple(rest)
                    m, trans, two, _, _, _ = check(r, S, order)
                    total += 1
                    if not (trans and two):
                        fails += 1
            print("r=%d, |Delta| = %d: %d sampled pairs over all %d-subsets, failures: %d" % (r, 2 * r - j, total, j, fails))
    print("done (%.1fs)" % (time.time() - t0))

if __name__ == "__main__":
    main()
