# count norm-2 vectors by brute force in a box via Cholesky/Fincke-Pohst-lite (dimension 8, small)
def count_norm(Gm, N):
    # Fincke-Pohst enumeration of x with x^T G x <= N
    import numpy.linalg as la
    n = Gm.shape[0]
    Q = np.array(Gm, dtype=float)
    # LDL^T style: q_ii and q_ij for Fincke-Pohst
    A = Q.copy(); q = np.zeros((n, n))
    for i in range(n):
        q[i, i] = A[i, i]
        for j in range(i+1, n):
            q[i, j] = A[i, j]/A[i, i]
        for j in range(i+1, n):
            for k in range(j, n):
                A[j, k] -= A[i, j]*A[i, k]/A[i, i]
                A[k, j] = A[j, k]
    cnt = {}
    x = [0]*n
    def rec(i, rem):
        c = -sum(q[i, j]*x[j] for j in range(i+1, n))
        r = math.sqrt(max(rem, 0)/q[i, i])
        for xi in range(math.ceil(c - r - 1e-9), math.floor(c + r + 1e-9)+1):
            x[i] = xi
            t = q[i, i]*(xi - c)**2
            if t > rem + 1e-9: continue
            if i == 0:
                v = np.array(x)
                nv = int(v @ Gm @ v)
                cnt[nv] = cnt.get(nv, 0) + 1
            else:
                rec(i-1, rem - t)
        x[i] = 0
    rec(n-1, N)
    return cnt
