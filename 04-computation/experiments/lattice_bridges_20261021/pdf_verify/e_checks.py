print("\n=== Lagrangian (maximal isotropic) subspace counts: brute force over small fields ===")
def subspaces(q, n, k):
    # enumerate k-dim subspaces of F_q^n via reduced row echelon forms
    for pivots in itertools.combinations(range(n), k):
        free = [(r, c) for r in range(k) for c in range(n) if c > pivots[r] and c not in pivots]
        for vals in itertools.product(range(q), repeat=len(free)):
            M = np.zeros((k, n), dtype=np.int64)
            for r, p in enumerate(pivots): M[r, p] = 1
            for (r, c), v in zip(free, vals): M[r, c] = v
            yield M
def count_lagr(q, m, form):
    n = 2*m
    if form == 'orth':   # hyperbolic quadratic form sum x_i y_i ; bilinear B = [[0,I],[I,0]]
        B = np.block([[np.zeros((m, m), int), np.eye(m, dtype=int)], [np.eye(m, dtype=int), np.zeros((m, m), int)]])
    else:                # symplectic
        B = np.block([[np.zeros((m, m), int), np.eye(m, dtype=int)], [-np.eye(m, dtype=int), np.zeros((m, m), int)]])
    tot = 0; through = 0
    v0 = np.zeros(n, dtype=np.int64); v0[0] = 1   # a fixed singular/isotropic vector
    for M in subspaces(q, n, m):
        G = (M @ B @ M.T) % q
        if form == 'orth':
            # q odd: totally singular <=> B-isotropic (Q(x)=B(x,x)/2)
            ok = not G.any()
        else:
            ok = not G.any()
        if ok:
            tot += 1
            # does the subspace contain v0?  check rank
            r1 = np.linalg.matrix_rank(np.vstack([M, v0]).astype(float))   # over Q is fine for 0/1 test? use mod-q rank instead
            Mq = sp.Matrix(np.vstack([M, v0]).tolist())
            if Mq.rank(iszerofunc=lambda x: x % q == 0) == m:
                through += 1
    return tot, through
def rank_mod(Mx, q):
    Mx = [list(map(int, r)) for r in Mx]; rows = len(Mx); cols = len(Mx[0]); r = 0
    for c in range(cols):
        piv = next((i for i in range(r, rows) if Mx[i][c] % q), None)
        if piv is None: continue
        Mx[r], Mx[piv] = Mx[piv], Mx[r]
        inv = pow(Mx[r][c], -1, q)
        Mx[r] = [(x*inv) % q for x in Mx[r]]
        for i in range(rows):
            if i != r and Mx[i][c] % q:
                f = Mx[i][c]; Mx[i] = [(a - f*b) % q for a, b in zip(Mx[i], Mx[r])]
        r += 1
    return r
def count_lagr2(q, m, form):
    n = 2*m
    if form == 'orth':
        B = np.block([[np.zeros((m, m), int), np.eye(m, dtype=int)], [np.eye(m, dtype=int), np.zeros((m, m), int)]])
    else:
        B = np.block([[np.zeros((m, m), int), np.eye(m, dtype=int)], [-np.eye(m, dtype=int), np.zeros((m, m), int)]])
    v0 = np.zeros(n, dtype=np.int64); v0[0] = 1
    tot = through = 0
    for M in subspaces(q, n, m):
        if not ((M @ B @ M.T) % q).any():
            tot += 1
            if rank_mod(np.vstack([M, v0]), q) == m: through += 1
    return tot, through
