#!/usr/bin/env python3
"""Search over totally positive twists lambda = u * lambda0, lambda0 = (zeta^30 delta/sqrt(-7))^{-1}, u in the group
generated by -1 and real cyclotomic units r_a = zeta^a + zeta^-a (a = 1..17), for which (O_K, Tr(lambda x ybar)) / 7
is even unimodular; then test for roots with PARI (Leech iff no norm-2 vectors). Writes candidate Grams."""
import itertools, math, subprocess, sys
from mpmath import mp, mpf, mpc, exp, pi, sqrt, nint, fabs
import numpy as np
mp.dps = 60
n = 35
units = [k for k in range(1, n) if math.gcd(k, n) == 1]
reps = [k for k in units if k < n/2]
H = [k for k in units if pow(k, 3, 7) == 1]
def leg7(k): return 1 if pow(k % 7, 3, 7) == 1 else -1
z = lambda k: exp(2j*pi*mpf(k)/n)
def sig_delta(k):
    r = mpc(1)
    for h in H:
        if h != 1: r *= (z(k) - z(k*h))
    return r
lam0 = {k: 1/(z(30*k) * sig_delta(k) / (leg7(k)*1j*sqrt(7))) for k in units}
gens = {('r', a): {k: (z(k*a) + z(-k*a)).real for k in units} for a in range(1, 18)}
gens[('m1',)] = {k: mpf(-1) for k in units}
names = list(gens)
def signvec(vals): return np.array([0 if vals[k] > 0 else 1 for k in reps], dtype=np.int64)
S = np.array([signvec(gens[g]) for g in names])        # rows: generators
t = signvec({k: lam0[k].real for k in units})
# solve x S = t over F2 ; enumerate solution coset (kernel basis)
def rref_mod2(A):
    A = A.copy() % 2; rows, cols = A.shape; piv = []; r = 0
    for c in range(cols):
        p = next((i for i in range(r, rows) if A[i, c]), None)
        if p is None: continue
        A[[r, p]] = A[[p, r]]
        for i in range(rows):
            if i != r and A[i, c]: A[i] ^= A[r]
        piv.append(c); r += 1
    return A, piv
# augmented system S^T x = t
Aug = np.concatenate([S.T, t.reshape(-1, 1)], axis=1)
R, piv = rref_mod2(Aug)
if len(S) in piv:
    print("no solution: lambda0 cannot be made totally positive with these units"); sys.exit()
nv = len(names)
x0 = np.zeros(nv, dtype=np.int64)
for i, c in enumerate(piv): x0[c] = R[i, -1]
free = [c for c in range(nv) if c not in piv]
kernel = []
for f in free:
    v = np.zeros(nv, dtype=np.int64); v[f] = 1
    for i, c in enumerate(piv): v[c] = R[i, f]
    kernel.append(v)
print("sign-vector rank of generators:", len(piv), " kernel dim (totally positive combos mod squares, over these gens):", len(kernel))
# the kernel combos are totally positive units; modulo squares they may be nontrivial. enumerate a few classes:
cands = []
for bits in itertools.product((0, 1), repeat=min(len(kernel), 12)):
    x = x0.copy()
    for b, v in zip(bits, kernel): x = (x + b*v) % 2
    cands.append(x)
print("number of candidate twists:", len(cands))
results = []
seen = set()
for ci, x in enumerate(cands):
    lam = {}
    for k in units:
        val = lam0[k].real
        for g, xi in zip(names, x):
            if xi: val *= gens[g][k]
        lam[k] = val
    assert all(lam[k] > 0 for k in units)
    G = [[sum(lam[k] * z(k*(a-b)) for k in units).real for b in range(24)] for a in range(24)]
    Gi = [[int(nint(v)) for v in row] for row in G]
    err = max(fabs(G[a][b] - Gi[a][b]) for a in range(24) for b in range(24))
    if err > 1e-20: continue
    if not all(v % 7 == 0 for row in Gi for v in row): continue
    M = [[v//7 for v in row] for row in Gi]
    key = tuple(sorted(M[a][a] for a in range(24)))
    results.append((ci, M))
print("candidates with integral Gram divisible by 7:", len(results))
with open('J_candidates.gp', 'w') as f:
    f.write("C = List();\n")
    for ci, M in results:
        f.write("listput(C, [" + ";".join(",".join(str(v) for v in row) for row in M) + "]);\n")
    f.write("""for(i=1,#C, G=C[i]; d=matdet(G); ev=vecmin(vector(24,j,G[j,j]%2==0)); m=qfminim(G,2,0,2); \\
  print(i, ": det=", d, " even=", ev, " #vectors norm<=2 (pairs): ", m[1]));
quit
""")
print("wrote J_candidates.gp")
