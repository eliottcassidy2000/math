def Hmat(k):
    M = np.array([[1, 1], [-1, 1]])
    for _ in range(k - 1):
        M = np.block([[M, M], [-M.T, M.T]])
    return M


def qform(k, x, y):
    s = 0
    for l in range(k):
        if (x >> l) & 1:
            s ^= 1 ^ ((y >> l) & 1) ^ (1 if (x & ((1 << l) - 1)) != (y & ((1 << l) - 1)) else 0)
    return s


