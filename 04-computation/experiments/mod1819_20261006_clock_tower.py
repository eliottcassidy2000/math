def ancestor_word(n, D=60):
    """exact integers: shortest-found inverse word to an odd ancestor x < n (None if none within depth D)"""
    if n % 3 == 0:
        return None
    stack, best = [(n, 0, ())], None
    while stack:
        x, d, w = stack.pop()
        if d == D:
            continue
        r = x % 3
        if r == 0:
            continue
        k = 1 if r == 2 else 2
        while True:
            y = ((x << k) - 1) // 3
            if y < n:
                if best is None or d + 1 < best[0]:
                    best = (d + 1, w + (k,), y)
                break
            if math.log2(y / n) - (D - d - 1) * (L2_3 - 1) > 0:
                break
            stack.append((y, d + 1, w + (k,)))
            k += 2
    return best


