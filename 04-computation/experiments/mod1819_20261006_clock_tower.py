def tower(k):
    S = Hmat(k) - np.eye(2 ** k, dtype=int)
    return (S[1:, 1:] > 0).astype(int)


def aut_orbits(A):
    n = A.shape[0]
    s = "d\nn=%d g\n" % n + ";\n".join(" ".join(str(j) for j in np.nonzero(A[i])[0]) for i in range(n)) + ".\nx\no\nq\n"
    out = subprocess.run(["dreadnaut"], input=s, capture_output=True, text=True).stdout
    g = int(float(re.search(r"grpsize=([0-9.e+]+)", out).group(1)))
    tail = out.split("grpsize")[1]
    tail = tail[tail.find("\n") + 1:]
    sizes = []
    for part in tail.replace("\n", " ").split(";"):
        part = part.strip()
        if not part:
            continue
        m = re.search(r"\((\d+)\)", part)
        if m:
            sizes.append(int(m.group(1)))
        else:
            c = 0
            for tok in part.split():
                if ":" in tok:
                    u, v = map(int, tok.split(":"))
                    c += v - u + 1
                elif tok.isdigit():
                    c += 1
            if c:
                sizes.append(c)
    return g, Counter(sizes)


