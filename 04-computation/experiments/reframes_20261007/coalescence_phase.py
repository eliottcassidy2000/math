#!/usr/bin/env python3
"""Coalescence phase diagram for generalized Collatz maps on Z_d (Haar), via the exact pair chain.
Map: T(x) = (m_i x + r_i)/d for x = i mod d, m_i units mod d (each branch maps its class onto Z_d, so the branch
sequence of a Haar point is iid uniform -- the d-adic Terras property).
Pair chain: u = M v + e with M a positive rational (the 'debt', in the multiplicative group generated by the m_i)
and e a d-adic integer in Q. v's branch j is a fresh uniform digit; u's branch is i = (M mod d) j + (e mod d) mod d;
then M' = M m_i/m_j, e' = (m_i e + r_i - (m_i/m_j) M r_j)/d.  Absorbed (equal-time merge) iff M = 1 and e = 0.
Usage: python3 coalescence_phase.py NAME NSAMP TMAX SEED"""
import sys, random, math
from fractions import Fraction as Fr
MAPS = {
  # name: (d, [(m_i, r_i)], description)
  '3x+1':     (2, [(1, 0), (3, 1)], 'rank 1, contracting (Collatz)'),
  '5x+1':     (2, [(1, 0), (5, 1)], 'rank 1, expanding'),
  '7x+1':     (2, [(1, 0), (7, 1)], 'rank 1, expanding'),
  'Z3_124':   (3, [(1, 0), (2, 1), (4, 1)], 'rank 1, contracting'),
  'Z3_1416':  (3, [(1, 0), (4, 2), (16, 1)], 'rank 1, expanding'),
  '9x+1':     (2, [(1, 0), (9, 1)], 'rank 1, expanding'),
  '11x+1':    (2, [(1, 0), (11, 1)], 'rank 1, expanding'),
  'x+1':      (2, [(1, 0), (1, 1)], 'rank 0, contracting'),
  'Z5_11111': (5, [(1, 0), (1, 4), (1, 3), (1, 2), (1, 1)], 'rank 0, contracting'),
  'Z3_125':   (3, [(1, 0), (2, 1), (5, 2)], 'rank 2, contracting'),
  'Z3_157':   (3, [(1, 0), (5, 1), (7, 1)], 'rank 2, expanding'),
  'Z5_12311': (5, [(1, 0), (2, 3), (3, 4), (1, 2), (1, 1)], 'rank 2, contracting'),
  'Z5_12371': (5, [(1, 0), (2, 3), (3, 4), (7, 4), (1, 1)], 'rank 3, contracting'),
  'Z5_12471': (5, [(1, 0), (2, 3), (4, 2), (7, 4), (1, 1)], 'rank 2 (2,7), contracting'),
}
def check(d, br):
    for i, (m, r) in enumerate(br):
        assert math.gcd(m, d) == 1 and (m * i + r) % d == 0, (i, m, r)
def modd(q, d):  # rational with denominator prime to d, reduced mod d
    return (q.numerator * pow(q.denominator, -1, d)) % d
def run(name, nsamp, tmax, seed, e0=1):
    d, br, desc = MAPS[name]; check(d, br)
    rnd = random.Random(seed)
    times = []
    for _ in range(nsamp):
        M, e = Fr(1), Fr(e0); t = 0
        while t < tmax and not (M == 1 and e == 0):
            j = rnd.randrange(d)
            i = (modd(M, d) * j + modd(e, d)) % d
            mi, ri = br[i]; mj, rj = br[j]
            e = (mi * e + ri - Fr(mi, mj) * M * rj) / d
            M = M * Fr(mi, mj)
            t += 1
        times.append(t if (M == 1 and e == 0) else None)
    return desc, times
if __name__ == '__main__':
    name, nsamp, tmax, seed = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4])
    desc, times = run(name, nsamp, tmax, seed)
    out = [f"{name}: {desc}; {nsamp} samples, start (M, e) = (1, 1)"]
    T = 4
    while T <= tmax:
        q = sum(1 for x in times if x is None or x > T) / nsamp
        out.append(f"  T={T:7d}  P(no merge by T) = {q:.4f}   sqrt(T)*q = {math.sqrt(T)*q:7.3f}   log(T)*q = {math.log(T)*q:6.3f}")
        T *= 4
    print("\n".join(out), flush=True)
