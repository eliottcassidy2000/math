"""Deep levels of the 3-adic Syracuse law (Tao's Syracuse random variable, Mazur's mu_q) by FFT.

The units of Z/3^n form a cyclic group generated by 2 (order L = 2 3^(n-1)); the step
Y_n = 2^-A (3 Y_(n-1) + 1) is, in discrete-log coordinates, a circular correlation with the
geometric law of A mod L.  This gives mu_n on Z/3^n for n <= 14 in seconds, against the exact
rational recursion for n <= 6.

Reported per level: rho_n(y) = (2/3) 3^n mu_n(y) at the seed 1 (its (3/2) rho_n(1) is the depth-n
harmonic mass of the Syracuse tree of 1), at the negative cycle points -1, -5, -7, -17, at the
seeds R_j = (4^j - 1)/3, the top atoms with signed representatives, the L2 norm of rho_n over
units, the entropy dimension estimate, and the low-density share of units.

Session: opus, collatz-poset-dag-20260927 (S19), 2026-09-28.
Run: python 04-computation/experiments/mazur_harmonic_mass_deep_20260928.py
"""
from __future__ import annotations

import math
import sys
import time
from fractions import Fraction

import numpy as np

sys.path.insert(0, "04-computation/experiments")
from mazur_harmonic_mass_20260928 import mu_exact  # noqa: E402


def level_up(mu: np.ndarray, lev: int) -> np.ndarray:
    """mu on Z/3^(lev-1) (array of length 3^(lev-1)) -> law on Z/3^lev (array of length 3^lev)."""
    mod = 3 ** lev
    L = 2 * 3 ** (lev - 1)
    pow2 = np.empty(L, dtype=np.int32)
    p = 1
    for k in range(L):
        pow2[k] = p
        p = (p * 2) % mod
    dlog = np.full(mod, -1, dtype=np.int32)
    dlog[pow2] = np.arange(L)
    y = np.arange(3 ** (lev - 1), dtype=np.int64)
    base = (3 * y + 1) % mod  # units
    f = np.zeros(L)
    np.add.at(f, dlog[base], mu)
    del y, base
    r = np.arange(L, dtype=np.float64)
    ker = np.zeros(L)
    ker[1:] = 2.0 ** (-r[1:])  # P(A = r mod L) proportional to 2^-r, r = 1..L (r = L stored at index 0)
    ker[0] = 2.0 ** (-L) if L < 1000 else 0.0
    ker /= ker.sum()
    # Y = 2^-a base: dlog(Y) = dlog(base) - a, so new[k] = sum_r ker[r] f[k + r] (a circular correlation)
    ker_rev = np.roll(ker[::-1], 1)  # ker_rev[s] = ker[-s mod L]
    g = np.fft.irfft(np.fft.rfft(f) * np.fft.rfft(ker_rev), n=L)
    del f, ker, ker_rev, r
    g[g < 0] = 0.0
    new = np.zeros(mod)
    new[pow2] = g
    del g, dlog, pow2
    return new


def signed_rep(y: int, mod: int) -> int:
    return y - mod if y > mod // 2 else y


if __name__ == "__main__":
    NMAX = int(sys.argv[1]) if len(sys.argv) > 1 else 15
    t0 = time.time()
    mu = np.array([0.0, 1 / 3, 2 / 3])  # level 1
    print("== 3-adic Syracuse law by FFT: rho_n = (2/3) 3^n mu_n on the units of Z/3^n ==")
    seeds = {j: (4 ** j - 1) // 3 for j in (1, 2, 4, 5, 7, 8)}
    prev = None
    levels = {}
    for n in range(1, NMAX + 1):
        if n >= 2:
            prev = mu
            mu = level_up(mu, n)
        mod = 3 ** n
        if prev is not None:
            # parents form of the recursion at the seed 1: rho_(n)(1) = 3 sum_(j>=1) 4^-j rho_(n-1)(R_j mod 3^(n-1))
            pm = 3 ** (n - 1)
            rec = 3 * sum(4.0 ** (-j) * (2 / 3) * pm * prev[((4 ** j - 1) // 3) % pm] for j in range(1, 40))
            assert abs(rec - (2 / 3) * mod * mu[1]) < 1e-9, (n, rec, (2 / 3) * mod * mu[1])
            # L1 increment of the Haar densities between consecutive levels (martingale Cauchy rate)
            l1inc = float(np.abs(mu - np.tile(prev, 3) / 3).sum())  # lift: z -> z mod 3^(n-1); the tile, not the repeat
        else:
            l1inc = float("nan")
        if n <= 9:
            levels[n] = mu.copy()
        if n <= 6:
            ex = mu_exact(n)
            err = max(abs(float(ex.get(y, Fraction(0))) - mu[y]) for y in range(mod))
            assert err < 1e-12, (n, err)
        units = np.arange(mod) % 3 != 0
        rho = (2 / 3) * mod * mu
        ru = rho[units]
        assert abs(ru.mean() - 1) < 1e-9
        idx = np.arange(mod)
        assert abs(rho[idx % 3 == 1].mean() - 2 / 3) < 1e-9 and abs(rho[idx % 3 == 2].mean() - 4 / 3) < 1e-9  # class means: Y_n mod 3 = 2^-a_n
        del idx
        ent = float(-(mu[mu > 0] * np.log(mu[mu > 0])).sum()) / (n * math.log(3))
        l2 = float((ru ** 2).mean())
        top = np.argsort(-rho)[:6] if n <= 14 else []
        tops = ", ".join(f"{signed_rep(int(t), mod)}:{rho[t]:.3g}" for t in top) if n <= 14 else "(skipped)"
        seedvals = " ".join(f"R{j}={rho[seeds[j] % mod]:.4f}" for j in seeds)
        print(f"   n={n:2d}: rho(1)={rho[1]:.5f} L1inc={l1inc:.4f} rho(-1)={rho[mod-1]:.4g} rho(-5)={rho[(-5)%mod]:.4g} rho(-7)={rho[(-7)%mod]:.4g} rho(-17)={rho[(-17)%mod]:.4g} | "
              f"{seedvals} | L2={l2:.4f} entdim={ent:.5f} share(rho<0.1)={(ru < 0.1).mean():.4f} median={np.median(ru):.4f} | top atoms {tops}   [{time.time()-t0:.1f}s]")
    # fine-scale distances at the top level: ell^1 between mu_N and the uniform lift of mu_m (Mazur (2.3), Tao Prop. 1.14)
    N = NMAX
    dists = []
    for m in range(1, min(N, 9) + 1):
        lift = np.tile(levels[m], 3 ** (N - m)) / 3 ** (N - m)
        dists.append((m, float(np.abs(mu - lift).sum())))
    print("   fine-scale ell^1 distances ||mu_N - lift(mu_m)||_1 at N = %d: " % N + ", ".join(f"m={m}: {d:.4f}" for m, d in dists))
    # spike profile: rational points x = p/2^k of the forward closure of -1; predicted D(x) = lim rho_n(x)/rho_n(-1)
    # from D(x) = 2 sum_a 2^-a D((2^a x - 1)/3), D(-1) = 1, D = 0 off the closure (path sums 2^(l - A))
    prof = {"-1/2": (-1, 2, 0.5), "-1/4": (-1, 4, 0.75), "1/8": (1, 8, 0.75), "11/16": (11, 16, 0.75), "49/32": (49, 32, 0.75),
            "-1/8": (-1, 8, 0.375), "1/16": (1, 16, 0.375), "-1/16": (-1, 16, 0.1875), "11/32": (11, 32, 0.375)}
    outs = []
    for name, (num, den, pred) in prof.items():
        cls = (num * pow(den, -1, mod)) % mod
        outs.append(f"{name}: {rho[cls] / rho[mod - 1]:.4f} (pred {pred})")
    print("   spike profile at level %d, rho_n(x)/rho_n(-1): " % N + "; ".join(outs))
    print(f"   rho_N(-1)/(3/2)^N = {rho[mod - 1] / 1.5 ** N:.4f}")
    # seed-1 extrapolation: if the other seed classes have converged, rho_inf(1) = 12 sum_(j>=2) 4^-j rho_N(R_j)
    ext = 12 * sum(4.0 ** (-j) * rho[((4 ** j - 1) // 3) % mod] for j in range(2, 40))
    print(f"   seed-1 fixed-point extrapolation from level {N}: rho_inf(1) ~ {ext:.4f} (H_inf ~ {1.5 * ext:.4f}); current rho_N(1) = {rho[1]:.4f}")
    print("   rho(-1)/(3/2)^n tends to a constant (loop word 1^n gives Y_n = -1 mod 3^n exactly, mass 2^-n, plus the rest of the tree of -1);")
    print("   rho(1): the seed-1 harmonic mass H_n = (3/2) rho_n(1); L2 growth = failure of a square-integrable density; entdim < 1 = singular limit")
    print("DONE")
