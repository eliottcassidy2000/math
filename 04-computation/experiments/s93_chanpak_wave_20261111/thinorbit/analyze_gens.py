#!/usr/bin/env python3
"""Lane thinorbit (S93).  Linear-algebraic anatomy of the base-2 port-chain generators (HYP-9640 (B)).

Input: a file of 3 x 3 matrices (rows (h, E, O)), with .reps.  Exact arithmetic (sympy / Python ints).
Reports: determinant and rank of every generator; the unimodular ones; images and kernels of the singular ones;
the seam coordinates (H, S, R) = (h, O - E, O + E) and the converse duality M -> J M^T J; the dimension of the
enveloping algebra; the test for Zariski density of the group generated by the invertible generators
(tribonacci-torus criterion, PROOFS.txt section Z); common invariant lines / planes / quadratic forms.
"""
import itertools
import sys
from math import gcd

import sympy as sp


def load(path):
    mats = []
    reps = []
    with open(path + ".reps") as f:
        for line in f:
            a, b = line.split("|")
            v = list(map(int, a.split()))
            mats.append(sp.Matrix(3, 3, v))
            reps.append(b.strip())
    return mats, reps


def primitive(v):
    g = 0
    for x in v:
        g = gcd(g, int(x))
    if g == 0:
        return tuple(int(x) for x in v)
    v = [int(x) // g for x in v]
    for x in v:
        if x != 0:
            if x < 0:
                v = [-y for y in v]
            break
    return tuple(v)


def main():
    path = sys.argv[1]
    mats, reps = load(path)
    n = len(mats)
    print(f"{n} generators from {path}")
    P = sp.Matrix([[1, 0, 0], [0, -1, 1], [0, 1, 1]])      # (h, E, O) -> (H, S, R)
    Pinv = P.inv()
    J = sp.diag(1, -1, 1)
    seam = [P * M * Pinv for M in mats]
    integral = all(all(x == int(x) for x in S) for S in seam)
    print("seam form P N P^-1 integral for all generators:", integral)
    # converse duality: the set {P N P^-1} is closed under M -> J M^T J
    sset = set(tuple(int(x) for x in S) for S in seam)
    closed = all(tuple(int(x) for x in (J * S.T * J)) in sset for S in seam)
    print("set of seam matrices closed under the converse duality M -> J M^T J:", closed)
    selfdual = sum(1 for S in seam if J * S.T * J == S)
    print("self-dual generators:", selfdual)
    dets = [int(M.det()) for M in mats]
    ranks = [M.rank() for M in mats]
    from collections import Counter
    print("determinants:", sorted(Counter(dets).items()))
    print("ranks:", sorted(Counter(ranks).items()))
    print()
    print("idx | matrix (h,E,O) | det rank | charpoly | block")
    t = sp.symbols("t")
    for i, M in enumerate(mats):
        cp = sp.factor(M.charpoly(t).as_expr())
        print(f"{i:3d} | {list(M)} | {dets[i]:4d} {ranks[i]} | {cp} | {reps[i]}")
    print()
    # rank-1 generators: image line and kernel functional
    print("rank-1 generators  M = a b^T (image a, functional b):")
    for i, M in enumerate(mats):
        if ranks[i] == 1:
            col = None
            for j in range(3):
                if any(M[r, j] != 0 for r in range(3)):
                    col = [M[r, j] for r in range(3)]
                    break
            a = primitive(col)
            # b: M = a b^T
            r0 = next(r for r in range(3) if a[r] != 0)
            b = [sp.Rational(M[r0, j], a[r0]) for j in range(3)]
            print(f"  {i:3d}: a = {a}, b = {b}   [{reps[i]}]")
    print("rank-2 generators: image plane (normal vector n with n . M = 0) and kernel line (M k = 0):")
    planes = Counter()
    kers = Counter()
    for i, M in enumerate(mats):
        if ranks[i] == 2:
            nvec = primitive(list(M.T.nullspace()[0] * 1))
            # scale to integers
            ns = M.T.nullspace()[0]
            den = sp.ilcm(*[sp.Rational(x).q for x in ns])
            nvec = primitive([int(x * den) for x in ns])
            ks = M.nullspace()[0]
            den = sp.ilcm(*[sp.Rational(x).q for x in ks])
            kvec = primitive([int(x * den) for x in ks])
            planes[nvec] += 1
            kers[kvec] += 1
            print(f"  {i:3d}: image normal {nvec}, kernel {kvec}   [{reps[i]}]")
    print("image planes by normal:", sorted(planes.items(), key=lambda kv: -kv[1]))
    print("kernel lines:", sorted(kers.items(), key=lambda kv: -kv[1]))
    print()
    # enveloping algebra
    basis = []

    def add(M):
        vec = sp.Matrix(1, 9, list(M))
        if not basis:
            basis.append(vec)
            return True
        A = sp.Matrix.vstack(*basis, vec)
        if A.rank() > len(basis):
            basis.append(vec)
            return True
        return False

    frontier = []
    for M in mats:
        if add(M):
            frontier.append(M)
    changed = True
    while changed and len(basis) < 9:
        changed = False
        newf = []
        for A in frontier:
            for M in mats:
                for Pm in (A * M, M * A):
                    if add(Pm):
                        newf.append(Pm)
                        changed = True
        frontier = newf
    print("dimension of the algebra generated by all generators:", len(basis))
    inv = [i for i in range(n) if dets[i] != 0]
    uni = [i for i in range(n) if abs(dets[i]) == 1]
    print("invertible generators:", inv)
    print("unimodular generators:", uni)
    basis.clear()
    frontier = []
    for i in uni:
        if add(mats[i]):
            frontier.append(mats[i])
    changed = True
    um = [mats[i] for i in uni]
    while changed and len(basis) < 9:
        changed = False
        newf = []
        for A in frontier:
            for M in um:
                for Pm in (A * M, M * A):
                    if add(Pm):
                        newf.append(Pm)
                        changed = True
        frontier = newf
    print("dimension of the algebra generated by the unimodular generators:", len(basis))
    # tower
    T = sp.Matrix([[1, 2, 0], [0, 0, 1], [1, 1, 0]])
    ti = [i for i, M in enumerate(mats) if M == T]
    print("tower matrix index:", ti, "charpoly", sp.factor(T.charpoly(t).as_expr()), "det", T.det())
    for pw in (2, 3, 4):
        idx = [i for i, M in enumerate(mats) if M == T ** pw]
        print(f"  T^{pw} is generator", idx)
    # Zariski density criterion: an invertible generator g with g T g^-1 not commuting with T
    wit = []
    for i in inv:
        g = mats[i]
        C = g * T * g.inv()
        if C * T != T * C:
            wit.append(i)
    print("invertible generators g with [g T g^-1, T] != 0 (each proves Zariski density, PROOFS.txt Z):", wit)
    # common invariant structures of ALL generators
    # (a) common eigenvector (invariant line): v with M v parallel to v for all M -> check via eigenvectors of first
    def common_invariant_lines(ms):
        cands = None
        for M in ms:
            ev = []
            for val, mult, vecs in M.eigenvects():
                if len(vecs) == 1:
                    ev.append(tuple(sp.nsimplify(x) for x in (vecs[0] / next(y for y in vecs[0] if y != 0))))
                else:
                    return "eigenspace of dim > 1 met; not decided by this routine"
            if cands is None:
                cands = set(ev)
            else:
                cands &= set(ev)
            if not cands:
                return set()
        return cands

    print("common invariant lines of the unimodular generators:", common_invariant_lines(um))
    print("common invariant lines of their transposes (invariant planes):",
          common_invariant_lines([M.T for M in um]))
    # (c) common invariant quadratic form up to scalar among the unimodular generators: M^T Q M = c_M Q
    q = sp.symbols("q0:6")
    Q = sp.Matrix([[q[0], q[1], q[2]], [q[1], q[3], q[4]], [q[2], q[4], q[5]]])
    # unimodular => c_M^3 = det^2 = 1 => c_M = 1 (real); solve linear system M^T Q M = Q for all unimodular M
    eqs = []
    for M in um:
        D = M.T * Q * M - Q
        eqs.extend(list(D))
    sol = sp.linsolve(eqs, q)
    print("quadratic forms Q with M^T Q M = Q for all unimodular generators:", sol)


if __name__ == "__main__":
    main()
