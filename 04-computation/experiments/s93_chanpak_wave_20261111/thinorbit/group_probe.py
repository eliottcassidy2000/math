#!/usr/bin/env python3
"""Lane thinorbit (S93).  Congruence images of the port-chain semigroup (56 base-2 generators of order <= 4).

 (1) the semigroup generated by the unimodular generators, reduced mod p (a finite semigroup of invertible
     matrices is a group): its order against |SL_3(F_p)| for p = 2, 3, 5, 7;
 (2) the monoid generated by ALL 56 generators mod p (p = 2, 3): its size, and the number of invertible elements;
 (3) the orbit of the start state (1, 0, 1) in (Z/q)^3 under all 56 generators, under the invertible ones and
     under the unimodular ones: number of states reached and the set of residues of h (no local obstruction
     means: every odd residue for q a power of 2, every residue for q odd);
 (4) the same for the modulus-q orbit of the transposed action on the readout functional (1, 0, 0).
"""
import itertools
import sys

import numpy as np
import sympy as sp


def load(path):
    return [np.array(list(map(int, l.split())), dtype=np.int64).reshape(3, 3) for l in open(path)]


def code(mats, p):
    w = p ** np.arange(9, dtype=np.int64)
    return (mats.reshape(-1, 9) % p) @ w


def closure_mod_p(gens, p, cap=40_000_000):
    """Semigroup generated by gens in Mat_3(F_p): BFS by right multiplication, returns array of elements."""
    seen = np.zeros(p ** 9, dtype=bool)
    G = np.array([g % p for g in gens], dtype=np.int64)
    front = G.copy()
    c = code(front, p)
    c, idx = np.unique(c, return_index=True)
    front = front[idx]
    seen[c] = True
    elems = [front]
    total = len(front)
    while len(front):
        new = []
        for g in G:
            prod = np.einsum("nij,jk->nik", front, g) % p
            c = code(prod, p)
            c, idx = np.unique(c, return_index=True)
            prod = prod[idx]
            mask = ~seen[c]
            if mask.any():
                seen[c[mask]] = True
                new.append(prod[mask])
        if new:
            front = np.concatenate(new)
            elems.append(front)
            total += len(front)
        else:
            front = np.zeros((0, 3, 3), dtype=np.int64)
        if total > cap:
            return None
    return np.concatenate(elems)


def det3(m, p):
    a = m.reshape(-1, 9)
    d = (a[:, 0] * (a[:, 4] * a[:, 8] - a[:, 5] * a[:, 7]) - a[:, 1] * (a[:, 3] * a[:, 8] - a[:, 5] * a[:, 6])
         + a[:, 2] * (a[:, 3] * a[:, 7] - a[:, 4] * a[:, 6]))
    return d % p


def orbit_mod_q(gens, q, start, transpose=False):
    G = [(g.T if transpose else g) % q for g in gens]
    seen = np.zeros(q ** 3, dtype=bool)
    s = np.array(start, dtype=np.int64) % q
    w = np.array([q * q, q, 1], dtype=np.int64)
    front = s.reshape(1, 3)
    seen[int(s @ w)] = True
    while len(front):
        new = []
        for g in G:
            img = (front @ g.T) % q
            c = img @ w
            c, idx = np.unique(c, return_index=True)
            img = img[idx]
            mask = ~seen[c]
            if mask.any():
                seen[c[mask]] = True
                new.append(img[mask])
        front = np.concatenate(new) if new else np.zeros((0, 3), dtype=np.int64)
    codes = np.nonzero(seen)[0]
    hs = np.unique(codes // (q * q))
    return len(codes), hs


def main():
    allg = load("blocks2_k4.txt")
    uni = load("sub_k4_uni.txt")
    inv = load("sub_k4_inv.txt")
    print("(1) group generated mod p by the 8 unimodular generators (order <= 4):")
    for p in (2, 3, 5, 7):
        el = closure_mod_p(uni, p)
        order_sl3 = p ** 3 * (p ** 2 - 1) * (p ** 3 - 1)
        print(f"    p = {p}: {len(el)} elements; |SL_3(F_{p})| = {order_sl3}; equal: {len(el) == order_sl3}")
    print("    (mod 2 the parity lemma confines every block to [[1,0,0],[*,x,y],[*,y,x]]: a subgroup of order 8 of SL_3(F_2))")
    print("(2) monoid generated mod p by all 56 generators:")
    for p in (2, 3):
        el = closure_mod_p(allg, p)
        d = det3(el, p)
        print(f"    p = {p}: {len(el)} elements, of which {int((d != 0).sum())} invertible; |Mat_3(F_{p})| = {p ** 9}, |GL_3(F_{p})| = "
              f"{(p ** 3 - 1) * (p ** 3 - p) * (p ** 3 - p ** 2)}")
    el = closure_mod_p(inv, 3)
    d = det3(el, 3)
    print(f"    the 21 invertible generators mod 3: {len(el)} elements, {int((d != 0).sum())} invertible (det 9, 21, 24 vanish mod 3)")
    el = closure_mod_p(inv, 5)
    d = det3(el, 5)
    print(f"    the 21 invertible generators mod 5: {len(el)} elements, {int((d != 0).sum())} invertible (det 5 vanishes mod 5); "
          f"|GL_3(F_5)| = {(5 ** 3 - 1) * (5 ** 3 - 5) * (5 ** 3 - 25)}")
    print("(3) orbit of (1,0,1) mod q: (#states reached, #residues of h reached, expected) for all 56 / invertible 21 / unimodular 8")
    for q in (2, 4, 8, 16, 32, 64, 3, 9, 27, 5, 25, 7, 49, 11, 13, 15, 21, 35, 45, 63, 105):
        row = []
        for gens in (allg, inv, uni):
            ns, hs = orbit_mod_q(gens, q, (1, 0, 1))
            row.append((ns, len(hs)))
        exp = q // 2 if q % 2 == 0 else q
        okall = all(r[1] == exp for r in row)
        print(f"    q = {q:3d}: {row}  expected residues {exp}  all three complete: {okall}")
    print("(4) orbit of the readout functional (1,0,0) under the transposed generators mod q (left orbit): #states, #first coordinates")
    for q in (8, 9, 5, 7):
        row = []
        for gens in (allg, inv, uni):
            ns, hs = orbit_mod_q(gens, q, (1, 0, 0), transpose=True)
            row.append((ns, len(hs)))
        print(f"    q = {q:3d}: {row}")


if __name__ == "__main__":
    main()
