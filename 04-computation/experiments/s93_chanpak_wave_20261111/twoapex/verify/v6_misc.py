    check("8  the lattice generated by the prefix states of length <= 6 is invariant under the four letters "
          "(so its index is the index for all prefixes); index = 2^21", (not grew) and idxs[max(idxs)] == 2 ** 21,
          f"(index {idxs[max(idxs)]})")

    print(f"total time {time.time() - t00:.1f} s")
    print("ALL VERIFIER CHECKS PASS" if OK else "SOME VERIFIER CHECK FAILED")


