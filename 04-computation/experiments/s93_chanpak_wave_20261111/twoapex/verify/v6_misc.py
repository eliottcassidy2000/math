    nxt = [np.searchsorted(keys, key((states @ A[l]) % m)) for l in range(4)]
    tt = np.searchsorted(keys, key((states + 2) % m))
    reps = np.flatnonzero(np.arange(N) < tt)                     # one state per pair {x, x + 2(1,..,1)}
