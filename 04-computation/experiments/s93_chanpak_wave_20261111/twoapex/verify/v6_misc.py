    # ---- 5
    def E_formula(a, b):
        n = len(a)
        if n == 0:
            return 1
        t = (b[0] == 1) + (a[-1] == 0) + sum(1 for k in range(n - 1) if a[k] == 0 and b[k + 1] == 1)
        t += sum(1 << (L - F - 1) for F in range(n) if b[F] for L in range(F + 1, n) if a[L] == 0)
        return t

    def E_literal(a, b):
        # paths [R1] u v [R3]: 2-colourings with (R1 empty or a(last R1) = 0) and (R3 empty or b(first R3) = 1)
        n = len(a)
        tot = 0
        for col in itertools.product((0, 1), repeat=n):
            R1 = [i for i in range(n) if col[i] == 0]
            R3 = [i for i in range(n) if col[i] == 1]
            if (not R1 or a[R1[-1]] == 0) and (not R3 or b[R3[0]] == 1):
                tot += 1
        return tot
    bad = {"E": 0, "x=H(a,0)": 0, "x=H(1,b)": 0, "H(0,b)": 0, "H(a,1)": 0, "2^n": 0}
