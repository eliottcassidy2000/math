#!/usr/bin/env python3
"""Lane twoapex, deliverable (a), part 3: the minimal representation in suffix-evaluation coordinates.

Finds 17 suffix words s_1 = empty, s_2, ..., s_17 such that the functions w -> H(w s_j) are a Z-basis of the lattice
of ALL suffix functions w -> H(w s) (saturation checked by Smith normal form at every step).  In these coordinates
the state of a prefix w is the vector of path counts x(w) = (H(w s_1), ..., H(w s_17)), and

    H(w l s_j) = sum_k x_k(w) A_l[k][j]     (integer matrices A_l, l = 0..3),      H(w) = x_1(w).

Also: the common triangular structure (characteristic polynomials of the letters and of products), the lattice
generated by the prefix states, and a triangularising basis over Q found from common eigenvectors.
Writes minrep17.json.
"""
import itertools
import json
import random

import sympy as sp
from sympy.matrices.normalforms import smith_normal_form

from ta_core import H36, matvec, vecmat, words, dot
from ta_lattice import Lattice, det_int, inv_frac, matmul, nullspace_frac, rank_frac


def main():
    d = json.load(open("minrep17_raw.json"))
    A, y0, rho, r = d["A"], d["y0"], d["rho"], d["dimension"]

    def beta(word):
        b = rho
        for l in reversed(word):
            b = matvec(A[l], b)
        return b

    def saturated(vecs):
        M = sp.Matrix(vecs)
        S = smith_normal_form(M, domain=sp.ZZ)
        k = len(vecs)
        return all(abs(S[i, i]) == 1 for i in range(k))

    chosen = []
    vecs = []
    for n in range(0, 6):
        for w in words(n):
            if len(chosen) == r:
                break
            b = beta(w)
            if rank_frac(vecs + [b]) == len(vecs) + 1 and saturated(vecs + [b]):
                chosen.append(w)
                vecs.append(b)
        if len(chosen) == r:
            break
    print("suffix basis words s_1..s_17:", ["".join(map(str, w)) or "(empty)" for w in chosen])
    B = [[vecs[j][i] for j in range(r)] for i in range(r)]          # columns = beta(s_j)
    print("det of the basis change:", det_int(B))
    Binv = inv_frac(B)
    # x(w) = y(w) B; x(w l) = y(w) A_l B = x(w) B^-1 A_l B
    newA = []
    for l in range(4):
        N = matmul(matmul(Binv, A[l]), B)
        assert all(x.denominator == 1 for row in N for x in row)
        newA.append([[int(x) for x in row] for row in N])
    x0 = vecmat(y0, B)
    newrho = [int(x) for x in matvec(Binv, rho)]
    print("x(empty) = (H(s_j))_j =", x0)
    print("readout =", newrho)
    print("entries of the four matrices: min", min(min(min(row) for row in M) for M in newA), "max",
          max(max(max(row) for row in M) for M in newA))

    def state(word):
        x = x0
        for l in word:
            x = vecmat(x, newA[l])
        return x

    bad = 0
    cnt = 0
    for n in range(0, 7):
        for w in words(n):
            x = state(w)
            cnt += 1
            if any(x[j] != H36(tuple(w) + tuple(chosen[j])) for j in range(r)):
                bad += 1
    rng = random.Random(3)
    for _ in range(1500):
        w = tuple(rng.randrange(4) for _ in range(rng.randrange(7, 40)))
        x = state(w)
        cnt += 1
        if any(x[j] != H36(w + tuple(chosen[j])) for j in range(r)):
            bad += 1
    print(f"x_j(w) = H(w s_j) for all j: {cnt} words (all of length <= 6, 1500 random of length 7..39), "
          f"violations {bad}")

    # ---- spectrum: the four letters, their sum, random products
    x = sp.symbols("x")
    mats = [sp.Matrix(M) for M in newA]
    for l in range(4):
        print(f"char poly of A_{l}:", sp.factor(mats[l].charpoly(x).as_expr()))
    print("char poly of A_0 + A_1 + A_2 + A_3:", sp.factor(sum(mats, sp.zeros(r)).charpoly(x).as_expr()))
    okp = True
    for _ in range(40):
        w = [rng.randrange(4) for _ in range(rng.randrange(2, 7))]
        P = sp.eye(r)
        for l in w:
            P = P * mats[l]
        L = len(w)
        target = sp.expand(x ** 4 * (x - 3 ** L) * (x - 2 ** L) ** 4 * (x - 1) ** 8)
        if sp.expand(P.charpoly(x).as_expr() - target) != 0:
            okp = False
    print("char poly of A(w) is x^4 (x - 3^L)(x - 2^L)^4 (x - 1)^8 for 40 random words of length L = 2..6:", okp)

    # ---- a common triangularising flag over Q (column space: A_l v = d v mod the flag built so far)
    flag = []          # list of column vectors (Fractions)
    diag = []
    from fractions import Fraction
    cur = [[[Fraction(v) for v in row] for row in M] for M in newA]
    dim = r
    basis_cols = [[Fraction(int(i == j)) for i in range(r)] for j in range(r)]   # current quotient basis lifts
    # work in successive quotients: find v with (A_l - d) v in span(flag) for all l
    span = []
    while len(span) < r:
        found = False
        for dval in (3, 2, 1, 0):
            # unknowns: v in Q^r (mod span) ; conditions: (A_l - d) v in span  <=> P (A_l - d) v = 0, P = projector
            # build constraint matrix by appending span coefficients as extra unknowns
            k = len(span)
            rows = []
            for l in range(4):
                for i in range(r):
                    row = [Fraction(newA[l][i][j]) - (dval if i == j else 0) for j in range(r)]
                    ext = [Fraction(0)] * (4 * k)
                    for t in range(k):
                        ext[l * k + t] = -span[t][i]
                    rows.append(row + ext)
            ns = nullspace_frac(rows) if rows else []
            cand = [v[:r] for v in ns]
            cand = [v for v in cand if rank_frac(span + [v]) == len(span) + 1] if cand else []
            if cand:
                span.append(cand[0])
                diag.append(dval)
                found = True
                break
        if not found:
            print("no common eigenvector found at step", len(span))
            break
    print("common flag found: dimension", len(span), "; diagonal along the flag (column action):", diag)
    from collections import Counter
    print("multiset of the common diagonal:", sorted(Counter(diag).items()))

    out = {
        "dimension": r,
        "suffix_basis": ["".join(map(str, w)) for w in chosen],
        "A": newA, "x0": x0, "readout": newrho,
        "convention": "x(w) = (H(w s_j))_j ; x(w l) = x(w) A[l] (row vector times matrix); H(w) = x(w) . readout; "
                      "letter l = a + 2 b, a = [u -> s], b = [v -> s], u -> v",
        "common_diagonal_multiset": {"0": 4, "1": 8, "2": 4, "3": 1},
    }
    with open("minrep17.json", "w") as f:
        json.dump(out, f, indent=0)
    print("written minrep17.json")


if __name__ == "__main__":
    main()
