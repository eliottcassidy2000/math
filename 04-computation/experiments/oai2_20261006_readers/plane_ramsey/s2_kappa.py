# kappa(q) := chromatic number of Cay(F_{q^2}, mu_{q+1}), the "unit circle graph" of the
# anisotropic finite plane F_q^2 (norm form N: F_{q^2} -> F_q).  This is the target of the
# residue colouring at a c-stable prime inert in L/L^+ with residue field F_q over L^+.
import itertools, sys, time
from pysat.solvers import Cadical153, Glucose4
from pysat.card import CardEnc, EncType

def gf(p, n):
    """GF(p^n): elements 0..p^n-1 as base-p digit vectors; returns add, mul tables."""
    N = p**n
    def to_vec(a): return [(a//p**i) % p for i in range(n)]
    def to_int(v): return sum(c*p**i for i, c in enumerate(v))
    # find monic irreducible poly of degree n (brute force) -- coefficients c0..c_{n-1}
    def polymulmod(a, b, mod):
        res = [0]*(2*n-1)
        for i, x in enumerate(a):
            if x:
                for j, y in enumerate(b):
                    res[i+j] = (res[i+j] + x*y) % p
        for d in range(2*n-2, n-1, -1):
            c = res[d]
            if c:
                res[d] = 0
                for i in range(n):
                    res[d-n+i] = (res[d-n+i] - c*mod[i]) % p
        return res[:n]
    if n == 1:
        mod = [0]
        add = [[(a+b) % p for b in range(N)] for a in range(N)]
        mul = [[(a*b) % p for b in range(N)] for a in range(N)]
        return N, add, mul
    for coeffs in itertools.product(range(p), repeat=n):
        mod = list(coeffs)
        if mod[0] == 0: continue
        # check irreducible: x^(p^n) == x and no smaller field closure -> just check it has no roots
        # and the multiplicative group generated by x has order dividing p^n-1 with field property:
        # simple test: the ring has no zero divisors (brute force)
        mul = [[to_int(polymulmod(to_vec(a), to_vec(b), mod)) for b in range(N)] for a in range(N)]
        if all(mul[a][b] != 0 for a in range(1, N) for b in range(1, N)):
            add = [[to_int([(x+y) % p for x, y in zip(to_vec(a), to_vec(b))]) for b in range(N)] for a in range(N)]
            return N, add, mul
    raise ValueError

def kappa_graph(q):
    # q = p^f ; build F_{q^2} = GF(p^{2f})
    p = [r for r in range(2, q+1) if q % r == 0][0]
    f = 0; t = q
    while t > 1: t //= p; f += 1
    N, add, mul = gf(p, 2*f)
    def pw(a, e):
        r = 1
        for _ in range(e): r = mul[r][a]
        return r
    U = [a for a in range(1, N) if pw(a, q+1) == 1]
    assert len(U) == q+1
    neg = [next(b for b in range(N) if add[a][b] == 0) for a in range(N)]
    edges = set()
    for x in range(N):
        for uu in U:
            y = add[x][uu]
            edges.add((min(x, y), max(x, y)))
    return N, sorted(edges), U

def colorable(N, edges, k, clique=None, timeout=None):
    var = lambda v, c: v*k + c + 1
    s = Cadical153()
    for v in range(N):
        s.add_clause([var(v, c) for c in range(k)])
        for c1 in range(k):
            for c2 in range(c1+1, k):
                s.add_clause([-var(v, c1), -var(v, c2)])
    for a, b in edges:
        for c in range(k):
            s.add_clause([-var(a, c), -var(b, c)])
    if clique:
        for i, v in enumerate(clique[:k]):
            s.add_clause([var(v, i)])
    else:
        s.add_clause([var(0, 0)])
    r = s.solve()
    s.delete()
    return r

def max_clique(N, edges):
    import networkx as nx
    G = nx.Graph(); G.add_nodes_from(range(N)); G.add_edges_from(edges)
    c, _ = nx.max_weight_clique(G, weight=None)
    return c

if __name__ == "__main__":
    qs = [int(a) for a in sys.argv[1:]] or [2, 3, 4, 5, 7, 8, 9, 11, 13]
    for q in qs:
        t0 = time.time()
        N, edges, U = kappa_graph(q)
        cl = max_clique(N, edges)
        k = len(cl)
        while not colorable(N, edges, k, clique=cl):
            k += 1
        print(f"q={q:3d}  |V|=q^2={N:4d}  degree={q+1:3d}  clique={len(cl)}  kappa(q)=chi={k}   ({time.time()-t0:.1f}s)", flush=True)
