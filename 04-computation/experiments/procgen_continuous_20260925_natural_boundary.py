        for _ in range(6):
            r = random.uniform(0.3, 0.85)
            th = random.uniform(0, 2 * math.pi)
            z = r * cmath.exp(1j * th)
            h = lambda w: series_eval(coef, w)
            om = cmath.exp(2j * math.pi / 3)
            lhs = h(z**3) - h(z**6)
            rhs = (z / 3) * sum(om**(-j) * h(om**j * z * z) for j in range(3))
            ze = cmath.exp(2j * math.pi / 6)
            rhs_w = z * sum(ze**(-2 * j) * h(ze**j * z) for j in range(6)) / 6
            worst = max(worst, abs(lhs - rhs), abs(lhs - rhs_w))
        print(f"    basin of {m}: max |LHS-RHS| over 6 random |z|<=0.85 (BM-form and w-form, b=-1): {worst:.2e}")
        check(worst < 1e-9, "numeric functional equation on a 3n-1 basin")

