            rp = strip(r, q)
            for M in range(1, 1002, 2):
                c = classes(M, q, r)
                d = math.gcd(M, rp)
                pred = orbits(d, q) if d > 1 else 1
                check(c == pred, f"class count M={M} q={q} r={r}: {c} vs predicted {pred}")
                runs += 1
                single += (c == 1)
