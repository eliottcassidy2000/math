    print("  three disjoint cycles => basin(1) of 5n+1 is nonempty and proper, r' = 1, so its series")
    print("  (and every nonempty proper invariant set's series) has |z| = 1 as natural boundary;")
    print("  and every backward-orbit series of 5n+1 is irrational (no backward orbit is cofinite).")
