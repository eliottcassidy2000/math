    hdr("NB6  Non-periodicity sanity for the 3n-1 basins (no period p <= 3000 on [N-10^6, N])")
    lo = N - 10**6
    for i, m in enumerate(cmin_m):
        s = (lab_m == i + 1).astype(np.int8)
        best = (1.0, None)
        for p in range(1, 3001):
            a = s[lo:N + 1 - p]
            bb = s[lo + p:N + 1]
            frac = float(np.count_nonzero(a != bb)) / a.size
            if frac < best[0]:
                best = (frac, p)
        print(f"    basin of {m}: min over p<=3000 of the mismatch fraction #{{n: s(n) != s(n+p)}}/#n "
              f"on [N-10^6,N] = {best[0]:.4f} (at p = {best[1]})")
        check(best[0] > 0.05, "no small period")
    del lab_m

