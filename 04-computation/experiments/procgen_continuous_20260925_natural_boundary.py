    hdr("NB2  The general periodicity lemma: classes of x~2x, x~qx+r on Z/M, M odd")

    def classes(M, q, r):
        x = np.arange(M)
        rows = np.concatenate([x, x])
        cols = np.concatenate([(2 * x) % M, (q * x + r) % M])
        A = coo_matrix((np.ones(2 * M, dtype=np.int8), (rows, cols)), shape=(M, M))
        return connected_components(A, directed=True, connection='weak')[0]

    def strip(r, q):
        r = abs(r)
        g = math.gcd(r, q)
        while g > 1:
            r //= g
            g = math.gcd(r, q)
        return r

    def orbits(d, q):
        seen = [False] * d
        cnt = 0
        for x0 in range(d):
            if seen[x0]:
                continue
            cnt += 1
            stack = [x0]
            seen[x0] = True
            while stack:
                x = stack.pop()
                for y in ((2 * x) % d, (q * x) % d):
                    if not seen[y]:
                        seen[y] = True
                        stack.append(y)
        return cnt

