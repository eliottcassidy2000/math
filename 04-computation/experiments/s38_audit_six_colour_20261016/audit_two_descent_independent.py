def kum(pl, x):
    return tuple(pl.cls(x))


def local_image(pl, e, want, extra_pts=()):
    e1, e2, e3 = e
    pts = []                     # representative local points (x-coordinates, or ('T', i))
    cls = set()

    def add_class(c1, c2, rep):
        key = (c1, c2)
        if key not in cls:
            cls.add(key)
            pts.append((key, rep))

    zero = tuple([0] * pl.dim)
    add_class(zero, zero, 'O')
    add_class(kum(pl, (e1 - e2) * (e1 - e3)), kum(pl, e1 - e2), 'T1')
    add_class(kum(pl, e2 - e1), kum(pl, (e2 - e1) * (e2 - e3)), 'T2')
    add_class(kum(pl, e3 - e1), kum(pl, e3 - e2), 'T3')
    unif = {'2inert': E5(2), '3inert': E5(3), '7inert': E5(7), 'sqrt5': S5, 'pi11': PI, 'pi11c': PIc}.get(pl.name, E5(3))
    cands = []
    for k in range(-6, 7):
        for t in [E5(1), E5(-1), PHI, -PHI, E5(1) + PHI, E5(2) + PHI, E5(3), E5(5), E5(1) - PHI, E5(2) - PHI * 3,
                  E5(7) + PHI * 2, E5(-3) + PHI * 5]:
            for base in (E5(0), e1, e2, e3):
                cands.append(base + t * (unif ** k))
    for _ in range(6000):
        cands.append(E5(Fr(rng.randint(-400, 400), rng.choice([1, 2, 3, 4, 5, 7, 8, 9, 11, 16, 25, 49, 121])),
                        Fr(rng.randint(-400, 400), rng.choice([1, 2, 3, 4, 5, 7, 11]))))
    cands += list(extra_pts)

    def closure():
        changed = True
        while changed:
            changed = False
            cur = list(cls)
            for A in cur:
                for B in cur:
                    C = (tuple((s + t) % 2 for s, t in zip(A[0], B[0])), tuple((s + t) % 2 for s, t in zip(A[1], B[1])))
                    if C not in cls:
                        cls.add(C); changed = True

    for x in cands:
        if len(cls) >= want:
            break
        f1, f2, f3 = x - e1, x - e2, x - e3
        if f1.is_zero() or f2.is_zero() or f3.is_zero():
            continue
        c1, c2, c3 = kum(pl, f1), kum(pl, f2), kum(pl, f3)
        tot = tuple((a + b + c) % 2 for a, b, c in zip(c1, c2, c3))
        if any(tot):
            continue                                   # f(x) not a local square: no local point with this x
        add_class(c1, c2, x)
        if len(cls) > want // 2:
            closure()
    closure()
    return cls


