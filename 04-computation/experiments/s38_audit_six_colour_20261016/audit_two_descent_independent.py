class Real:
    def __init__(self, s):
        self.s = s; self.name = f'real{"+" if s > 0 else "-"}'; self.dim = 1

    def sign(self, x):
        # x = a + b phi, phi -> (1 + s sqrt5)/2 ; value = (2a + b + s b sqrt5)/2
        A, B = 2 * x.a + x.b, self.s * x.b
        # sign of A + B sqrt5
        if A >= 0 and B >= 0:
            return 1 if (A > 0 or B > 0) else 0
        if A <= 0 and B <= 0:
            return -1
        if A > 0:      # B < 0
            return 1 if A * A > 5 * B * B else -1
        return 1 if 5 * B * B > A * A else -1

    def cls(self, x):
        return (0,) if self.sign(x) > 0 else (1,)

    def hilbert(self, x, y):
        return -1 if (self.sign(x) < 0 and self.sign(y) < 0) else 1


class Inert:
    """p inert in K0 (p = 2, 3, 7): O_v = Z_p[phi], residue F_p[phi]/(phi^2 - phi - 1)."""
    def __init__(self, p):
        self.p = p; self.name = f'{p}inert'
        self.dim = 2 if p != 2 else 4
        if p == 2:
            self._setup2()

    def val_unit(self, x):
        v = min(t for t in (vq(x.a, self.p), vq(x.b, self.p)) if t is not None)
        sc = Fr(self.p) ** (-v)
        return v, E5(x.a * sc, x.b * sc)

    def _res_mul(self, u, w, m):
        # (u0 + u1 phi)(w0 + w1 phi) mod m
        return ((u[0] * w[0] + u[1] * w[1]) % m, (u[0] * w[1] + u[1] * w[0] + u[1] * w[1]) % m)

    def _setup2(self):
        m = 8
        units = [(c, d) for c in range(m) for d in range(m) if (c % 2, d % 2) != (0, 0)]
        sq = {self._res_mul(u, u, m) for u in units}
        # verify Hensel: u is a square mod 64 iff u mod 8 is a square mod 8 (for units)
        sq64 = {self._res_mul(u, u, 64) for u in [(c, d) for c in range(64) for d in range(64) if (c % 2, d % 2) != (0, 0)]}
        for c in range(64):
            for d in range(64):
                if (c % 2, d % 2) == (0, 0):
                    continue
                assert ((c, d) in sq64) == ((c % 8, d % 8) in sq), 'Hensel criterion mod 8 fails'
        # quotient U/U^2 (order 8): label classes by a basis found greedily
        classes = {}
        reps = []
        for u in units:
            found = None
            for i, r in enumerate(reps):
                # u ~ r iff u * r^{-1} in sq ; compute r^{-1}
                rinv = next(w for w in units if self._res_mul(r, w, m) == (1, 0))
                if self._res_mul(u, rinv, m) in sq:
                    found = i; break
            if found is None:
                reps.append(u); found = len(reps) - 1
            classes[u] = found
        assert len(reps) == 8
        # F2 coordinates: choose generators g1, g2, g3 and express each class
        def cls_of(u):
            return classes[(u[0] % m, u[1] % m)]
        gens, span = [], {cls_of((1, 0)): (0, 0, 0)}
        cand = [(7, 0), (0, 1), (5, 0), (1, 2), (3, 0), (1, 4), (3, 2), (5, 2), (1, 1)]
        elems = {(1, 0): (0, 0, 0)}
        for g in cand:
            if cls_of(g) in span:
                continue
            k = len(gens)
            gens.append(g)
            new = {}
            for e, bits in elems.items():
                prod = self._res_mul(e, g, m)
                b = list(bits); b[k] = 1
                new[prod] = tuple(b)
            elems.update(new)
            span = {cls_of(e): bits for e, bits in elems.items()}
            if len(gens) == 3:
                break
        assert len(span) == 8
        self.u2_bits = span
        self.cls_of2 = cls_of
        self.gens2 = gens

    def unit_bits(self, u):
        p = self.p
        if p == 2:
            r = (modp(u.a, 8), modp(u.b, 8))
            return self.u2_bits[self.cls_of2(r)]
        r0, r1 = modp(u.a, p), modp(u.b, p)
        # Euler criterion in F_{p^2}: u^((p^2-1)/2)
        e = (p * p - 1) // 2
        acc, base = (1, 0), (r0, r1)
        while e:
            if e & 1:
                acc = self._res_mul(acc, base, p)
            base = self._res_mul(base, base, p)
            e >>= 1
        assert acc in ((1, 0), (p - 1, 0))
        return (0,) if acc == (1, 0) else (1,)

    def cls(self, x):
        v, u = self.val_unit(x)
        return (v % 2,) + tuple(self.unit_bits(u))

    def is_square(self, x):
        return all(b == 0 for b in self.cls(x))


class Prime1:
    """Degree-one prime with uniformizer w in Z[phi]: sqrt5 (ramified, 5 = w^2) or the primes over 11
    (split, 11 = w * wbar).  Residue map phi -> r mod p.  Valuations and unit residues are computed EXACTLY:
    x = alpha / n with alpha in Z[phi], n in Z; alpha is divided by w in Z[phi] while its residue vanishes."""
    def __init__(self, name, p, w, r, ramified):
        self.name = name; self.p = p; self.w = w; self.r = r; self.dim = 2; self.ramified = ramified
        if ramified:
            assert w * w == E5(p)
            self.wbar = None
        else:
            self.wbar = E5(p) / w
            assert self.wbar.a.denominator == 1 and self.wbar.b.denominator == 1
            self.res_wbar = self.res_int(self.wbar)
            assert self.res_wbar != 0
        assert self.res_int(w) == 0

    def res_int(self, al):
        assert al.a.denominator == 1 and al.b.denominator == 1
        return (int(al.a) + int(al.b) * self.r) % self.p

    def val_res(self, x):
        n = math.lcm(x.a.denominator, x.b.denominator)
        al = x * E5(n)
        k = 0
        while self.res_int(al) == 0:
            al = al / self.w
            assert al.a.denominator == 1 and al.b.denominator == 1
            k += 1
        m, n2 = 0, n
        while n2 % self.p == 0:
            n2 //= self.p; m += 1
        res = self.res_int(al) * pow(n2 % self.p, -1, self.p) % self.p
        if self.ramified:
            v = k - 2 * m
        else:
            v = k - m
            res = res * pow(pow(self.res_wbar, m, self.p), -1, self.p) % self.p
        return v, res

    def cls(self, x):
        v, res = self.val_res(x)
        leg = pow(res, (self.p - 1) // 2, self.p)
        return (v % 2, 0 if leg == 1 else 1)


