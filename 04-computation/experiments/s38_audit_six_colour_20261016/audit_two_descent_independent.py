class E5:
    """a + b*phi, phi^2 = phi + 1."""
    __slots__ = ('a', 'b')

    def __init__(self, a, b=0):
        self.a = Fr(a); self.b = Fr(b)

    def __add__(self, o):
        o = o if isinstance(o, E5) else E5(o)
        return E5(self.a + o.a, self.b + o.b)

    __radd__ = __add__

    def __neg__(self):
        return E5(-self.a, -self.b)

    def __sub__(self, o):
        o = o if isinstance(o, E5) else E5(o)
        return E5(self.a - o.a, self.b - o.b)

    def __rsub__(self, o):
        return E5(o) - self

    def __mul__(self, o):
        o = o if isinstance(o, E5) else E5(o)
        return E5(self.a * o.a + self.b * o.b, self.a * o.b + self.b * o.a + self.b * o.b)

    __rmul__ = __mul__

    def conj(self):                     # phi -> 1 - phi
        return E5(self.a + self.b, -self.b)

    def norm(self):
        return self.a * self.a + self.a * self.b - self.b * self.b

    def inv(self):
        n = self.norm()
        c = self.conj()
        return E5(c.a / n, c.b / n)

    def __truediv__(self, o):
        o = o if isinstance(o, E5) else E5(o)
        return self * o.inv()

    def __pow__(self, k):
        r = E5(1)
        base = self if k >= 0 else self.inv()
        for _ in range(abs(k)):
            r = r * base
        return r

    def is_zero(self):
        return self.a == 0 and self.b == 0

    def __eq__(self, o):
        o = o if isinstance(o, E5) else E5(o)
        return self.a == o.a and self.b == o.b

    def __hash__(self):
        return hash((self.a, self.b))

    def __repr__(self):
        return f'({self.a}+{self.b}phi)'


PHI = E5(0, 1)
S5 = E5(-1, 2)                       # sqrt5 = 2 phi - 1
assert S5 * S5 == E5(5)
PI = E5(4) + S5                      # 4 + sqrt5 = 3 + 2 phi
PIc = E5(4) - S5                     # 4 - sqrt5 = 5 - 2 phi
assert PI * PIc == E5(11)
DELTA = E5(Fr(55, 2)) + E5(Fr(11, 2)) * S5
assert DELTA == E5(11) * S5 * PHI


def vq(q, p):
    q = Fr(q)
    if q == 0:
        return None
    n, d, v = q.numerator, q.denominator, 0
    while n % p == 0:
        n //= p; v += 1
    while d % p == 0:
        d //= p; v -= 1
    return v


def modp(q, m):
    q = Fr(q)
    return q.numerator * pow(q.denominator, -1, m) % m


