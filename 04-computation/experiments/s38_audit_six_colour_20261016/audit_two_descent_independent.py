    if wants_override:
        wants.update(wants_override)
    t0 = time.time()
    ker, images = selmer(e, pls, gens, wants)
    dim = len(ker)
    rec = dict(curve=label, places=[p.name for p in pls], selmer_dim=dim, selmer_size=2 ** dim,
               rank_bound=dim - 2, seconds=round(time.time() - t0, 1))
    log(json.dumps(rec))
    return rec, ker, pls, images


