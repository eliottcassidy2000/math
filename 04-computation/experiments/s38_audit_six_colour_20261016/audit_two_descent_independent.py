# ------------------------------------------------------------------------------------------------ Hilbert symbols
def hilbert(pl, x, y):
    """(x, y)_v.  Real: signs.  Odd residue characteristic: tame symbol ((-1)^(ab) u^b / w^a | F_q).
    Dyadic: norm-group criterion (x is a norm from K_v(sqrt y)), the norm subgroup being generated by sampled norms."""
    if isinstance(pl, Real):
        return pl.hilbert(x, y)
    if isinstance(pl, Prime1):
        p = pl.p
        a, ux = pl.val_res(x); b, uy = pl.val_res(y)
        t = ((-1) ** ((a * b) % 2)) * pow(ux, b % (p - 1), p) * pow(pow(uy, a % (p - 1), p), -1, p) % p
        return 1 if pow(t, (p - 1) // 2, p) == 1 else -1
    if pl.p != 2:
        a, ux = pl.val_unit(x); b, uy = pl.val_unit(y)
        t = E5((-1) ** ((a * b) % 2)) * (ux ** b) / (uy ** a)
        return 1 if pl.unit_bits(t)[0] == 0 else -1
    return dyadic_hilbert(pl, x, y)


_norm_groups = {}


def dyadic_hilbert(pl, x, y):
    cy = tuple(pl.cls(y))
    if not any(cy):
        return 1
    if cy not in _norm_groups:
        H = {tuple([0] * pl.dim)}
        tries = 0
        while len(H) < 8 and tries < 100000:
            tries += 1
            a = E5(Fr(rng.randint(-200, 200), rng.choice([1, 2, 4, 8])), Fr(rng.randint(-200, 200), rng.choice([1, 2, 4])))
            b = E5(Fr(rng.randint(-200, 200), rng.choice([1, 2, 4, 8])), Fr(rng.randint(-200, 200), rng.choice([1, 2, 4])))
            nrm = a * a - y * b * b
            if nrm.is_zero():
                continue
            c = tuple(pl.cls(nrm))
            if c not in H:
                H |= {tuple((s + t) % 2 for s, t in zip(c, h)) for h in H}
        assert len(H) == 8, ('norm group', len(H))
        _norm_groups[cy] = H
    return 1 if tuple(pl.cls(x)) in _norm_groups[cy] else -1


def tate_pairing(pl, A, B):
    """<(a1,a2),(b1,b2)> = (a1,b2)(a2,b1) -- the Weil-pairing cup product on H^1(K_v, E[2]) in Kummer coordinates."""
    return hilbert(pl, A[0], B[1]) * hilbert(pl, A[1], B[0])


