# ------------------------------------------------------------------------------------------------ F2 linear algebra
def rank_f2(rows):
    rows = [int(''.join(map(str, r)), 2) if not isinstance(r, int) else r for r in rows]
    basis = []
    for r in rows:
        for b in basis:
            r = min(r, r ^ b)
        if r:
            basis.append(r)
    return len(basis)


def nullspace_f2(M, ncols):
    """M: list of rows (lists of 0/1) of length ncols; returns a basis of {x : M x = 0}."""
    rows = [list(r) for r in M]
    piv_cols = []
    r = 0
    for c in range(ncols):
        pr = next((i for i in range(r, len(rows)) if rows[i][c]), None)
        if pr is None:
            continue
        rows[r], rows[pr] = rows[pr], rows[r]
        for i in range(len(rows)):
            if i != r and rows[i][c]:
                rows[i] = [(s + t) % 2 for s, t in zip(rows[i], rows[r])]
        piv_cols.append(c)
        r += 1
        if r == len(rows):
            break
    free = [c for c in range(ncols) if c not in piv_cols]
    basis = []
    for f in free:
        x = [0] * ncols
        x[f] = 1
        for i, c in enumerate(piv_cols):
            x[c] = rows[i][f] % 2
        basis.append(x)
    return basis


def selmer(e, places, gens, wants):
    """Two-Selmer group of y^2 = (x-e1)(x-e2)(x-e3) inside K0(S,2)^2 spanned by gens; returns basis (as bit lists)."""
    n = len(gens)
    images = {}
    for pl in places:
        img = local_image(pl, e, wants[pl.name])
        assert len(img) == wants[pl.name], (pl.name, len(img), wants[pl.name])
        images[pl.name] = img
    # localisation of generators
    loc = {pl.name: [kum(pl, g) for g in gens] for pl in places}
    # constraint: for each place, the pair (sum m1_i loc_i, sum m2_i loc_i) lies in the image subspace W_v.
    # W_v^perp (inside F2^(2 dim)) gives linear equations.
    rowsM = []
    for pl in places:
        dim = pl.dim
        Wv = [list(c1) + list(c2) for (c1, c2) in images[pl.name]]
        # annihilator of W_v w.r.t. the standard dot product
        ann = nullspace_f2(Wv, 2 * dim)
        for a in ann:
            row = []
            for i in range(n):          # m1 coefficients
                row.append(sum(a[j] * loc[pl.name][i][j] for j in range(dim)) % 2)
            for i in range(n):          # m2 coefficients
                row.append(sum(a[dim + j] * loc[pl.name][i][j] for j in range(dim)) % 2)
            rowsM.append(row)
    ker = nullspace_f2(rowsM, 2 * n) if rowsM else [[int(i == j) for j in range(2 * n)] for i in range(2 * n)]
    return ker, images


def elem(gens, bits):
    r = E5(1)
    for g, b in zip(gens, bits):
        if b:
            r = r * g
    return r


