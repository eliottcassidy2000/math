#!/usr/bin/env python3
"""Audit check (b) of THM-4710: the admissible spaces S_L, computed EXACTLY over Q (Fractions; no primes).

Coordinates.  A degree-N monomial of Li degree L is x_0^(N - l(mu)) x_mu with mu a partition of L into at most N
parts (parts >= 1).  These are faithful coordinates for every N (no stable-range assumption; for N >= L every
partition of L occurs).  Operators (derivations of C[x], x_j <-> L_(-j-2)):
    d x_j = (j+1) x_(j+1):        d(mu) = (N - l(mu)) (mu + {1}) + sum_i (mu_i + 1) (mu_i -> mu_i + 1)
    D_n x_j = (j+n+2) x_(j-n):    D_n(mu) = sum_(mu_i >= n) (mu_i + n + 2) (mu_i -> mu_i - n; zero parts dropped)
Recursion (THM-4710): M_0 = C x_0^N;  S_L = {g : D_1 g = 0, D_m g in M_(L-m) for 2 <= m <= L};
M_L = d M_(L-1) + S_L for L in the pattern {3,5,7,9}, else d M_(L-1).
Also computed: the variant with only the m = 2 condition (S'_L), which must agree with S_L because the positive
Witt algebra is generated by D_1, D_2 and M is D_1-, D_2-stable.
Cayley coordinates for N >= L: G = x_0^(N-L) sum_nu c_nu A_nu, A_j = sum_(i=0..j) C(j+3,i)(-1/4)^i x_0^(j-1-i) x_1^i x_(j-i),
normalized by c_(L) = 1.
Usage: python witt_closure_exact.py N1 N2 ...   (prints dims and Cayley coordinates; writes witt_closure_exact_<tag>.json)
"""
import sys, json, os
from fractions import Fraction
from math import comb

HERE = os.path.dirname(os.path.abspath(__file__))
PATTERN = (3, 5, 7, 9)


def partitions(n, maxpart=None, minpart=1):
    if maxpart is None:
        maxpart = n
    if n == 0:
        yield ()
        return
    for k in range(min(n, maxpart), minpart - 1, -1):
        for rest in partitions(n - k, k, minpart):
            yield (k,) + rest


def basis(L, N):
    return [m for m in partitions(L) if len(m) <= N] if L > 0 else [()]


def d_op(vec, N):
    out = {}
    for mu, c in vec.items():
        if N - len(mu):
            new = tuple(sorted(mu + (1,), reverse=True))
            out[new] = out.get(new, 0) + c * (N - len(mu))
        for i, j in enumerate(mu):
            new = tuple(sorted(mu[:i] + (j + 1,) + mu[i + 1:], reverse=True))
            out[new] = out.get(new, 0) + c * (j + 1)
    return {k: v for k, v in out.items() if v}


def D_op(vec, n):
    out = {}
    for mu, c in vec.items():
        for i, j in enumerate(mu):
            if j >= n:
                rest = mu[:i] + ((j - n,) if j - n > 0 else ()) + mu[i + 1:]
                new = tuple(sorted(rest, reverse=True))
                out[new] = out.get(new, 0) + c * (j + n + 2)
    return {k: v for k, v in out.items() if v}


# ------------------------------------------------------------- exact linear algebra over Q
def rref(rows, ncols):
    """Return (reduced rows, pivot columns) for a list of Fraction rows."""
    A = [list(r) for r in rows]
    piv = []
    rr = 0
    for col in range(ncols):
        p = next((i for i in range(rr, len(A)) if A[i][col] != 0), None)
        if p is None:
            continue
        A[rr], A[p] = A[p], A[rr]
        inv = 1 / Fraction(A[rr][col])
        A[rr] = [x * inv for x in A[rr]]
        for i in range(len(A)):
            if i != rr and A[i][col] != 0:
                f = A[i][col]
                A[i] = [x - f * y for x, y in zip(A[i], A[rr])]
        piv.append(col)
        rr += 1
        if rr == len(A):
            break
    return A[:rr], piv


def nullspace(rows, ncols):
    R, piv = rref(rows, ncols) if rows else ([], [])
    free = [j for j in range(ncols) if j not in piv]
    basisv = []
    for f in free:
        v = [Fraction(0)] * ncols
        v[f] = Fraction(1)
        for r, pc in zip(R, piv):
            v[pc] = -r[f]
        basisv.append(v)
    return basisv


def to_vec(d, idx):
    v = [Fraction(0)] * len(idx)
    for k, x in d.items():
        v[idx[k]] += x
    return v


def span_basis(dicts, cols):
    idx = {m: i for i, m in enumerate(cols)}
    rows = [to_vec(d, idx) for d in dicts]
    R, piv = rref(rows, len(cols)) if rows else ([], [])
    return [{cols[i]: x for i, x in enumerate(r) if x} for r in R]


def admissible(N, L, M, conds):
    """S_L for given M (dict L' -> list of basis dicts); conds = list of m (>= 2) for D_m g in M_(L-m)."""
    cols = basis(L, N)
    n = len(cols)
    idx = {m: i for i, m in enumerate(cols)}
    blocks = []  # (m, rows target basis, list of M vectors)
    nb = 0
    for m in conds:
        if L - m < 0:
            continue
        blocks.append((m, basis(L - m, N), M[L - m], nb))
        nb += len(M[L - m])
    nvar = n + nb
    eqs = []
    # D_1 g = 0
    t1 = basis(L - 1, N)
    t1i = {m: i for i, m in enumerate(t1)}
    img1 = [to_vec(D_op({mu: 1}, 1), t1i) for mu in cols]
    for r in range(len(t1)):
        eqs.append([img1[j][r] for j in range(n)] + [Fraction(0)] * nb)
    for (m, tb, Mv, off) in blocks:
        ti = {x: i for i, x in enumerate(tb)}
        img = [to_vec(D_op({mu: 1}, m), ti) for mu in cols]
        Mvec = [to_vec(v, ti) for v in Mv]
        for r in range(len(tb)):
            row = [img[j][r] for j in range(n)] + [Fraction(0)] * nb
            for k, mv in enumerate(Mvec):
                row[n + off + k] = -mv[r]
            eqs.append(row)
    ns = nullspace(eqs, nvar)
    proj = [v[:n] for v in ns]
    R, piv = rref(proj, n) if proj else ([], [])
    return [{cols[i]: x for i, x in enumerate(r) if x} for r in R]


def closure(N, Lmax=9, pattern=PATTERN, only_m2=False):
    M = {0: [{(): Fraction(1)}]}
    S = {0: [{(): Fraction(1)}]}
    for L in range(1, Lmax + 1):
        conds = [2] if only_m2 else list(range(2, L + 1))
        SL = admissible(N, L, M, conds)
        S[L] = SL
        dM = [d_op(v, N) for v in M[L - 1]]
        dM = [v for v in dM if v]
        M[L] = span_basis(dM + (SL if L in pattern else []), basis(L, N))
    return S, M


# ------------------------------------------------------------- Cayley coordinates
def cayley_A(j):
    f = {}
    for i in range(0, j + 1):
        coef = Fraction(comb(j + 3, i)) * Fraction(-1, 4) ** i
        parts = [1] * i + ([j - i] if j - i > 0 else [])
        m = tuple(sorted(parts, reverse=True))
        f[m] = f.get(m, 0) + coef
    return {k: v for k, v in f.items() if v}


def poly_mul(f, g):
    out = {}
    for a, ca in f.items():
        for b, cb in g.items():
            m = tuple(sorted(a + b, reverse=True))
            out[m] = out.get(m, 0) + ca * cb
    return {k: v for k, v in out.items() if v}


def cayley_basis(L):
    nus = list(partitions(L, minpart=2))
    polys = []
    for nu in nus:
        f = {(): Fraction(1)}
        for j in nu:
            f = poly_mul(f, cayley_A(j))
        polys.append(f)
    return nus, polys


def cayley_coords(G, L):
    """G in mu-coordinates (N >= L), returns {nu: c_nu} with c_(L) = 1; asserts G lies in the Cayley span."""
    nus, polys = cayley_basis(L)
    mus = list(partitions(L))
    midx = {m: i for i, m in enumerate(mus)}
    top = G.get((L,), 0)
    assert top != 0
    Gn = {k: v / top for k, v in G.items()}
    # unknowns c_nu; equations sum_nu c_nu A_nu[mu] = G[mu]
    rows = []
    for mu in mus:
        rows.append([poly.get(mu, Fraction(0)) for poly in polys] + [Gn.get(mu, Fraction(0))])
    R, piv = rref(rows, len(nus) + 1)
    assert len(nus) not in piv, 'not in Cayley span'
    sol = {}
    for r, pc in zip(R, piv):
        sol[nus[pc]] = r[-1]
    return {nu: sol.get(nu, Fraction(0)) for nu in nus}


def D1_kills_cayley(Lmax=12):
    for L in range(2, Lmax + 1):
        nus, polys = cayley_basis(L)
        for f in polys:
            assert D_op(f, 1) == {}, (L, f)   # x_0 -> 1 is harmless: D_1 x_0 = 0 and D_1 lowers Li degree
    # independence of the Cayley products and spanning of ker D_1 (dimension p(L) - p(L-1))
    out = {}
    for L in range(2, Lmax + 1):
        nus, polys = cayley_basis(L)
        mus = list(partitions(L))
        midx = {m: i for i, m in enumerate(mus)}
        rows = [to_vec(f, midx) for f in polys]
        R, piv = rref(rows, len(mus))
        tgt = list(partitions(L - 1))
        tidx = {m: i for i, m in enumerate(tgt)}
        imgs = [to_vec(D_op({mu: 1}, 1), tidx) for mu in mus]
        mat = [[imgs[j][r] for j in range(len(mus))] for r in range(len(tgt))]
        kerdim = len(nullspace(mat, len(mus)))
        out[L] = (len(nus), len(R), kerdim)
        assert len(R) == len(nus) == kerdim, (L, out[L])
    return out


if __name__ == '__main__':
    Ns = [int(a) for a in sys.argv[1:]] or [6, 10, 15, 20, 37, 70, 100]
    chk = D1_kills_cayley(12)
    print('Cayley A_nu: D_1-invariant (x_0 -> 1 coordinates, exact) and a basis of ker D_1 for L = 2..12:',
          {L: v[0] for L, v in chk.items()})
    res = {}
    for N in Ns:
        S, M = closure(N)
        S2, M2 = closure(N, only_m2=True)
        dims = {L: len(S[L]) for L in S}
        dims2 = {L: len(S2[L]) for L in S2}
        same = all(span_basis(S[L], basis(L, N)) == span_basis(S2[L], basis(L, N)) for L in S)
        entry = {'dims': dims, 'dims_m2_only': dims2, 'S_equal_m2_only': same,
                 'dimM': {L: len(M[L]) for L in M}}
        cay = {}
        for L in (3, 5, 7, 9):
            if dims.get(L) == 1 and N >= L:
                cay[L] = cayley_coords(S[L][0], L)
        entry['cayley'] = {L: {str(k): str(v) for k, v in c.items()} for L, c in cay.items()}
        res[N] = entry
        print(f'N={N}: dim S_L = {dims}; m=2-only variant equal: {same}; dim M_L = {entry["dimM"]}')
        for L, c in cay.items():
            print(f'    G_{L}: ' + ', '.join(f'A{list(k)}: {v}' for k, v in c.items()))
    tag = '_'.join(str(n) for n in Ns) if len(Ns) <= 8 else f'{Ns[0]}_{Ns[-1]}'
    json.dump(res, open(os.path.join(HERE, f'witt_closure_exact_{tag}.json'), 'w'), indent=1, default=str)
