from functools import lru_cache


def odd_step(n, q=3, sign=1):
    z = q*n+sign
    k = (z & -z).bit_length()-1
    return z >> k, k


def distinct_path(n, q=3, sign=1, cap=2000):
    seen, out = set(), []
    while n not in seen and len(out) < cap:
        seen.add(n)
        out.append(n)
        n, _ = odd_step(n, q, sign)
    return out, n, n in seen


def balanced_lift(r):
    # Integer-only floor(j log_2 3); exact final-odd cylinder.
    s = [(3**j).bit_length()-1 for j in range(r+1)]
    w = [s[j+1]-s[j] for j in range(r)]
    c = sum(3**(r-1-j)*2**s[j] for j in range(r))
    modulus = 2**(s[-1]+1)
    n = ((2**s[-1]-c)*pow(3**r, -1, modulus)) % modulus + modulus*(r+1)*4**r
    path, x = [n], n
    for k in w:
        y, actual = odd_step(x)
        assert k == actual
        path.append(y)
        x = y
    assert len(set(path)) == len(path)
    assert all(n <= x < 3*n for x in path)
    assert all(Fraction(n) <= Fraction(x*2**s[j], 3**j) <= n+Fraction(j,3)
               for j, x in enumerate(path) if j)
    return n, path


@lru_cache(None)
def factor(n):
    out, p = {}, 2
    while p*p <= n:
        while n % p == 0:
            out[p] = out.get(p, 0)+1
            n //= p
        p = 3 if p == 2 else p+2
    if n > 1:
        out[n] = out.get(n, 0)+1
    return out


def transition_rank(path):
    # Rank of the subgroup generated by (-3m_j,2^k_j*m_(j+1)).
    # Sign torsion is discarded, both prime-coordinate slots are retained.
    basis = {}
    for x, y in zip(path, path[1:]):
        z, k = odd_step(x)
        assert z == y
        row = {(0,p): Fraction(e) for p,e in factor(3*x).items()}
        row.update({(1,p): Fraction(e) for p,e in factor(y).items()})
        row[1,2] = Fraction(k)
        while row:
            pivot = min(row)
            if pivot not in basis:
                a = row[pivot]
                basis[pivot] = {p:v/a for p,v in row.items()}
                break
            a = row[pivot]
            for p,v in basis[pivot].items():
                row[p] = row.get(p, 0)-a*v
                if row[p] == 0:
                    del row[p]
    return len(basis)


def transition_rank_mod(path, q=3, sign=1, closing=None):
    prime = 1000000007
    basis = {}
    pairs = list(zip(path, path[1:]))
    if closing is not None:
        pairs.append((path[-1],closing))
    for x,y in pairs:
        z = q*x+sign
        k = (z & -z).bit_length()-1
        assert z >> k == y
        row = {(0,p):e for p,e in factor(q*x).items()}
        row.update({(1,p):e for p,e in factor(y).items()})
        row[1,2] = k
        while row:
            pivot = min(row)
            if pivot not in basis:
                a = pow(row[pivot],prime-2,prime)
                basis[pivot] = {p:v*a%prime for p,v in row.items()}
                break
            a = row[pivot]
            for p,v in basis[pivot].items():
                row[p] = (row.get(p,0)-a*v)%prime
                if row[p] == 0:
                    del row[p]
    return len(basis), len(pairs)


