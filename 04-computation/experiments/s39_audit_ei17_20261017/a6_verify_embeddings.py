# ----------------------------------------------------------------------------- pure-python F_p[t]/(t^2 - t - b)
class Fq2:
    def __init__(self, p, b):
        self.p, self.b = p, b

    def mul(self, x, y):
        p, b = self.p, self.b
        # (x0 + x1 t)(y0 + y1 t), t^2 = t + b
        return ((x[0] * y[0] + b * x[1] * y[1]) % p, (x[0] * y[1] + x[1] * y[0] + x[1] * y[1]) % p)

    def pow(self, x, e):
        r = (1, 0)
        while e:
            if e & 1:
                r = self.mul(r, x)
            x = self.mul(x, x); e >>= 1
        return r

    def sub(self, x, y):
        return ((x[0] - y[0]) % self.p, (x[1] - y[1]) % self.p)


def mu_set(F):
    p = F.p
    N = p * p - 1
    fac = list(factorint(N))
    for a0 in range(p):
        for a1 in range(1, p):
            g = (a0, a1)
            if all(F.pow(g, N // q) != (1, 0) for q in fac):
                h = F.pow(g, p - 1)
                S, x = set(), (1, 0)
                for _ in range(p + 1):
                    S.add(x); x = F.mul(x, h)
                assert len(S) == p + 1 and x == (1, 0)
                return S, g
    raise RuntimeError


def verify_twisted(p):
    b, sols = A2.solutions(1, p, ARR)
    F = Fq2(p, b)
    MU, g = mu_set(F)
    # transport to F_p(sqrt n): n the least non-residue (as in the S39 script), s^2 n = 1 + 4b
    n = next(x for x in range(2, p) if pow(x, (p - 1) // 2, p) == p - 1)
    s = next(x for x in range(p) if (x * x * n - (1 + 4 * b)) % p == 0)
    inv2 = pow(2, -1, p)
    ok = 0
    for sol in sols:
        P = {v: (int(sol[v - 1][0]), int(sol[v - 1][1])) for v in range(1, 18)}
        assert P[17] == (0, 0) and P[11] == (p - 1, 0)
        assert len(set(P.values())) == 17
        assert all(F.sub(P[i], P[j]) in MU for i, j in PE)
        assert all(F.pow(F.sub(P[i], P[j]), p + 1) == (1, 0) for i, j in PE)
        # a0 + a1 t -> a0 + a1 (1 + s sqrt n)/2 = (a0 + a1/2) + (a1 s/2) sqrt n
        Q = {v: ((P[v][0] + P[v][1] * inv2) % p, (P[v][1] * s * inv2) % p) for v in P}
        assert len(set(Q.values())) == 17
        assert all(((Q[i][0] - Q[j][0]) ** 2 - n * (Q[i][1] - Q[j][1]) ** 2) % p == 1 for i, j in PE)
        ok += 1
    # Klein four-group orbits
    key = lambda P: tuple(P[v] for v in range(1, 18))
    S = {key({v: (int(sol[v - 1][0]), int(sol[v - 1][1])) for v in range(1, 18)}) for sol in sols}
    conj = lambda z: ((z[0] + z[1]) % p, (-z[1]) % p)          # t -> 1 - t

    def inv(z):
        return F.pow(z, p * p - 2)

    def mirror(T):
        return tuple(conj(z) for z in T)

    def autom(T):
        P = {v: T[v - 1] for v in range(1, 18)}
        r = F.mul((p - 1, 0), inv(P[14]))
        return tuple(F.mul(r, P[AUT[v]]) for v in range(1, 18))
    return ok, len(sols), orbit_report(S, mirror, autom), g


def verify_split_sets(p, spl):
    b, sols = A2.solutions(0, p, ARR)
    mine = set()
    for sol in sols:
        P = {v: (int(sol[v - 1][0]), int(sol[v - 1][1])) for v in range(1, 18)}
        d = lambda i, j: (P[j][0] - P[i][0]) % p
        mine.add((d(1, 4), d(1, 7), d(14, 17), d(9, 11), d(2, 6), d(3, 5)))
    ef = np.zeros(1, dtype=np.int64)
    f, tot, deg, us = spl.count(p, spl.sqrt_table(p), spl.VM, spl.EDGES, ef)
    theirs = {tuple(int(x) for x in us[k]) for k in range(min(f, 64))}
    S = {tuple(tuple(int(c) for c in sol[v - 1]) for v in range(1, 18)) for sol in sols}
    inv = lambda x: pow(x, -1, p)

    def mirror(T):
        return tuple((w, z) for z, w in T)

    def autom(T):
        P = {v: T[v - 1] for v in range(1, 18)}
        r = ((-inv(P[14][0])) % p, (-inv(P[14][1])) % p)
        return tuple(((r[0] * P[AUT[v]][0]) % p, (r[1] * P[AUT[v]][1]) % p) for v in range(1, 18))
    return f, len(sols), mine == theirs, orbit_report(S, mirror, autom)


def orbit_report(S, mirror, autom):
    assert all(mirror(T) in S and autom(T) in S for T in S), 'group does not preserve the solution set'
    sizes, seen = [], set()
    for T in S:
        if T in seen:
            continue
        orb = {T, mirror(T), autom(T), mirror(autom(T))}
        seen |= orb
        sizes.append(len(orb))
    # block {4, 6, 13, 16} re-placement pairs
    blk = {4, 6, 13, 16}
    rest = lambda T: tuple(T[v - 1] for v in range(1, 18) if v not in blk)
    from collections import Counter
    c = Counter(rest(T) for T in S)
    return 'orbit sizes %s; solutions sharing the 13 vertices outside {4,6,13,16}: class sizes %s' % (
        sorted(sizes), sorted(c.values()))


