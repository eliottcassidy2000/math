AUT = {1: 2, 2: 1, 3: 7, 4: 6, 5: 9, 6: 4, 7: 3, 8: 10, 9: 5, 10: 8, 11: 14, 12: 15, 13: 16, 14: 11, 15: 12, 16: 13, 17: 17}
