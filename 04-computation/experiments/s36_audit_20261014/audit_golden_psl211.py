# ---------------- (2) return quotients R_n = Z[phi]/(phi^n - 1) and G_n = <x+1, phi x> on unordered pairs ----------------
def egcd(a, b):
    if b == 0:
        return (a, 1, 0) if a >= 0 else (-a, -1, 0)
    g, x, y = egcd(b, a % b)
    return g, y, x - (a // b) * y


def quotient(n):
    a, b = F[n - 1] - 1, F[n]          # phi^n - 1 = a + b phi
    N = abs(norm(a, b))
    g, s, t = egcd(a, b)                 # s a + t b = g
    w = s * b + t * (a + b)
    h = N // g
    # lattice rows (g, w), (0, h); canonical rep of (u, v)
    def red(u, v):
        k = u // g
        u -= k * g
        v -= k * w
        return (u, v % h)
    elems = [(x, y) for x in range(g) for y in range(h)]
    return N, g, h, red, elems


print('\n(2) return quotients and the pair action of G_n (paper Table 4: (|R_n|, |G_n|) = (4, 12), (5, 20), (11, 55) for n = 3, 4, 5)')
for n in range(3, 11):
    N, g, h, red, elems = quotient(n)
    index = {e: i for i, e in enumerate(elems)}
    plus1 = [index[red(x + 1, y)] for (x, y) in elems]
    mphi = [index[red(y, x + y)] for (x, y) in elems]
    # generate the permutation group
    ident = tuple(range(N))
    grp = {ident}
    frontier = [ident]
    gens = [tuple(plus1), tuple(mphi)]
    while frontier:
        nf = []
        for p in frontier:
            for q in gens:
                r = tuple(q[p[i]] for i in range(N))
                if r not in grp:
                    grp.add(r)
                    nf.append(r)
        frontier = nf
    # order of phi in R_n
    one = index[red(1, 0)]
    dn = 1
    cur = index[red(0, 1)]
    phi_idx = cur
    while cur != one:
        x, y = elems[cur]
        cur = index[red(y, x + y)]
        dn += 1
    pairs = [(i, j) for i in range(N) for j in range(i + 1, N)]
    pid = {pr: k for k, pr in enumerate(pairs)}
    seen = [False] * len(pairs)
    norb = 0
    for k, (i, j) in enumerate(pairs):
        if not seen[k]:
            norb += 1
            for p in grp:
                a2, b2 = p[i], p[j]
                seen[pid[(min(a2, b2), max(a2, b2))]] = True
    print(f'    n = {n}: L_n = {L[n]}, |R_n| = {N} (additive type Z/{g} x Z/{h}), ord(phi) = {dn}, |G_n| = {len(grp)} (n|R_n| = {n * N}, n L_n = {n * L[n]}), '
          f'unordered pairs = {len(pairs)}, pair orbits = {norb}, regular = {norb == 1 and len(grp) == len(pairs)}')

# ---------------- (3) PSL(2, 11) on P^1(F_11) ----------------
p = 11
INF = 11
QR = sorted({x * x % p for x in range(1, p)})
NQR = sorted(set(range(1, p)) - set(QR))


def mob(a, b, c, d):
    out = []
    for x in range(p + 1):
        if x == INF:
            out.append(INF if c % p == 0 else a * pow(c, -1, p) % p)
        else:
            den = (c * x + d) % p
            out.append(INF if den == 0 else (a * x + b) * pow(den, -1, p) % p)
    return tuple(out)


def comp(g, h):  # g o h
    return tuple(g[h[x]] for x in range(p + 1))


def closure(gens):
    e = tuple(range(p + 1))
    S = {e}
    fr = [e]
    while fr:
        nf = []
        for x in fr:
            for g in gens:
                y = comp(g, x)
                if y not in S:
                    S.add(y)
                    nf.append(y)
        fr = nf
    return S


T1 = mob(1, 1, 0, 1)
Sinv = mob(0, p - 1, 1, 0)
G = closure([T1, Sinv])
print('\n(3) |PSL(2,11)| =', len(G))
D = mob(2, 0, 0, 6)  # x -> 4x
assert D == tuple((4 * x) % p if x < p else INF for x in range(p + 1))
B = {g for g in G if g[INF] == INF}
Baff = {tuple((s * x + t) % p if x < p else INF for x in range(p + 1)) for s in QR for t in range(p)}
print('    Borel = Stab(inf): order', len(B), '; equals {x -> s x + t : s in QR}:', B == Baff)
arcs = {(i, j) for i in range(p) for j in range(p) if i != j and (j - i) % p in QR}
orb = {(g[0], g[1]) for g in B}
print('    P_11: #arcs =', len(arcs), '; Borel orbit of arc (0,1) =', len(orb), '; orbit == all arcs:', orb == arcs,
      '; arc stabiliser trivial:', sum(1 for g in B if g[0] == 0 and g[1] == 1) == 1)
A5s = []
for g in G:
    H = closure([D, g])
    if len(H) == 60 and H not in A5s:
        A5s.append(H)
print('    subgroups of order 60 containing x -> 4x:', len(A5s))


def order(g):
    e = tuple(range(p + 1))
    k, y = 1, g
    while y != e:
        y = comp(g, y)
        k += 1
    return k


ico = nx.icosahedral_graph()
for idx, A in enumerate(A5s):
    orders = {}
    for g in A:
        o = order(g)
        orders[o] = orders.get(o, 0) + 1
    trans = len({g[INF] for g in A}) == 12
    stab = [g for g in A if g[INF] == INF]
    AB = {comp(a, b) for a in A for b in B}
    pairs = [(x, y) for x in range(p + 1) for y in range(p + 1) if x != y]
    seen = set()
    orbitals = []
    for pr in pairs:
        if pr in seen:
            continue
        o = {(g[pr[0]], g[pr[1]]) for g in A}
        seen |= o
        orbitals.append(o)
    print(f'    A5 #{idx}: element orders {dict(sorted(orders.items()))}; transitive on 12 points: {trans}; |Stab(inf)| = {len(stab)}, '
          f'Stab(inf) = <x->4x>: {set(stab) == closure([D])}; |A cap B| = {len(A & B)}; |AB| = {len(AB)} (= G: {AB == G})')
    print(f'      off-diagonal orbital sizes: {sorted(len(o) for o in orbitals)}')
    for o in orbitals:
        if len(o) == 60:
            Gr = nx.Graph()
            Gr.add_edges_from((x, y) for (x, y) in o)
            sym = all((y, x) in o for (x, y) in o)
            dist = nx.single_source_shortest_path_length(Gr, INF)
            antip = [v for v, dd in dist.items() if dd == 3]
            print(f'      valency-5 orbital: symmetric {sym}, icosahedron {nx.is_isomorphic(Gr, ico)}, antipode of inf {antip}, '
                  f'N(inf) = {sorted(Gr[INF])}, N(0) = {sorted(Gr[0])}, N(inf) is QR: {sorted(Gr[INF]) == QR}, NQR: {sorted(Gr[INF]) == NQR}')
# conjugacy of the two A5's
if len(A5s) == 2:
    conj = any({comp(comp(x, a), tuple(x.index(i) for i in range(p + 1))) for a in A5s[0]} == A5s[1] for x in G)
    print('    the two A5 subgroups are conjugate in PSL(2,11):', conj)
