#!/usr/bin/env python3
"""spine_grammar_ranks_20261104.py -- opus-2026-11-04-S79

Exact linear invariants of the Hamiltonian-path series on a graded spine grammar G(k, w), from the automaton dumped by
`spine_grammar_census_20261104.cpp` (run with maxm = -1):

  * the Hankel rank of the series H on G(k, w): the dimension of the smallest linear representation, computed as the
    rank of the pairing between the reachable space (row vectors e_0 M_u over all chain words u) and the observable
    space (column vectors M_r f over all suffixes r, with f = apex placement followed by the complete-cut indicator);
  * the seam rank at a cut with c pending chain slots: the same pairing restricted to prefixes whose cut has exactly c
    pending slots and suffixes continuing from such a cut.  c = 1 is the one-arc seam (Lorentzian law, rank 3 expected).

Arithmetic is exact (Python integers / Fractions); the spans are generated by breadth-first closure under the letter
matrices with exact Gaussian elimination.
Usage: python3 spine_grammar_ranks_20261104.py dump.txt
"""
import sys
from fractions import Fraction
from collections import defaultdict

def parse(path):
    states = {}; trans = defaultdict(list); apex = defaultdict(list); letters = {}
    with open(path) as f:
        for line in f:
            parts = line.split()
            if not parts: continue
            if parts[0] == 'STATES': nstates = int(parts[1])
            elif parts[0] == 'S':
                sid = int(parts[1]); c = int(parts[2][2:]); comp = int(parts[3].split('=')[1]); states[sid] = (c, comp)
            elif parts[0] == 'T':
                sid = int(parts[1]); li = int(parts[2]); T, b, A = int(parts[3]), int(parts[4]), int(parts[5])
                lst = [(int(x.split('*')[0]), int(x.split('*')[1])) for x in parts[7:]]
                trans[(sid, li)] = lst; letters[(states[sid][0], li)] = (T, b, A)
            elif parts[0] == 'A':
                sid = int(parts[1]); a = int(parts[2]); lst = [(int(x.split('*')[0]), int(x.split('*')[1])) for x in parts[4:]]
                apex[(sid, a)] = lst
    return nstates, states, trans, apex, letters

def reduce_into(basis, vec):
    """basis: list of (pivot index, row dict) in echelon form over Fractions; returns True if vec was independent (and adds it)."""
    v = dict(vec)
    for piv, row in basis:
        if piv in v and v[piv] != 0:
            f = v[piv] / row[piv]
            for k2, val in row.items():
                nv = v.get(k2, Fraction(0)) - f * val
                if nv == 0: v.pop(k2, None)
                else: v[k2] = nv
    v = {k2: val for k2, val in v.items() if val != 0}
    if not v: return False
    piv = min(v); basis.append((piv, v)); return True

def main():
    path = sys.argv[1]
    nstates, states, trans, apex, letters = parse(path)
    K = 1 + max([a for (_, a) in apex] + [-1]); n = max(states) + 1
    letters_by_c = defaultdict(list)
    for (c, li), (T, b, A) in letters.items(): letters_by_c[c].append(li)
    # reachable space: row vectors from e_0 (state 0 = empty cut) closed under letters
    def apply_row(vec, li):
        out = defaultdict(int)
        for s, val in vec.items():
            for (t, m) in trans.get((s, li), []): out[t] += val * m
        return {k2: v for k2, v in out.items() if v}
    def apply_apex_row(vec, a):
        out = defaultdict(int)
        for s, val in vec.items():
            for (t, m) in apex.get((s, a), []): out[t] += val * m
        return {k2: v for k2, v in out.items() if v}
    reach_basis = []; frontier = [{0: 1}]; reduce_into(reach_basis, {0: Fraction(1)}); reach_vecs_by_c = defaultdict(list)
    reach_vecs_by_c[0].append({0: 1})
    seen_count = 0
    while frontier:
        nxt = []
        for vec in frontier:
            c = states[next(iter(vec))][0]
            for li in letters_by_c[c]:
                w = apply_row(vec, li)
                if not w: continue
                if reduce_into(reach_basis, {k2: Fraction(v) for k2, v in w.items()}):
                    nxt.append(w); reach_vecs_by_c[states[next(iter(w))][0]].append(w)
        frontier = nxt
    # observable space: column functionals; f = apex placement then complete indicator (as a functional on cut vectors)
    comp = {s: 1 for s, (c, cp) in states.items() if cp}
    def apply_col(func, li):   # (M_li f)(s) = sum_t M_li[s,t] f(t)
        out = {}
        for s in states:
            tot = 0
            for (t, m) in trans.get((s, li), []): tot += m * func.get(t, 0)
            if tot: out[s] = tot
        return out
    def apply_apex_col(func, a):
        out = {}
        for s in states:
            tot = 0
            for (t, m) in apex.get((s, a), []): tot += m * func.get(t, 0)
            if tot: out[s] = tot
        return out
    f = comp
    for a in reversed(range(K)): f = apply_apex_col(f, a)
    obs_basis = []; frontier = [f]; reduce_into(obs_basis, {k2: Fraction(v) for k2, v in f.items()}); obs_funcs = [f]
    while frontier:
        nxt = []
        for func in frontier:
            for (c, li) in letters:
                g = apply_col(func, li)
                if not g: continue
                if reduce_into(obs_basis, {k2: Fraction(v) for k2, v in g.items()}):
                    nxt.append(g); obs_funcs.append(g)
        frontier = nxt
    # pairing rank between the reachable row space and observable column space
    R = [dict(row) for _, row in reach_basis]; O = [dict(col) for _, col in obs_basis]
    def pairing_rank(rows, cols):
        basis = []
        for row in rows:
            vec = {}
            for j, col in enumerate(cols):
                v = sum(row.get(s, 0) * col.get(s, 0) for s in set(row) | set(col))
                if v: vec[j] = Fraction(v)
            reduce_into(basis, vec)
        return len(basis)
    hankel = pairing_rank(R, O)
    print(f"states {nstates}, K = {K}; reachable dim {len(R)}, observable dim {len(O)}, Hankel rank of H on this grammar = {hankel}")
    # seam ranks: restrict to cut vectors with exactly c pending slots
    cs = sorted(set(c for (c, cp) in states.values()))
    for c in cs:
        rows = []
        basis_c = []
        for vec in reach_vecs_by_c[c]:
            if reduce_into(basis_c, {k2: Fraction(v) for k2, v in vec.items()}): rows.append(vec)
        # also take the reach basis vectors supported on c-states
        states_c = {s for s, (cc, cp) in states.items() if cc == c}
        cols = [{s: v for s, v in col.items() if s in states_c} for col in O]
        cols = [col for col in cols if col]
        r = pairing_rank(rows, cols)
        print(f"  seam with c = {c} pending slots: {len(states_c)} cut states, reachable dim {len(rows)}, seam rank = {r}")

main()
