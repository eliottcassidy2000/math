#!/usr/bin/env python3
"""New lines on the tiling grid: the staircase delta_{n-2} = {(r,c): r,c >= 1, r+c <= n-1} has an S_3 symmetry group
generated by the path-reversal mirror m1: (r,c) -> (r, n-r-c) (a vertex relabelling) and the transpose m2: (r,c) -> (c,r)
(tile (a,b) -> (a, a-b-1), NOT a relabelling). Question: does m2 (or the rotation rho = m1 m2) preserve the isomorphism
class, the converse class, H(T), the score multiset, the number of 3-cycles? Checked on all tilings for n = 4..7."""
import subprocess
from collections import Counter
def tiles_of(n): return [(a, b) for b in range(1, n - 1) for a in range(b + 2, n + 1)]
def to_d6(n, arcs):
    A = [[0] * n for _ in range(n)]
    for u, v in arcs: A[u][v] = 1
    bits = [A[i][j] for i in range(n) for j in range(n)]
    while len(bits) % 6: bits.append(0)
    s = '&' + chr(63 + n)
    for k in range(0, len(bits), 6): s += chr(63 + int(''.join(map(str, bits[k:k + 6])), 2))
    return s
def labelg(lines):
    r = subprocess.run(['labelg', '-q'], input='\n'.join(lines) + '\n', capture_output=True, text=True).stdout.split()
    assert len(r) == len(lines); return r
def ham(n, adj):
    full = (1 << n) - 1; dp = [[0] * n for _ in range(1 << n)]
    for v in range(n): dp[1 << v][v] = 1
    for mask in range(1 << n):
        for v in range(n):
            c = dp[mask][v]
            if not c: continue
            for w in range(n):
                if not (mask >> w) & 1 and adj[v][w]: dp[mask | 1 << w][w] += c
    return sum(dp[full])
for n in range(4, 8):
    tiles = tiles_of(n); m = len(tiles); idx = {t: i for i, t in enumerate(tiles)}
    def rc(t): a, b = t; return (a - b - 1, b)
    def tile(r, c): return (r + c + 1, c)
    m1 = [idx[tile(r, n - r - c)] for (r, c) in map(rc, tiles)]
    m2 = [idx[tile(c, r)] for (r, c) in map(rc, tiles)]
    def apply(perm, mask):
        out = 0
        for i, j in enumerate(perm):
            if (mask >> i) & 1: out |= 1 << j
        return out
    def arcs_of(mask):
        arcs = [(i, i - 1) for i in range(1, n)]
        for k, (a, b) in enumerate(tiles): arcs.append((b - 1, a - 1) if (mask >> k) & 1 else (a - 1, b - 1))
        return arcs
    N = 1 << m
    can = labelg([to_d6(n, arcs_of(mk)) for mk in range(N)])
    conv = labelg([to_d6(n, [(v, u) for u, v in arcs_of(mk)]) for mk in range(N)])
    def stats(mask):
        arcs = arcs_of(mask); adj = [[0] * n for _ in range(n)]
        for u, v in arcs: adj[u][v] = 1
        sc = tuple(sorted(sum(r) for r in adj)); H = ham(n, adj)
        c3 = sum(1 for i in range(n) for j in range(n) for k in range(n) if adj[i][j] and adj[j][k] and adj[k][i]) // 3
        return sc, H, c3
    st = [stats(mk) for mk in range(N)]
    res = Counter()
    for mk in range(N):
        t2 = apply(m2, mk); rho = apply(m1, apply(m2, mk))
        res['m2 preserves class'] += can[t2] == can[mk]
        res['m2 maps to converse class'] += can[t2] == conv[mk]
        res['m2 preserves H'] += st[t2][1] == st[mk][1]
        res['m2 preserves scores'] += st[t2][0] == st[mk][0]
        res['m2 preserves #3-cycles'] += st[t2][2] == st[mk][2]
        res['rho preserves H'] += st[rho][1] == st[mk][1]
        res['m1 preserves class (control)'] += can[apply(m1, mk)] == conv[mk]
    print(f"n = {n} ({N} tilings):", dict(res))
