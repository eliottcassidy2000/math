#!/usr/bin/env python3
"""algebra.py -- structure of the 14-dimensional integer representation of span 2:
(1) a semantic Q-basis by short suffixes (length <= 3); (2) the dimension of the matrix algebra
generated by the letters on the space spanned by the states of nonempty words (irreducibility test);
(3) the same for the strong sub-alphabet {1},{2},{1,2}; (4) invariant subspaces of single letters."""
import itertools, sympy as sp
from intrep import build, vecmat, in_module_coeffs
from ribbon import letters
w = 2
basis, A, y0, hcoef, order, states, mats, final = build(w, verbose=False)
r = len(basis); d = len(order); L = letters(w)
names = {frozenset(): '-', frozenset([1]): '1', frozenset([2]): '2', frozenset([1, 2]): '12'}
Am = {a: sp.Matrix(A[a]) for a in L}
phi = [0] * d
for j in final: phi[j] = 1
# (1) semantic basis
funcs = []
for n in range(0, 4):
    for v in itertools.product(L, repeat=n):
        f = phi
        for a in reversed(v): f = vecmat(f, mats[a], d)
        funcs.append((v, in_module_coeffs(basis, f)))
chosen = []; mat = sp.zeros(0, r)
for v, c in funcs:
    cand = mat.col_join(sp.Matrix([c]))
    if cand.rank() > mat.rank():
        mat = cand; chosen.append(v)
print("(1) semantic Q-basis of the observables: u -> H(u v) for v in", ['.'.join(names[a] for a in v) or 'eps' for v in chosen])
# (2) space of states of nonempty words
y = sp.Matrix(y0)
vecs = []
frontier = [y]
S = sp.zeros(r, 0)
for n in range(1, 6):
    nf = []
    for v in frontier:
        for a in L:
            nv = Am[a] * v
            nf.append(nv)
            cand = S.row_join(nv)
            if cand.rank() > S.rank():
                S = cand
    frontier = nf
print("(2) dimension of the span of nonempty-word states:", S.rank(), "(all words incl. empty: 14)")
# restrict letters to this subspace: columns of S form a basis; A_a S = S B_a
pivots = S.T.rref()[1]
Ssq = S.extract(list(pivots), list(range(S.cols)))
def restrict(M):
    MS = M * S
    B = Ssq.inv() * MS.extract(list(pivots), list(range(S.cols)))
    assert MS == S * B
    return B
B = {a: restrict(Am[a]) for a in L}
k = S.cols
def algebra_dim(gens):
    alg = [sp.eye(k)]
    mat = sp.Matrix.hstack(*[m.reshape(k * k, 1) for m in alg])
    frontier = list(alg)
    while frontier:
        nf = []
        for X in frontier:
            for G in gens:
                Y = G * X
                cand = mat.row_join(Y.reshape(k * k, 1))
                if cand.rank() > mat.rank():
                    mat = cand; nf.append(Y)
        frontier = nf
    return mat.rank()
print(f"(2) algebra generated by all four letters on the {k}-dim space: dimension {algebra_dim([B[a] for a in L])} (full matrix algebra = {k*k})")
strong = [frozenset([1]), frozenset([2]), frozenset([1, 2])]
print(f"(3) algebra generated by the three nonempty letters: dimension {algebra_dim([B[a] for a in strong])}")
for a in L:
    cp = sp.factor(B[a].charpoly().as_expr())
    print(f"(4) charpoly of letter {names[a]} on the {k}-dim space: {cp}")
