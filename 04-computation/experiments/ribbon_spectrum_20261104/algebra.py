#!/usr/bin/env python3
"""algebra.py -- structure of the 14-dimensional integer representation of span 2 (numpy ranks on
small-integer matrices): (1) a semantic Q-basis by short suffixes (length <= 3); (2) dimension of the
matrix algebra generated by the letters on the span of the states of nonempty words (irreducibility
test); (3) the same for the strong sub-alphabet; (4) characteristic polynomials of single letters."""
import itertools, numpy as np, sympy as sp
from intrep import build, vecmat, in_module_coeffs
from ribbon import letters
w = 2
basis, A, y0, hcoef, order, states, mats, final = build(w, verbose=False)
r = len(basis); d = len(order); L = letters(w)
names = {frozenset(): '-', frozenset([1]): '1', frozenset([2]): '2', frozenset([1, 2]): '12'}
Am = {a: np.array(A[a], dtype=np.int64) for a in L}
phi = [0] * d
for j in final: phi[j] = 1
def rank(M): return np.linalg.matrix_rank(np.array(M, dtype=np.float64))
# (1)
funcs = []
for n in range(0, 4):
    for v in itertools.product(L, repeat=n):
        f = phi
        for a in reversed(v): f = vecmat(f, mats[a], d)
        funcs.append((v, in_module_coeffs(basis, f)))
chosen = []; mat = []
for v, c in funcs:
    if rank(mat + [c]) > len(mat):
        mat.append(c); chosen.append(v)
print("(1) semantic Q-basis of the observables, u -> H(u v) for v in:", ['.'.join(names[a] for a in v) or 'eps' for v in chosen])
# (2) span of states of nonempty words
y = np.array(y0, dtype=np.int64)
S = []
frontier = [y]
for n in range(1, 6):
    nf = []
    for v in frontier:
        for a in L:
            nv = Am[a] @ v
            nf.append(nv)
            if rank(S + [nv]) > len(S): S.append(nv)
    frontier = nf
S = np.array(S, dtype=np.float64).T   # r x k
k = S.shape[1]
print("(2) dimension of the span of nonempty-word states:", k, "(with the empty word: 14)")
# restrict: A_a S = S B_a  ->  B_a = pinv(S) A_a S
Sp = np.linalg.pinv(S)
B = {a: Sp @ (Am[a] @ S) for a in L}
for a in L:
    assert np.allclose(Am[a] @ S, S @ B[a], atol=1e-6)
def algebra_dim(gens):
    vecs = [np.eye(k).reshape(-1)]
    frontier = [np.eye(k)]
    while frontier:
        nf = []
        for X in frontier:
            for G in gens:
                Y = G @ X
                if rank(vecs + [Y.reshape(-1)]) > len(vecs):
                    vecs.append(Y.reshape(-1)); nf.append(Y)
        frontier = nf
    return len(vecs)
print(f"(2) algebra generated by all four letters on the {k}-dim space: dimension {algebra_dim([B[a] for a in L])} (full matrix algebra = {k*k})")
strong = [frozenset([1]), frozenset([2]), frozenset([1, 2])]
print(f"(3) algebra generated by the three nonempty letters: dimension {algebra_dim([B[a] for a in strong])}")
for a in L:
    Bi = sp.Matrix(np.rint(B[a]).astype(int)) if np.allclose(B[a], np.rint(B[a])) else sp.Matrix(B[a])
    print(f"(4) charpoly of letter {names[a]} on the {k}-dim space: {sp.factor(sp.Matrix(np.rint(B[a]).astype(int)).charpoly().as_expr()) if np.allclose(B[a], np.rint(B[a]), atol=1e-6) else 'non-integer restriction'}")
