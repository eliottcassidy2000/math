def integer(x, minimum=0):
    if type(x) is not int or x < minimum:
        raise ValueError('exact integer outside domain')
    return x


def word(w):
    if type(w) is not tuple:
        raise ValueError('exact word tuple required')
    for a in w:
        integer(a, 1)
    return w


def v2(n):
    integer(n, 1)
    return (n & -n).bit_length()-1


def carrier(w):
    word(w)
    p,q,b = 1,1,0
    for a in w:
        p,q,b = 3*p,q*2**a,3*b+q
    return p,q,b


def native_cell(w):
    p,q,b = carrier(w)
    return ((q-b)*pow(p,-1,2*q)) % (2*q), 2*q


def decode(length, cost, carry):
    """Unique positive valuation word with this length, cost and carry."""
    integer(length, 1)
    integer(cost, 1)
    integer(carry, 1)
    if cost < length:
        return None
    original = length,cost,carry
    prefix = []
    while length > 1:
        delta = carry-3**(length-1)
        if delta <= 0:
            return None
        a = v2(delta)
        if a < 1 or cost-a < length-1:
            return None
        prefix.append(a)
        carry = delta >> a
        cost -= a
        length -= 1
    if carry != 1 or cost < 1:
        return None
    answer = tuple(prefix)+(cost,)
    p,q,b = carrier(answer)
    return answer if (len(answer),q.bit_length()-1,b) == original else None


def log3_binary(target, bits):
    integer(target)
    integer(bits, 3)
    target %= 2**bits
    if target % 8 not in (1,3):
        raise ValueError('target is outside the subgroup generated by three')
    exponent = 0 if target%8 == 1 else 1
    period = 2
    for b in range(4,bits+1):
        choices = [exponent+d*period for d in (0,1)
                   if pow(3,exponent+d*period,2**b) == target % 2**b]
        if len(choices) != 1:
            raise RuntimeError('binary exponent lift failed')
        exponent = choices[0]
        period *= 2
    return exponent,period


@dataclass(frozen=True)
class Rule:
    head: tuple
    partner: tuple
    phase: int
    period: int
    minimum: int


def compile_rule(head):
    word(head)
    if len(head) not in (1,2) or head[0] < 3:
        raise ValueError('short nonpadding head required')
    p,q,b = carrier(head)
    if q < 16 or (p+b)%4:
        return None
    cost = sum(head)-4
    if cost < len(head)+1:
        return None
    partner = decode(len(head)+1,cost,(p+b)//4+q//16)
    if partner is None:
        return None
    pv,qv,bv = carrier(partner)
    if (pv,qv,bv) != (3*p,q//16,(p+b)//4+q//16):
        raise RuntimeError('wrong anchored carrier')
    residue,modulus = native_cell(head)
    phase,period = log3_binary(2*residue+1,sum(head)+2)
    cutoff = 2*sum(head)+3
    minimum = phase + period*max(0,(cutoff-phase+period-1)//period)
    if phase%4 != 3:
        raise RuntimeError('head does not follow one maximal two')
    return Rule(head,partner,phase,period,minimum)


def audit_rule(rule):
    if type(rule) is not Rule:
        raise ValueError('typed rule required')
    word(rule.head)
    word(rule.partner)
    for x in (rule.phase,rule.period,rule.minimum):
        integer(x,1)
    if compile_rule(rule.head) != rule:
        raise ValueError('noncanonical rule')
    return rule


def rules():
    return tuple(compile_rule(u) for u in ((6,),(3,6),(4,4),(5,2)))


def guard(exponent,rule):
    integer(exponent,2)
    audit_rule(rule)
    return exponent >= rule.minimum and exponent%rule.period == rule.phase


def run_data(exponent):
    integer(exponent,2)
    reset = 2 if exponent%2 else 3+v2(exponent)
    twos = 1+v2(exponent-1)//2 if exponent%2 else 0
    return exponent-1,reset,twos


def replay(source,w):
    integer(source,1)
    if source%2 != 1:
        raise ValueError('positive odd source required')
    word(w)
    x = source
    for a in w:
        if x == 1:
            raise ValueError('ROOT padding')
        z = 3*x+1
        if v2(z) != a:
            raise ValueError('non-native source word')
        x = z >> a
    return x


def head_endpoint_residue(exponent,rule,modulus):
    integer(exponent,2)
    integer(modulus,1)
    audit_rule(rule)
    if not guard(exponent,rule):
        raise ValueError('wrong exponent phase')
    p,q,b = carrier(rule.head)
    denominator = 2*q
    numerator = (p*(pow(3,exponent,denominator*modulus)-1)+2*b) % (denominator*modulus)
    if numerator%denominator:
        raise RuntimeError('exact division lost')
    return numerator//denominator


def terminal_valuation(exponent,rule,precision=256):
    integer(precision,1)
    residue = (3*head_endpoint_residue(exponent,rule,2**precision)+1) % 2**precision
    return None if residue == 0 else v2(residue)


@dataclass(frozen=True)
class Join:
    source_exponent: int
    child_exponent: int
    source_word: tuple
    child_word: tuple
    endpoint: int


def audit_join(j):
    if type(j) is not Join:
        raise ValueError('typed join required')
    integer(j.source_exponent,2)
    integer(j.child_exponent,1)
    integer(j.endpoint,1)
    word(j.source_word)
    word(j.child_word)
    if j.child_exponent >= j.source_exponent:
        raise ValueError('unpaid child')
    if replay(2**j.source_exponent-1,j.source_word) != j.endpoint:
        raise ValueError('source mismatch')
    if replay(2**j.child_exponent-1,j.child_word) != j.endpoint:
        raise ValueError('child mismatch')
    if len(j.source_word) != len(j.child_word):
        raise ValueError('nonzero odd-count defect')
    if sum(j.source_word)-sum(j.child_word) != j.source_exponent-j.child_exponent:
        raise ValueError('nonzero normalized cost defect')
    return j


def materialize_join(exponent,rule,deletion=2,bit_cap=10000):
    integer(exponent,2)
    integer(deletion,1)
    integer(bit_cap,1)
    audit_rule(rule)
    if deletion not in (1,2) or not guard(exponent,rule):
        raise ValueError('wrong deletion or source phase')
    if exponent > bit_cap:
        raise ValueError('materialization cap; symbolic phase remains valid')
    x = (3**exponent-1)//2
    z = replay(x,rule.head)
    c = v2(3*z+1)
    source = (1,)*(exponent-1)+(2,)+rule.head+(c,)
    clearing = (4,) if deletion == 1 else (2,2)
    child = (1,)*(exponent-deletion-1)+clearing+rule.partner+(c+2,)
    endpoint = (3*z+1)//2**c
    return audit_join(Join(exponent,exponent-deletion,source,child,endpoint))


def even_reset_join(exponent):
    integer(exponent,4)
    if exponent%2:
        raise ValueError('even exponent required')
    a = 3+v2(exponent)
    sw = (1,)*(exponent-1)+(a,)
    cw = (1,)*(exponent-2)+(2,a-2)
    return audit_join(Join(exponent,exponent-1,sw,cw,replay(2**exponent-1,sw)))


def discharge(j,supplied_child_word):
    audit_join(j)
    word(supplied_child_word)
    if replay(2**j.child_exponent-1,supplied_child_word) != 1:
        raise ValueError('supplied child certificate is not ROOT')
    count = len(j.child_word)
    if supplied_child_word[:count] != j.child_word:
        raise ValueError('child certificate does not match the common-future seam')
    result = j.source_word+supplied_child_word[count:]
    if replay(2**j.source_exponent-1,result) != 1:
        raise RuntimeError('strict transport failed')
    return result


def certificate_rows():
    obj = json.loads(DATA.read_text(encoding='utf-8'))
    rows = obj['certificates']
    if type(rows) is not list or len(rows) != 4:
        raise ValueError('exact four supplied terminal rows required')
    if any(type(r) is not dict or type(r.get('exponent')) is not int for r in rows):
        raise ValueError('typed source rows required')
    if {r['exponent'] for r in rows} != {29,77,197,321}:
        raise ValueError('changed supplied source universe')
    return rows


def root_word(exponent):
    integer(exponent,2)
    rows = [r for r in certificate_rows() if type(r.get('exponent')) is int and r['exponent']==exponent]
    if len(rows) != 1:
        raise ValueError('no unique supplied certificate for that source')
    r = rows[0]
    w = []
    if type(r.get('runs')) is not list:
        raise ValueError('run list required')
    previous = None
    for pair in r['runs']:
        if type(pair) is not list or len(pair) != 2:
            raise ValueError('typed run pair required')
        a,count = pair
        integer(a,1)
        integer(count,1)
        if a == previous:
            raise ValueError('noncanonical adjacent runs')
        previous = a
        w.extend((a,)*count)
    answer = tuple(w)
    for field in ('rank','cost','peak_bits'):
        integer(r[field],1)
    if r['rank'] != len(answer) or r['cost'] != sum(answer):
        raise ValueError('certificate clocks differ')
    if r['word_sha256'] != sha256(','.join(map(str,answer)).encode()).hexdigest():
        raise ValueError('word hash differs')
    if replay(2**exponent-1,answer) != 1:
        raise ValueError('supplied word fails strict ROOT')
    x,peak = 2**exponent-1,exponent
    for a in answer:
        x=(3*x+1)>>a
        peak=max(peak,x.bit_length())
    if peak != r['peak_bits']:
        raise ValueError('supplied peak metadata differs')
    return answer


def continuation_phases():
    """Intersect the unchanged D2 child phase with the frozen 225-head bank."""
    import collatz_general_head_phases_20261007b as old
    from collatz_twoanchor_head_decoder_20261007b import finite_head_bank
    rows=[]
    for packet in finite_head_bank():
        head=old.compile_head(packet.head,packet.partner,packet.gap)
        phase=old.phase(head,4)
        if (phase.residue-321)%min(phase.period,512)==0:
            if phase.period<512 or phase.first_parameter!=0:
                raise RuntimeError('intersection requires a retained cutoff')
            rows.append({'head':list(packet.head),'partner':list(packet.partner),
                         'gap':packet.gap,'child_phase':phase.residue,
                         'source_phase':phase.residue+2,'period':phase.period})
    return rows


CHECKS = 0


def check(condition,label):
    global CHECKS
    CHECKS += 1
    if not condition:
        raise RuntimeError(label)


def rejects(call):
    try:
        call()
    except (ValueError,TypeError):
        check(True,'rejected hostile')
        return
    check(False,'accepted hostile')


def main():
    bank = rules()
    expected = [((6,),(1,1),31,64),((3,6),(2,2,1),323,512),
                ((4,4),(1,2,1),199,256),((5,2),(1,1,1),79,128)]
    check([(r.head,r.partner,r.phase,r.period) for r in bank] == expected,'exact short bank')
    # Independently bounded reconstruction, supporting the all-length proof.
    found = []
    for a in range(3,65):
        result = compile_rule((a,))
        if result:
            found.append(result.head)
        check((result is not None) == (a==6),'one-letter finite universe')
        for b in range(1,65):
            result = compile_rule((a,b))
            if result:
                found.append(result.head)
            check((result is not None) == ((a,b) in ((3,6),(4,4),(5,2))),
                  'two-letter finite universe')
    check(set(found)=={r.head for r in bank},'classification controls')
    # Exact first reset, maximal two-run and unchanged-source growth.
    for e in range(2,257):
        k,a,j = run_data(e)
        x = replay(2**e-1,(1,)*k)
        check(x==2*3**(e-1)-1,'initial ones endpoint')
        check(v2(3*x+1)==a,'extra factor two in first reset')
        if e%2:
            check(j<=k//2,'joint run guard')
            word2 = (1,)*k+(2,)*j
            y = replay(2**e-1,word2)
            check(v2(3*y+1)!=2,'two-run maximality')
            check(y>2**e-1,'maximal pair still grows')
            p,q,b = carrier(word2)
            check(p>q and b>0,'all final paired slopes grow')
    phase_rows=[]
    grounded=[]
    for r in bank:
        audit_rule(r)
        p,q,b = carrier(r.head)
        pv,qv,bv = carrier(r.partner)
        check((pv*q, bv*q)==(48*p*qv,(4*p+4*b+q)*qv),
              'independent anchored coefficient identity')
        residue,modulus = native_cell(r.head)
        hits=[]
        for e in range(1,r.period+1,2):
            native = pow(3,e,2*modulus)==2*residue+1
            if native:
                hits.append(e)
            check(native==(e==r.phase),'complete native exponent period')
        check(hits==[r.phase] and r.minimum==r.phase,'no omitted positive phase members')
        for t in range(4):
            e=r.phase+r.period*t
            direct=materialize_join(e,r,2)
            one=materialize_join(e,r,1)
            reset=even_reset_join(e-1)
            check(reset.source_word==one.child_word[:len(reset.source_word)],'context seam')
            composite=reset.child_word+one.child_word[len(reset.source_word):]
            check(composite==direct.child_word,'ordinary reset gives exact D2 factorization')
            check(terminal_valuation(e,r)==direct.source_word[-1],'terminal modular precision')
            z=replay((3**e-1)//2,r.head)
            for m in (2,3,9,16,27,64,729,1001):
                check(head_endpoint_residue(e,r,m)==z%m,'full denominator reader')
            phase_rows.append({'head':list(r.head),'exponent':e,'terminal':direct.source_word[-1],
                               'join_rank':len(direct.source_word),'endpoint_bits':direct.endpoint.bit_length()})
        # Huge exponent controls only query exact modular data, not giant sources.
        e=r.phase+r.period*(10**30+7)
        for m in (2,9,32,81,1001):
            x=((pow(3,e,2*m)-1)//2)%m
            y=((pow(3,e-1,8*m)-1)//8)%m
            z=head_endpoint_residue(e,r,m)
            check((x-12*y-1)%m==0,'symbolic marked anchor')
            check((p*x+b-q*z)%m==0,'symbolic native head')
            check((pv*y+bv-qv*(4*z+1))%m==0,'symbolic partner')
        child=root_word(r.phase-2)
        even=discharge(even_reset_join(r.phase-1),child)
        source=discharge(materialize_join(r.phase,r,2),child)
        source1=discharge(materialize_join(r.phase,r,1),even)
        check(source==source1,'same literal ROOT export through both factorizations')
        check(len(source)==len(even)==len(child),'odd ROOT rank preserved')
        check(sum(source)==sum(child)+2 and sum(even)==sum(child)+1,'normalized ROOT cost preserved')
        for e,w in ((r.phase-2,child),(r.phase-1,even),(r.phase,source)):
            grounded.append({'exponent':e,'rank':len(w),'cost':sum(w),
                             'word_sha256':sha256(','.join(map(str,w)).encode()).hexdigest()})
    # A single exact period gives the disjoint shell fraction, independently.
    shell=[e for e in range(512) if e%4==3]
    counts=[sum(e%r.period==r.phase for e in shell) for r in bank]
    check(counts==[8,1,2,4],'shell occupancy')
    check(all(sum(e%r.period==r.phase for r in bank)<=1 for e in shell),'prefix-separated phases')
    check(sum(counts)==15 and len(shell)==128,'exact shell union15/128')
    check(not any(guard(327,r) for r in bank),'explicit remaining phase327')
    continuations=continuation_phases()
    check(len(continuations)==24,'complete declared bank intersection')
    continuation_mass=sum((Fraction(512,r['period']) for r in continuations),Fraction())
    check(continuation_mass==Fraction(429,32768),'exact conditional continuation mass')
    check((continuations[0]['head'],continuations[0]['source_phase'],continuations[0]['period'])
          ==([1,10],52547,131072),'simplest simultaneous guard')
    for i,row in enumerate(continuations):
        check(guard(row['source_phase'],bank[1]),'same-source parent phase')
        check(row['child_phase']%512==321 and v2(row['child_phase']-1)==6,'J4 child shell')
        check((321-row['child_phase'])%row['period']!=0,'least grounded child is outside continuation bank')
        for other in continuations[:i]:
            check((row['child_phase']-other['child_phase'])%min(row['period'],other['period'])!=0,
                  'continuation cells are disjoint')
    for r in bank:
        target_run=4 if r.head==(3,6) else 2
        check(run_data(r.phase-2)[2]==target_run,'child maximal two-run type')
    maximum=max(row['rank'] for row in certificate_rows())
    check(maximum==1774,'finite-anchor rank ceiling')
    check(all(row['rank']>=row['exponent'] for row in grounded),'initial-run rank lower bound')
    sample=bank[1]
    j=materialize_join(sample.phase,sample,2)
    for bad in (True,323.0,0,-1):
        rejects(lambda bad=bad: guard(bad,sample))
    rejects(lambda: audit_rule(replace(sample,phase=323.0)))
    rejects(lambda: audit_rule(replace(sample,period=True)))
    rejects(lambda: audit_rule(replace(sample,partner=(2,1,2))))
    rejects(lambda: audit_join(replace(j,endpoint=float(j.endpoint))))
    rejects(lambda: materialize_join(sample.phase+2,sample))
    rejects(lambda: materialize_join(sample.phase,sample,3))
    rejects(lambda: materialize_join(sample.phase+sample.period*10**30,sample))
    rejects(lambda: root_word(323))
    rejects(lambda: discharge(j,root_word(197)))
    rejects(lambda: replay(1,(2,)))
    result={'status':'PROVED native families and rank obstruction; FINITE-EXACT supplied terminals; universal coverage OPEN',
            'checks':CHECKS,
            'rules':[{'head':list(r.head),'partner':list(r.partner),'phase':r.phase,'period':r.period,
                      'minimum':r.minimum,'deletions':[1,2],'baseline':r.head==(6,)} for r in bank],
            'shell_density':{'shell':'E=3mod4','old':'1/16','new':'7/128','union':'15/128','uncovered':'113/128'},
            'discovery':{'method':'bounded actual forward search on four explicitly selected children','odd_step_cap':100000},
            'certificates':certificate_rows(),'grounded_mersennes':grounded,
            'continuation_225_bank':{'child_shell':'F321mod512,J4','conditional_mass':'429/32768',
                                     'rows':continuations,'total_deletion':6,'ROOT':'supplied terminal still required'},
            'literal_join_controls':phase_rows,'terminal_rank_ceiling':maximum,
            'scope':'The family guards give paid children; only listed supplied terminals are ROOT-grounded. Zero odd-count defect blocks unbounded finite-anchor closure.'}
    print(json.dumps(result,indent=2))


if __name__=='__main__':
    main()
