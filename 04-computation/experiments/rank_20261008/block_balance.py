#!/usr/bin/env python3
"""Block balance: a k-step Lamperti criterion for debt walks whose couplings have degenerate covariances.

Pair chain of a Matthews-Watts map T(x) = (m_i x + r_i)/d on x = i mod d:  u = M v + e,  v's digit j fresh uniform,
u's digit i = (M j + e) mod d,  M' = M m_i/m_j,  e' = (m_i e + r_i - (m_i/m_j) M r_j)/d.  The debt step is the root
xi = v_i - v_j (v_j = log-vector of m_j).  Given F_t the k-step debt increment eta has conditional mean 0 and conditional
second moment  Sigma_k = sum_{s<k} E[C_{pi_(t+s)} | F_t]  (cross terms vanish: each step is a martingale difference).
Sigma_k depends on F_t only through h = (M mod d^k, e mod d^k).  If one positive definite Q has
        tr(Sigma Q^-1) > 2 lambda_max(Sigma Q^-1)      for every h with Sigma_k(h) != 0,
then V(x) = |x|_Q^(-alpha) sampled every k steps is a supermartingale far out (Taylor; Sigma_k(h) = 0 means the debt
does not move during the block), and the debt walk is transient in the sense of THM-4609 (3).

Exact integer DP:  A_s(h) = d^s Sigma_s(h) = d^(s-1) D(pi(h)) + sum_j A_(s-1)(next(h, j)),  D(pi) = sum_j xi xi^T.
States: M ranges over the subgroup H_k of (Z/d^k)^* generated by the ratios m_i/m_j (a superset of the reachable
residues), e over Z/d^k.  Usage: python3 block_balance.py [kmax]"""
import itertools, math, random, sys
from fractions import Fraction as Fr
import numpy as np

def factor(n):
    f = {}; p = 2
    while p * p <= n:
        while n % p == 0: f[p] = f.get(p, 0) + 1; n //= p
        p += 1
    if n > 1: f[n] = f.get(n, 0) + 1
    return f

def int_coords(m):
    """Integer coordinates (rank rho) for the log-vectors of the m_j, up to a common GL(rho, Q) change of basis."""
    primes = sorted({p for x in m for p in factor(x)})
    E = [[Fr(factor(x).get(p, 0)) for p in primes] for x in m]
    diffs = [[a - b for a, b in zip(E[j], E[0])] for j in range(len(m))]
    basis = []                                    # independent subset of the differences, kept as raw vectors
    for v in diffs:
        trial = basis + [v]
        if rank_of(trial) == len(trial): basis.append(v)
    rho = len(basis)
    if rho == 0: return 0, [[] for _ in m]
    coords = [solve_in_basis(basis, v) for v in diffs]
    den = 1
    for c in coords:
        for x in c: den = den * x.denominator // math.gcd(den, x.denominator)
    return rho, [[int(x * den) for x in c] for c in coords]

def rank_of(vecs):
    rows = [r[:] for r in vecs]; rk = 0; ncol = len(rows[0])
    for c in range(ncol):
        pr = next((i for i in range(rk, len(rows)) if rows[i][c] != 0), None)
        if pr is None: continue
        rows[rk], rows[pr] = rows[pr], rows[rk]
        for i in range(len(rows)):
            if i != rk and rows[i][c] != 0:
                f = rows[i][c] / rows[rk][c]; rows[i] = [x - f * y for x, y in zip(rows[i], rows[rk])]
        rk += 1
    return rk

def solve_in_basis(B, v):
    n = len(B); rows = [[B[k][r] for k in range(n)] + [v[r]] for r in range(len(v))]; piv = []; rk = 0
    for c in range(n):
        pr = next((i for i in range(rk, len(rows)) if rows[i][c] != 0), None)
        if pr is None: continue
        rows[rk], rows[pr] = rows[pr], rows[rk]
        pv = rows[rk][c]; rows[rk] = [x / pv for x in rows[rk]]
        for i in range(len(rows)):
            if i != rk and rows[i][c] != 0:
                f = rows[i][c]; rows[i] = [x - f * y for x, y in zip(rows[i], rows[rk])]
        piv.append(c); rk += 1
    sol = [Fr(0)] * n
    for i, c in enumerate(piv): sol[c] = rows[i][n]
    assert all(rows[i][n] == 0 for i in range(rk, len(rows))), "inconsistent"
    return sol

def coupling_D(v, a, b, d, rho):
    D = [[0] * rho for _ in range(rho)]
    for j in range(d):
        xi = [p - q for p, q in zip(v[(a * j + b) % d], v[j])]
        for x in range(rho):
            if xi[x]:
                for y in range(rho): D[x][y] += xi[x] * xi[y]
    return tuple(tuple(r) for r in D)

def ratio_group(m, mod):
    gens = [x * pow(m[0], -1, mod) % mod for x in m]
    H = {1}; frontier = [1]
    while frontier:
        nxt = []
        for h in frontier:
            for g in gens:
                y = h * g % mod
                if y not in H: H.add(y); nxt.append(y)
        frontier = nxt
    return sorted(H)

def block_matrices(d, m, r, v, rho, k):
    """Return dict state(M mod d^k, e mod d^k) -> A_k (tuple of tuples, integer)."""
    Dcache = {}
    def D(a, b):
        key = (a, b)
        if key not in Dcache: Dcache[key] = coupling_D(v, a, b, d, rho)
        return Dcache[key]
    zero = tuple(tuple(0 for _ in range(rho)) for _ in range(rho))
    prev = {}
    for s in range(1, k + 1):
        mod = d ** s; H = ratio_group(m, mod); cur = {}
        inv = {x: pow(x, -1, mod) for x in m}
        for M in H:
            a = M % d
            for e in range(mod):
                b = e % d
                base = D(a, b); scale = d ** (s - 1)
                acc = [[scale * base[x][y] for y in range(rho)] for x in range(rho)]
                if s > 1:
                    pmod = d ** (s - 1)
                    for j in range(d):
                        i = (a * j + b) % d
                        N = (m[i] * e + r[i] - m[i] * inv[m[j]] * M * r[j]) % mod
                        assert N % d == 0
                        e2 = (N // d) % pmod; M2 = M * m[i] * inv[m[j]] % pmod
                        Ap = prev[(M2, e2)]
                        for x in range(rho):
                            for y in range(rho): acc[x][y] += Ap[x][y]
                cur[(M, e)] = tuple(tuple(rw) for rw in acc)
        prev = cur
    return prev

def margins(L, As):
    Li = np.linalg.inv(L)
    W = Li @ As @ Li.T
    ev = np.linalg.eigvalsh(W)
    tr = ev.sum(axis=1)
    return (tr - 2 * ev[:, -1]) / tr

def search_Q(As, rho, rnd, iters=6000, Q0=None):
    if Q0 is None: Q0 = As.mean(axis=0)
    L = np.linalg.cholesky(Q0 / np.trace(Q0))
    best = margins(L, As).min(); step = 0.2
    for it in range(iters):
        Ln = L + np.tril(rnd.normal(0, step, (rho, rho)))
        if np.any(np.diag(Ln) <= 1e-3): continue
        mn = margins(Ln, As).min()
        if mn > best: best, L = mn, Ln
        if it % 1000 == 999: step *= 0.6
    return L @ L.T, best

def det_exact(M):
    n = len(M); A = [row[:] for row in M]; dv = Fr(1)
    for c in range(n):
        pr = next((i for i in range(c, n) if A[i][c] != 0), None)
        if pr is None: return Fr(0)
        if pr != c: A[c], A[pr] = A[pr], A[c]; dv = -dv
        dv *= A[c][c]
        for i in range(c + 1, n):
            f = A[i][c] / A[c][c]; A[i] = [x - f * y for x, y in zip(A[i], A[c])]
    return dv

def posdef_exact(S): return all(det_exact([row[:t] for row in S[:t]]) > 0 for t in range(1, len(S) + 1))

def inv_exact(M):
    n = len(M); A = [list(map(Fr, row)) + [Fr(int(i == j)) for j in range(n)] for i, row in enumerate(M)]
    for c in range(n):
        pr = next(i for i in range(c, n) if A[i][c] != 0); A[c], A[pr] = A[pr], A[c]
        pv = A[c][c]; A[c] = [x / pv for x in A[c]]
        for i in range(n):
            if i != c and A[i][c] != 0:
                f = A[i][c]; A[i] = [x - f * y for x, y in zip(A[i], A[c])]
    return [row[n:] for row in A]

def exact_check(Q, distinct, rho):
    """Round Q (scaled so its largest entry is S) to integers for several S; return the first that balances exactly."""
    Qn = Q / np.abs(Q).max()
    for S in (4, 6, 8, 10, 12, 16, 20, 24, 32, 50, 64, 100, 128, 200, 500, 1000, 10000):
        Qr = [[Fr(int(round(Qn[i][j] * S))) for j in range(rho)] for i in range(rho)]
        Qr = [[(Qr[i][j] + Qr[j][i]) / 2 for j in range(rho)] for i in range(rho)]
        if not posdef_exact(Qr): continue
        Qi = inv_exact(Qr); ok = True
        for A in distinct:
            t = sum(A[x][y] * Qi[y][x] for x in range(rho) for y in range(rho))
            Sm = [[t / 2 * Qr[x][y] - A[x][y] for y in range(rho)] for x in range(rho)]
            if not posdef_exact(Sm): ok = False; break
        if ok: return Qr
    return None

def analyse(name, d, m, r, kmax, rnd, out):
    for i in range(d): assert (m[i] * i + r[i]) % d == 0, (name, i)
    rho, v = int_coords(m)
    Lam = sum(math.log(x / d) for x in m) / d
    G1 = ratio_group(m, d)
    print(f"{name}: d = {d}, m = {m}, r = {r}, rank {rho}, Lambda = {Lam:+.4f}, coupling group mod d = {G1}", file=out, flush=True)
    if rho < 3:
        print("   rank < 3: no balanced form can exist (trace <= rank * lambda_max)", file=out, flush=True); return
    for k in range(1, kmax + 1):
        states = block_matrices(d, m, r, v, rho, k)
        nz = {A for A in states.values() if any(any(x for x in row) for row in A)}
        nzero = sum(1 for A in states.values() if not any(any(x for x in row) for row in A))
        distinct = sorted(nz)
        As = np.array(distinct, dtype=float)
        ranks = np.linalg.matrix_rank(As)
        minrank = int(ranks.min())
        line = f"   k = {k}: {len(states)} states, {nzero} frozen (Sigma = 0), {len(distinct)} distinct nonzero Sigma_k, min rank {minrank}"
        if minrank < 3:
            print(line + " -> impossible (some block covariance has rank <= 2)", file=out, flush=True); continue
        Q, mg = search_Q(As, rho, rnd)
        line += f", best margin {mg:+.4f}"
        if mg > 0:
            Qr = exact_check(Q, distinct, rho)
            if Qr is not None:
                den = 1
                for row in Qr:
                    for x in row: den = den * x.denominator // math.gcd(den, x.denominator)
                Qi = [[int(x * den) for x in row] for row in Qr]
                g = 0
                for row in Qi:
                    for x in row: g = math.gcd(g, x)
                Qi = [[x // g for x in row] for row in Qi]
                line += f" -> BALANCED, exact form Q = {Qi}"
                Qf = np.array(Qi, dtype=float); amax = (1 / (1 - margins(np.linalg.cholesky(Qf), As).min()) * 2) - 2
                line += f", alpha_max = {amax:.4f}"
                print(line, file=out, flush=True); return k, Qi
            line += " -> float margin positive, exact rationalization failed"
        print(line, file=out, flush=True)
    return None

def std_r(m):
    d = len(m); return [(-m[i] * i) % d for i in range(d)]
MAPS = [
    ("Z5 (1,2,3,7,1) [HYP-9244 rank-3 row]", 5, [1, 2, 3, 7, 1], [0, 3, 4, 4, 1]),
    ("Z5 (1,2,3,7,11)", 5, [1, 2, 3, 7, 11], std_r([1, 2, 3, 7, 11])),
    ("Z5 (1,1,2,3,7)", 5, [1, 1, 2, 3, 7], std_r([1, 1, 2, 3, 7])),
    ("Z5 (1,3,9,2,1) [audit F hunt; rank 2]", 5, [1, 3, 9, 2, 1], [0, 2, 2, 4, 1]),
    ("Z4 (1,3,5,7)", 4, [1, 3, 5, 7], std_r([1, 3, 5, 7])),
    ("Z7 (1,1,1,1,2,3,5)", 7, [1, 1, 1, 1, 2, 3, 5], std_r([1, 1, 1, 1, 2, 3, 5])),
]

if __name__ == '__main__':
    kmax = int(sys.argv[1]) if len(sys.argv) > 1 else 3
    rnd = np.random.default_rng(11)
    for name, d, m, r in MAPS:
        analyse(name, d, m, r, kmax, rnd, sys.stdout)
