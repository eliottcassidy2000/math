#!/usr/bin/env python3
"""P3 of PREREGISTRATION.md (pushed in efdf0b0a5f before this script was written).  kind-pasteur-2026-10-27-S8.

For every tournament TYPE on n = 4..7 vertices, the coherent carrier set Sigma(T) subset of {L, C, S}:
  L: T has a directed Hamiltonian path (always, Redei);
  C: T has a directed (n-1)-cycle (with the remaining vertex as solo), i.e. some T - v is strong (Camion/Moon);
  S: T has a source or a sink.
Checks the predicted class sizes s_n, 2 s_(n-1), 2 t_(n-1) - t_(n-2) - 2 s_(n-1), remainder, and that Sigma = {L}
exactly for non-strong T whose first and last strong components have >= 3 vertices.
Types are generated by one-vertex extension with WL-hash buckets and exact isomorphism tests.
"""
import itertools, json
from collections import Counter, defaultdict
import networkx as nx


def types_upto(nmax):
    reps = {1: [nx.DiGraph([(0, 0)])]}
    reps[1][0].remove_edge(0, 0)
    for n in range(2, nmax + 1):
        buckets = defaultdict(list); out = []
        for T in reps[n - 1]:
            for mask in range(1 << (n - 1)):
                U = T.copy(); U.add_node(n - 1)
                for v in range(n - 1):
                    if (mask >> v) & 1:
                        U.add_edge(n - 1, v)
                    else:
                        U.add_edge(v, n - 1)
                h = (tuple(sorted(d for _, d in U.out_degree())), nx.weisfeiler_lehman_graph_hash(U, iterations=3))
                if any(nx.is_isomorphic(U, W) for W in buckets[h]):
                    continue
                buckets[h].append(U); out.append(U)
        reps[n] = out
    return reps


def has_ham_path(T):
    n = T.number_of_nodes()
    # DP over subsets
    adj = {v: set(T.successors(v)) for v in T}
    reach = {(1 << v, v) for v in range(n)}
    for size in range(1, n):
        new = set()
        for S, v in reach:
            if bin(S).count('1') != size:
                continue
            for w in adj[v]:
                if not (S >> w) & 1:
                    new.add((S | (1 << w), w))
        reach |= new
    return any(S == (1 << n) - 1 for S, _ in reach)


def sigma(T):
    n = T.number_of_nodes()
    s = set()
    if has_ham_path(T):
        s.add('L')
    if any(nx.is_strongly_connected(T.subgraph([u for u in T if u != v])) for v in T):
        s.add('C')
    if any(d == 0 for _, d in T.out_degree()) or any(d == 0 for _, d in T.in_degree()):
        s.add('S')
    return frozenset(s)


def scc_sizes_in_order(T):
    C = nx.condensation(T)
    order = list(nx.topological_sort(C))
    return [len(C.nodes[c]['members']) for c in order]


def main():
    reps = types_upto(7)
    t = {n: len(reps[n]) for n in reps}; t[0] = 1
    strong = {n: sum(1 for T in reps[n] if nx.is_strongly_connected(T)) for n in reps}
    print('types t_n =', [t[n] for n in range(1, 8)], ' strong s_n =', [strong[n] for n in range(1, 8)])
    out = {}
    for n in range(4, 8):
        c = Counter(); lone_ok = True
        for T in reps[n]:
            S = sigma(T)
            c[''.join(sorted(S))] += 1
            if S == frozenset('L'):
                sz = scc_sizes_in_order(T)
                lone_ok &= (len(sz) >= 2 and sz[0] >= 3 and sz[-1] >= 3)
            else:
                sz = scc_sizes_in_order(T)
                lone_ok &= not (len(sz) >= 2 and sz[0] >= 3 and sz[-1] >= 3)
        pred = {'CL': strong[n], 'CLS': 2 * strong[n - 1], 'LS': 2 * t[n - 1] - t[n - 2] - 2 * strong[n - 1]}
        pred['L'] = t[n] - sum(pred.values())
        out[n] = {'observed': dict(c), 'predicted': pred, 'L_alone_characterised': lone_ok,
                  'pair_or_triple_for_all': all(len(k) >= 2 for k in c)}
        print(n, out[n], flush=True)
    json.dump({str(k): v for k, v in out.items()}, open('coherent_carrier_sets.json', 'w'), indent=1)


if __name__ == '__main__':
    main()
