# Discriminant of degree-5 polynomial is complex. Let me compute it numerically.
# Disc = (-1)^{n(n-1)/2} * Res(p, p') / a_n
# For degree 5: Disc = (-1)^10 * Res(p, p') / 1 = Res(p, p')

from numpy.polynomial import polynomial as P

# p(λ) = λ⁵ - λ⁴ - λ³ - λ² - λ - 1
# Coefficients in numpy convention (highest degree first):
# [1, -1, -1, -1, -1, -1]

# Compute discriminant via resultant of p and p'
# p'(λ) = 5λ⁴ - 4λ³ - 3λ² - 2λ - 1
# Use the fact that disc = product of (r_i - r_j)^2 over i<j, times leading^{2n-2}

