# The 5-state transfer matrix (pentanacci-like at coupling x)
# M_5(x) analogous to M_3(x) = [[1,2x,0],[0,0,1],[1,x,0]]
# The pentanacci transfer matrix for "no 5 consecutive" constraint:
def penta_transfer(x):
    k = 5
    M = np.zeros((k, k))
    for i in range(k):
        M[i][0] = 1       # can always place 0
        if i < k-1:
            M[i][i+1] = 1  # can place 1 if run < k-1
    # This is the k-nacci transfer matrix
    return M

