def tournament_stats(names: list[str], edge_score) -> None:
    edges = {name: set() for name in names}
    for a, b in combinations(names, 2):
        sa, sb = edge_score(a), edge_score(b)
        if sa > sb:
            edges[a].add(b)
        elif sb > sa:
            edges[b].add(a)
        else:
            # deterministic tie path
            edges[a].add(b)
    scores = {name: len(edges[name]) for name in names}
    hist = Counter(scores.values())
    cycles = 0
    for a, b, c in combinations(names, 3):
        triples = ((a, b, c), (a, c, b))
        cyc = False
        for x, y, z in triples:
            if y in edges[x] and z in edges[y] and x in edges[z]:
                cyc = True
        cycles += int(cyc)

    # Hamiltonian path count by brute force; small tournaments only.
    hpaths = 0
    for perm in permutations(names):
        if all(perm[i + 1] in edges[perm[i]] for i in range(len(perm) - 1)):
            hpaths += 1
    print(f"    scores={scores}")
    print(f"    score_hist={dict(sorted(hist.items()))} directed_3cycles={cycles}")
    print(f"    Hamiltonian_path_count={hpaths}")


def tournament_analysis() -> None:
    print("PART E -- Tournament Analysis: what should be a vertex?")
    print("  Shape tournament, size 8.  Vertices are cluster shapes, not runners.")
    shapes = [
        tuple(range(8)),
        (0, 2, 3, 4, 5, 6, 8, 10),
        (0, 1, 2, 3, 4, 5, 6, 8),
        (0, 1, 2, 3, 4, 5, 7, 8),
        (0, 1, 2, 3, 4, 6, 7, 8),
        (0, 1, 2, 4, 5, 6, 7, 8),
    ]
    name = {shape: "K8" if shape == tuple(range(8)) else str(shape) for shape in shapes}
    names = [name[s] for s in shapes]
    by_name = {name[s]: s for s in shapes}
    print("  Switch 1: full-cover scalar q_C(all six); larger wins.")
    tournament_stats(names, lambda n: grid_capacity_vector(by_name[n])[FULL_MASK])
    print("  Switch 2: residual-majority; larger number of residual masks won vs K8 proxy.")

    def residual_majority_score(n: str) -> int:
        shape = by_name[n]
        vec = grid_capacity_vector(shape)
        # Score each vertex by total wins against all other vertices over residual masks.
        wins = 0
        for other_name in names:
            if other_name == n:
                continue
            other = grid_capacity_vector(by_name[other_name])
            wins += sum(1 for r in range(1, 64) if vec[r] > other[r] + 1e-12)
        return wins

    tournament_stats(names, residual_majority_score)
    print("  Lens tournament.  Vertices are proof obligations; larger tuple wins.")
    lenses = {
        "coordinatewise_residual_dominance": (0, 5, 1),
        "full_cover_scalar": (3, 3, 2),
        "context_weighted_cone": (4, 4, 4),
        "split_vs_single_margin": (5, 3, 5),
        "single_block_diagonal_freeze": (5, 2, 4),
        "joint_multi_carrier_error": (2, 5, 5),
    }
    print("    observable=(proved_or_supported, generality, proof_reach)")
    print("    switch: lexicographic proof-usefulness; tie path is listed order")
    tournament_stats(list(lenses), lambda n: lenses[n])
    print()


