#!/usr/bin/env python3
"""HYP-2697 / T933 / S62: arbitrary bounded cluster-shape compression scout.

THM-557 proves the coherent-block quotient: once every far cluster is a
consecutive block, the single block is the exact decorrelated maximizer.  The
remaining HYP-2694 gap is to compress arbitrary bounded shapes into that
coherent-block quotient.

This scout tests several possible meanings of "compression":

1. Coordinatewise residual-capacity dominance.
   For a shape C and residual sector set R, q_C(R) is the probability, averaged
   over slow x and carrier phase phi, that C covers every sector in R.  If
   q_C(R) <= q_K(R) for all R, with K={0,...,|C|-1}, then K can replace C in any
   independent context.  This turns out to be FALSE.

2. Full-cover scalar dominance.
   The same q_C(R), but only for R=all six inner sectors.  This is the scalar
   one-cluster cover.  Consecutive remains the winner in the bounded grid boxes
   tested here.

3. Context-weighted compression.
   Actual HYP-2694 contexts do not use arbitrary nonnegative weights on R; they
   use residual profiles generated by other clusters.  Beam scans of split
   contexts keep the split below the one-block value.  This suggests the right
   theorem is a cone statement: decorrelated LRC contexts lie in a large-residual
   cone where the consecutive block maximizes the weighted capacity functional.

The broad scans are midpoint-grid scouts, not proofs.  The small dominance
failures and named context checks are exact Fractions.
"""

from __future__ import annotations

from collections import Counter, defaultdict
from dataclasses import dataclass
from functools import lru_cache
from fractions import Fraction as F
from itertools import combinations, permutations
from math import gcd


INNER = tuple(range(1, 7))
FULL_MASK = (1 << 6) - 1
NX = 42
NPHI = 42


def mask_to_sectors(mask: int) -> tuple[int, ...]:
    return tuple(i + 1 for i in range(6) if mask & (1 << i))


def mask_size(mask: int) -> int:
    return mask.bit_count()


def primitive(shape: tuple[int, ...]) -> bool:
    g = 0
    for x in shape:
        g = gcd(g, x)
    return g == 1


def bounded_shapes(size: int, span: int) -> list[tuple[int, ...]]:
    if size == 1:
        return [(0,)]
    out: list[tuple[int, ...]] = []
    for rest in combinations(range(1, span + 1), size - 1):
        shape = (0,) + rest
        if primitive(shape):
            out.append(shape)
    return out


@lru_cache(maxsize=None)
def exact_breakpoints(shape: tuple[int, ...]) -> tuple[F, ...]:
    bps = {F(0), F(1)}
    for d in shape:
        if d == 0:
            continue
        for a in range(7 * d + 1):
            bps.add(F(a, 7 * d))
    return tuple(sorted(bps))


@lru_cache(maxsize=None)
def exact_dist_at_x(shape: tuple[int, ...], x: F) -> tuple[tuple[int, F], ...]:
    base = tuple((d * x) % 1 for d in shape)
    cuts = {F(0), F(1)}
    for b in base:
        for s in range(7):
            cuts.add((F(s, 7) - b) % 1)
    cuts = sorted(cuts)
    dist: dict[int, F] = defaultdict(F)
    for lo, hi in zip(cuts, cuts[1:]):
        if hi <= lo:
            continue
        mid = (lo + hi) / 2
        mask = 0
        for b in base:
            sec = int(((b + mid) % 1) * 7)
            if 1 <= sec <= 6:
                mask |= 1 << (sec - 1)
        dist[mask] += hi - lo
    return tuple(sorted(dist.items()))


@lru_cache(maxsize=None)
def exact_capacity_vector(shape: tuple[int, ...]) -> tuple[F, ...]:
    """q_C(R) for every residual mask R, exact."""
    total = [F(0) for _ in range(64)]
    xs = exact_breakpoints(shape)
    for lo, hi in zip(xs, xs[1:]):
        if hi <= lo:
            continue
        mid = (lo + hi) / 2
        dist = exact_dist_at_x(shape, mid)
        for hit, mass in dist:
            sub = hit
            while True:
                total[sub] += (hi - lo) * mass
                if sub == 0:
                    break
                sub = (sub - 1) & hit
    return tuple(total)


@lru_cache(maxsize=None)
def grid_distributions(shape: tuple[int, ...]) -> tuple[tuple[float, ...], ...]:
    """Midpoint grid law of hit masks for each slow-x grid point."""
    rows: list[tuple[float, ...]] = []
    for ix in range(NX):
        x = (ix + 0.5) / NX
        base = tuple((d * x) % 1.0 for d in shape)
        counts = [0] * 64
        for ip in range(NPHI):
            phi = (ip + 0.5) / NPHI
            mask = 0
            for b in base:
                sec = int(((phi + b) % 1.0) * 7)
                if 1 <= sec <= 6:
                    mask |= 1 << (sec - 1)
            counts[mask] += 1
        rows.append(tuple(c / NPHI for c in counts))
    return tuple(rows)


def zeta_capacity_float(dist: tuple[float, ...]) -> list[float]:
    cap = [0.0] * 64
    for hit, mass in enumerate(dist):
        if mass == 0.0:
            continue
        sub = hit
        while True:
            cap[sub] += mass
            if sub == 0:
                break
            sub = (sub - 1) & hit
    return cap


@lru_cache(maxsize=None)
def grid_capacity_vector(shape: tuple[int, ...]) -> tuple[float, ...]:
    total = [0.0] * 64
    for dist in grid_distributions(shape):
        cap = zeta_capacity_float(dist)
        for i, v in enumerate(cap):
            total[i] += v
    return tuple(v / NX for v in total)


def grid_pcover(shapes: tuple[tuple[int, ...], ...]) -> float:
    """Grid pcover for independent carriers sharing slow x."""
    dists = [grid_distributions(shape) for shape in shapes]
    total = 0.0
    for ix in range(NX):
        cur = [0.0] * 64
        cur[0] = 1.0
        for ds in dists:
            nxt = [0.0] * 64
            dist = ds[ix]
            for old, old_mass in enumerate(cur):
                if old_mass == 0.0:
                    continue
                for hit, hit_mass in enumerate(dist):
                    if hit_mass:
                        nxt[old | hit] += old_mass * hit_mass
            cur = nxt
        total += cur[FULL_MASK]
    return total / NX


def exact_named_failures() -> None:
    print("PART A -- exact failures of naive residual-vector dominance")
    named = [
        ((0, 1, 2), (0, 1, 3)),
        ((0, 1, 2, 3), (0, 1, 2, 4)),
        ((0, 1, 2, 3, 4), (0, 1, 2, 3, 5)),
    ]
    for consec, challenger in named:
        vc = exact_capacity_vector(consec)
        vv = exact_capacity_vector(challenger)
        gains = [(vv[r] - vc[r], r) for r in range(1, 64) if vv[r] > vc[r]]
        gains.sort(reverse=True)
        print(f"  size={len(consec)} consec={consec} challenger={challenger}")
        print(f"    full-cover: challenger-consec = {vv[FULL_MASK] - vc[FULL_MASK]}")
        for diff, mask in gains[:5]:
            print(
                f"    residual {mask_to_sectors(mask)} gain = {diff} ({float(diff):+.9f})"
            )
    print("  Conclusion: compression cannot be coordinatewise stochastic dominance.")
    print()


def grid_full_cover_scan() -> dict[int, tuple[float, tuple[int, ...], int, tuple[float, tuple[int, ...], int]]]:
    print("PART B -- grid scan: full-cover scalar compression")
    print(f"  midpoint grid NX={NX}, Nphi={NPHI}; these rows are scouting evidence")
    summary = {}
    for size, span in ((6, 11), (7, 12), (8, 11), (9, 11)):
        consec = tuple(range(size))
        cv = grid_capacity_vector(consec)
        best = (cv[FULL_MASK], consec, 0)
        max_gain = (0.0, consec, 0)
        viol = 0
        rows = bounded_shapes(size, span)
        for shape in rows:
            vv = grid_capacity_vector(shape)
            if vv[FULL_MASK] > best[0]:
                best = (vv[FULL_MASK], shape, 0)
            gains = [(vv[r] - cv[r], r) for r in range(1, 64) if vv[r] > cv[r] + 1e-12]
            if gains:
                viol += 1
                gain, mask = max(gains)
                if gain > max_gain[0]:
                    max_gain = (gain, shape, mask)
        summary[size] = (cv[FULL_MASK], best[1], viol, max_gain)
        print(
            f"  size={size}, span<={span}, shapes={len(rows)}: "
            f"consec_full={cv[FULL_MASK]:.9f}, best_full={best[1]} {best[0]:.9f}, "
            f"vector_violators={viol}, max_residual_gain={max_gain[0]:.9f} "
            f"at {max_gain[1]} for R={mask_to_sectors(max_gain[2])}"
        )
    print("  Read: full-cover scalar favors consecutive, but residual-vector gains persist.")
    print()
    return summary


def grid_split_beam() -> None:
    print("PART C -- grid beam: arbitrary split contexts vs one coherent block")
    print("  Candidate shapes per size are top 8 by full-cover scalar in a small span box.")
    for total in range(7, 12):
        single = (tuple(range(total)),)
        single_value = grid_pcover(single)
        best = (0.0, None)
        for left_size in range(1, total):
            right_size = total - left_size
            left_span = min(10, left_size + 4)
            right_span = min(10, right_size + 4)
            left_shapes = bounded_shapes(left_size, left_span)
            right_shapes = bounded_shapes(right_size, right_span)
            left_shapes = sorted(
                left_shapes, key=lambda s: grid_capacity_vector(s)[FULL_MASK], reverse=True
            )[:8]
            right_shapes = sorted(
                right_shapes, key=lambda s: grid_capacity_vector(s)[FULL_MASK], reverse=True
            )[:8]
            for left in left_shapes:
                for right in right_shapes:
                    value = grid_pcover((left, right))
                    if value > best[0]:
                        best = (value, (left_size, right_size, left, right))
        print(
            f"  m={total}: one-block={single_value:.9f}, "
            f"best split beam={best[0]:.9f}, gap={single_value - best[0]:+.9f}, "
            f"arg={best[1]}"
        )
    print("  Read: the dangerous split is singleton + large block, matching THM-557.")
    print()


