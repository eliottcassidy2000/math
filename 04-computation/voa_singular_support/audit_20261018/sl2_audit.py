#!/usr/bin/env python3
"""Independent audit of THM-4672 (L_{-1/2}(sl2)); does not import the author's modules.

Exact over Q (flint.fmpq / fmpq_mat) unless a prime is given.
  * singular vector at weight 4, charge 4 (e_0 v = e_1 v = h_1 v = f_1 v = 0);
  * maximal submodule M_D of V^k computed from scratch:  w in M_D  iff  a_1 w in M_{D-1} for
    a in {e,h,f}  (t g[t] is generated by g (x) t; V_0 = C|0>), so dim L_D needs no character formula;
  * I_D = U(g[t^-1]t^-1) U(g) v, compared with M_D;
  * dim L_D compared with the Z_2-even part of prod_{n>=0} (1-q^{n+1/2})^{-2};
  * grI (leading forms, Li degree = weight - #modes), I_0 = Li-degree-0 part of grI, compared
    with the ideal generated by the 5 quartics;  J = differential ideal generated by I_0;
  * dim ker(pi) per (weight, Li degree, charge); minimal differential-ideal generators of grI;
  * HS(C[x]/J) vs char L; the displayed weight-7 highest-weight vector; Cas^2, Cas^3 in I_0.
Usage: python sl2_audit.py Dmax [prime]     (exact if no prime)
"""
import sys
import time
import flint
from alin import rref_vectors, rank, nullspace, leading_forms, in_span
from sl2mod import (AffSl2, colored_partitions, charge, weight, lidegree, pmul, pd, pretty,
                    E, H, F, modekey)

Dmax = int(sys.argv[1]) if len(sys.argv) > 1 else 8
P = int(sys.argv[2]) if len(sys.argv) > 2 else None
if P is None:
    one = flint.fmpq(1)
    K_LEVEL = flint.fmpq(-1, 2)
    MAT = lambda r, c: flint.fmpq_mat(r, c)
else:
    one = flint.nmod(1, P)
    K_LEVEL = flint.nmod(-1, P) / flint.nmod(2, P)
    MAT = lambda r, c: flint.nmod_mat(r, c, P)

t0 = time.time()
V = AffSl2(K_LEVEL, one)
bases = {D: colored_partitions(D) for D in range(Dmax + 1)}
sector = {}
for D in range(Dmax + 1):
    for m in bases[D]:
        sector.setdefault((D, charge(m)), []).append(m)


def log(*a):
    print(*a, flush=True)


log(f"V^k(sl2), k=-1/2, {'exact over Q' if P is None else 'mod ' + str(P)}, Dmax={Dmax}")
log("dim V_D:", [len(bases[D]) for D in range(Dmax + 1)])

# ---------------- singular vector --------------------------------------------------------
B44 = sector[(4, 4)]
eqs = {}
for (t, m) in [(E, 0), (E, 1), (H, 1), (F, 1)]:
    for b in B44:
        for mono, cc in V.act(t, m, b).items():
            eqs.setdefault((t, m, mono), {})[b] = cc
ker = nullspace(list(eqs.values()), B44, P)
log("weight-4 charge-4 singular space dim:", len(ker), " (#PBW monomials in sector:", len(B44), ")")
assert len(ker) == 1
v = ker[0]
log("v has", len(v), "PBW terms")
# all charge-4 weight-4 states annihilated by the positive part? check also other sectors at weight<=4
for D in range(1, 5):
    for c in sorted({charge(m) for m in bases[D]}):
        Bs = sector[(D, c)]
        eqs = {}
        for (t, m) in [(E, 0), (E, 1), (H, 1), (F, 1)]:
            for b in Bs:
                for mono, cc in V.act(t, m, b).items():
                    eqs.setdefault((t, m, mono), {})[b] = cc
        kk = nullspace(list(eqs.values()), Bs, P)
        if kk:
            log(f"  singular (h.w.) vectors at weight {D} charge {c}: {len(kk)}")


# ---------------- maximal submodule ------------------------------------------------------
def op_matrix(t, m, src, tgt):
    idx = {b: i for i, b in enumerate(tgt)}
    A = MAT(len(tgt), len(src))
    for j, b in enumerate(src):
        for mono, cc in V.act(t, m, b).items():
            A[idx[mono], j] = cc
    return A


Kf = {(0, 0): MAT(1, 1)}
Kf[(0, 0)][0, 0] = one
dimL = {0: 1}
for D in range(1, Dmax + 1):
    tot = 0
    for c in sorted({charge(m) for m in bases[D]}):
        Bs = sector[(D, c)]
        rows = []
        for (t, dc) in [(E, 2), (H, 0), (F, -2)]:
            key = (D - 1, c + dc)
            if key not in Kf or Kf[key].nrows() == 0:
                continue
            A = op_matrix(t, 1, Bs, sector[key])
            Mb = Kf[key] * A
            ent = Mb.entries()
            nc = Mb.ncols()
            for i in range(Mb.nrows()):
                r = {Bs[j]: ent[i * nc + j] for j in range(nc) if ent[i * nc + j] != 0}
                if r:
                    rows.append(r)
        rr = rref_vectors(rows, Bs, P) if rows else []
        Km = MAT(len(rr), len(Bs))
        col = {b: j for j, b in enumerate(Bs)}
        for i, (_, row) in enumerate(rr):
            for mono, cc in row.items():
                Km[i, col[mono]] = cc
        Kf[(D, c)] = Km
        tot += len(rr)
    dimL[D] = tot
log("dim L_D (maximal-submodule recursion):", [dimL[D] for D in range(Dmax + 1)])

# Z2-even part of beta-gamma character prod_{n>=0}(1-s^{2n+1})^{-2}, s=q^{1/2}
S = 2 * Dmax + 2
ser = [0] * (S + 1)
ser[0] = 1
for n in range(0, S):
    e = 2 * n + 1
    if e > S:
        break
    for _ in range(2):
        for i in range(e, S + 1):
            ser[i] += ser[i - e]
bg_even = [ser[2 * D] for D in range(Dmax + 1)]
log("Z2-even beta-gamma:              ", bg_even, " match:", bg_even == [dimL[D] for D in range(Dmax + 1)])

# ---------------- the ideal I generated by v ---------------------------------------------
I = {}
fv = [v]
for j in range(4):
    fv.append(V.actv(F, 0, fv[-1]))
I[4] = [row for _, row in rref_vectors([w for w in fv if w], bases[4], P)]
for D in range(5, Dmax + 1):
    gens = []
    for w in I[D - 1]:
        for t in (E, H, F):
            g = V.actv(t, -1, w)
            if g:
                gens.append(g)
    I[D] = [row for _, row in rref_vectors(gens, bases[D], P)]
ok_max = True
for D in range(4, Dmax + 1):
    dI = len(I[D])
    dM = len(bases[D]) - dimL[D]
    # I subset M:
    sub = True
    for w in I[D]:
        c = charge(next(iter(w)))
        Bs = sector[(D, c)]
        col = {b: j for j, b in enumerate(Bs)}
        x = MAT(len(Bs), 1)
        for mono, cc in w.items():
            x[col[mono], 0] = cc
        y = Kf[(D, c)] * x
        if any(y[i, 0] != 0 for i in range(y.nrows())):
            sub = False
    log(f"  D={D}: dim I_D={dI}  dim M_D={dM}  I<=M:{sub}")
    ok_max = ok_max and sub and dI == dM
log("I_D == M_D (maximal ideal) for all D<=Dmax:", ok_max)

# ---------------- grI, I_0, J ------------------------------------------------------------
gr = {D: leading_forms(I[D], bases[D], degree=len, modulus=P) for D in range(4, Dmax + 1)}
quartics = gr[4]
assert all(len(next(iter(g))) == 4 for g in quartics) and len(quartics) == 5
Cas = {((1, E), (1, F)): one, ((1, H), (1, H)): one / 4}
e0sq = {((1, E), (1, E)): one}
sym_v = gr[4]
log("symbol of v proportional to e0^2*Cas:",
    rank([v_ for v_ in [ {m: c for m, c in v.items() if len(m) == 4} ]] + [pmul(e0sq, Cas)], bases[4], P) == 1)


def monomials(D, li=None):
    return [m for m in bases[D] if li is None or lidegree(m) == li]


ok_I0 = True
for D in range(4, Dmax + 1):
    I0_D = [g for g in gr[D] if all(lidegree(m) == 0 for m in g)]
    gen_D = [pmul({m: one}, g) for m in monomials(D - 4, 0) for g in quartics]
    r_gen = rank(gen_D, bases[D], P) if gen_D else 0
    same = (r_gen == len(I0_D)) and all(in_span(g, I0_D, bases[D], P) for g in gen_D)
    log(f"  degree {D}: dim (I_0)_D = {len(I0_D)}   dim (quartic ideal)_D = {r_gen}   equal: {same}")
    ok_I0 = ok_I0 and same
log("I_0 generated by the five quartics in degrees <= Dmax:", ok_I0)


def J_span(D):
    gens = []
    for s in range(0, D - 4 + 1):
        dq = quartics
        for _ in range(s):
            dq = [pd(g) for g in dq]
        for m in bases[D - 4 - s]:
            for g in dq:
                gens.append(pmul({m: one}, g))
    return gens


report_rows = []
kerdims = {}
Jbases = {}
for D in range(4, Dmax + 1):
    Jg = J_span(D)
    Jr = [row for _, row in rref_vectors(Jg, bases[D], P)]
    Jbases[D] = Jr
    J_in_gr = all(in_span(g, gr[D], bases[D], P) for g in Jr)
    # per (Li degree, charge) dims
    secs = {}
    for g in gr[D]:
        m0 = next(iter(g))
        secs.setdefault((lidegree(m0), charge(m0)), [0, 0])[0] += 1
    for g in Jr:
        # J rows from rref may mix sectors? J_span is bigraded and charge graded -> rref rows homogeneous
        m0 = next(iter(g))
        assert all(lidegree(m) == lidegree(m0) and charge(m) == charge(m0) for m in g)
        secs.setdefault((lidegree(m0), charge(m0)), [0, 0])[1] += 1
    kerdims[D] = {s: a - b for s, (a, b) in secs.items() if a - b != 0}
    tot = len(gr[D]) - len(Jr)
    HS = len(bases[D]) - len(Jr)
    log(f"  D={D}: dim grI={len(gr[D])} dim J={len(Jr)} J<=grI:{J_in_gr} dim ker(pi)={tot} "
        f"HS(C[x]/J)={HS} charL={dimL[D]}  ker by (Li,charge): {dict(sorted(kerdims[D].items()))}")
    report_rows.append((D, len(gr[D]), len(Jr), J_in_gr, tot, HS, dimL[D]))

log("HS(C[x]/J):", [1, 3, 9, 22] + [r[5] for r in report_rows])
log("char L    :", [dimL[D] for D in range(Dmax + 1)])

# ---------------- minimal generators of grI as a differential ideal ----------------------
variables = {}
for D in range(1, Dmax + 1):
    variables[D] = [(D, t) for t in (E, H, F)]
for D in range(5, Dmax + 1):
    sub = []
    for g in gr[D - 1]:
        sub.append(pd(g))
    for w in range(1, D - 4 + 1):
        for var in variables[w]:
            for g in gr[D - w]:
                sub.append(pmul({(var,): one}, g))
    subr = [row for _, row in rref_vectors(sub, bases[D], P)]
    secs = {}
    for g in gr[D]:
        m0 = next(iter(g))
        secs.setdefault((lidegree(m0), charge(m0)), [0, 0])[0] += 1
    for g in subr:
        m0 = next(iter(g))
        secs.setdefault((lidegree(m0), charge(m0)), [0, 0])[1] += 1
    newg = {s: a - b for s, (a, b) in secs.items() if a - b != 0}
    log(f"  minimal generators of grI at weight {D} by (Li,charge): {dict(sorted(newg.items()))}")

# ---------------- the displayed weight-7 vector ------------------------------------------
if Dmax >= 7:
    def x(t, j):
        return (j + 1, t)

    def mono(*vs):
        return tuple(sorted(vs, key=modekey))
    e0, h0, f0 = x(E, 0), x(H, 0), x(F, 0)
    e1, h1, f1 = x(E, 1), x(H, 1), x(F, 1)
    e2, h2, f2 = x(E, 2), x(H, 2), x(F, 2)
    t23 = one * 2 / 3
    inner = [(one, (h1, e1, f0)), (t23, (h1, h1, h0)), (t23, (f1, e1, h0)), (one, (f1, h1, e0)),
             (t23, (e2, f0, h0)), (-one * 4 / 3, (h2, f0, e0)), (t23, (f2, h0, e0))]
    Pv = {}
    for cf, vs in inner:
        mm = mono(e0, e0, *vs)
        Pv[mm] = Pv.get(mm, 0) + cf
    inGr = in_span(Pv, gr[7], bases[7], P)
    inJ = in_span(Pv, Jbases[7], bases[7], P)
    log(f"displayed weight-7 vector: in grI: {inGr}   in J: {inJ}")
    # is it annihilated by ad(e) modulo J?  ad(e) acts on x_{t,j} by [e,t]
    def ade(p):
        out = {}
        for m, cc in p.items():
            seen = set()
            for md in m:
                if md in seen:
                    continue
                seen.add(md)
                mult = m.count(md)
                n, t = md
                tgt = {H: (E, -2), F: (H, 1)}.get(t)
                if tgt is None:
                    continue
                lst = list(m)
                lst.remove(md)
                lst.append((n, tgt[0]))
                nm = tuple(sorted(lst, key=modekey))
                out[nm] = out.get(nm, 0) + cc * mult * tgt[1]
        return {k_: c_ for k_, c_ in out.items() if c_ != 0}
    adeP = ade(Pv)
    log("ad(e) P in J (highest weight mod J):", (not adeP) or in_span(adeP, Jbases[7], bases[7], P))
    # is there a representative of the charge-4 class with fewer terms? report the class dim
    log("charge-4 part of ker(pi)_7 by Li:", {s: d for s, d in kerdims[7].items() if s[1] == 4})

# ---------------- Cas powers in I_0 ------------------------------------------------------
cas2 = pmul(Cas, Cas)
cas3 = pmul(cas2, Cas)
I0 = {D: [g for g in gr[D] if all(lidegree(m) == 0 for m in g)] for D in range(4, Dmax + 1)}
log("Cas^2 in I_0:", in_span(cas2, I0[4], bases[4], P))
if Dmax >= 6:
    log("Cas^3 in I_0:", in_span(cas3, I0[6], bases[6], P))
# Sugawara vector symbol
kk = K_LEVEL
T = {}
for (a, b, cf) in [(E, F, one), (F, E, one), (H, H, one / 2)]:
    w = V.actv(a, -1, V.actv(b, -1, {(): one}))
    for mm, c2 in w.items():
        T[mm] = T.get(mm, 0) + cf * c2 / (2 * (kk + 2))
Tsym = {m: c for m, c in T.items() if len(m) == 2}
log("Sugawara T symbol == Cas/(k+2):", Tsym == {m: c / (kk + 2) for m, c in Cas.items()})
log(f"time {time.time() - t0:.1f}s")
