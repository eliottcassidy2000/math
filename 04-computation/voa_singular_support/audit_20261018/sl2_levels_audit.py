#!/usr/bin/env python3
"""Mod-P spot check of HYP-9293 (admissible L_k(sl2), k = -2 + a/b) with independent code.

Per (weight D, charge c) sector:
  * singular vector at weight (a-1)b, charge 2(a-1)  (e_0, e_1, h_1, f_1 annihilate it);
  * maximal submodule M by the recursion  w in M_D  iff  a_1 w in M_{D-1}  (no character formula);
  * I = U(g[t^-1]t^-1) U(g) v, compared with M;
  * grI (leading forms, Li degree = weight - #modes); I_0 = Li-0 part;
  * J by the recursion J_D = (I_0)_D + sum_x x J_{D-wt x} + d J_{D-1};
  * dim ker(pi) and minimal differential-ideal generators of grI per (D, Li, charge).
Usage: python sl2_levels_audit.py a b Dmax [P] [nomax]
  nomax: skip the maximal-submodule recursion (then I is the ideal generated by v; maximality is
         taken from the literature) -- used only for the expensive k = 3/2 spot check.
"""
import sys
import time
import flint
from alin import rref_vectors, rank, nullspace, leading_forms
from sl2mod import AffSl2, colored_partitions, charge, lidegree, pmul, pd, E, H, F

a, b, Dmax = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3])
P = int(sys.argv[4]) if len(sys.argv) > 4 else 2147483647
NOMAX = len(sys.argv) > 5 and sys.argv[5] == 'nomax'
one = flint.nmod(1, P)
k = one * (a - 2 * b) / b          # k = -2 + a/b
D0, c0 = (a - 1) * b, 2 * (a - 1)
t0 = time.time()
V = AffSl2(k, one)
sector = {}
for D in range(Dmax + 1):
    for m in colored_partitions(D):
        sector.setdefault((D, charge(m)), []).append(m)


def charges(D):
    return sorted(c for (DD, c) in sector if DD == D)


def log(*x):
    print(*x, flush=True)


log(f"L_k(sl2), k = -2 + {a}/{b}, mod {P}; singular vector expected at weight {D0}, charge {c0}")
# singular vectors at weights <= D0
for D in range(1, D0 + 1):
    for c in charges(D):
        Bs = sector[(D, c)]
        eqs = {}
        for (t, m) in [(E, 0), (E, 1), (H, 1), (F, 1)]:
            for bb in Bs:
                for mono, cc in V.act(t, m, bb).items():
                    eqs.setdefault((t, m, mono), {})[bb] = cc
        kk = nullspace(list(eqs.values()), Bs, P)
        if kk:
            log(f"  singular vectors at weight {D}, charge {c}: {len(kk)}")
            if (D, c) == (D0, c0):
                v = kk[0]
Kf = {(0, 0): flint.nmod_mat(1, 1, [1], P)}
dimL = {0: 1}
I = {}
gr = {}
J = {}
results = []
for D in range(1, Dmax + 1):
    totL = 0
    for c in (charges(D) if not NOMAX else []):
        Bs = sector[(D, c)]
        rows = []
        for (t, dc) in [(E, 2), (H, 0), (F, -2)]:
            key = (D - 1, c + dc)
            if key not in Kf or Kf[key].nrows() == 0:
                continue
            tgt = sector[key]
            idx = {m: i for i, m in enumerate(tgt)}
            A = flint.nmod_mat(len(tgt), len(Bs), P)
            for j, bb in enumerate(Bs):
                for mono, cc in V.act(t, 1, bb).items():
                    A[idx[mono], j] = cc
            Mb = Kf[key] * A
            ent = Mb.entries()
            nc = Mb.ncols()
            for i in range(Mb.nrows()):
                r = {Bs[j]: ent[i * nc + j] for j in range(nc) if ent[i * nc + j] != 0}
                if r:
                    rows.append(r)
        rr = rref_vectors(rows, Bs, P) if rows else []
        Km = flint.nmod_mat(len(rr), len(Bs), P)
        col = {m: j for j, m in enumerate(Bs)}
        for i, (_, row) in enumerate(rr):
            for mono, cc in row.items():
                Km[i, col[mono]] = cc
        Kf[(D, c)] = Km
        totL += len(rr)
    dimL[D] = totL
    if D < D0:
        continue
    # ideal
    for c in charges(D):
        Bs = sector[(D, c)]
        gens = []
        if D == D0:
            w = v
            seeds = [w]
            for _ in range(2 * (a - 1)):
                w = V.actv(F, 0, w)
                seeds.append(w)
            gens = [s for s in seeds if s and charge(next(iter(s))) == c]
        else:
            for (t, dc) in [(E, 2), (H, 0), (F, -2)]:
                for w in I.get((D - 1, c - dc), []):
                    g = V.actv(t, -1, w)
                    if g:
                        gens.append(g)
        I[(D, c)] = [row for _, row in rref_vectors(gens, Bs, P)] if gens else []
        gr[(D, c)] = leading_forms(I[(D, c)], Bs, degree=len, modulus=P) if I[(D, c)] else []
    dimI = sum(len(I[(D, c)]) for c in charges(D))
    dimM = sum(len(sector[(D, c)]) for c in charges(D)) - dimL[D] if not NOMAX else -1
    # J and ker
    kerinfo = {}
    geninfo = {}
    for c in charges(D):
        Bs = sector[(D, c)]
        I0 = [g for g in gr[(D, c)] if lidegree(next(iter(g))) == 0]
        jg = list(I0)
        subg = []
        for g in J.get((D - 1, c), []):
            jg.append(pd(g))
        for g in gr.get((D - 1, c), []):
            subg.append(pd(g))
        for w in range(1, D - D0 + 1):
            for t in (E, H, F):
                cc_ = c - {E: 2, H: 0, F: -2}[t]
                xv = {((w, t),): one}
                for g in J.get((D - w, cc_), []):
                    jg.append(pmul(xv, g))
                for g in gr.get((D - w, cc_), []):
                    subg.append(pmul(xv, g))
        J[(D, c)] = [row for _, row in rref_vectors(jg, Bs, P)] if jg else []
        rg, rj = len(gr[(D, c)]), len(J[(D, c)])
        if rj:
            assert rank(gr[(D, c)] + J[(D, c)], Bs, P) == rg, "J not inside grI"
        # per Li degree
        for li in sorted({lidegree(next(iter(g))) for g in gr[(D, c)]}):
            ng = sum(1 for g in gr[(D, c)] if lidegree(next(iter(g))) == li)
            nj = sum(1 for g in J[(D, c)] if lidegree(next(iter(g))) == li)
            if ng - nj:
                kerinfo[(li, c)] = ng - nj
        subr = [row for _, row in rref_vectors(subg, Bs, P)] if subg else []
        for li in sorted({lidegree(next(iter(g))) for g in gr[(D, c)]}):
            ng = sum(1 for g in gr[(D, c)] if lidegree(next(iter(g))) == li)
            ns = sum(1 for g in subr if lidegree(next(iter(g))) == li)
            if ng - ns:
                geninfo[(li, c)] = ng - ns
    kertot = sum(kerinfo.values())
    log(f"D={D}: dimL={dimL[D]} dimI={dimI} dimM={dimM} I==M:{dimI == dimM}  ker(pi)={kertot} "
        f"{dict(sorted(kerinfo.items()))}  new generators {dict(sorted(geninfo.items()))}  [{time.time() - t0:.0f}s]")
log("dim L:", [dimL[D] for D in range(Dmax + 1)])
