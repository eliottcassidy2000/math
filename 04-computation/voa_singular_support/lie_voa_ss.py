#!/usr/bin/env python3
"""Generic singular-support engine for vertex (super)algebras whose modes form a
Lie (super)algebra with central extension: Virasoro, affine Kac-Moody, N=1 and
N=2 superconformal, ...

Conventions.  A mode is (w, t): generator t, w = weight it adds (so L_{-n} is
(n, L), e_{-n} is (n, e), G_{-r} is (r, G); annihilators have w < h_t).  A PBW
monomial is a tuple of creation modes (w >= h_t) sorted by key (w, t)
descending; odd modes appear at most once.  Its Li-degree is sum(w - h_t).

Li filtration.  F^p V^univ = span of PBW monomials of Li-degree >= p, and
gr_F V^univ = supercommutative C[x_{t,j}], x_{t,j} <-> mode (h_t + j, t),
d x_{t,j} = (j+1) x_{t,j+1}.  The symbol of u is its lowest-Li-degree part.

For L = V^univ / I (I generated by given singular vectors), grI = symbols of
I; J = (grI in Li-degree 0)_d is the defining ideal of the arc space of the
C_2-algebra R_L; L is classically free iff grI = J iff grI has no minimal
differential-ideal generator of positive Li-degree.  Minimal generator count at
trigrade (Delta, p, charge):
    dim grI - dim( sum_{t,j} x_{t,j} grI + d grI )      [graded Nakayama]

All ranks modulo a prime P (two primes for confirmation); exact rationals for
singular vectors via sympy.
"""
import sys, time, functools
from fractions import Fraction
import flint

# ============================================================== algebras
class ModeAlgebra:
    """Subclasses define: gens = [(name, h, parity, charge_tuple)], bracket(m1, m2)."""
    name = "abstract"

    def __init__(self, P):
        self.P = P
        self.h = [g[1] for g in self.gens]
        self.par = [g[2] for g in self.gens]
        self.chg = [g[3] for g in self.gens]
        self._apply_cache = {}

    def F(self, x):
        """Reduce a rational/int to F_P."""
        P = self.P
        if isinstance(x, Fraction):
            return x.numerator % P * pow(x.denominator % P, -1, P) % P
        return x % P

    def is_creation(self, m):
        w, t = m
        return w >= self.h[t]

    # bracket returns (list of (mode, coeff_in_F_P), central_coeff_in_F_P)
    def bracket(self, m1, m2):
        raise NotImplementedError

    def apply(self, m, mono):
        """Mode m applied to PBW monomial `mono` (tuple), result dict mono->coef mod P."""
        key = (m, mono)
        c = self._apply_cache.get(key)
        if c is not None:
            return c
        res = self._apply(m, mono)
        self._apply_cache[key] = res
        return res

    def _apply(self, m, mono):
        P = self.P
        w, t = m
        if not mono:
            if w < self.h[t]:
                return {}
            return {(m,): 1}
        first = mono[0]
        if self.is_creation(m):
            if m > first:
                return {(m,) + mono: 1}
            if m == first:
                if self.par[t] == 0:
                    return {(m,) + mono: 1}
                # odd: X X rest = 1/2 [X, X] rest
                out = {}
                terms, cen = self.bracket(m, m)
                inv2 = pow(2, -1, P)
                for (mm, co) in terms:
                    for mo, cc in self.apply(mm, mono[1:]).items():
                        out[mo] = (out.get(mo, 0) + co * cc * inv2) % P
                if cen:
                    out[mono[1:]] = (out.get(mono[1:], 0) + cen * inv2) % P
                return {k: v for k, v in out.items() if v}
        # commute m past first: m Y rest = s Y (m rest) + [m, Y} rest
        Y = first
        rest = mono[1:]
        s = -1 if (self.par[t] and self.par[Y[1]]) else 1
        out = {}
        for mo, co in self.apply(m, rest).items():
            for mo2, co2 in self.apply(Y, mo).items():
                out[mo2] = (out.get(mo2, 0) + s * co * co2) % P
        terms, cen = self.bracket(m, Y)
        for (mm, cb) in terms:
            for mo, co in self.apply(mm, rest).items():
                out[mo] = (out.get(mo, 0) + cb * co) % P
        if cen:
            out[rest] = (out.get(rest, 0) + cen) % P
        return {k: v for k, v in out.items() if v}

    def apply_vec(self, m, vec):
        P = self.P
        out = {}
        for mono, co in vec.items():
            for mo, cc in self.apply(m, mono).items():
                out[mo] = (out.get(mo, 0) + co * cc) % P
        return {k: v for k, v in out.items() if v}

    # ---------------------------------------------------------- PBW bases
    def creation_modes(self, Dmax):
        out = []
        for t, (nm, h, par, ch) in enumerate(self.gens):
            w = h
            while w <= Dmax:
                out.append((w, t))
                w += 1
        return sorted(out, reverse=True)

    def pbw_basis(self, Dmax):
        """dict (Delta, charge) -> list of monomials (all Li-degrees)."""
        modes = self.creation_modes(Dmax)
        out = {}
        def rec(i, cur, wsum, ch):
            out.setdefault((wsum, ch), []).append(tuple(cur))
            for j in range(i, len(modes)):
                m = modes[j]
                w, t = m
                if wsum + w > Dmax:
                    continue
                if self.par[t] and cur and cur[-1] == m:
                    continue  # odd modes at most once
                if cur and m > cur[-1]:
                    continue
                cur.append(m)
                rec(j if not self.par[t] else j + 1, cur, wsum + w,
                    tuple(a + b for a, b in zip(ch, self.chg[t])))
                cur.pop()
        rec(0, [], 0, tuple(0 for _ in self.chg[0]))
        return out

    def li(self, mono):
        return sum(w - self.h[t] for (w, t) in mono)


# ---------------------------------------------------------------- Virasoro
class Virasoro(ModeAlgebra):
    name = "Vir"
    def __init__(self, c, P):
        self.gens = [("L", 2, 0, ())]
        self.c = c
        super().__init__(P)
        self.cP = self.F(c)

    def bracket(self, m1, m2):
        # L_a = mode (w=-a); [L_a, L_b] = (a-b) L_{a+b} + c/12 (a^3-a) delta
        a, b = -m1[0], -m2[0]
        terms = []
        if a - b:
            terms.append(((-(a + b), 0), (a - b) % self.P))
        cen = 0
        if a + b == 0:
            cen = self.cP * self.F(Fraction(a ** 3 - a, 12)) % self.P
        return terms, cen

    def positive_ops(self):
        return [(-1, 0), (-2, 0)]  # L_1, L_2


# ---------------------------------------------------------------- affine sl2
class AffineSL2(ModeAlgebra):
    """e (charge +2), h (0), f (-2); (e|f)=1, (h|h)=2.  Order of types: e=0, h=1, f=2."""
    name = "sl2"
    def __init__(self, k, P):
        self.gens = [("e", 1, 0, (2,)), ("h", 1, 0, (0,)), ("f", 1, 0, (-2,))]
        self.k = k
        super().__init__(P)
        self.kP = self.F(k)

    def bracket(self, m1, m2):
        P = self.P
        a, ta = -m1[0], m1[1]   # mode index a (x_a), type
        b, tb = -m2[0], m2[1]
        n = a + b
        terms = []
        cen = 0
        E, H, Fm = 0, 1, 2
        if ta == H and tb == H:
            if n == 0:
                cen = 2 * self.kP * a % P
        elif ta == H and tb == E:
            terms.append(((-n, E), 2))
        elif ta == E and tb == H:
            terms.append(((-n, E), P - 2))
        elif ta == H and tb == Fm:
            terms.append(((-n, Fm), P - 2))
        elif ta == Fm and tb == H:
            terms.append(((-n, Fm), 2))
        elif ta == E and tb == Fm:
            terms.append(((-n, H), 1))
            if n == 0:
                cen = self.kP * a % P
        elif ta == Fm and tb == E:
            terms.append(((-n, H), P - 1))
            if n == 0:
                cen = self.kP * a % P
        return terms, cen

    def positive_ops(self):
        # e_0 and f_1 (simple root vectors of the affine Borel)
        return [(0, 0), (-1, 2)]


# ---------------------------------------------------------------- N=1 super-Virasoro (NS)
class NeveuSchwarz(ModeAlgebra):
    name = "NS"
    def __init__(self, c, P):
        self.gens = [("L", 2, 0, ()), ("G", Fraction(3, 2), 1, ())]
        self.c = c
        super().__init__(P)
        self.cP = self.F(c)

    def bracket(self, m1, m2):
        P = self.P
        a, ta = -m1[0], m1[1]
        b, tb = -m2[0], m2[1]
        n = a + b
        terms, cen = [], 0
        if ta == 0 and tb == 0:
            if a - b:
                terms.append(((-n, 0), self.F(Fraction(a - b))))
            if n == 0:
                cen = self.cP * self.F(Fraction(a ** 3 - a, 12)) % P
        elif ta == 0 and tb == 1:
            co = Fraction(a, 2) - b
            if co:
                terms.append(((-n, 1), self.F(co)))
        elif ta == 1 and tb == 0:
            co = -(Fraction(b, 2) - a)
            if co:
                terms.append(((-n, 1), self.F(co)))
        else:  # {G_a, G_b} = 2 L_{a+b} + c/3 (a^2 - 1/4) delta
            terms.append(((-n, 0), 2))
            if n == 0:
                cen = self.cP * self.F(Fraction(1, 3) * (a * a - Fraction(1, 4))) % P
        return terms, cen

    def positive_ops(self):
        return [(Fraction(-1, 2), 1), (Fraction(-3, 2), 1)]  # G_{1/2}, G_{3/2} generate NS_+


# ---------------------------------------------------------------- engine
class SingularSupport:
    def __init__(self, alg, Dmax, singular_vectors, verbose=True):
        """singular_vectors: list of dicts mono->coef (mod P) generating I (as a module);
        each must be a lowest-weight-type vector; I is generated by repeatedly applying
        the 'generating' creation modes plus zero-mode lowering operators given by alg."""
        self.alg = alg
        self.P = alg.P
        self.Dmax = Dmax
        self.sv = singular_vectors
        self.verbose = verbose
        self.basis = alg.pbw_basis(Dmax)
        # columns per (Delta, charge): ordered by Li-degree ascending, then key
        self.cols = {}
        self.colidx = {}
        for key, monos in self.basis.items():
            srt = sorted(monos, key=lambda mo: (alg.li(mo), tuple(-x for m in mo for x in (m[0], m[1]))))
            self.cols[key] = srt
            self.colidx[key] = {mo: i for i, mo in enumerate(srt)}

    def weights(self):
        ws = sorted({k[0] for k in self.basis})
        return ws

    def run(self, gen_modes, extra_ops=()):
        """gen_modes: creation modes whose action generates I from lower weights
        (together with extra_ops = weight-0 operators applied to closure)."""
        alg, P = self.alg, self.P
        I = {}       # (Delta, charge) -> list of rows (RREF)
        grI = {}     # (Delta, Li, charge) -> list of dict symbols (RREF in block)
        self.J = {}  # (Delta, Li, charge) -> basis of arc ideal block
        self.arc_table = []
        self.gens_found = []
        self.table = []
        # seed
        seeds = {}
        for v in self.sv:
            some = next(iter(v))
            D = sum(m[0] for m in some)
            ch = tuple(sum(alg.chg[t][i] for (w, t) in some) for i in range(len(alg.chg[0])))
            seeds.setdefault((D, ch), []).append(v)
        for D in self.weights():
            t0 = time.time()
            keys = [k for k in self.basis if k[0] == D]
            # build candidate vectors for each charge
            cand = {k: [] for k in keys}
            for k in keys:
                for v in seeds.get(k, []):
                    cand[k].append(dict(v))
            for m in gen_modes:
                w, t = m
                Dsrc = D - w
                for k2, rows in I.items():
                    if k2[0] != Dsrc:
                        continue
                    tgt = (D, tuple(a + b for a, b in zip(k2[1], alg.chg[t])))
                    if tgt not in cand:
                        continue
                    cols2 = self.cols[k2]
                    for row in rows:
                        vec = {cols2[j]: x for j, x in enumerate(row) if x}
                        cand[tgt].append(alg.apply_vec(m, vec))
            # closure under extra weight-0 operators
            for k in keys:
                pass
            changed = True
            rowsD = {}
            for k in keys:
                rowsD[k] = self._rref(cand[k], k)
            if extra_ops:
                while changed:
                    changed = False
                    for op in extra_ops:
                        w, t = op
                        for k in keys:
                            tgt = (D, tuple(a + b for a, b in zip(k[1], alg.chg[t])))
                            if tgt not in rowsD:
                                continue
                            cols = self.cols[k]
                            new = [alg.apply_vec(op, {cols[j]: x for j, x in enumerate(r) if x}) for r in rowsD[k]]
                            colsT = self.cols[tgt]
                            old = [{colsT[j]: x for j, x in enumerate(r) if x} for r in rowsD[tgt]]
                            merged = self._rref(old + new, tgt)
                            if len(merged) > len(rowsD[tgt]):
                                rowsD[tgt] = merged
                                changed = True
            for k in keys:
                I[k] = rowsD[k]
            # symbols
            stats = {}
            for k in keys:
                cols = self.cols[k]
                bylevel = {}
                for row in I[k]:
                    piv = next(j for j, x in enumerate(row) if x)
                    p = alg.li(cols[piv])
                    sym = {cols[j]: x for j, x in enumerate(row) if x and alg.li(cols[j]) == p}
                    bylevel.setdefault(p, []).append(sym)
                for p, syms in bylevel.items():
                    grI[(D, p, k[1])] = syms
            # arc ideal J = (grI in Li-degree 0)_d, computed blockwise
            kerdim = 0
            Jdim = 0
            for k in keys:
                ch = k[1]
                lis = sorted({alg.li(mo) for mo in self.cols[k]})
                for p in lis:
                    if p == 0:
                        Jb = grI.get((D, 0, ch), [])
                    else:
                        dec = self.decomposables(self.J, D, p, ch)
                        Jb = self._rref_block(dec, D, p, ch) if dec else []
                    self.J[(D, p, ch)] = Jb
                    Jdim += len(Jb)
                    kerdim += len(grI.get((D, p, ch), [])) - len(Jb)
            self.arc_table.append((D, kerdim, Jdim))
            # generator count per (D, p, charge)
            newgens = []
            for k in keys:
                ch = k[1]
                lis = sorted({alg.li(mo) for mo in self.cols[k]})
                for p in lis:
                    g = grI.get((D, p, ch), [])
                    if not g:
                        continue
                    dec = self.decomposables(grI, D, p, ch)
                    rk_dec = self._rank(dec, D, p, ch)
                    rk_all = self._rank(dec + g, D, p, ch)
                    assert rk_all == len(g), f"decomposables escape grI at {(D, p, ch)}"
                    nn = len(g) - rk_dec
                    if nn:
                        newgens.append((p, ch, nn))
                        self.gens_found.append((D, p, ch, nn))
            self.grI = grI
            self.I = I
            dimV = sum(len(self.cols[k]) for k in keys)
            dimI = sum(len(I[k]) for k in keys)
            pos = [(p, ch, nn) for (p, ch, nn) in newgens if p > 0]
            self.table.append((D, dimV, dimI, newgens))
            if self.verbose:
                print(f"D={str(D):>5} dimV={dimV:7d} dimI={dimI:7d} dimL={dimV-dimI:7d} arcHS={dimV-Jdim:7d} ker={kerdim:5d} "
                      f"gens(Li,charge,#)={newgens}{'  <-- NON-ARC' if pos else ''} ({time.time()-t0:.1f}s)",
                      flush=True)
        return self.gens_found

    def _block_cols(self, D, p, ch):
        return [mo for mo in self.cols[(D, ch)] if self.alg.li(mo) == p]

    def _rank(self, vecs, D, p, ch):
        if not vecs:
            return 0
        cols = self._block_cols(D, p, ch)
        idx = {mo: i for i, mo in enumerate(cols)}
        n = len(cols)
        P = self.P
        data = []
        for v in vecs:
            row = [0] * n
            for mo, co in v.items():
                row[idx[mo]] = (row[idx[mo]] + co) % P
            data.extend(row)
        M = flint.nmod_mat(len(vecs), n, data, P)
        return M.rank()

    def _rref_block(self, vecs, D, p, ch):
        cols = self._block_cols(D, p, ch)
        idx = {mo: i for i, mo in enumerate(cols)}
        n = len(cols)
        P = self.P
        if not vecs or n == 0:
            return []
        data = []
        for v in vecs:
            row = [0] * n
            for mo, co in v.items():
                row[idx[mo]] = (row[idx[mo]] + co) % P
            data.extend(row)
        M = flint.nmod_mat(len(vecs), n, data, P)
        R, rk = M.rref()
        out = []
        for r in R.tolist()[:rk]:
            out.append({cols[j]: int(x) for j, x in enumerate(r) if int(x)})
        return out

    def _rref(self, vecs, key):
        P = self.P
        cols = self.cols[key]
        idx = self.colidx[key]
        n = len(cols)
        if not vecs or n == 0:
            return []
        data = []
        for v in vecs:
            row = [0] * n
            for mo, co in v.items():
                row[idx[mo]] = (row[idx[mo]] + co) % P
            data.extend(row)
        M = flint.nmod_mat(len(vecs), n, data, P)
        R, rk = M.rref()
        return [[int(x) for x in r] for r in R.tolist()[:rk]]

    # ---------------------------------------------------------- polynomial operations
    def mult_var(self, vec, var):
        """Multiply symbol vector by variable var = mode (w, t) (supercommutative)."""
        alg, P = self.alg, self.P
        out = {}
        odd_v = alg.par[var[1]]
        for mo, co in vec.items():
            if odd_v and var in mo:
                continue
            lst = list(mo)
            # insert var into descending order; sign = (-1)^(#odd modes before insertion point)
            pos = 0
            while pos < len(lst) and lst[pos] > var:
                pos += 1
            # count odd modes strictly before pos (var placed at front then moved right past them)
            nodd = sum(1 for m in lst[:pos] if alg.par[m[1]]) if odd_v else 0
            sgn = -1 if (nodd % 2) else 1
            new = tuple(lst[:pos] + [var] + lst[pos:])
            out[new] = (out.get(new, 0) + sgn * co) % P
        return {k: v for k, v in out.items() if v}

    def deriv(self, vec):
        alg, P = self.alg, self.P
        out = {}
        for mo, co in vec.items():
            lst = list(mo)
            for i, (w, t) in enumerate(lst):
                j = w - alg.h[t]
                fac = j + 1
                newm = (w + 1, t)
                rest = lst[:i] + lst[i + 1:]
                if alg.par[t] and newm in rest:
                    continue
                # remove position i (sign: moving an odd element from position i to front)
                nodd_before = sum(1 for m in lst[:i] if alg.par[m[1]]) if alg.par[t] else 0
                s1 = -1 if nodd_before % 2 else 1
                # now insert newm into rest from the front
                pos = 0
                while pos < len(rest) and rest[pos] > newm:
                    pos += 1
                nodd2 = sum(1 for m in rest[:pos] if alg.par[m[1]]) if alg.par[t] else 0
                s2 = -1 if nodd2 % 2 else 1
                new = tuple(rest[:pos] + [newm] + rest[pos:])
                out[new] = (out.get(new, 0) + s1 * s2 * self.alg.F(fac) * co) % P
        return {k: v for k, v in out.items() if v}

    def decomposables(self, grI, D, p, ch):
        alg = self.alg
        out = []
        for t, (nm, h, par, chg) in enumerate(alg.gens):
            for j in range(0, int(p) + 1):
                var = (h + j, t)
                Ds = D - h - j
                ps = p - j
                chs = tuple(a - b for a, b in zip(ch, chg))
                for v in grI.get((Ds, ps, chs), []):
                    out.append(self.mult_var(v, var))
        for v in grI.get((D - 1, p - 1, ch), []):
            dv = self.deriv(v)
            if dv:
                out.append(dv)
        return [v for v in out if v]


# ---------------------------------------------------------------- singular vectors
def find_singular(alg, D, ch, extra_kill=()):
    """Vectors at (D, ch) annihilated by alg.positive_ops() (and extra_kill). Mod P nullspace."""
    P = alg.P
    basis = alg.pbw_basis(D)[(D, ch)]
    ops = list(alg.positive_ops()) + list(extra_kill)
    eqs = {}
    for j, mo in enumerate(basis):
        for op in ops:
            img = alg.apply(op, mo)
            for mo2, co in img.items():
                eqs.setdefault((op, mo2), [0] * len(basis))[j] = (eqs.setdefault((op, mo2), [0] * len(basis))[j] + co) % P
    rows = list(eqs.values())
    if not rows:
        return [{mo: 1} for mo in basis]
    M = flint.nmod_mat(len(rows), len(basis), [x for r in rows for x in r], P)
    ns, nullity = M.nullspace()
    vecs = []
    nsl = ns.tolist()
    for col in range(nullity):
        v = {basis[i]: int(nsl[i][col]) for i in range(len(basis)) if int(nsl[i][col])}
        vecs.append(v)
    return vecs
