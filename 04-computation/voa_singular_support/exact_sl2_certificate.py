#!/usr/bin/env python3
"""EXACT (over Q) singular-support computation for L_k(sl2), k admissible, up to weight Dmax.

Everything is rational arithmetic (Fractions for the mode action, flint.fmpq_mat for RREF/rank),
so the resulting dimensions are exact, not mod-p.  Used for THM-4672 (k = -1/2, weight 7).

Pipeline (same as lie_voa_ss.py, exact):
  v      = singular vector at weight (a-1)b, charge 2(a-1): nullspace of {e_0, f_1} (exact)
  I_D    = span( x_{-1} I_{D-1} : x in {e,h,f} ) closed under e_0, f_0          (exact RREF)
  grI    = lowest-Li-degree components of RREF rows (columns ordered by Li ascending)
  J      = differential ideal generated by grI in Li degree 0 (arc ideal of R_V)
  ker pi = grI / J   per (weight, Li, charge)
Also checks dim L_D against the Kac-Wakimoto character (kw_char.kw).
Usage: python exact_sl2_certificate.py kp kq Dmax
"""
import sys, functools
from fractions import Fraction
import flint
from kw_char import kw

E, H, Fm = 0, 1, 2
CHG = {E: 2, H: 0, Fm: -2}

def make(k):
    @functools.lru_cache(maxsize=None)
    def bracket(m1, m2):
        a, ta = -m1[0], m1[1]
        b, tb = -m2[0], m2[1]
        n = a + b
        terms, cen = [], Fraction(0)
        if ta == H and tb == H:
            if n == 0: cen = 2 * k * a
        elif ta == H and tb == E: terms = [((-n, E), Fraction(2))]
        elif ta == E and tb == H: terms = [((-n, E), Fraction(-2))]
        elif ta == H and tb == Fm: terms = [((-n, Fm), Fraction(-2))]
        elif ta == Fm and tb == H: terms = [((-n, Fm), Fraction(2))]
        elif ta == E and tb == Fm:
            terms = [((-n, H), Fraction(1))]
            if n == 0: cen = k * a
        elif ta == Fm and tb == E:
            terms = [((-n, H), Fraction(-1))]
            if n == 0: cen = k * a
        return tuple(terms), cen

    @functools.lru_cache(maxsize=None)
    def apply(m, mono):
        w, t = m
        if not mono:
            return () if w < 1 else (((m,), Fraction(1)),)
        first = mono[0]
        if w >= 1 and m >= first:
            return (((m,) + mono, Fraction(1)),)
        Y, rest = first, mono[1:]
        out = {}
        for mo, co in apply(m, rest):
            for mo2, co2 in apply(Y, mo):
                out[mo2] = out.get(mo2, 0) + co * co2
        terms, cen = bracket(m, Y)
        for mm, cb in terms:
            for mo, co in apply(mm, rest):
                out[mo] = out.get(mo, 0) + cb * co
        if cen:
            out[rest] = out.get(rest, 0) + cen
        return tuple((kk, v) for kk, v in out.items() if v)
    return apply

def apply_vec(apply, m, vec):
    out = {}
    for mono, co in vec.items():
        for mo, cc in apply(m, mono):
            out[mo] = out.get(mo, 0) + co * cc
    return {kk: v for kk, v in out.items() if v}

def pbw(Dmax):
    modes = sorted([(w, t) for w in range(1, Dmax + 1) for t in (E, H, Fm)], reverse=True)
    out = {}
    def rec(i, cur, ws, ch):
        out.setdefault((ws, ch), []).append(tuple(cur))
        for j in range(i, len(modes)):
            m = modes[j]
            if ws + m[0] > Dmax: continue
            cur.append(m); rec(j, cur, ws + m[0], ch + CHG[m[1]]); cur.pop()
    rec(0, [], 0, 0)
    return out

li = lambda mono: sum(w - 1 for (w, t) in mono)

def to_mat(vecs, cols):
    idx = {c: i for i, c in enumerate(cols)}
    M = flint.fmpq_mat(len(vecs), len(cols))
    for r, v in enumerate(vecs):
        for mo, co in v.items():
            M[r, idx[mo]] = flint.fmpq(co.numerator, co.denominator)
    return M

def rref_vecs(vecs, cols):
    if not vecs or not cols:
        return []
    R, rk = to_mat(vecs, cols).rref()
    out = []
    for i in range(rk):
        v = {}
        for j, c in enumerate(cols):
            x = R[i, j]
            if x != 0:
                v[c] = Fraction(int(x.p), int(x.q))
        out.append(v)
    return out

def rank(vecs, cols):
    if not vecs or not cols:
        return 0
    return to_mat(vecs, cols).rank()

def mult_var(vec, var):
    out = {}
    for mo, co in vec.items():
        new = tuple(sorted(mo + (var,), reverse=True))
        out[new] = out.get(new, 0) + co
    return out

def deriv(vec):
    out = {}
    for mo, co in vec.items():
        lst = list(mo)
        for i, (w, t) in enumerate(lst):
            new = tuple(sorted(lst[:i] + [(w + 1, t)] + lst[i + 1:], reverse=True))
            out[new] = out.get(new, 0) + co * w     # d x_{t,j} = (j+1) x_{t,j+1}, j+1 = w
    return {kk: v for kk, v in out.items() if v}

SHOW = None

def main():
    global SHOW
    kp, kq, Dmax = map(int, sys.argv[1:4])
    if len(sys.argv) > 6:
        SHOW = tuple(int(x) for x in sys.argv[4:7])
    k = Fraction(kp, kq)
    a, b = (k + 2).numerator, (k + 2).denominator
    D0, ch0 = (a - 1) * b, 2 * (a - 1)
    apply = make(k)
    basis = pbw(Dmax)
    cols = {key: sorted(ms, key=lambda mo: (li(mo), mo)) for key, ms in basis.items()}
    # exact singular vector
    B = cols[(D0, ch0)]
    eqs = {}
    for j, mo in enumerate(B):
        for op in ((0, E), (-1, Fm)):
            for mo2, co in apply(op, mo):
                eqs.setdefault((op, mo2), {})[j] = co
    rows = list(eqs.values())
    M = flint.fmpq_mat(len(rows), len(B))
    for r, d in enumerate(rows):
        for j, co in d.items():
            M[r, j] = flint.fmpq(co.numerator, co.denominator)
    # nullspace over Q via rref
    R, rk = M.rref()
    pivots = []
    for i in range(rk):
        pivots.append(next(j for j in range(len(B)) if R[i, j] != 0))
    free = [j for j in range(len(B)) if j not in pivots]
    assert len(free) == 1, f"singular space dim {len(free)}"
    fj = free[0]
    v = {B[fj]: Fraction(1)}
    for i, pj in enumerate(pivots):
        x = R[i, fj]
        if x != 0:
            v[B[pj]] = -Fraction(int(x.p), int(x.q))
    print(f"k={k}: exact singular vector at weight {D0}, charge {ch0}, {len(v)} terms")
    tot, _, _ = kw(a, b, Dmax)
    I, grI, J = {}, {}, {}
    for D in range(0, Dmax + 1):
        keys = sorted(kk for kk in basis if kk[0] == D)
        cand = {kk: [] for kk in keys}
        if D == D0:
            cand[(D0, ch0)].append(v)
        for kk in keys:
            for t in (E, H, Fm):
                src = (D - 1, kk[1] - CHG[t])
                for vec in I.get(src, []):
                    cand[kk].append(apply_vec(apply, (1, t), vec))
        rowsD = {kk: rref_vecs(cand[kk], cols[kk]) for kk in keys}
        changed = True
        while changed:
            changed = False
            for op in ((0, Fm), (0, E)):
                for kk in keys:
                    tgt = (D, kk[1] + CHG[op[1]])
                    if tgt not in rowsD: continue
                    new = [apply_vec(apply, op, vec) for vec in rowsD[kk]]
                    merged = rref_vecs(rowsD[tgt] + [x for x in new if x], cols[tgt])
                    if len(merged) > len(rowsD[tgt]):
                        rowsD[tgt] = merged; changed = True
        dimV = dimI = kerD = 0
        for kk in keys:
            I[kk] = rowsD[kk]
            dimV += len(cols[kk]); dimI += len(I[kk])
            bylev = {}
            for row in I[kk]:
                p = min(li(mo) for mo in row)
                bylev.setdefault(p, []).append({mo: c for mo, c in row.items() if li(mo) == p})
            for p in range(0, D + 1):
                blk = [mo for mo in cols[kk] if li(mo) == p]
                g = bylev.get(p, [])
                grI[(D, p, kk[1])] = g
                if p == 0:
                    Jb = g
                else:
                    dec = []
                    for t in (E, H, Fm):
                        for j in range(0, p + 1):
                            for vec in J.get((D - 1 - j, p - j, kk[1] - CHG[t]), []):
                                dec.append(mult_var(vec, (1 + j, t)))
                    for vec in J.get((D - 1, p - 1, kk[1]), []):
                        dv = deriv(vec)
                        if dv: dec.append(dv)
                    Jb = rref_vecs(dec, blk) if dec else []
                J[(D, p, kk[1])] = Jb
                if g:
                    rJ = len(Jb); rg = len(g)
                    rboth = rank(g + Jb, blk)
                    assert rboth == rg, f"J not inside grI at {(D, p, kk[1])}"
                    if rg > rJ:
                        kerD += rg - rJ
                        if D <= 9:
                            print(f"   ker pi at weight {D}, Li {p}, charge {kk[1]}: dim {rg - rJ}")
                        if (D, p, kk[1]) == SHOW:
                            # canonical representative: RREF of J, then reduce grI rows modulo J, RREF the rest
                            Jr = rref_vecs(Jb, blk) if Jb else []
                            reps = []
                            for gvec in g:
                                vv = dict(gvec)
                                for jr in Jr:
                                    piv = next(c for c in blk if jr.get(c, 0) != 0)
                                    if vv.get(piv, 0) != 0:
                                        f = vv[piv] / jr[piv]
                                        for c2, x in jr.items():
                                            vv[c2] = vv.get(c2, 0) - f * x
                                        vv = {c2: x for c2, x in vv.items() if x != 0}
                                if vv: reps.append(vv)
                            reps = rref_vecs(reps, blk)
                            names = {E: 'e', H: 'h', Fm: 'f'}
                            for rv in reps:
                                terms = [f"({c}){'*'.join(names[t]+'_'+str(w-1) for (w,t) in mo)}" for mo, c in rv.items()]
                                print("   NON-ARC representative:", " + ".join(terms))
        assert dimV - dimI == tot[D], f"dim L mismatch at {D}: {dimV - dimI} vs KW {tot[D]}"
        print(f"D={D}: dim V={dimV} dim I={dimI} dim L={dimV - dimI} (= KW) ker pi={kerD}", flush=True)

if __name__ == '__main__':
    main()
