#!/usr/bin/env python3
"""N=2 minimal model at c = 3k/(k+2) (chiral algebra of the LG model W = x^(k+2)):
python run_n2.py k Dmax [prime]; ideal generated by the weight-(k+1) charge-0 singular vector,
dims cross-checked against max_submodule (no-assumption) dims."""
import sys
from fractions import Fraction
from n2_sca import N2SCA, L, J, GP, GM
from lie_voa_ss import SingularSupport, find_singular
from max_submodule import simple_quotient_dims, per_weight
kk, Dmax = int(sys.argv[1]), int(sys.argv[2]); P = int(sys.argv[3]) if len(sys.argv) > 3 else 2147483647
c = Fraction(3 * kk, kk + 2)
alg = N2SCA(c, P)
sv = find_singular(alg, kk + 1, (0,))
print(f"N=2 k={kk} c={c}: singular vectors at weight {kk+1} charge 0: {len(sv)}", flush=True)
ss = SingularSupport(alg, Dmax, sv)
h = Fraction(1, 2)
ss.run(gen_modes=[(h, GP), (h, GM), (1, J)])
eng = {}
for (D, dV, dI, ng) in ss.table:
    eng[D] = dV - dI
ref = per_weight(simple_quotient_dims(alg, Dmax, [(-h, GP), (-h, GM), (-1, L), (-2, L), (-1, J)]))
mism = [(D, eng.get(D), ref.get(D)) for D in ref if eng.get(D) != ref.get(D)]
print("dims vs max-submodule:", "MATCH" if not mism else f"MISMATCH {mism[:5]}")
print("non-arc generators (D, Li, charge, #):", [g for g in ss.gens_found if g[1] > 0] or "none")
