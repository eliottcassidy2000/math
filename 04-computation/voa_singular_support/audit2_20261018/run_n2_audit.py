#!/usr/bin/env python3
"""Audit of THM-4673 / HYP-9295.  usage: python run_n2_audit.py k Dmax [P]
- universal N=2 vacuum module at c = 3k/(k+2), maximal submodule = radical of the contravariant form (every block);
- singular vectors (common kernel of all positive modes of weight <= 2) at each (weight, charge) up to weight k+2;
- submodule generated by the singular vectors of weight k+1 compared with the radical;
- simple-quotient character compared with an independent formula (k=1: lattice sqrt3 Z; k=2: Ising x U(1));
- gr I (Li-ordered echelon), arc ideal J = (gr I in Li 0)_d, ker pi = gr I / J, minimal generators of gr I."""
import sys, time
from fractions import Fraction
import flint
from aud_algebras import N2, L_, J_, GP, GM
from vamod import GradedAnalysis, rowspace_basis

k = int(sys.argv[1]); Dmax = Fraction(sys.argv[2]); P = int(sys.argv[3]) if len(sys.argv) > 3 else 2147483647
W2max = int(2 * Dmax)
c = Fraction(3 * k, k + 2)
va = N2(c, P)
t0 = time.time()
G = va.gram_all(W2max)
I = va.radical(G)
print(f'N=2 k={k} c={c} P={P}: gram+radical to weight {Dmax} in {time.time()-t0:.1f}s', flush=True)

# ---- simple quotient dims by (weight, charge)
dimL = {}
for (W2, ch), (B, Gm) in G.items():
    dimL[(W2, ch)] = len(B) - len(I[(W2, ch)])

# ---- independent character
def partitions_series(N):
    p = [0] * (N + 1); p[0] = 1
    for n in range(1, N + 1):
        for i in range(n, N + 1):
            p[i] += p[i - n]
    return p

pN = partitions_series(W2max)
ref = {}
if k == 1:
    # V_{sqrt3 Z}: sum_n y^n q^{3n^2/2} / (q)_inf ; in doubled weight: 3 n^2 + 2*partition
    for n in range(-10, 11):
        base = 3 * n * n
        for j in range(0, W2max + 1):
            W2 = base + 2 * j
            if W2 <= W2max:
                ref[(W2, n)] = ref.get((W2, n), 0) + pN[j]
elif k == 2:
    # Ising (c=1/2) x Fock: charge m sector = q^{m^2} chi_{h(m)} / (q)_inf, h = 0 (m even), 1/2 (m odd)
    # chi_0 +- chi_1/2 = prod (1 +- q^{n+1/2}); work in doubled weight
    N = W2max + 2
    plus = [0] * (N + 1); plus[0] = 1
    minus = [0] * (N + 1); minus[0] = 1
    for n2 in range(1, N + 1, 2):  # q^{n+1/2} -> doubled exponent odd
        for i in range(N, n2 - 1, -1):
            plus[i] += plus[i - n2]
            minus[i] -= minus[i - n2]
    chi0 = [(plus[i] + minus[i]) // 2 for i in range(N + 1)]      # even doubled exponents
    chi12 = [(plus[i] - minus[i]) // 2 for i in range(N + 1)]     # odd doubled exponents
    pd = [0] * (N + 1)
    for j in range(0, N // 2 + 1):
        pd[2 * j] = pN[j] if j < len(pN) else 0
    def conv(a, b):
        out = [0] * (N + 1)
        for i in range(N + 1):
            if a[i]:
                for j in range(N + 1 - i):
                    out[i + j] += a[i] * b[j]
        return out
    s0 = conv(chi0, pd); s12 = conv(chi12, pd)
    for m in range(-10, 11):
        base = 2 * m * m
        ser = s0 if m % 2 == 0 else s12
        for e in range(0, W2max + 1 - base):
            if ser[e]:
                ref[(base + e, m)] = ref.get((base + e, m), 0) + ser[e]
if ref:
    bad = [(key, dimL.get(key, 0), ref.get(key, 0)) for key in set(dimL) | set(ref)
           if key[0] <= W2max and dimL.get(key, 0) != ref.get(key, 0)]
    print('simple quotient vs independent character formula:', 'MATCH' if not bad else f'MISMATCH {sorted(bad)[:8]}')
print('dim L by weight:', [sum(v for (W2, ch), v in dimL.items() if W2 == w) for w in range(W2max + 1)])
print('charge-2 sector dims (weights 4..):', [dimL.get((w, 2), 0) for w in range(8, W2max + 1, 2)])

# ---- singular vectors: kernel of positive modes L_1, L_2, J_1, G^+-_{1/2}, G^+-_{3/2} on V^univ
pos = [(L_, 2), (L_, 4), (J_, 2), (GP, 1), (GM, 1), (GP, 3), (GM, 3)]
sing = {}
for W2 in range(1, min(W2max, 2 * max(4, k + 2)) + 1):
    for ch, B in va.blocks(W2).items():
        # matrix of all positive ops stacked
        rows = []
        tgt_index = {}
        allcols = []
        imgs = [[va.apply(X, b) for b in B] for X in pos]
        keys = sorted({m for lst in imgs for v in lst for m in v})
        ki = {m: i for i, m in enumerate(keys)}
        if not keys:
            sing[(W2, ch)] = len(B); continue
        M = flint.nmod_mat(len(keys), len(B), [0] * (len(keys) * len(B)), P)
        for lst in imgs:
            for j, v in enumerate(lst):
                for m, cc in v.items():
                    M[ki[m], j] = (int(M[ki[m], j]) + cc) % P
        # keys from different ops may coincide only if same monomial (different weights otherwise) -> separate them
        # rebuild properly: stack op-by-op
        rowsM = []
        for oi, lst in enumerate(imgs):
            ks = sorted({m for v in lst for m in v})
            kk = {m: i for i, m in enumerate(ks)}
            for m in ks:
                row = [0] * len(B)
                for j, v in enumerate(lst):
                    if m in v:
                        row[j] = v[m]
                rowsM.append(row)
        M = flint.nmod_mat(rowsM, P)
        _, nul = M.nullspace()
        if nul:
            sing[(W2, ch)] = nul
print('singular vectors (doubled weight, charge): dim', {key: v for key, v in sorted(sing.items())})

# ---- submodule generated by singular vectors at weight k+1
W2s = 2 * (k + 1)
svecs = []
for ch, B in va.blocks(W2s).items():
    rowsM = []
    imgs = [[va.apply(X, b) for b in B] for X in pos]
    for lst in imgs:
        ks = sorted({m for v in lst for m in v})
        for m in ks:
            rowsM.append([v.get(m, 0) for v in lst])
    M = flint.nmod_mat(rowsM, P)
    X, nul = M.nullspace()
    for kk in range(nul):
        svecs.append({B[i]: int(X[i, kk]) for i in range(len(B)) if int(X[i, kk])})
neg = [m for m in va.creation_modes_upto(W2max)] + [(L_, -2), (GP, -1), (GM, -1)]
S = {}
for W2 in range(W2s, W2max + 1):
    for ch, B in va.blocks(W2).items():
        cand = []
        if W2 == W2s:
            cand += [v for v in svecs if va.mono_chg(next(iter(v))) == ch]
        for X in neg:
            lw = W2 + X[1]
            lc = ch - va.chg(X)
            if lw < W2s:
                continue
            for b in S.get((lw, lc), []):
                v = va.apply_vec(X, b)
                if v:
                    cand.append(v)
        S[(W2, ch)] = rowspace_basis(cand, B, P)
mism = []
for (W2, ch), vecs in I.items():
    if W2 > W2max:
        continue
    a = len(S.get((W2, ch), []))
    if a != len(vecs):
        mism.append((Fraction(W2, 2), ch, a, len(vecs)))
print('submodule generated by weight-(k+1) singular vectors vs radical:', 'EQUAL' if not mism else f'DIFFER {mism[:8]}')

# ---- graded analysis
t0 = time.time()
GA = GradedAnalysis(va, I, W2max)
GA.run()
summ = GA.summary_by_weight()
print(f'graded analysis in {time.time()-t0:.1f}s')
print(' weight  dimV  dimI  dimL  arcHS  ker   minimal generators of grI (Li, charge, #)')
for W2 in range(W2max + 1):
    if W2 not in summ:
        continue
    o = summ[W2]
    gens = o['gens']
    flag = '  <-- NON-ARC' if any(g[0] > 0 for g in gens) else ''
    print(f" {str(Fraction(W2,2)):>6} {o['V']:5d} {o['I']:5d} {o['V']-o['I']:5d} {o['V']-o['J']:6d} {o['ker']:4d}   {gens}{flag}")
# kernel by charge at the first non-arc weight
first = [W2 for W2 in sorted(summ) if any(g[0] > 0 for g in summ[W2]['gens'])]
if first:
    W2 = first[0]
    kb = {}
    for (D, nV, nI, nJ, ng) in GA.table:
        if D[0] == W2 and nI - nJ:
            kb[(D[1], D[2])] = nI - nJ
    print('ker pi at first non-arc weight', Fraction(W2, 2), 'by (charge, Li):', kb)
