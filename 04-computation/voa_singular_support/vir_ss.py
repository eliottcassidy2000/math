#!/usr/bin/env python3
"""Singular support of Virasoro minimal-model vertex algebras (exact, mod-p ranks).

Object.  V^c = universal Virasoro VOA at c = c_{p,q}; L = V^c / I its simple
quotient, I = U(Vir_-) v with v the singular vector of weight (p-1)(q-1).

Li filtration.  For V^c the Li filtration is the PBW-length filtration
(Li-degree of L_{-k1}...L_{-kr}|0> is sum(k_i - 2) = weight - 2r), and
gr_F V^c = C[x_0, x_1, ...] with x_j <-> L_{-j-2}, wt(x_j) = j + 2,
d x_j = (j+1) x_{j+1}  (d = image of L_{-1}).

gr_F L = C[x]/grI where grI = span of top-length components (symbols) of I.
J = differential ideal generated by sigma(v) = x_0^N, N = (p-1)(q-1)/2, so
C[x]/J = J_infty(R_L) (arc algebra of Zhu's C_2-algebra C[x]/(x^N)) and
ker(pi: C[x]/J -> gr_F L) = grI/J.

Minimal generators of grI as a differential ideal, bidegree (Delta, r):
    dim grI_{D,r} - dim( sum_j x_j grI_{D-j-2,r-1} + d grI_{D-1,r} )
(graded Nakayama over the Ore algebra C[x][d]).

Monomials of C[x] of weight D and degree r are partitions of D into r parts
>= 2 (part k <-> x_{k-2}); the same tuples index PBW monomials of V^c.

Exactness.  Ranks are computed modulo primes P (flint nmod_mat).  A rank mod P
is <= the rank over Q, and equality holds for all but finitely many P; we run
two primes and require agreement.  Exact singular vectors are computed over Q.

Usage:  python vir_ss.py p q Dmax [--primes P1,P2] [--show]
"""
import sys, time, functools, argparse
from fractions import Fraction
import flint

DEFAULT_PRIMES = (2147483647, 2147483629)

# ---------------------------------------------------------------- partitions
@functools.lru_cache(maxsize=None)
def parts_ge2(n, maxpart):
    """Nonincreasing tuples of parts in [2, maxpart] summing to n."""
    if n == 0:
        return ((),)
    out = []
    for k in range(min(n, maxpart), 1, -1):
        for rest in parts_ge2(n - k, k):
            out.append((k,) + rest)
    return tuple(out)

@functools.lru_cache(maxsize=None)
def block(D, r):
    """Sorted list of partitions of D into exactly r parts >= 2."""
    return tuple(sorted((lam for lam in parts_ge2(D, D) if len(lam) == r), reverse=True))

@functools.lru_cache(maxsize=None)
def block_index(D, r):
    return {lam: i for i, lam in enumerate(block(D, r))}

@functools.lru_cache(maxsize=None)
def full_order(D):
    """Columns of V_D ordered by length descending (longest first)."""
    cols = []
    for r in range(D // 2, -1, -1):
        cols.extend(block(D, r))
    return tuple(cols)

@functools.lru_cache(maxsize=None)
def full_index(D):
    return {lam: i for i, lam in enumerate(full_order(D))}

# ---------------------------------------------------------------- Virasoro modes
@functools.lru_cache(maxsize=None)
def apply_neg(m, mono):
    """L_{-m} (m >= 1) applied to the ordered PBW monomial `mono`; integer coefficients."""
    if not mono:
        return () if m == 1 else (((m,), 1),)
    k1 = mono[0]
    if m >= k1:
        return (((m,) + mono, 1),)
    rest = mono[1:]
    res = {}
    for mo, co in apply_neg(m, rest):
        for mo2, co2 in apply_neg(k1, mo):
            res[mo2] = res.get(mo2, 0) + co * co2
    cc = k1 - m
    for mo, co in apply_neg(m + k1, rest):
        res[mo] = res.get(mo, 0) + cc * co
    return tuple((k, v) for k, v in res.items() if v)

def apply_mode(n, vec, c):
    """L_n applied to a vector {mono: coeff}; c a Fraction (exact)."""
    out = {}
    for mono, co in vec.items():
        for mo2, co2 in _apply_mode_mono(n, mono, c):
            out[mo2] = out.get(mo2, 0) + co * co2
    return {k: v for k, v in out.items() if v}

def _apply_mode_mono(n, mono, c):
    if n < 0:
        return apply_neg(-n, mono)
    if n == 0:
        return ((mono, sum(mono)),) if True else ()
    # n > 0
    if not mono:
        return ()
    k1 = mono[0]
    rest = mono[1:]
    res = {}
    # L_{-k1} (L_n rest)
    for mo, co in _apply_mode_mono(n, rest, c):
        for mo2, co2 in apply_neg(k1, mo):
            res[mo2] = res.get(mo2, 0) + co * co2
    # [L_n, L_{-k1}] rest = (n+k1) L_{n-k1} rest + c/12 (n^3-n) delta_{n,k1} rest
    for mo, co in _apply_mode_mono(n - k1, rest, c):
        res[mo] = res.get(mo, 0) + (n + k1) * co
    if n == k1:
        res[rest] = res.get(rest, 0) + c * Fraction(n ** 3 - n, 12)
    return tuple((k, v) for k, v in res.items() if v)

def central_charge(p, q):
    return 1 - Fraction(6 * (p - q) ** 2, p * q)

# ---------------------------------------------------------------- linear algebra helpers
def rref_rows(mat_rows, ncols, P):
    """RREF of a list of rows (lists of ints mod P); returns (list of nonzero rows, pivots)."""
    if not mat_rows:
        return [], []
    M = flint.nmod_mat(len(mat_rows), ncols, [x % P for row in mat_rows for x in row], P)
    R, rk = M.rref()
    rows = []
    pivots = []
    for row in R.tolist()[:rk]:
        row = [int(x) for x in row]
        piv = next(j for j in range(ncols) if row[j])
        rows.append(row)
        pivots.append(piv)
    return rows, pivots

def rank_mod(mat_rows, ncols, P):
    if not mat_rows or ncols == 0:
        return 0
    M = flint.nmod_mat(len(mat_rows), ncols, [x % P for row in mat_rows for x in row], P)
    return M.rank()

def nullspace_exact(rows, ncols):
    """Exact nullspace over Q of rows (list of lists of Fractions)."""
    import sympy
    M = sympy.Matrix(rows)
    ns = M.nullspace()
    return [[sympy.Rational(x) for x in v] for v in ns]

# ---------------------------------------------------------------- singular vector
def singular_vector(p, q):
    """Exact singular vector of V^c at weight (p-1)(q-1), normalized so coeff(L_{-2}^N)=1."""
    c = central_charge(p, q)
    h = (p - 1) * (q - 1)
    basis = full_order(h)
    idx = {lam: i for i, lam in enumerate(basis)}
    # equations: L_1 v = 0 and L_2 v = 0
    eqs = {}
    for n in (1, 2):
        for j, lam in enumerate(basis):
            img = apply_mode(n, {lam: Fraction(1)}, c)
            for mo, co in img.items():
                eqs.setdefault((n, mo), [Fraction(0)] * len(basis))[j] += co
    rows = list(eqs.values())
    ns = nullspace_exact(rows, len(basis))
    assert len(ns) == 1, f"singular space dim {len(ns)}"
    v = ns[0]
    N = h // 2
    top = (2,) * N
    lead = v[idx[top]]
    assert lead != 0, "L_{-2}^N coefficient vanishes"
    vec = {basis[i]: Fraction(int(v[i].p), int(v[i].q)) / Fraction(int(lead.p), int(lead.q))
           for i in range(len(basis)) if v[i] != 0}
    return vec

# ---------------------------------------------------------------- characters
def vacuum_character(p, q, Dmax):
    """Coefficients of the normalized vacuum character of M(p,q) up to q^Dmax."""
    num = [0] * (Dmax + 1)
    K = 0
    while True:
        added = False
        for k in ({K, -K} if K else {0}):
            e1 = p * q * k * k + k * (q - p)
            e2 = (p * k + 1) * (q * k + 1)
            if 0 <= e1 <= Dmax:
                num[e1] += 1; added = True
            if 0 <= e2 <= Dmax:
                num[e2] -= 1; added = True
        if not added and K > 2:
            break
        K += 1
    # divide by (q;q)_inf
    part = [0] * (Dmax + 1)
    part[0] = 1
    for n in range(1, Dmax + 1):
        for m in range(n, Dmax + 1):
            part[m] += part[m - n]
    out = [sum(num[i] * part[D - i] for i in range(D + 1)) for D in range(Dmax + 1)]
    return out

# ---------------------------------------------------------------- polynomial ops on blocks
def mult_x(vec_block, D, r, j):
    """Multiply a vector in block (D, r) by x_j -> block (D+j+2, r+1). vec_block: dict lam->coef."""
    out = {}
    k = j + 2
    for lam, co in vec_block.items():
        new = tuple(sorted(lam + (k,), reverse=True))
        out[new] = out.get(new, 0) + co
    return out

def deriv(vec_block):
    """Apply d (x_j -> (j+1) x_{j+1}; part k -> (k-1) * part k+1)."""
    out = {}
    for lam, co in vec_block.items():
        lst = list(lam)
        seen = set()
        for i, k in enumerate(lst):
            # each occurrence contributes (product rule); identical parts give multiplicity
            new = lst[:i] + [k + 1] + lst[i + 1:]
            t = tuple(sorted(new, reverse=True))
            out[t] = out.get(t, 0) + co * (k - 1)
    return {k: v for k, v in out.items() if v}

# ---------------------------------------------------------------- main engine
class SingularSupport:
    def __init__(self, p, q, Dmax, P):
        self.p, self.q, self.Dmax, self.P = p, q, Dmax, P
        self.h = (p - 1) * (q - 1)
        self.N = self.h // 2
        self.v = singular_vector(p, q)
        self.I = {}        # D -> list of rows (in full_order(D) coordinates), RREF basis of I_D mod P
        self.grI = {}      # (D, r) -> list of dict vectors (symbols, block coordinates), echelon
        self.J = {}        # (D, r) -> list of dict vectors spanning J_{D,r} (basis)
        self.gens = []     # (D, r, vector dict) new differential-ideal generators of grI
        self.char = vacuum_character(p, q, Dmax)

    def vec_mod(self, vec):
        P = self.P
        out = {}
        for k, v in vec.items():
            if isinstance(v, Fraction):
                out[k] = v.numerator * pow(v.denominator, -1, P) % P
            else:
                out[k] = v % P
        return out

    def lower_matrix(self, D, m):
        """Sparse action of L_{-m}: V_{D-m} -> V_D as list of dicts (row per source basis elt)."""
        src = full_order(D - m)
        tgt_idx = full_index(D)
        rows = []
        for lam in src:
            img = apply_neg(m, lam)
            rows.append({tgt_idx[mo]: co for mo, co in img})
        return rows

    def build_I(self, D):
        P = self.P
        ncols = len(full_order(D))
        if D < self.h:
            self.I[D] = []
            return
        if D == self.h:
            vm = self.vec_mod(self.v)
            idx = full_index(D)
            row = [0] * ncols
            for lam, co in vm.items():
                row[idx[lam]] = co
            rows, piv = rref_rows([row], ncols, P)
            self.I[D] = rows
            return
        cand = []
        for m in (1, 2):
            if D - m < self.h:
                continue
            A = self.lower_matrix(D, m)
            for row in self.I[D - m]:
                new = [0] * ncols
                for i, co in enumerate(row):
                    if co:
                        for t, a in A[i].items():
                            new[t] = (new[t] + co * a) % P
                cand.append(new)
        rows, piv = rref_rows(cand, ncols, P)
        self.I[D] = rows

    def symbols(self, D):
        """Split RREF rows of I_D by pivot block -> symbol dicts per r."""
        cols = full_order(D)
        out = {}
        for row in self.I[D]:
            piv = next(j for j, x in enumerate(row) if x)
            r = len(cols[piv])
            sym = {cols[j]: row[j] for j in range(len(cols)) if row[j] and len(cols[j]) == r}
            out.setdefault(r, []).append(sym)
        return out

    def span_rank(self, vecs, D, r):
        idx = block_index(D, r)
        n = len(idx)
        rows = []
        for v in vecs:
            row = [0] * n
            for lam, co in v.items():
                row[idx[lam]] = (row[idx[lam]] + co) % self.P
            rows.append(row)
        return rank_mod(rows, n, self.P), rows

    def reduce_basis(self, vecs, D, r):
        idx = block_index(D, r)
        cols = block(D, r)
        n = len(idx)
        rows = []
        for v in vecs:
            row = [0] * n
            for lam, co in v.items():
                row[idx[lam]] = (row[idx[lam]] + co) % self.P
            rows.append(row)
        R, piv = rref_rows(rows, n, self.P)
        return [{cols[j]: x for j, x in enumerate(row) if x} for row in R]

    def products(self, store, D, r):
        """span( x_j * store[D-j-2, r-1]  +  d store[D-1, r] ) as list of dicts."""
        out = []
        for j in range(0, D):
            src = store.get((D - j - 2, r - 1))
            if src:
                for v in src:
                    out.append(mult_x(v, D - j - 2, r - 1, j))
        src = store.get((D - 1, r))
        if src:
            for v in src:
                dv = deriv(v)
                if dv:
                    out.append({k: x % self.P for k, x in dv.items()})
        return out

    def run(self, verbose=True, show=False):
        P = self.P
        table = []
        for D in range(0, self.Dmax + 1):
            t0 = time.time()
            self.build_I(D)
            dimV = len(full_order(D))
            dimI = len(self.I[D])
            dimL = self.char[D]
            assert dimV - dimI == dimL, f"D={D}: dim V {dimV} - dim I {dimI} != char {dimL}"
            syms = self.symbols(D)
            row = {'D': D, 'dimL': dimL, 'r': {}}
            for r in range(0, D // 2 + 1):
                nb = len(block(D, r))
                g = self.reduce_basis(syms.get(r, []), D, r) if syms.get(r) else []
                self.grI[(D, r)] = g
                # J recursion
                if D == self.h and r == self.N:
                    Jb = [{(2,) * self.N: 1}]
                else:
                    Jb = self.reduce_basis(self.products(self.J, D, r), D, r) if D > self.h else []
                self.J[(D, r)] = Jb
                # differential-ideal decomposables of grI
                dec = self.products(self.grI, D, r)
                rk_dec, _ = self.span_rank(dec, D, r)
                # check containments
                rk_all, _ = self.span_rank(dec + g, D, r)
                assert rk_all == len(g), f"decomposables not inside grI at {(D, r)}"
                rkJ_all, _ = self.span_rank(Jb + g, D, r)
                assert rkJ_all == len(g), f"J not inside grI at {(D, r)}"
                new = len(g) - rk_dec
                if new:
                    # choose canonical complement reps: reduce g modulo dec
                    decb = self.reduce_basis(dec, D, r) if dec else []
                    reps = self.complement(decb, g, D, r)
                    for rep in reps:
                        self.gens.append((D, r, rep))
                row['r'][r] = (nb, len(g), len(Jb), new)
            table.append(row)
            if verbose:
                ker = sum(v[1] - v[2] for v in row['r'].values())
                ng = sum(v[3] for v in row['r'].values())
                gens_here = [(r, v[3]) for r, v in row['r'].items() if v[3]]
                arc = sum(v[0] - v[2] for v in row['r'].values())
                print(f"D={D:3d} dimV={dimV:6d} dimL={dimL:6d} arcHS={arc:6d} ker(pi)={ker:5d} "
                      f"newgens={ng} {gens_here}  ({time.time()-t0:.1f}s)", flush=True)
        self.table = table
        return table

    def complement(self, decb, g, D, r):
        """Vectors of g reduced modulo span(decb), returned as RREF complement basis."""
        idx = block_index(D, r)
        cols = block(D, r)
        n = len(idx)
        P = self.P
        def tolist(v):
            row = [0] * n
            for lam, co in v.items():
                row[idx[lam]] = co % P
            return row
        drows = [tolist(v) for v in decb]
        R, piv = rref_rows(drows, n, P) if drows else ([], [])
        reduced = []
        for v in g:
            row = tolist(v)
            for rr, pj in zip(R, piv):
                if row[pj]:
                    f = row[pj]
                    row = [(a - f * b) % P for a, b in zip(row, rr)]
            reduced.append(row)
        R2, piv2 = rref_rows(reduced, n, P)
        return [{cols[j]: x for j, x in enumerate(row) if x} for row in R2]


def ratrec(a, m):
    """Rational reconstruction of a mod m."""
    a %= m
    if a == 0:
        return Fraction(0)
    import math
    bound = int(math.isqrt(m // 2))
    r0, r1 = m, a
    s0, s1 = 0, 1
    while r1 > bound:
        qq = r0 // r1
        r0, r1 = r1, r0 - qq * r1
        s0, s1 = s1, s0 - qq * s1
    if s1 == 0 or abs(s1) > bound:
        return None
    return Fraction(r1, s1)


def fmt_poly(vec, P, normalize=True):
    items = sorted(vec.items(), key=lambda kv: kv[0], reverse=True)
    if normalize and items:
        lead = items[0][1]
        inv = pow(lead, -1, P)
        items = [(k, v * inv % P) for k, v in items]
    terms = []
    for lam, co in items:
        fr = ratrec(co, P)
        mon = "*".join(f"L{-k}" for k in lam)
        terms.append(f"({fr}){mon}")
    return " + ".join(terms)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('p', type=int)
    ap.add_argument('q', type=int)
    ap.add_argument('Dmax', type=int)
    ap.add_argument('--primes', default=",".join(map(str, DEFAULT_PRIMES)))
    ap.add_argument('--show', action='store_true')
    a = ap.parse_args()
    primes = [int(x) for x in a.primes.split(',')]
    results = []
    for P in primes:
        print(f"=== Vir_({a.p},{a.q})  c={central_charge(a.p, a.q)}  N={(a.p-1)*(a.q-1)//2}  prime={P}")
        ss = SingularSupport(a.p, a.q, a.Dmax, P)
        ss.run()
        results.append(ss)
        print("generators (D, r):", [(D, r) for D, r, _ in ss.gens])
        if a.show:
            for D, r, vec in ss.gens:
                print(f"  gen at weight {D}, degree {r}: {fmt_poly(vec, P)}")
    if len(results) > 1:
        g0 = [(D, r) for D, r, _ in results[0].gens]
        same = all([(D, r) for D, r, _ in s.gens] == g0 for s in results[1:])
        tabs = [[(row['D'], tuple(sorted(row['r'].items()))) for row in s.table] for s in results]
        print("primes agree on generator bidegrees:", same, "| full tables agree:", all(t == tabs[0] for t in tabs))


if __name__ == '__main__':
    main()
