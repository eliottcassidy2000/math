"""NUMERICAL-SCOUT / NO VERDICT: AMM 12592 entry-cone LP.

This program salvages the useful model-building part of the untracked kps-S179
entry-cone probe.  It constructs the causal real relaxation only through the
state entering the first feed-free row and imposes the divided THM-3332
F1--F3 cone there.  The golden-floor profile and all unscaled loads/caps are
generated by exact integer arithmetic.  Conversion to floating point occurs
only when the diagonally scaled sparse LP is assembled.

Solver status is NEVER a certificate here.  In particular:

* HiGHS presolve can report infeasible on the R=32 model even though the
  exact rule-A state below is a feasible point.
* Clarabel can return an ``optimal`` boundary candidate whose small scaled
  residual becomes enormous after undoing the diagonal scaling.

The script therefore prints both scaled and reconstructed-native residuals,
the exact positive control when requested, dependency versions, and an
unambiguous no-verdict footer.

Representative reproduction commands:

  python 04-computation/amm12592_entry_cone_solver_boundary_numerical_scout_kps_s184.py 32 0 --exact-rule-a-control
  python 04-computation/amm12592_entry_cone_solver_boundary_numerical_scout_kps_s184.py 32 0 --solver highs
  python 04-computation/amm12592_entry_cone_solver_boundary_numerical_scout_kps_s184.py 32 0 --solver highs --presolve
  python 04-computation/amm12592_entry_cone_solver_boundary_numerical_scout_kps_s184.py 512 0 --solver clarabel
  python 04-computation/amm12592_entry_cone_solver_boundary_numerical_scout_kps_s184.py 512 0 --solver clarabel --zero-entry

Scope: numerical diagnostics and exact model-input/control checks only.  No
rational point, integer witness, infeasibility certificate, AMM closure, or
deadline improvement is claimed.
"""

