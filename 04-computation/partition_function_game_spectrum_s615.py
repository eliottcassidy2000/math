def Hcount(n, adj):
    if n == 0: return 1
    size = 1 << n; dp = [[0]*n for _ in range(size)]
    for v in range(n): dp[1 << v][v] = 1
    for mask in range(size):
        row = dp[mask]
        for v in range(n):
            c = row[v]
            if c:
                av = adj[v]
                for w in range(n):
                    if not (mask >> w & 1) and av >> w & 1: dp[mask | 1 << w][w] += c
    return sum(dp[size-1])

