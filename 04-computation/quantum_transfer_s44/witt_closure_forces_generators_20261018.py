#!/usr/bin/env python3
"""Closure under the c-independent positive Witt action forces the degree-N singular-support generators (S44).

Fact used (elementary).  For n >= 1, L_n maps a PBW monomial of length r to (length r part) + (lower), and on the
length-r part it acts as the derivation D_n x_j = (j+n+2) x_(j-n) (j >= n), D_n x_j = 0 (j < n) of C[x] = gr V^c:
the central term of [L_n, L_(-n)] and every commutator producing L_(-1) or L_(>=0) lowers the length.  Since I is
Vir-stable, grI_N (degree-N symbols) is stable under d = D_(-1) and every D_n, n >= 1, which do not involve c.
Recursion (actual generator pattern, Li 3, 5, 7, 9).  M_0 = C x_0^N.  At Li degree L the admissible new generators are
    S_L = { g in Sym^N(V_2)_L : D_1 g = 0 and D_n g in M_(L-n) for 2 <= n <= L },
and M_L = d M_(L-1) + S_L if L is a generator position (3, 5, 7, 9), else d M_(L-1).
(A first run that added every S_L, including the unused A_2 at Li 2, is recorded in the JSON as 'maximal' for contrast.)  (A lowest weight vector never lies in d M_(L-1).)
If dim S_L = 1 for odd L and 0 for even L, every degree-N generator of grI is forced up to scalar, independently of
c: grI_N must be one of the truncations M^(k) generated by x_0^N, G_3, ..., G_(2k+1).
This script computes dim S_L for given N (exact, mod three primes, in the actual basis block(2N+L, N), so no
stable-range assumption), records the vectors, and compares them with the generators extracted from the singular
support of actual minimal models (semiinvariant_generators.json).
Usage: python witt_closure_forces_generators_20261018.py
"""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'voa_singular_support'))
import flint
from vir_ss import block, block_index, deriv
from semiinvariant_generators_20261018 import D1_block, to_mu, cayley_basis, solve_cayley_modp, crt, ratrec_big
from fractions import Fraction

PRIMES = (2147483647, 2147483629, 2147483587)


def Dn_block(vec, n):
    """D_n x_j = (j+n+2) x_(j-n) for j >= n: part k (x_(k-2)) with k >= n+2 -> (k+n) * part (k-n)."""
    out = {}
    for lam, co in vec.items():
        lst = list(lam)
        for i, k in enumerate(lst):
            if k >= n + 2:
                new = tuple(sorted(lst[:i] + [k - n] + lst[i + 1:], reverse=True))
                out[new] = out.get(new, 0) + co * (k + n)
    return {k: v for k, v in out.items() if v}


def rref(rows, ncols, P):
    if not rows:
        return []
    M = flint.nmod_mat(len(rows), ncols, [x % P for r in rows for x in r], P)
    R, rk = M.rref()
    return [[int(x) for x in r] for r in R.tolist()[:rk]]


def to_row(vec, idx, P):
    row = [0] * len(idx)
    for lam, co in vec.items():
        row[idx[lam]] = (row[idx[lam]] + co) % P
    return row


def closure(N, Lmax, P, gen_pattern=None):
    """Return dims of S_L and the S_L basis vectors (dicts over block(2N+L, N)).  If gen_pattern (a set of Li
    degrees) is given, only those S_L are added to M (the actual generator positions); otherwise all S_L are added."""
    M = {}   # L -> list of row vectors (basis) in block(2N+L, N) coordinates (as dicts)
    S = {}
    base = {(2,) * N: 1}
    M[0] = [base]
    S[0] = [base]
    for L in range(1, Lmax + 1):
        D = 2 * N + L
        cols = block(D, N)
        idx = block_index(D, N)
        n = len(cols)
        # d M_(L-1)
        dM = [{k: v % P for k, v in deriv(v).items()} for v in M[L - 1]]
        dM = [v for v in dM if v]
        # lowest weight vectors at L: nullspace of D_1 on the full block
        tgt1 = block(D - 1, N)
        t1idx = block_index(D - 1, N)
        cols_img = []
        for lam in cols:
            w = D1_block({lam: 1})
            cols_img.append(to_row(w, t1idx, P))
        A = flint.nmod_mat(len(tgt1), n, [cols_img[j][i] for i in range(len(tgt1)) for j in range(n)], P) if tgt1 else None
        if A is not None:
            ns, nul = A.nullspace()
            lw = [[int(ns[i, t]) for i in range(n)] for t in range(nul)]
        else:
            lw = [[1 if i == j else 0 for i in range(n)] for j in range(n)]
        # conditions: D_m g in M_(L-m), m = 2..L.  Unknown g = sum_t a_t lw_t.  For each m, project D_m g onto the
        # complement of span M_(L-m): (D_m g) must vanish modulo M_(L-m).
        cond_rows = []
        for m in range(2, L + 1):
            Dm_ = 2 * N + L - m
            ccols = block(Dm_, N)
            if not ccols:
                continue
            cidx = block_index(Dm_, N)
            Mrows = rref([to_row(v, cidx, P) for v in M[L - m]], len(ccols), P)
            piv = [next(j for j, x in enumerate(r) if x) for r in Mrows]
            images = []
            for vec in lw:
                g = {cols[i]: vec[i] for i in range(n) if vec[i]}
                row = to_row(Dn_block(g, m), cidx, P)
                for r, pj in zip(Mrows, piv):
                    if row[pj]:
                        f = row[pj]
                        row = [(a - f * b) % P for a, b in zip(row, r)]
                images.append(row)
            # each coordinate of the reduced image gives a linear condition on the a_t
            for c in range(len(ccols)):
                cond_rows.append([images[t][c] for t in range(len(lw))])
        if lw:
            if cond_rows:
                C = flint.nmod_mat(len(cond_rows), len(lw), [x for r in cond_rows for x in r], P)
                ns2, nul2 = C.nullspace()
                sols = [[int(ns2[t, s]) for t in range(len(lw))] for s in range(nul2)]
            else:
                sols = [[1 if t == s else 0 for t in range(len(lw))] for s in range(len(lw))]
        else:
            sols = []
        Svecs = []
        for a in sols:
            vec = [0] * n
            for t, at in enumerate(a):
                if at:
                    for i in range(n):
                        vec[i] = (vec[i] + at * lw[t][i]) % P
            Svecs.append({cols[i]: vec[i] for i in range(n) if vec[i]})
        S[L] = Svecs
        add = Svecs if (gen_pattern is None or L in gen_pattern) else []
        M[L] = dM + add
        # reduce M[L] to a basis
        rows = rref([to_row(v, idx, P) for v in M[L]], n, P)
        M[L] = [{cols[i]: r[i] for i in range(n) if r[i]} for r in rows]
    return S, M


def cayley_of(vec, L, P):
    vmu = {}
    for lam, co in vec.items():
        vmu[to_mu(lam)] = (vmu.get(to_mu(lam), 0) + co) % P
    top = vmu.get((L,), 0)
    if not top:
        return None
    inv = pow(top, -1, P)
    vmu = {k: x * inv % P for k, x in vmu.items()}
    nus, sol = solve_cayley_modp(vmu, L, P)
    return dict(zip(nus, sol))


if __name__ == '__main__':
    gens = json.load(open(os.path.join(HERE, 'semiinvariant_generators.json')))
    report = {}
    for N in (3, 4, 5, 6, 7, 8, 9, 10, 12, 14, 15, 16):
        Lmax = 9 if N >= 9 else min(9, N + 3)
        per = []
        for P in PRIMES:
            S, M = closure(N, Lmax, P, gen_pattern={3, 5, 7, 9})
            per.append(S)
        dims = {L: len(per[0][L]) for L in per[0]}
        assert all({L: len(s[L]) for L in s} == dims for s in per)
        # exact Cayley coordinates of 1-dim S_L (stable range only)
        cay = {}
        for L, d in dims.items():
            if d == 1 and L >= 3 and N >= L:
                co = [cayley_of(s[L][0], L, P) for s, P in zip(per, PRIMES)]
                if all(c is not None for c in co):
                    cay[L] = {nu: ratrec_big(*crt([c[nu] for c in co], PRIMES)) for nu in co[0]}
        report[N] = {'dims_S_L': dims, 'cayley': {L: {str(k): str(v) for k, v in c.items()} for L, c in cay.items()}}
        print(f'N={N}: dim S_L = {dims}')
        for L, c in cay.items():
            print(f'    forced G_{L}: ' + ', '.join(f'A{list(k)}: {v}' for k, v in c.items()))
        # compare with actual generators of models with this N
        for key, ent in gens.items():
            if ent['N'] != N:
                continue
            for Ls, e in ent['L'].items():
                L = int(Ls)
                if L in cay and e['cayley']:
                    actual = {k: Fraction(v) for k, v in e['cayley'].items()}
                    forced = {str(k): v for k, v in cay[L].items()}
                    same = all(Fraction(str(forced[k])) == actual[k] for k in actual)
                    print(f'    Vir({key}) generator at L={L} equals forced G_{L}: {same}')
                    report[N].setdefault('model_matches', []).append((key, L, same))
    json.dump(report, open(os.path.join(HERE, 'witt_closure_forces_generators.json'), 'w'), indent=1, default=str)
