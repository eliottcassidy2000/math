    require(formal_active_image == ((-1 % P, 0), (0, -1 % P))
            and rank_mod(formal_active_image) == 2,
            "formal graft-role target span changed")

    # The minimum-support lawful directions are the paired blocker--graft
    # dipoles D_a=e_a-e_(k_a), D_c=e_c-e_(k_b).  Their image is 2I; 2 is a
    # unit modulo thirteen, so the lawful paired bank also spans the plane.
