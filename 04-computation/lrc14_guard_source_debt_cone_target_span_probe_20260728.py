def audit_anchored_pullbacks():
    # Use the basis of the full space of anchored repair tables:
    # K_(r0,s0)=1 for one s0!=0 and zero elsewhere.  Pullback along a role
    # covector lambda evaluates K(r,lambda(delta)).  If lambda=0, every
    # target point samples s=0 and the whole anchored table vanishes.
    deltas = tuple((u, v) for u in range(P) for v in range(P))

    def scalar(covector, delta):
        return sum(a * b for a, b in zip(covector, delta)) % P

    def pulled_basis_support(covector, r0, s0):
        require(s0 != 0, "anchored repair basis cannot use s=0")
        return tuple(delta for delta in deltas
                     if scalar(covector, delta) == s0)

    zero_covector = (0, 0)
    active_covectors = ((-1, 0), (0, -1))
    for r0 in range(P):
        for s0 in range(1, P):
            require(not pulled_basis_support(zero_covector, r0, s0),
                    "target-neutral anchored repair stopped pulling back to zero")
            for covector in active_covectors:
                support = pulled_basis_support(covector, r0, s0)
                require(len(support) == P,
                        "nonzero target line stopped having thirteen-point fibres")

    anchored_dimension = P * (P - 1)
    neutral_pullback_rank = 0
    active_pullback_rank = anchored_dimension
    require((anchored_dimension, neutral_pullback_rank, active_pullback_rank)
            == (156, 0, 156), "anchored pullback rank ledger changed")
    return anchored_dimension, neutral_pullback_rank, active_pullback_rank


