#!/usr/bin/env python3
"""Exact audit for THM-4069: basis-dependent even-graph metagraphs.

The labelled cycle space of K_n is generated by the fundamental cycles of
any spanning tree T.  This script quotients the associated cube edges by
graph isomorphism, compares a star and a path basis, and constructs the
canonical envelope generated by every simple cycle.

No floating-point arithmetic or Python assertions are used.
"""

from itertools import combinations, permutations, product


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def complete_edges(n):
    return tuple(combinations(range(n), 2))


def edge_bit(edge_index, u, v):
    return 1 << edge_index[tuple(sorted((u, v)))]


def tree_path(tree_edges, n, source, target):
    adjacency = [[] for _ in range(n)]
    for u, v in tree_edges:
        adjacency[u].append(v)
        adjacency[v].append(u)
    parent = {source: -1}
    stack = [source]
    while stack:
        vertex = stack.pop()
        if vertex == target:
            break
        for neighbor in adjacency[vertex]:
            if neighbor not in parent:
                parent[neighbor] = vertex
                stack.append(neighbor)
    require(target in parent, "tree path not found")
    path = []
    vertex = target
    while parent[vertex] != -1:
        path.append(tuple(sorted((vertex, parent[vertex]))))
        vertex = parent[vertex]
    return path


def fundamental_cycles(n, tree_edges):
    edges = complete_edges(n)
    edge_index = {edge: index for index, edge in enumerate(edges)}
    tree = {tuple(sorted(edge)) for edge in tree_edges}
    require(len(tree) == n - 1, "wrong tree edge count")
    cycles = []
    for chord in edges:
        if chord in tree:
            continue
        mask = edge_bit(edge_index, *chord)
        for edge in tree_path(tree, n, *chord):
            mask ^= edge_bit(edge_index, *edge)
        cycles.append(mask)
    require(len(cycles) == (n - 1) * (n - 2) // 2,
            "wrong fundamental-cycle count")
    return tuple(cycles)


def span(generators):
    values = [0]
    for generator in generators:
        values += [value ^ generator for value in values]
    require(len(set(values)) == len(values), "generators are dependent")
    return tuple(values)


def permuted_mask(mask, n, permutation):
    edges = complete_edges(n)
    edge_index = {edge: index for index, edge in enumerate(edges)}
    result = 0
    for index, (u, v) in enumerate(edges):
        if mask & (1 << index):
            result |= edge_bit(edge_index, permutation[u], permutation[v])
    return result


def canonicalizer(n):
    permutations_n = tuple(permutations(range(n)))
    cache = {}

    def canonical(mask):
        if mask not in cache:
            cache[mask] = min(permuted_mask(mask, n, perm)
                              for perm in permutations_n)
        return cache[mask]

    return canonical


def simple_cycle_masks(n):
    """Return each labelled unoriented simple cycle exactly once."""
    edge_index = {edge: index for index, edge in enumerate(complete_edges(n))}
    result = set()
    for length in range(3, n + 1):
        for vertices in combinations(range(n), length):
            anchor = vertices[0]
            for tail in permutations(vertices[1:]):
                order = (anchor,) + tail
                # Reverse orientations describe the same cycle.
                if order[1] > order[-1]:
                    continue
                mask = 0
                for index in range(length):
                    mask ^= edge_bit(edge_index, order[index],
                                     order[(index + 1) % length])
                result.add(mask)
    expected = sum(
        product_value(range(1, length))
        * combination_value(n, length) // 2
        for length in range(3, n + 1)
    )
    require(len(result) == expected, "simple-cycle enumeration mismatch")
    return tuple(sorted(result))


def product_value(values):
    result = 1
    for value in values:
        result *= value
    return result


def combination_value(n, k):
    numerator = product_value(range(n - k + 1, n + 1))
    denominator = product_value(range(1, k + 1))
    return numerator // denominator


def quotient_data(states, generators, canonical):
    classes = tuple(sorted({canonical(state) for state in states}))
    class_index = {representative: index
                   for index, representative in enumerate(classes)}
    edges = set()
    loops = 0
    for state in states:
        source = class_index[canonical(state)]
        for generator in generators:
            target = class_index[canonical(state ^ generator)]
            if source == target:
                loops += 1
            else:
                edges.add(tuple(sorted((source, target))))
    adjacency = [set() for _ in classes]
    for source, target in edges:
        adjacency[source].add(target)
        adjacency[target].add(source)
    return classes, frozenset(edges), loops, adjacency


def connected(adjacency):
    if not adjacency:
        return True
    seen = {0}
    stack = [0]
    while stack:
        vertex = stack.pop()
        for neighbor in adjacency[vertex]:
            if neighbor not in seen:
                seen.add(neighbor)
                stack.append(neighbor)
    return len(seen) == len(adjacency)


def bipartite(adjacency):
    colors = {}
    for root in range(len(adjacency)):
        if root in colors:
            continue
        colors[root] = 0
        stack = [root]
        while stack:
            vertex = stack.pop()
            for neighbor in adjacency[vertex]:
                wanted = 1 - colors[vertex]
                if neighbor in colors and colors[neighbor] != wanted:
                    return False
                if neighbor not in colors:
                    colors[neighbor] = wanted
                    stack.append(neighbor)
    return True


def degree_sequence(mask, n):
    degrees = [0] * n
    for index, (u, v) in enumerate(complete_edges(n)):
        if mask & (1 << index):
            degrees[u] += 1
            degrees[v] += 1
    return tuple(sorted(degrees))


def prufer_tree(sequence, n):
    degrees = [1] * n
    for vertex in sequence:
        degrees[vertex] += 1
    tree = []
    for vertex in sequence:
        leaf = min(index for index, degree in enumerate(degrees)
                   if degree == 1)
        tree.append(tuple(sorted((leaf, vertex))))
        degrees[leaf] -= 1
        degrees[vertex] -= 1
    leaves = [index for index, degree in enumerate(degrees) if degree == 1]
    require(len(leaves) == 2, "Pruefer decoding failed")
    tree.append(tuple(sorted(leaves)))
    return tuple(sorted(tree))


def is_star(tree_edges, n):
    degrees = [0] * n
    for u, v in tree_edges:
        degrees[u] += 1
        degrees[v] += 1
    return max(degrees) == n - 1


def all_generators_odd(tree_edges, n):
    return all(cycle.bit_count() % 2 == 1
               for cycle in fundamental_cycles(n, tree_edges))


def audit_tree_parity(max_n):
    rows = []
    for n in range(3, max_n + 1):
        tree_count = 0
        star_count = 0
        odd_basis_count = 0
        for sequence in product(range(n), repeat=n - 2):
            tree = prufer_tree(sequence, n)
            tree_count += 1
            star = is_star(tree, n)
            odd_basis = all_generators_odd(tree, n)
            require(star == odd_basis,
                    "odd fundamental cycles did not characterize a star")
            star_count += int(star)
            odd_basis_count += int(odd_basis)
        rows.append((n, tree_count, star_count, odd_basis_count))
    return rows


def named_class(mask, n):
    edge_total = mask.bit_count()
    degrees = degree_sequence(mask, n)
    if edge_total == 0:
        return "empty"
    if n == 4 and edge_total == 3 and degrees == (0, 2, 2, 2):
        return "triangle+isolated"
    if n == 4 and edge_total == 4 and degrees == (2, 2, 2, 2):
        return "four-cycle"
    return "edges=%d,degrees=%s" % (edge_total, degrees)


def main():
    print("THM-4069 primary exact audit")
    print("arithmetic=integer/GF(2); assertions=disabled-by-construction")
    print()

    quotient_rows = []
    for n in range(3, 7):
        path_tree = tuple((vertex, vertex + 1) for vertex in range(n - 1))
        star_tree = tuple((0, vertex) for vertex in range(1, n))
        path_basis = fundamental_cycles(n, path_tree)
        star_basis = fundamental_cycles(n, star_tree)
        states = span(path_basis)
        require(set(states) == set(span(star_basis)),
                "tree bases span different labelled spaces")
        require(all(all(degree % 2 == 0 for degree in degree_sequence(state, n))
                    for state in states), "cycle-space state is not Eulerian")
        canonical = canonicalizer(n)
        cycles = simple_cycle_masks(n)
        star_data = quotient_data(states, star_basis, canonical)
        path_data = quotient_data(states, path_basis, canonical)
        envelope_data = quotient_data(states, cycles, canonical)
        classes = star_data[0]
        require(classes == path_data[0] == envelope_data[0],
                "canonical vertex sets disagree")
        require(star_data[1].issubset(envelope_data[1]),
                "star quotient escaped envelope")
        require(path_data[1].issubset(envelope_data[1]),
                "path quotient escaped envelope")
        require(path_data[1] == envelope_data[1],
                "path quotient did not realize the full envelope")
        require(connected(star_data[3]) and connected(path_data[3])
                and connected(envelope_data[3]), "quotient disconnected")
        require(bipartite(star_data[3]), "star quotient lost parity coloring")
        quotient_rows.append((n, len(states), len(classes), len(cycles),
                              len(star_data[1]), len(path_data[1]),
                              len(envelope_data[1]),
                              bipartite(path_data[3]),
                              bipartite(envelope_data[3])))

        if n == 4:
            labels = {index: named_class(mask, n)
                      for index, mask in enumerate(classes)}
            star_edges = sorted((labels[u], labels[v])
                                for u, v in star_data[1])
            path_edges = sorted((labels[u], labels[v])
                                for u, v in path_data[1])
            envelope_edges = sorted((labels[u], labels[v])
                                    for u, v in envelope_data[1])
            require(len(classes) == 3, "n=4 class count changed")
            require(len(star_edges) == 2, "n=4 star quotient is not P3")
            require(len(path_edges) == 3, "n=4 path quotient is not K3")
            require(path_edges == envelope_edges,
                    "n=4 path quotient is not the envelope")
            print("n=4 minimal witness")
            print("  classes=%s" % [labels[index] for index in range(3)])
            print("  star_edges=%s" % star_edges)
            print("  path_edges=%s" % path_edges)
            print("  envelope_edges=%s" % envelope_edges)
            print()

    print("quotient census")
    print("  n labelled_states iso_classes simple_cycles star_E path_E envelope_E path_bip envelope_bip")
    for row in quotient_rows:
        print("  %d %d %d %d %d %d %d %s %s" % row)
    print()

    print("all-labelled-tree parity audit")
    print("  n trees stars all_odd_fundamental_cycles")
    for row in audit_tree_parity(7):
        print("  %d %d %d %d" % row)
    print()

    for n in range(3, 7):
        union = set()
        tree_count = 0
        for sequence in product(range(n), repeat=n - 2):
            union.update(fundamental_cycles(n, prufer_tree(sequence, n)))
            tree_count += 1
        cycles = set(simple_cycle_masks(n))
        require(union == cycles,
                "union of tree generators is not the simple-cycle set")
        print("generator_union n=%d trees=%d generators=%d simple_cycles=%d PASS"
              % (n, tree_count, len(union), len(cycles)))

    print()
    print("PASS: basis dependence, star parity, connectivity, and canonical envelope verified")


if __name__ == "__main__":
    main()
