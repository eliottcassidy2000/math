# ----------------------------------------------------------------------
def p1_F7_analysis(P, val):
    """Express S as a function of the slope z=p/q in P^1(F_P) (8 points for P=7),
    and report the orbits under <z->-z, z->1/z> (Klein 4-group) and PSL_2 pieces."""
    if P != 7:
        return
    print("  P^1(F_7) slope realization (z = p q^{-1} mod 7; q-residue invertible):")
    # for each residue pair with b!=0 invertible, slope z = a * inv(b)
    inv = {b: pow(b, -1, P) for b in range(1, P)}
    slope_val = {}
    for (a, b), v in val.items():
        if b % P == 0:
            z = "inf"
        else:
            z = (a * inv[b % P]) % P
        # S should depend only on z up to the quotient; collect
        slope_val.setdefault(z, set()).add(v)
    print("     slope z -> set of S values seen (if not singleton, S is NOT a pure")
    print("     function of the slope -> it needs the FULL P^1 quotient, not just z):")
    for z in sorted(slope_val, key=lambda x: (x == "inf", x)):
        print(f"        z={str(z):>4s}: S in {sorted(slope_val[z])}")
    # Klein-4 group on P^1(F_7): generated by sigma: z->-z and tau: z->1/z
    pts = list(range(P)) + ["inf"]

    def neg(z):
        return "inf" if z == "inf" else (-z) % P

    def inv_map(z):
        if z == "inf":
            return 0
        if z == 0:
            return "inf"
        return pow(z, -1, P)

    # build the group <neg, inv>
    def compose_orbit(z):
        seen = set()
        frontier = {z}
        while frontier:
            w = frontier.pop()
            if w in seen:
                continue
            seen.add(w)
            frontier.add(neg(w))
            frontier.add(inv_map(w))
        return frozenset(seen)

    orbits = set()
    for z in pts:
        orbits.add(compose_orbit(z))
    print(f"  orbits of P^1(F_7) under <z->-z, z->1/z> (Klein 4-grp):")
    for o in sorted(orbits, key=lambda s: (len(s), str(sorted(map(str, s))))):
        # pick S value of a representative if defined
        rep_vals = set()
        for z in o:
            if z in slope_val:
                rep_vals |= slope_val[z]
        print(f"     orbit {sorted(o, key=str)}  ->  S {sorted(rep_vals) if rep_vals else '(inf, q=0)'}")
    # the +- / inversion quotient maps z to the pair (||num||,||den||) up to swap
    print("  => the quotient P^1(F_7)/<+-,inv> has orbits indexed by the UNORDERED")
    print("     pair {||p||,||q||}; that is exactly the symmetry of the f-table.")


