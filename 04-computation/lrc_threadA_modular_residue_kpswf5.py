# ----------------------------------------------------------------------
# Core: row-0 integer counts on the Ppq grid via the verified cov model.
# (matches HYP-2739 / general_prime script; cov-model == direct grid == closed form)
# ----------------------------------------------------------------------
def cmatrix_row0(p, q, P):
    """row 0 of the P-sector integer matrix on the Ppq grid (cov model)."""
    r = [0] * P
    for a in range(q):
        for t in range(p):
            v = (P * a + t) % (P * q)
            r[v // q] += 1
    return r


def S_of_pq(p, q, P):
    """full-matrix defect S = sum_ij |P c_ij - pq|.
    By cyclic-shift collapse (Lemma B), every row is a shift of row 0 when P nmid q,
    so S = P * sum_j |P c_0j - pq|.  We compute row 0 and multiply by P."""
    r0 = cmatrix_row0(p, q, P)
    rowdef = sum(abs(P * x - p * q) for x in r0)
    return P * rowdef, rowdef


def norm_P(x, P):
    """||x||_P = min(x%P, P-x%P) in {0,...,(P-1)/2}."""
    m = x % P
    return min(m, P - m)


# ----------------------------------------------------------------------
# (1)+(2): build residue tables S_P, check residue-only, factor through ||.||,
# extract reduced f_P, and search for a uniform closed form.
# ----------------------------------------------------------------------
def build_residue_table(P, qmax=24):
    """For each residue class (a,b)=(p%P,q%P) collect the value S_P (= P*rowdef).
    Returns dict (a,b)->set of S values (should be singletons => residue-only)."""
    table = defaultdict(set)
    rowtable = defaultdict(set)
    n = 0
    for q in range(1, qmax + 1):
        for p in range(q + 1, P * q):  # window 1 < p/q < P (cov form valid)
            if gcd(p, q) != 1:
                continue
            S, rowdef = S_of_pq(p, q, P)
            table[(p % P, q % P)].add(S)
            rowtable[(p % P, q % P)].add(rowdef)
            n += 1
    return table, rowtable, n


def reduce_to_norm(P, table):
    """Check S_P(a,b) factors through (||a||,||b||); return reduced f-table on
    {0..(P-1)/2}^2 of the *rowdef* value (S/P) for cleanliness, plus consistency flag."""
    half = (P - 1) // 2
    fred = {}  # (||a||,||b||) -> rowdef value
    consistent = True
    for (a, b), Sset in table.items():
        if len(Sset) != 1:
            consistent = False
            continue
        S = next(iter(Sset))
        rowdef = S // P
        key = (norm_P(a, P), norm_P(b, P))
        if key in fred and fred[key] != rowdef:
            consistent = False
        fred[key] = rowdef
    return fred, half, consistent


def grid_print(P, fred):
    """Pretty-print the reduced f_P table (rowdef = S/P) over ||a||,||b|| in 0..half."""
    half = (P - 1) // 2
    print(f"  reduced rowdef table f_P (=S/P) for P={P}, indices ||.||_P in 0..{half}:")
    header = "      " + "".join(f"{b:5d}" for b in range(half + 1))
    print(header)
    for a in range(half + 1):
        row = "".join(f"{fred.get((a, b), -1):5d}" for b in range(half + 1))
        print(f"   a={a}: {row}")
    # also S = P * rowdef table max
    Smax = max(P * v for v in fred.values())
    print(f"   max S_P = {Smax}  (= P*{Smax//P})")
    return Smax


# ----------------------------------------------------------------------
# (1) symmetry group of S_P as function on (Z/P)^2.
# Test invariance under the natural PGL_2(F_P) generators acting on the slope p/q.
# We treat (p,q) as homogeneous coords of slope z=p/q in P^1(F_P).
# ----------------------------------------------------------------------
def symmetry_report(P, table):
    """Report which slope-transformations preserve S_P.
    Represent S as a function on P^1(F_P) where possible (p,q with q!=0 -> z=p/q;
    plus q=0 means infinity). Within our window q>=1, but residue q%P can be 0.
    We test maps on the residue pair (a,b)=(p%P,q%P)."""
    # canonical value function on residue pairs (only where defined & singleton)
    val = {}
    for (a, b), Sset in table.items():
        if len(Sset) == 1:
            val[(a, b)] = next(iter(Sset))

    def test_map(name, fn):
        ok = True
        checked = 0
        for (a, b), v in val.items():
            na, nb = fn(a, b)
            na %= P
            nb %= P
            if (na, nb) in val:
                checked += 1
                if val[(na, nb)] != v:
                    ok = False
                    break
        return ok, checked

    maps = {
        "transpose (p,q)->(q,p)  [z->1/z]": lambda a, b: (b, a),
        "neg-p     (p,q)->(-p,q) [z->-z] ": lambda a, b: (-a, b),
        "neg-q     (p,q)->(p,-q) [z->-z] ": lambda a, b: (a, -b),
        "modular S (p,q)->(q,-p) [z->-1/z]": lambda a, b: (b, -a),
        "double-p  (p,q)->(2p,q) [z->2z] ": lambda a, b: (2 * a, b),
        "scale2    (p,q)->(2p,2q)[z->z]  ": lambda a, b: (2 * a, 2 * b),
        "scale-by-g g=primroot   [z->z]  ": None,  # filled below
        "shift     (p,q)->(p+q,q)[z->z+1]": lambda a, b: (a + b, b),
        "U: (p,q)->(p,p+q)       [z->z/(z+1)]": lambda a, b: (a, a + b),
    }
    # primitive-root scaling on BOTH coords leaves slope fixed -> should be invariant trivially.
    # primitive-root scaling on numerator only = doubling-like.
    print(f"  symmetry of S_P, P={P} (residue-pair invariance test):")
    for name, fn in maps.items():
        if fn is None:
            continue
        ok, ch = test_map(name, fn)
        print(f"     {name:38s}: invariant={ok}   ({ch} pairs checked)")
    # full automorphism: which F_P^* scalings of the NUMERATOR preserve S?
    # (scaling numerator p->c p with q fixed = the slope map z->c z)
    print(f"     -- slope-scaling z->c z, c in F_{P}^* (which c preserve S):")
    good_c = []
    for c in range(1, P):
        ok, ch = test_map(f"z->{c}z", lambda a, b, c=c: (c * a, b))
        if ok:
            good_c.append(c)
    print(f"        preserved by c in {good_c}  (out of 1..{P-1})")
    return good_c, val


