def fnv_add(value, word):
    for shift in range(0, 64, 8):
        value ^= (word >> shift) & 0xFF
        value = (value * 0x100000001B3) & ((1 << 64) - 1)
    return value


def exact_geometry(speeds):
    denominator = 1
    for speed in speeds:
        denominator = lcm(denominator, 14 * speed)
    walls = {0, denominator}
    for speed in speeds:
        unit = denominator // (14 * speed)
        for tooth in range(speed):
            walls.add((14 * tooth + 1) * unit)
            walls.add((14 * tooth + 13) * unit)
    walls = sorted(walls)
    safe = []
    mass = 0
    for left, right in zip(walls, walls[1:]):
        twice_midpoint = left + right
        period = 2 * denominator
        good = all(
            denominator <= 7 * (speed * twice_midpoint % period) <= 13 * denominator
            for speed in speeds
        )
        safe.append(good)
        if good:
            mass += right - left
    components = sum(value and not safe[index - 1] for index, value in enumerate(safe))
    return denominator, len(walls), mass, components


