def decide_value(S, v):
    """Return ('GT', cert) if a cycle beats v; ('EQ',pattern) if max mean == v;
       ('LT', None) if all cycles have mean < v (no tight cycle)."""
    p, q = v.numerator, v.denominator
    states, t0, t1 = build_window_graph(S)
    V = len(states)
    D = np.zeros(V, dtype=np.int64)
    has1 = t1 >= 0
    src1 = np.nonzero(has1)[0]
    t1v = t1[src1]
    w0, w1 = -p, q - p
    for it in range(V + 5):
        Dn = D.copy()
        np.maximum.at(Dn, t0, D + w0)
        np.maximum.at(Dn, t1v, D[src1] + w1)
        if np.array_equal(Dn, D):
            break
        D = Dn
    else:
        return ("GT", None, V)
    # tight subgraph, trimmed to recurrent part
    te = []
    for s in range(V):
        if D[t0[s]] == D[s] + w0:
            te.append((s, int(t0[s]), 0))
        if t1[s] >= 0 and D[t1[s]] == D[s] + w1:
            te.append((s, int(t1[s]), 1))
    while True:
        outd = defaultdict(int); ind = defaultdict(int); nodes = set()
        for s, t, b in te:
            outd[s] += 1; ind[t] += 1; nodes.update((s, t))
        bad = {u for u in nodes if outd[u] == 0 or ind[u] == 0}
        if not bad:
            break
        te = [(s, t, b) for (s, t, b) in te if s not in bad and t not in bad]
    if not te:
        return ("LT", None, V)
    # extract one tight cycle's pattern
    outs = {}
    for s, t, b in te:
        outs.setdefault(s, (t, b))
    start = te[0][0]
    seen = {}
    x = start; bits = []
    while x not in seen:
        seen[x] = len(bits)
        t, b = outs[x]
        bits.append(b); x = t
    i = seen[x]
    cyc = bits[i:]
    pos = [j for j, b in enumerate(cyc) if b == 1]
    return ("EQ", (len(cyc), pos), V)

